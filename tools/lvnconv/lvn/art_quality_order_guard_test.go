// СТУПЕНЬ КАЧЕСТВА РЕШАЕТСЯ ДО ПЕРВОГО ПРОГРЕВА.
//
// Выбор игрока (@2k/@1440/@1k) применялся в WireQuickMenu — то есть ПОСЛЕ
// PrepareStage, который уже поставил греться полотно витрины и куклу героини.
// Комментарий рядом обещал «синхронизируем до первой загрузки», и обещание
// было ложным: первая загрузка к этому мигу уже случилась, по совету
// устройства вместо выбора игрока.
//
// Цена — в живом трейсе холодного входа (04.09, кэш снесён руками): прогрев
// тянул слои героини как «@1440», через четверть секунды показ просил «@2k» и
// качал их заново — крупнее и дороже. Четыре слоя, четыре лишних расшифровки
// по 44–58 мс, и всё это время на витрине стоял силуэт вместо героини.
//
// Дефект тихий: ошибок нет, всё «работает», просто медленно и дважды. Увидеть
// его можно было только сложив два лога — прогрева и показа — и заметив, что
// имена файлов отличаются одним суффиксом.
//
// Порядок двух строк в одном методе не выражается ни типом, ни тестом
// поведения: обе стороны по отдельности правы. Поэтому страж смотрит на
// порядок прямо в исходнике.
func TestArtQualitySettledBeforeAnyWarmup(t *testing.T) {
	const boot = "../../../unity/Packages/com.lvn.engine.shell/Runtime/NovelApp.Boot.cs"
	raw, err := os.ReadFile(boot)
	if err != nil {
		t.Skipf("нет %s: %v", boot, err)
	}
	src := string(raw)

	const settle = "DownloadPolicy.PreferredSuffix = DownloadPolicy.SuffixFor(EffectiveArtQuality())"
	const warm = "PrepareStage(manifest"

	at := strings.Index(src, settle)
	if at < 0 {
		t.Fatalf("в запуске не осталось строки, применяющей выбор ступени качества (%s) — "+
			"прогрев снова возьмёт совет устройства вместо выбора игрока", settle)
	}
	warmAt := strings.Index(src, warm)
	if warmAt < 0 {
		t.Fatalf("не нашёл вызов PrepareStage — страж смотрит не туда, поправьте его")
	}
	if at > warmAt {
		t.Errorf("ступень качества применяется ПОСЛЕ первого прогрева (строка %d против %d): "+
			"полотно и кукла поедут в одном боксе, показ попросит в другом, "+
			"и всё скачается дважды",
			1+strings.Count(src[:at], "\n"), 1+strings.Count(src[:warmAt], "\n"))
	}

	// Второе присваивание вернуло бы ту же гонку с другой стороны.
	if n := strings.Count(src, settle); n > 1 {
		t.Errorf("выбор ступени применяется в запуске %d раза — у ответа должен быть один хозяин", n)
	}
}
