package lvn

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// ВУАЛЬ ОБЯЗАНА ГОВОРИТЬ НА ЯЗЫКЕ ИГРЫ, А НЕ НА ЯЗЫКЕ КОДА.
//
// Подписи интерфейса живут в манифесте (ui.words) и попадают в движок через
// LvnWords.Learn. Учил их один ApplyManifest — то есть уже после запуска. А
// вуаль говорит РАНЬШЕ: в ResolveManifestAsync стоит цикл восстановления, и
// это самый долгий экран, какой игрок вообще видит. Каталог к тому моменту
// пуст, LvnWords.Of отдаёт запасную строку из кода — и ровно там, где важнее
// всего понять, что происходит, движок разговаривает по-английски.
//
// Замер 07.09: живой манифест несёт ui.words на 292 ключа, среди них ЕСТЬ
// boot.reconnecting. Игрок при этом видел на устройстве «no connection to the
// server — reconnecting… (2)»: перевод автора лежал готовым и не использовался.
//
// Сторожим ПОРЯДОК, потому что дефект — в нём: в разрешении манифеста слова
// учатся раньше, чем вуаль скажет первое слово. Проверка текстовая, как и у
// соседних стражей: она читает исходник и не требует ни Unity, ни устройства.
func TestVeilSpeaksAfterWordsAreLearned(t *testing.T) {
	root := repoRoot(t)
	путь := filepath.Join(root, "unity", "Packages", "com.lvn.engine.shell",
		"Runtime", "NovelApp.Manifest.cs")
	raw, err := os.ReadFile(путь)
	if err != nil {
		t.Fatalf("не читается %s: %v", путь, err)
	}
	исходник := string(raw)

	начало := strings.Index(исходник, "ResolveManifestAsync(")
	if начало < 0 {
		t.Fatal("не нашёл ResolveManifestAsync — страж смотрит не туда")
	}
	// Тело метода кончается там, где начинается следующий член класса.
	конец := strings.Index(исходник[начало:], "\n        private static void LogManifestFailure")
	if конец < 0 {
		t.Fatal("не нашёл конец ResolveManifestAsync — страж смотрит не туда")
	}
	тело := исходник[начало : начало+конец]

	// ИМЕННО ВЫЗОВ, А НЕ ОБЪЯВЛЕНИЕ. Первая редакция искала «LearnWords(» и
	// находила саму сигнатуру метода: положи её выше по файлу — и страж
	// зеленел бы при полностью отсутствующем вызове. Поймано на собственном
	// укусе: он покраснел по верной причине, но по неверной находке.
	учим := strings.Index(тело, "LearnWords(manifest)")
	говорим := strings.Index(тело, "BootVeil.Status(")
	if учим < 0 {
		t.Fatal("в разрешении манифеста нет вызова LearnWords(manifest): вуаль заговорит " +
			"по-английски при готовом переводе автора (замер 07.09: 292 ключа " +
			"в ui.words, среди них boot.reconnecting)")
	}
	if говорим < 0 {
		// Вуаль перестала говорить отсюда — правило не нарушено, но и стеречь
		// стало нечего: пусть это будет видно, а не считается зелёным молча.
		t.Skip("вуаль больше не говорит из разрешения манифеста — стеречь нечего")
	}
	if учим > говорим {
		t.Errorf("вуаль говорит раньше, чем выучены слова (обучение на %d, "+
			"первая подпись на %d): игрок увидит английский запасной текст, "+
			"хотя перевод у игры есть", учим, говорим)
	}
}
