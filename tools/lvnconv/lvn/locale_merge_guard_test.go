package lvn

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// КАТАЛОГ ПЕРЕВОДОВ СЛИВАЕТСЯ, А НЕ ПЕРЕЗАПИСЫВАЕТСЯ.
//
// Ключ каталога — сама исходная строка, а инструмент запускают снова после
// КАЖДОЙ правки текста. Цена ошибки считается не в минутах, а в неделях чужой
// работы: потерянный перевод восстанавливать неоткуда.
//
// Замерено живьём (qa/locale-check.sh):
//
//	правка соседней строки   переводы на месте, новая добавлена, старый ключ цел
//	-prune                   мёртвый ключ убран, живые переводы не тронуты
//	-check с дырой           код 1, файл не тронут
//
// Три свойства, каждое теряется по-своему:
//
//	ЧИТАЕТ ПРЕЖНЕЕ  без загрузки существующего каталога слияние превращается в
//	                перезапись, и первая же правка главы стирает всё;
//	-check НЕ ПИШЕТ проверка, которая чинит по дороге, показывает не состояние
//	                дерева, а состояние после себя (за ночь это уже случалось
//	                с генератором грамматики);
//	УДАЛЯЕТ ТОЛЬКО ПО ПРОСЬБЕ  осиротевший ключ живёт до -prune: исчезни он
//	                сам, автор потерял бы работу, не нажав ничего.
func TestLocaleCatalogMergesInsteadOfOverwriting(t *testing.T) {
	root := repoRoot(t)
	path := filepath.Join(root, "tools", "lvnconv", "main_locale.go")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("команда локализации не прочитана: %v", err)
	}
	src := string(raw)

	readAt := strings.Index(src, "readCatalog(")
	mergeAt := strings.Index(src, "MergeCatalog(")
	writeAt := strings.Index(src, "os.WriteFile(")
	checkAt := strings.Index(src, "if *check {")

	if readAt < 0 {
		t.Error("прежний каталог больше не читается — слияние стало перезаписью, " +
			"и первая правка главы сотрёт все переводы")
	}
	if mergeAt < 0 {
		t.Fatal("слияние каталога исчезло — страж потерял предмет охраны")
	}
	if writeAt < 0 {
		t.Fatal("запись каталога не найдена")
	}
	if readAt > mergeAt {
		t.Error("каталог читается ПОСЛЕ слияния — сливать будет не с чем")
	}
	// -check обязан выйти ДО записи: проверка, чинящая по дороге, показывает
	// состояние после себя, а не то, что есть.
	if checkAt < 0 {
		t.Error("режим -check исчез — полноту каталога больше нечем проверить")
	} else if checkAt > writeAt {
		t.Error("-check разбирается ПОСЛЕ записи: проверка перестала быть только чтением")
	}
	// Удаление — только по явной просьбе.
	if !strings.Contains(src, "*prune") {
		t.Error("-prune исчез — либо осиротевшие ключи копятся вечно, либо их " +
			"удаляют молча, и автор теряет работу, не нажав ничего")
	}
}
