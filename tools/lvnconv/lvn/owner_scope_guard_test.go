package lvn

import (
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

// Данные одного игрока не достаются другому.
//
// На одном телефоне играют двое. Правило записано в LvnKeep прямым текстом:
// ключи БЕЗ приставки принадлежат тому, кто вошёл здесь первым, а любой другой
// аккаунт получает собственное пространство через Scoped. У правила есть и
// второй, тихий смысл: Scoped попутно вносит ключ в реестр личных данных, по
// которому исполняется «удалите меня».
//
// Способов исполнить правило в движке ДВА, и оба законные: развести ключи по
// владельцам (сейвы, прогресс, галерея, «прочитано») либо ВЫБРОСИТЬ местное
// при смене владельца (кошелёк: очередь начислений не должна проиграться в
// чужой). А сторожа не было ни одного — и гардероб не сделал ни того, ни
// другого. Замер 07.09: второй игрок открывал гардероб с нарядом первого,
// включая купленное, и затирал его, переодевшись; шесть обращений шли по голым
// ключам lvn_wardrobe_<герой>.
//
// Промах этого рода не ломает игру и не виден в логе: он виден только тому, у
// кого пропало своё или появилось чужое. Поэтому файл, который пишет ЛИЧНОЕ в
// записную книжку устройства, обязан звать Scoped — либо стоять ниже с
// причиной, почему его данные принадлежат устройству, а не игроку.
func TestPlayerDataIsScopedToItsOwner(t *testing.T) {
	root := repoRoot(t)
	scanned := 0

	// Не личное игрока — или личное, но разведённое иначе. Каждая строка с
	// причиной: без причины список тихо разрастётся до «всё исключено».
	deviceOwned := map[string]string{
		"LvnMark.cs":            "метки УСТРОЙСТВА: его идентификатор и секрет состояния — их надо знать ДО всякого входа",
		"LvnPrefs.cs":           "настройки устройства: громкость, язык, скорость текста — свойство телефона, а не игрока",
		"VnStage.Background.cs": "последний фон — подсказка для мгновенного показа, не история игрока",
		"NovelApp.Manifest.cs":  "кэш манифеста: содержимое каталога, одинаковое для всех, кто играет на этом телефоне",
		"LvnAttribution.cs":     "откуда пришла УСТАНОВКА: свойство устройства и кампании",
		"LvnExperiments.cs":     "раскладка экспериментов приходит с сервера и переживает игрока",
		"LvnBackend.cs":         "дом самой учётки: тут ключи и хранятся, приставке взяться неоткуда",
		"LvnOutbox.cs":          "очередь на отправку: ключ выдаёт владелец очереди, буфер уходит с ближайшей отправкой",
		"LvnWallet.cs":          "разведён ИНАЧЕ: NoteUser при смене учётки выбрасывает зеркало и очередь — они не должны проиграться в чужой кошелёк",
	}

	writeRe := regexp.MustCompile(`LvnKeep\.(Put|Jot)\(`)
	var missing []string
	seen := map[string]bool{}

	for _, pkg := range []string{"com.lvn.engine", "com.lvn.engine.shell", "com.lvn.engine.services"} {
		dir := filepath.Join(root, "unity", "Packages", pkg, "Runtime")
		if _, err := os.Stat(dir); err != nil {
			continue
		}
		err := filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
			if err != nil || info.IsDir() || !strings.HasSuffix(path, ".cs") {
				return err
			}
			scanned++
			b, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if !writeRe.Match(b) {
				return nil
			}
			base := filepath.Base(path)
			seen[base] = true
			if _, ok := deviceOwned[base]; ok {
				return nil
			}
			// Ключ, собранный через Scoped, несёт владельца и попадает в реестр.
			if strings.Contains(string(b), "Scoped(") {
				return nil
			}
			missing = append(missing, base)
			return nil
		})
		if err != nil {
			t.Fatalf("обход %s: %v", pkg, err)
		}
	}

	atLeast(t, scanned, 60, "просмотренных файлов")

	// Список исключений обязан ссылаться на живые файлы: переименовали дом —
	// исключение осталось бы прикрывать пустоту, и следующий промах прошёл бы
	// молча под чужим именем.
	var stale []string
	for name := range deviceOwned {
		if !seen[name] {
			stale = append(stale, name)
		}
	}
	sort.Strings(stale)
	if len(stale) > 0 {
		t.Errorf("исключения ссылаются на файлы, которые больше не пишут в книжку: %s\n"+
			"уберите их из списка, иначе они прикрывают пустоту", strings.Join(stale, ", "))
	}

	sort.Strings(missing)
	if len(missing) > 0 {
		t.Fatalf("пишут личное в книжку устройства мимо владельца: %s\n"+
			"на общем телефоне это достаётся следующему игроку и не стирается по «удалите меня».\n"+
			"Соберите ключ через LvnKeep.Scoped — или, если данные принадлежат устройству, "+
			"назовите файл в deviceOwned этого стража с причиной",
			strings.Join(missing, ", "))
	}
}
