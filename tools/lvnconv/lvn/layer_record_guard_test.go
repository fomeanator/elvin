// СЛОЙ ФИГУРЫ — ОДНА ЗАПИСЬ, А НЕ ЧЕТЫРЕ ПАМЯТИ.
//
// Про каждый слой знали врозь: сам элемент, спрайт-основа (к нему возвращаются
// после кадровой анимации), отметка «погашен за неимением картинки» и кость,
// если слой ею работает. Все четыре по одному ключу, и почти каждый обход
// фигуры соединял их вручную: пройти по элементам, а остальное доставать
// TryGetValue по тому же ключу.
//
// Урок к этому месту повторился ТРЕТИЙ раз — до него были мизансцена
// (WorldStage.Slot, пять памятей) и скелеты (VnStage.Skeleton, четыре). Каждый
// раз ломалось одно и то же: уборка знала не про все памяти. Здесь пересборка
// облика чистила четыре Clear подряд — пока их четыре, это верно, и ровно
// поэтому незаметно, что список надо продлевать.
func TestActorLayerIsOneRecord(t *testing.T) {
	root := repoRoot(t)
	file := filepath.Join(root, "unity/Packages/com.lvn.engine/Runtime/UI/World/WorldActor.cs")
	body := stripComments(string(mustRead(t, file)))

	for _, gone := range []string{"_baseSprite", "_hushed", "_bones"} {
		if strings.Contains(body, gone) {
			t.Errorf("WorldActor снова держит %s — это память про слой ВРОЗЬ от "+
				"остальных, и очередная уборка узнает не про все", gone)
		}
	}

	// Пересборка облика — ОДНА уборка. Смотрим в тело метода, а не в файл:
	// страж, ищущий подстроку где угодно, отвечает на вопрос «встречается ли
	// она», а спрашивают «делает ли это ВОТ ЭТО место» (поймано мутацией на
	// стороже скелетов).
	i := strings.Index(body, "_layers.Clear()")
	if i < 0 {
		t.Fatal("пересборка облика больше не чистит слои узнаваемым образом")
	}
	around := body[maxInt(0, i-400) : i+200]
	if strings.Count(around, ".Clear()") > 2 {
		t.Error("рядом с уборкой слоёв снова стоят соседние Clear — значит " +
			"память про слой опять живёт врозь, и список надо помнить наизусть")
	}
}

func maxInt(a, b int) int {
	if a > b {
		return a
	}
	return b
}

// ЦЕЛОСТНОСТЬ ФИГУРЫ СПРАШИВАЮТ У СЛОЁВ, А НЕ У ОТДЕЛЬНОГО СПИСКА.
//
// «Есть ли погашенный слой» отвечал счётчик отдельного множества, и всё
// держалось на том, что множество пополняют и чистят в четырёх местах
// синхронно с самими слоями. Живой дефект отсюда и пришёл: гашение убирало
// пятно с экрана, выключенный элемент переставал попадать в проверку — и
// Лекарь считал фигуру здоровой, когда героини на экране не было вовсе.
func TestWholenessIsAskedOfTheLayers(t *testing.T) {
	root := repoRoot(t)
	body := stripComments(string(mustRead(t, filepath.Join(root,
		"unity/Packages/com.lvn.engine/Runtime/UI/World/WorldActor.cs"))))
	if !strings.Contains(body, "private bool AnyHushed()") {
		t.Fatal("исчез вопрос «есть ли погашенный слой» — он снова будет " +
			"заданным по отдельной памяти, которую забудут обновить")
	}
	for _, asker := range []string{"if (AnyHushed()) return true;", "if (AnyHushed()) return false;"} {
		if !strings.Contains(body, asker) {
			t.Errorf("проверка целостности больше не спрашивает %q — "+
				"погашенный слой снова читается как здоровый", asker)
		}
	}
}
