package lvn

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// КОНФЛИКТ ДВУХ УСТРОЙСТВ РАЗРЕШАЕТСЯ СЛИЯНИЕМ, А НЕ ПОВТОРОМ.
//
// Сервер отвечает 409, когда другое устройство писало между нашим чтением и
// нашей записью, и отдаёт вместе с отказом ТЕКУЩИЙ документ. Смысл этого — не
// «попробуй ещё раз»: повтор с тем же телом просто затрёт чужое со второй
// попытки. Смысл в пополевом слиянии: побеждает документ другого устройства, а
// поверх ложатся только те ключи, которые ЭТО устройство меняло с последней
// сходимости.
//
// Замерено живьём (qa/two-devices-check.sh, настоящий сервер и настоящий
// HttpStateStore в проекте с одним пакетом):
//
//	второе устройство ПРОЧИТАЛО и записало   золото 100 цело, глава 5 добавлена
//	второе устройство записало НЕ ЧИТАЯ      осталось {"глава":9} — золото стёрто
//
// Второй случай — не дефект, а договор: Save означает «вот эти переменные
// теперь», и на этом стоит обряд стирания статов (пустой набор вместо глагола
// удаления). Слить внутри Put было бы «очевидной починкой», которая сломала бы
// стирание: оно вернуло бы стёртое с сервера обратно.
//
// Значит беречь надо ровно то, что работает: слияние на 409 и повтор после него.
func TestStateConflictMergesInsteadOfRetrying(t *testing.T) {
	root := repoRoot(t)
	path := filepath.Join(root, "unity", "Packages", "com.lvn.engine",
		"Runtime", "Content", "LvnStateStore.cs")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("клиентское хранилище состояния не прочитано: %v", err)
	}
	src := string(raw)

	const put = "private async Task Put("
	start := strings.Index(src, put)
	if start < 0 {
		t.Fatal("отправка состояния не найдена — страж потерял предмет охраны")
	}
	body := src[start:]
	if end := strings.Index(body[len(put):], "\n        private "); end >= 0 {
		body = body[:len(put)+end]
	}

	conflict := strings.Index(body, "409")
	if conflict < 0 {
		t.Fatal("клиент перестал разбирать 409 — запись со второго устройства будет теряться")
	}
	tail := body[conflict:]

	if !strings.Contains(tail, "MergeVars(") {
		t.Error("на 409 нет пополевого слияния: повтор с тем же телом затрёт чужой прогресс " +
			"со второй попытки — отказ станет отсрочкой, а не защитой")
	}
	if !strings.Contains(tail, "continue") {
		t.Error("после слияния нет повтора — слитый документ никуда не отправится, " +
			"и правка останется только локальной")
	}
	if !strings.Contains(body, `send["_version"]`) {
		t.Error("клиент перестал слать версию — сервер не сможет отличить свежую запись " +
			"от устаревшей, и 409 не придёт вовсе")
	}

	// Одна попытка повтора, а не бесконечный цикл: два устройства, спорящие
	// вечно, держали бы сеть и батарею.
	if !strings.Contains(body, "attempt < 2") {
		t.Log("число попыток повтора изменилось — сверьтесь, что спор конечен")
	}
}
