package lvn

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// ФИГУРА ВЫХОДИТ ЦЕЛОЙ ИЛИ НЕ ВЫХОДИТ ВОВСЕ.
//
// Партнёрский репорт 29.08 («базовый баг», скриншот главного экрана): героиня
// без лица. Первая сессия, пролог, выход в меню. Правило «фигура неделима»
// было записано в сцене словами и соблюдалось наполовину:
//
//   1. силуэт-заготовка (быстрый вход на холодной сети) собиралась из тех
//      слоёв, у кого нашёлся @mini, а остальные пропускались молча;
//   2. признак «облик надет» ставился по списку ЗАПРОШЕННОГО, и хватало
//      одного доехавшего слоя — после чего проверка «облик тот же и арт цел»
//      честно отвечала «да», и неполную фигуру показывали включением, без
//      пересборки. Безликость переставала быть временной.
//
// Страж держит оба места: заготовка сверяется по ПОЛНОМУ числу слоёв, а облик
// закрепляется только целым.
func TestФигураВыходитЦелой(t *testing.T) {
	root := repoRoot(t)
	actors := filepath.Join(root, "unity", "Packages", "com.lvn.engine",
		"Runtime", "UI", "VnStage.Actors.cs")
	b, err := os.ReadFile(actors)
	if err != nil {
		t.Fatalf("сцена не найдена: %v", err)
	}
	src := string(b)

	// Правило одно, а записать его можно двумя сторонами: «показываем, если
	// собралось всё» и «уходим, если собралось не всё». Страж держит ПРАВИЛО,
	// поэтому принимает обе — и краснеет, только когда сверки нет вовсе.
	if !strings.Contains(src, "mini.Count == urls.Count") &&
		!strings.Contains(src, "mini.Count != urls.Count") {
		t.Error("силуэт-заготовка снова показывается неполной:\n" +
			"  условие показа обязано сверять mini.Count == urls.Count.\n" +
			"  Слой без @mini пропускается молча — и на экран выходит фигура без лица.\n" +
			"  Ждать лишние полсекунды честнее: задержку игрок читает как загрузку,\n" +
			"  безликость — как сломанную игру.")
	}

	if !strings.Contains(src, "layers.Count == urls.Count") &&
		!strings.Contains(src, "layers.Count != urls.Count") {
		t.Error("облик закрепляется, не будучи надетым целиком:\n" +
			"  _actorLook[id] = look разрешён только при layers.Count == urls.Count.\n" +
			"  Иначе проверка «облик тот же и арт цел» отвечает «да» на неполную фигуру,\n" +
			"  показ идёт включением без пересборки, и самолечение слоя (оно живёт,\n" +
			"  пока показ новейший) уже не спасёт: выход в меню его обрывает.")
	}
}
