package lvn

import "testing"

// ПОРОГ ОХВАТА — против стража, который молча проверил пустоту.
//
// Страж, собирающий множество из исходников, держится на якоре: имени метода,
// форме объявления, заголовке таблицы. Промахнись якорь — множество окажется
// пустым, проверять станет нечего, и страж ПОЗЕЛЕНЕЕТ, ничего не проверив. Это
// хуже, чем его отсутствие: отсутствующий страж никого не убеждает.
//
// Случай не гипотетический. В этот же день скрапер схемы манифеста молча терял
// семнадцать классов из сорока пяти — и обе сверявшиеся стороны врали
// одинаково, потому что смотрели друг на друга, а не на охват.
//
// Правило простое: собрал множество — назови, сколько его должно быть хотя бы.
func atLeast(t *testing.T, n, min int, what string) {
	t.Helper()
	if n < min {
		t.Fatalf("страж охватил всего %d %s (ожидалось не меньше %d) — "+
			"якорь разбора промахнулся, и проверка прошла бы по пустоте", n, what, min)
	}
}
