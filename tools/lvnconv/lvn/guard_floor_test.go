package lvn

import "testing"

// ПОРОГ ОХВАТА — против стража, который молча проверил пустоту.
//
// Страж, собирающий множество из исходников, держится на якоре: имени метода,
// форме объявления, заголовке таблицы. Промахнись якорь — множество окажется
// пустым, проверять станет нечего, и страж ПОЗЕЛЕНЕЕТ, ничего не проверив. Это
// хуже, чем его отсутствие: отсутствующий страж никого не убеждает.
//
// Случай не гипотетический. В этот же день скрапер схемы манифеста молча терял
// семнадцать классов из сорока пяти — и обе сверявшиеся стороны врали
// одинаково, потому что смотрели друг на друга, а не на охват.
//
// Правило простое: собрал множество — назови, сколько его должно быть хотя бы.
func atLeast(t *testing.T, n, min int, what string) {
	t.Helper()
	if n < min {
		t.Fatalf("страж охватил всего %d %s (ожидалось не меньше %d) — "+
			"якорь разбора промахнулся, и проверка прошла бы по пустоте", n, what, min)
	}
}

// ПОРОГ ОХВАТА У РАТЧЕТА СТАВИТСЯ НА ПРОСМОТРЕННОЕ, А НЕ НА НАЙДЕННОЕ.
//
// Обычный страж собирает множество ТОГО, ЧТО ПРОВЕРЯЕТ, и пустое множество там
// означает промах якоря. Ратчет собирает множество НАРУШЕНИЙ, и цель его — свести
// это множество к нулю. Поставить порог охвата на число нарушений значит объявить
// поломкой каждое улучшение: прогон краснеет ровно тогда, когда стало лучше.
//
// Стоило это 01.09 двух десятиминутных прогонов. Оба раза счёт нарушений падал
// раньше, чем я успевал переписать порог, и `RUN-ALL FAIL` означал «стало лучше».
// Ошибка не в числе, а в том, ЧТО меряется охватом: перепутаны предмет проверки
// и её результат.
//
// Здесь охват меряется просмотренными файлами: если якорь промахнулся, их будет
// ноль, а нарушений — тоже ноль, и отличить одно от другого можно только так.
func sawSources(t *testing.T, scanned, min int, what string) {
	t.Helper()
	if scanned < min {
		t.Fatalf("ратчет прочитал всего %d %s (ожидалось не меньше %d) — "+
			"обход промахнулся, и «нарушений ноль» означало бы пустоту, а не порядок",
			scanned, what, min)
	}
}
