package lvn

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// У РАЗМЕРА ЗОНЫ ТАПА ОДИН ХОЗЯИН.
//
// Верхняя кромка сцены — единственный способ вызвать игровой бар: бургер из
// сцены убран (решение Ильи 26.08), и если зона не ловит палец, до меню,
// истории и гардероба из главы не добраться вовсе.
//
// Ответов на «какая она высотой» в одном классе накопилось три: сорок восемь
// юнитов, потом пятнадцать процентов экрана — двумя строками ниже, в том же
// конструкторе, — и ещё раз сорок восемь плюс кромка, в SetSafeTop, который
// зовётся при КАЖДОМ замере выреза. Побеждал последний: на телефоне с чёлкой
// зона схлопывалась в полоску высотой с саму чёлку.
//
// Дефект тихий вдвойне. На маке и на телефоне без выреза он не
// воспроизводится совсем (кромка нулевая — числа сходятся), а игрок видит не
// «зона мала», а «бар не вызывается» — и ищет поломку в баре.
//
// Правило: высота зоны назначается РОВНО ОДИН РАЗ и долей экрана. Вырез
// сдвигает зону вниз (`top`), а не режет её.
func TestTapZoneHasOneHeight(t *testing.T) {
	path := filepath.Join(repoRoot(t), "unity", "Packages", "com.lvn.engine.shell",
		"Runtime", "LvnTopBar.cs")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Skipf("нет %s", path)
	}

	assign := regexp.MustCompile(`_tapCatcher\.style\.height\s*=\s*([^;]+);`)
	hits := assign.FindAllStringSubmatch(string(raw), -1)

	if len(hits) != 1 {
		var got []string
		for _, h := range hits {
			got = append(got, strings.TrimSpace(h[1]))
		}
		t.Fatalf("высота зоны тапа назначается %d раз(а): %s\n"+
			"Ответ должен быть один и в конструкторе: последний по времени "+
			"перебивает остальные, и на телефоне с вырезом зона схлопывается "+
			"в полоску — игровой бар перестаёт вызываться тапом сверху.",
			len(hits), strings.Join(got, " | "))
	}
	if !strings.Contains(hits[0][1], "Percent") {
		t.Errorf("высота зоны тапа задана как %q — нужна ДОЛЯ экрана: "+
			"«верхняя кромка» на планшете и на телефоне это разное число "+
			"пикселей, а доля одна.", strings.TrimSpace(hits[0][1]))
	}
}
