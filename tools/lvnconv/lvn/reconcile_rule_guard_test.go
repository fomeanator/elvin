package lvn

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// СВЕДЕНИЕ ПРИ ЗАГРУЗКЕ — ПОПОЛЕВОЕ, А НЕ «НОВЕЕ ПОБЕЖДАЕТ ЦЕЛИКОМ».
//
// Здесь однажды стояло «новее побеждает целиком», и это ТЕРЯЛО ИГРУ: телефон
// играл в самолёте (записано локально, отправка не ушла), планшет тем временем
// писал на сервер — и первая же онлайн-загрузка выбрасывала офлайн-сессию.
// Правило для конфликта ЗАПИСИ уже было пополевым; в дверь, которой пользуются
// чаще, стояло правило похуже.
//
// Замерено живьём (qa/wipe-sync-check.sh, настоящий сервер и клиент, два
// разведённых устройства):
//
//	сброс на первом → второе, ничего не менявшее, видит {}   сброс не воскрес
//	офлайн-игра на втором → чужой сброс → {"золото":150}     сессия цела
//
// Одно правило обязано давать ОБА ответа, и они тянут в разные стороны: не
// менял — чужая пустота побеждает; менял — своё переживает. Замена на «новее
// целиком» ломает вторую половину и не трогает первую, поэтому заметить подмену
// одним сценарием нельзя.
func TestLoadReconcileMergesFieldwise(t *testing.T) {
	root := repoRoot(t)
	path := filepath.Join(root, "unity", "Packages", "com.lvn.engine",
		"Runtime", "Content", "LvnStateStore.cs")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("клиентское хранилище состояния не прочитано: %v", err)
	}
	src := string(raw)

	const fn = "internal static JObject Reconcile("
	start := strings.Index(src, fn)
	if start < 0 {
		t.Fatal("сведение при загрузке не найдено — страж потерял предмет охраны")
	}
	body := src[start:]
	if end := strings.Index(body[len(fn):], "\n        internal "); end >= 0 {
		body = body[:len(fn)+end]
	}

	if !strings.Contains(body, "MergeVars(") {
		t.Error("загрузка перестала сводить пополевой: офлайн-сессия будет выброшена " +
			"первой же синхронизацией с другого устройства")
	}
	// «Новее целиком» допустимо РОВНО в одном случае — базы нет, сравнивать не с
	// чем (свежая установка). Без этой привязки оно тихо вернётся на общий путь.
	if n := strings.Index(body, "Newer("); n >= 0 {
		before := body[:n]
		if !strings.Contains(before, "baseVars == null") {
			t.Error("«новее побеждает целиком» стоит не только при отсутствующей базе — " +
				"именно так однажды и терялась игра")
		}
	}
	// Правило области разбирается ПЕРВЫМ: свёрток прогресса не плоский набор, и
	// пополевое слияние отдало бы его целиком одной стороне.
	rule := strings.Index(body, "rule(")
	merge := strings.Index(body, "MergeVars(")
	if rule < 0 {
		t.Error("правило области больше не спрашивается — у прогресса и статов разная цена ошибки")
	} else if rule > merge {
		t.Error("правило области спрашивают ПОСЛЕ пополевого слияния — оно уже ничего не решает")
	}
}
