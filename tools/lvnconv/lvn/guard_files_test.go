package lvn

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// ВСЕ ИСХОДНИКИ ПОД ЭТИМ КОРНЕМ — один обход на всех стражей.
//
// Стражи читают текст C#, и каждый начинался с одного и того же обхода:
// пройти дерево, взять файлы на «.cs», пропустить каталоги. Написан он был
// сорока шестью копиями, и копии разошлись в мелочи, которая решает, СЧИТАЕТ
// ли страж: одни пропускают «/Tests/», другие нет.
//
// СЧИТАНО, ПРЕЖДЕ ЧЕМ ПРАВИТЬ (01.09): разошлись — да, но вреда нет ни у
// одной. Все сорок шесть ходят по корням «…/Runtime» и «…/Editor», а тесты
// движка лежат отдельной ветвью — под эти корни они просто не попадают.
// Массовый перевод копий на общий обход поэтому НЕ сделан: он не закрывает
// ни одного дефекта, а правка в сорока шести файлах прячет настоящие. Дом
// заведён, чтобы новые стражи не добавляли сорок седьмую копию, и чтобы
// правило «тесты не читаем» имело одно место, когда оно понадобится.
//
// Тесты исключены здесь всё равно: они пишут нарочно неправильный код, чтобы
// проверить, что на него ругаются, и страж, читающий их наравне с рантаймом,
// ловит собственную мишень.
func csFiles(t *testing.T, dir string) []string {
	t.Helper()
	var out []string
	err := filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || !strings.HasSuffix(path, ".cs") {
			return err
		}
		if strings.Contains(filepath.ToSlash(path), "/Tests/") {
			return nil
		}
		out = append(out, path)
		return nil
	})
	if err != nil {
		t.Fatalf("обход %s: %v", dir, err)
	}
	if len(out) == 0 {
		t.Fatalf("под %s нет ни одного .cs — путь устарел, и страж молчал бы вечно", dir)
	}
	return out
}
