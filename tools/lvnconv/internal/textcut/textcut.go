//
// Дом заведён 01.09 по замеру: три копии одной работы под тремя именами —
// `truncateRunes` в выгрузке, `trunc` в отчёте, `truncRunes` в разборе эмоций.
// Тела совпадали построчно.
//
// Копия здесь опаснее обычной. Обрезать строку можно по БАЙТАМ или по РУНАМ, и
// на латинице разницы не видно: она проступает ровно на кириллице, японском и
// эмодзи — там байтовая обрезка рвёт символ пополам и оставляет в отчёте
// битую последовательность. Три копии — это три места, где кто-то однажды
// напишет `s[:n]`, потому что «так короче», и никто не заметит до первого
// имени с буквой «ё».
package textcut

// Runes отдаёт не больше n символов, добавляя многоточие, когда обрезала.
// Считает РУНАМИ, а не байтами: см. причину в заголовке пакета.
func Runes(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n]) + "…"
}
