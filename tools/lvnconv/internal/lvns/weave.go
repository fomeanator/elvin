package lvns

// weave — проза и поток прямо внутри ветки выбора, со схождением и без
// выдуманных имён.
//
// ЗАЧЕМ. Выбор из двух веток с прозой сегодня требует придумать три-четыре
// имени: метку на каждую ветку, метку схождения и переходы к ней. Замер по
// репозиторию: в написанном руками .lvns 206 меток из 390 (53%) не имеют
// отношения к сюжету — это леса вокруг choice. В импортированных главах ровно
// та же половина. На главе в 10 тысяч строк это тысячи имён, каждое из которых
// надо придумать, не столкнуть с соседним и потом читать.
//
// ЭТО КОНСТРУКЦИЯ ВРЕМЕНИ КОМПИЛЯЦИИ (docs/adding-an-op.md): новых опов не
// появляется, рантайм видит ровно те же label/goto, которые автор написал бы
// руками. Поэтому цена — две реализации (этот компилятор и его C#-порт), а не
// шесть.
//
// ОДИН СИНТАКСИС, ДВА МЕХАНИЗМА. Блок `{ … }` у опции уже существует и
// компилируется в рантайм-поле `body`. Заводить рядом второй, внешне такой же,
// синтаксис — ловушка: два похожих блока с разным лоурингом невозможно
// различить глазами. Поэтому решение то же, что уже принято для `func` (тело из
// одного `return <expr>` инлайнится, тело из команд идёт через call/return):
// СИНТАКСИС ОДИН, механизм выбирает компилятор по содержимому.
//
//	{ set / inc / goto }        → поле `body`, как и раньше: ноль меток
//	{ проза, if, choice, wait } → лоуринг в метку + переход (этот файл)
//
// Граница не вкусовая. LvnPlayer.Choose диспетчеризует внутри body только
// set/inc/goto, а команда в body не имеет индекса в скрипте — трасса
// восстановления индексирует скрипт, поэтому всё остальное, положенное в body,
// проигралось бы один раз и исчезло при первой же загрузке сейва. То есть
// список «что нельзя в body» — это не запрет, а РАЗВИЛКА: ровно то, что не
// умещается в body, и лоурится в обычный скрипт.
//
// СХОЖДЕНИЕ БЕСПЛАТНОЕ. Отдельного маркера нет — точка схождения это просто
// «сразу после выбора». Раскладка:
//
//	choice(… -> __weave_x_1, -> __weave_x_2)
//	goto __wend_x_1          ← путь опции, которая продолжает исполнение за choice
//	:__weave_x_1
//	  <команды блока>
//	  goto __wend_x_1        ← или к стрелке опции, если она была
//	:__weave_x_2
//	  <команды блока>
//	  goto __wend_x_1
//	:__wend_x_1
//	  <дальше по главе>
//
// Переход сразу за choice обязателен, и вот из-за чего именно. Опции нужна
// стрелка ИЛИ блок — просто так провалиться язык не даёт (parseChoiceOption).
// Но блок из set/inc БЕЗ стрелки стрелки и не имеет: он отрабатывает как
// рантайм-body, после чего управление идёт на команду за выбором. Если в том же
// choice есть сплетённая ветка, эта команда — начало чужой ветки. То есть без
// этого перехода игрок с чужой прозой в глазах, и ни одной ошибки нигде.

// weaveBlock — один блок опции, отложенный до момента после emit(choice).
type weaveBlock struct {
	label  string // минтованная метка ветки
	cmds   []Cmd  // команды блока, уже скомпилированные
	target string // стрелка опции, если была; иначе схождение
	line   int    // строка исходника для диагностики
}

// needsWeaving отвечает на единственный вопрос развилки: помещается этот блок
// в рантайм-поле `body` или обязан стать скриптом. Список — тот же
// optionBodyDenied, который раньше был причиной ОШИБКИ; теперь он причина
// лоуринга, и ошибки не остаётся вовсе.
func needsWeaving(cmds []Cmd) bool {
	for _, c := range cmds {
		if op, _ := c["op"].(string); optionBodyDenied[op] {
			return true
		}
	}
	return false
}

// emitWeaves дописывает лоуринг сразу за командой choice. Ничего не делает,
// когда ни один блок не потребовал плетения — цена конструкции для обычного
// выбора строго нулевая, ни одной лишней метки в .lvn.
func emitWeaves(emit func(Cmd, int), names *synthNamer, weaves []weaveBlock, choiceLine int) {
	if len(weaves) == 0 {
		return
	}
	end := names.name("wend", names.site())

	// Провал за выбор. Пишется всегда, когда есть хоть одно плетение: иначе
	// опция без стрелки продолжила бы исполнение прямо в тело первой ветки.
	emit(Cmd{"op": "goto", "label": end}, choiceLine)

	for _, w := range weaves {
		emit(Cmd{"op": "label", "id": w.label}, w.line)
		for _, c := range w.cmds {
			emit(c, w.line)
		}
		// Блок, который сам заканчивается переходом (автор написал `-> …`
		// последней строкой), уже ушёл — второй переход был бы мёртвым кодом
		// в .lvn и лишней строкой при декомпиляции.
		if endsFlow(w.cmds) {
			continue
		}
		to := w.target
		if to == "" {
			to = end
		}
		emit(Cmd{"op": "goto", "label": to}, w.line)
	}
	emit(Cmd{"op": "label", "id": end}, choiceLine)
}

// endsFlow — последняя команда блока уже уводит управление.
func endsFlow(cmds []Cmd) bool {
	if len(cmds) == 0 {
		return false
	}
	op, _ := cmds[len(cmds)-1]["op"].(string)
	return op == "goto" || op == "return"
}

// absorb registers the author labels of a nested source in this namer, so a
// minted name can never collide with a label written inside a woven block.
func (n *synthNamer) absorb(lines []string) {
	for _, l := range lines {
		if id, ok := sourceLabelID(l); ok {
			n.taken[id] = true
		}
	}
}
