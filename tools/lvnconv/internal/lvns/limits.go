// reLintOk — «я знаю, что делаю»: комментарий снимает проверки со строки.
//
// Без такого выхода линтер становится врагом: автор, которому нужен нарочно
// странный кадр (обзор 8° для подзорной трубы, солнце в пять сил для вспышки),
// либо терпит ложную тревогу в каждой сборке, либо перестаёт читать
// предупреждения вовсе — и тогда пропускает настоящие.
const lintOkMark = "lvn-ok"

func lintSuppressed(line string) bool {
	i := strings.Index(line, "//")
	if i < 0 {
		return false
	}
	return strings.Contains(line[i:], lintOkMark)
}

// lintLimits проверяет числа строки по таблице границ.
func lintLimits(line string, n int, op, id string) []string {
	if lintSuppressed(line) {
		return nil
	}
	table, ok := sceneLimits[op]
	if !ok {
		return nil
	}
	// Порядок обхода таблицы в Go случаен, а предупреждения читают глазами и
	// сравнивают между сборками. Идём по отсортированным именам полей, чтобы
	// один и тот же файл всегда давал один и тот же вывод.
	keys := make([]string, 0, len(table))
	for k := range table {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var warns []string
	for _, key := range keys {
		lim := table[key]
		raw := fieldStr(line, key)
		if raw == "" {
			continue
		}
		// Выражение в фигурных скобках считается в рантайме — проверять нечего.
		if strings.Contains(raw, "{") {
			continue
		}
		v := fieldNum(line, key)
		if raw != "0" && v == 0 {
			continue // не число (проценты, ссылка) — не наше дело
		}
		if v >= lim.min && v <= lim.max {
			continue
		}
		who := id
		if who == "" || who == "без имени" {
			who = op
		}
		warns = append(warns, fmt.Sprintf(
			"line %d: %s=%s у «%s» вне разумного (%g…%g) — %s. Если так задумано, допишите в конце строки «// %s»",
			n, key, raw, who, lim.min, lim.max, lim.why, lintOkMark))
	}
	return warns
}
