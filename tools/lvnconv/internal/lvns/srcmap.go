package lvns

// КАРТА СТРОК — чья это была строка.
//
// Между тем, что написал автор, и тем, что видит построчный разбор, лежат три
// прохода, МЕНЯЮЩИЕ число строк: flattenInline раскладывает однострочный блок
// на отдельные строки, expandLoops разворачивает for/while/if/func в метки и
// goto, expandCalls разворачивает вызовы процедур. После любого из них «строка
// N» — это строка N ВЫВОДА, а не строка автора.
//
// Цена ошибки не косметическая. Один `for` в начале главы съезжал диагностику
// на шесть строк, `func` — на две, каждый однострочный `if c { x }` — ещё на
// две. Компилятор называл место, где ошибки нет, автор правил там, а SrcLine в
// готовом .lvn (по нему IDE ставит курсор, а редактор — подсветку) указывал
// мимо на то же расстояние. Чем длиннее глава, тем дальше промах.
//
// lineWriter — обёртка над append толщиной в одно поле: он помнит, какую
// строку автора проход обрабатывает сейчас, и приписывает её номер каждой
// выданной строке. Выдал проход одну строку на входную или шесть — карта
// верна в обоих случаях, и следующему проходу она достаётся входом.
type lineWriter struct {
	lines []string
	src   []int
	cur   int
}

func newLineWriter(capacity int) *lineWriter {
	return &lineWriter{
		lines: make([]string, 0, capacity),
		src:   make([]int, 0, capacity),
	}
}

// at объявляет, какую строку автора проход разбирает дальше.
func (w *lineWriter) at(line int) { w.cur = line }

// add кладёт строки вывода, помечая каждую текущей строкой автора.
func (w *lineWriter) add(lines ...string) {
	for _, l := range lines {
		w.lines = append(w.lines, l)
		w.src = append(w.src, w.cur)
	}
}

// srcAt — номер авторской строки для строки входа i. Карта может быть короче
// входа или отсутствовать вовсе (проход позвали напрямую, из теста): тогда
// вход И ЕСТЬ исходник, и номер — просто порядковый. Молчаливый возврат нуля
// здесь означал бы «ошибка в строке 0» в сообщении автору.
func srcAt(srcNo []int, i int) int {
	if i >= 0 && i < len(srcNo) {
		return srcNo[i]
	}
	return i + 1
}
