// Package nearest — «вы имели в виду…»: ближайшее по написанию из списка.
//
// Дом заведён 01.09 по замеру: расстояние правок стояло ДВУМЯ реализациями —
// `levenshtein` у проверяющего и `editDistance` у разбора .lvns, — и вокруг
// каждой была своя копия перебора «пройти кандидатов, оставить лучшего».
// Работа одна: подсказать автору, что он опечатался, и в чём.
//
// # Порядок кандидатов — часть ответа, а не мелочь
//
// Обе прежние копии перебирали кандидатов ИЗ КАРТЫ (`for op := range
// KnownOps`), а порядок обхода карты в Go намеренно случаен. На равном
// расстоянии — а такое бывает часто: `bg` против `fg`, `show` против `slow` —
// подсказка менялась от запуска к запуску. Автор видел «имели в виду show?»,
// перезапускал и получал «имели в виду slow?»; отчёт компилятора переставал
// быть воспроизводимым, и сравнить два прогона было нельзя.
//
// Здесь кандидаты сортируются перед перебором, и равные разрешаются по имени.
package nearest

import "slices"

// Distance — классическое расстояние правок, по РУНАМ.
//
// По рунам, а не по байтам: на кириллице байтовое расстояние между «фон» и
// «фн» равно двум, хотя разница в один символ, и подсказка не находилась бы
// вовсе.
func Distance(a, b string) int {
	ra, rb := []rune(a), []rune(b)
	prev := make([]int, len(rb)+1)
	cur := make([]int, len(rb)+1)
	for j := range prev {
		prev[j] = j
	}
	for i := 1; i <= len(ra); i++ {
		cur[0] = i
		for j := 1; j <= len(rb); j++ {
			cost := 1
			if ra[i-1] == rb[j-1] {
				cost = 0
			}
			cur[j] = min(prev[j]+1, cur[j-1]+1, prev[j-1]+cost)
		}
		prev, cur = cur, prev
	}
	return prev[len(rb)]
}

// Of — ближайший кандидат не дальше maxDistance, либо "".
//
// Список копируется и сортируется: см. про порядок в заголовке пакета. Пустые
// кандидаты пропускаются — пустая строка ближе всего к чему угодно короткому и
// давала бы подсказку «вы имели в виду ничего?».
func Of(word string, candidates []string, maxDistance int) string {
	sorted := slices.Clone(candidates)
	slices.Sort(sorted)
	best, bestD := "", maxDistance+1
	for _, c := range sorted {
		if c == "" {
			continue
		}
		if d := Distance(word, c); d < bestD {
			best, bestD = c, d
		}
	}
	return best
}
