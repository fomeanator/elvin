package nearest

import "testing"

func TestРасстояниеСчитаетсяПоРунам(t *testing.T) {
	if d := Distance("фон", "фн"); d != 1 {
		t.Fatalf("кириллица: между «фон» и «фн» один символ, получено %d — "+
			"значит считаем байтами, и подсказка на русских именах не найдётся", d)
	}
}

func TestПодсказкаНеЗависитОтПорядкаКандидатов(t *testing.T) {
	// «slow» и «show» равноудалены от «shlow»; ответ обязан быть один и тот же
	// при любом порядке входа, иначе отчёт компилятора невоспроизводим.
	a := Of("shlow", []string{"slow", "show"}, 2)
	b := Of("shlow", []string{"show", "slow"}, 2)
	if a != b {
		t.Fatalf("подсказка зависит от порядка: %q против %q", a, b)
	}
	if a != "show" {
		t.Fatalf("равные обязаны разрешаться по имени (первое по алфавиту), получено %q", a)
	}
}

func TestДальшеПорогаНеПодсказываем(t *testing.T) {
	if got := Of("совершенно-другое", []string{"bg", "actor"}, 2); got != "" {
		t.Fatalf("подсказали далёкое: %q — автор пойдёт исправлять не то", got)
	}
}

func TestПустойКандидатНеПобеждает(t *testing.T) {
	if got := Of("ab", []string{"", "abc"}, 2); got != "abc" {
		t.Fatalf("пустая строка ближе всего к любому короткому слову; получено %q", got)
	}
}
