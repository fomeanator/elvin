// derived.go — ОБЩЕЕ ДЛЯ ПРОИЗВОДНЫХ ФАЙЛОВ.
//
// Сервер отдаёт три вида файлов, которых на диске может ещё не быть:
// уменьшенный вариант (@2k, downscale.go), код для видеокарты (.ktx2,
// ktx2.go) — и раньше был третий, сырой ASTC. Все трое делают одно и то же:
// берут запрошенный путь, ищут рядом исходник с тем же именем и другим
// расширением, и, если производного нет, собирают его.
//
// Помощники этой работы — «какие расширения считать исходником», «есть ли
// файл», «куда на диске ложится путь запроса» — жили в astc.go, потому что
// он приехал первым. Двое остальных ходили к нему в гости; когда мёртвый
// формат сняли (01.09), сборка встала: общий механизм уехал вместе с одним
// из потребителей. Дом, названный по потребителю, — это дом не про то.
//
// Теперь общее живёт здесь и ни от одного формата не зависит.

import (
	"os"
	"path/filepath"
	"strings"
)

// sourceExts — расширения, которые считаются ИСХОДНИКОМ для производного
// файла. Порядок значим: он же порядок предпочтения при поиске соседа.
//
// Список ОДИН на все производные пути. Была уже цена за копию: тот же список
// в клиенте (SplitSourceImage) стерёгся тестом ровно потому, что забыть одну
// копию значит получить формат, который «почему-то не собирается».
var sourceExts = []string{".png", ".jpg", ".jpeg"}

// fileExists — «файл на месте и это файл». Каталог с подходящим именем не
// считается: обслужить его нельзя, а перепутать легко.
func fileExists(path string) bool {
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}

// contentPath переводит путь запроса в путь на диске, отказывая любому "..".
//
// net/http вычищает ".." до маршрутизации, и filepath.Join из фиксированной
// базы всё равно не выпускает — но обработчик, который ПИШЕТ файлы, стоит
// явного отказа: проверку читают глазами, а неявное поведение приходится
// вспоминать.
func (s *server) contentPath(rel string) (string, bool) {
	if strings.Contains(rel, "..") {
		return "", false
	}
	return filepath.Join(s.content, filepath.Clean("/"+rel)), true
}

// transcodeError — отказ кодировщика вместе с тем, что он написал в вывод.
// Без вывода в логе остаётся «exit status 1», по которому нельзя отличить
// «нет такого файла» от «формат не поддержан».
type transcodeError struct {
	src    string
	output string
	err    error
}

func (e *transcodeError) Error() string {
	return e.src + ": " + e.err.Error() + ": " + e.output
}
