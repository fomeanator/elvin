package main

import (
	"os"
	"strings"
	"testing"
)

// АВТОРА СТАВИТ СЕРВЕР ИЗ МАНИФЕСТА, А НЕ КЛИЕНТ ИЗ ТЕЛА ЗАПРОСА.
//
// Доверие здесь разделено осознанно: клиент говорит, В КАКОМ ТИТУЛЕ он играет
// (этого не знает больше никто), сервер говорит, ЧЕЙ это титул. Вторая половина
// — деньги автора, и клиент не должен уметь назвать своим плательщиком кого
// угодно.
//
// Замерено живьём (qa/attribution-check.sh):
//
//	подставленный в теле author   в журнал НЕ попал, записан автор манифеста
//	незнакомый титул              автор пуст — честное «не знаю», а не догадка
//	смена автора в манифесте      следующая трата уехала новому автору
//
// Ловушка проверки: если бы сервер писал пустого автора ВСЕГДА, проверка
// подмены прошла бы сама собой — подставленного имени нет, значит «держит».
// Поэтому стенд сперва обязан увидеть настоящее имя. Здесь та же мысль в
// структурном виде: поле author не должно существовать во входной структуре.
func TestPayeeIsNamedByTheServer(t *testing.T) {
	raw, err := os.ReadFile("wallet.go")
	if err != nil {
		t.Fatalf("кошелёк не прочитан: %v", err)
	}
	src := string(raw)

	// Входная структура траты: клиент вправе назвать титул и не вправе — автора.
	const marker = "OpID string `json:\"op_id\"`"
	at := strings.Index(src, marker)
	if at < 0 {
		t.Fatal("входная структура траты не найдена — страж потерял предмет охраны")
	}
	head := src[:at]
	open := strings.LastIndex(head, "var req struct {")
	if open < 0 {
		t.Fatal("начало входной структуры не найдено")
	}
	body := src[open:]
	if end := strings.Index(body, "\n\t\t}"); end >= 0 {
		body = body[:end]
	}
	if !strings.Contains(body, `json:"title"`) {
		t.Error("клиент больше не сообщает титул — атрибуцию будет неоткуда взять")
	}
	if strings.Contains(body, `json:"author"`) {
		t.Error("во входной структуре появилось поле author — клиент получил возможность " +
			"назвать своим плательщиком кого угодно")
	}

	// Автор берётся из индекса владельцев, и только оттуда.
	if !strings.Contains(src, "s.owners.authorOf(req.Title)") {
		t.Error("автор ставится не из индекса владельцев — источником стал запрос " +
			"или догадка, а это чужие деньги")
	}

	// Индекс отвечает пустотой на незнакомый титул: догадка здесь хуже отказа.
	att, err := os.ReadFile("attribution.go")
	if err != nil {
		t.Fatalf("индекс владельцев не прочитан: %v", err)
	}
	if !strings.Contains(string(att), "o.authors[titleID]") {
		t.Error("поиск автора идёт не по объявленным титулам — пустота заменена вычислением")
	}
}
