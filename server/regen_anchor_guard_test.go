package main

import (
	"os"
	"strings"
	"testing"
)

// ЯКОРЬ ДВИГАЕТСЯ НА ОТРАБОТАННЫЕ ОКНА, А НЕ В «СЕЙЧАС».
//
// Энергия глав — монетизационный шлюз: её нельзя заработать, только ждать или
// купить. Поэтому ошибка в ритме бьёт по игроку деньгами в любую сторону.
//
// Опасность несимметрична, и потому её обычно видят наполовину. «Опрос
// ускоряет» ищут все. Вторая тише и хуже: поставь якорь в now — и КАЖДЫЙ
// запрос обнулит недосчитанные секунды. Игрок, у которого открыт экран с
// обратным отсчётом, не получит энергию НИКОГДА, а жалоба прозвучит как «у
// меня просто не идёт», и искать будут в клиенте.
//
// Замерено живьём (qa/energy-regen-check.sh, окно 2 с, опрос каждые 100 мс):
// прибавки на 1,5 / 3,5 / 5,5 с — шаг ровно в окно, потолок держится. Первая
// приходит до полусекунды раньше: якорь ставится в ЦЕЛЫХ секундах, и округление
// отдаётся игроку. Это осознанно и в его пользу.
func TestRefillAnchorAdvancesByWholeWindows(t *testing.T) {
	raw, err := os.ReadFile("wallet.go")
	if err != nil {
		t.Fatalf("начисление по времени не прочитано: %v", err)
	}
	src := string(raw)

	const fn = "func (s *WalletService) accrue("
	start := strings.Index(src, fn)
	if start < 0 {
		t.Fatal("начисление по времени не найдено — страж потерял предмет охраны")
	}
	body := src[start:]
	if end := strings.Index(body[len(fn):], "\nfunc "); end >= 0 {
		body = body[:len(fn)+end]
	}

	if !strings.Contains(body, "gained") {
		t.Fatal("исчез счёт отработанных окон — страж смотрит не на тот код")
	}
	// Тот самый сдвиг: якорь уезжает ровно на отработанное, остаток остаётся
	// игроку. Без него частый опрос крадёт время.
	if !strings.Contains(body, "anchor+gained*rule.Interval") &&
		!strings.Contains(body, "anchor + gained*rule.Interval") {
		t.Error("якорь двигается не на отработанные окна: недосчитанные секунды будут " +
			"сгорать на каждом запросе, и при открытом экране отсчёта энергия не придёт никогда")
	}
	// Обнуление якоря законно РОВНО в двух местах: на потолке (часы паркуются)
	// и при старте часов из припаркованного состояния. Присвоение «сейчас»
	// внутри ветки начисления — это и есть кража остатка.
	if i := strings.Index(body, "gained"); i >= 0 {
		tail := body[i:]
		if strings.Contains(tail, "setAnchor(doc, cur, nowU)") {
			t.Error("в ветке начисления якорь ставится в «сейчас» — остаток сгорает")
		}
	}
	if !strings.Contains(body, "bal >= rule.Cap") {
		t.Error("исчезла проверка потолка — восстановление перевалит за предел")
	}
}
