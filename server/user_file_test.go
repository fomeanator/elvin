package main

import (
	"os"
	"path/filepath"
	"testing"
)

// ПИСЬМО ЗАПИСИ ИГРОКА — один дом на все службы.
//
// Реклама, ежедневные награды и кошелёк держали эти четыре строки своей копией.
// В файле игрока лежат баланс и покупки, и права 0600 значат «только владелец
// процесса»: повтори кто-нибудь копию с 0644 — записи станут читаемы всем на
// машине, и заметить это можно только выборочной проверкой прав.
func TestЗаписьИгрокаТолькоДляВладельца(t *testing.T) {
	dir := t.TempDir()
	if err := writeUserFile(dir, "u1", []byte(`{"ok":true}`)); err != nil {
		t.Fatalf("запись не удалась: %v", err)
	}
	st, err := os.Stat(filepath.Join(dir, "u1.json"))
	if err != nil {
		t.Fatalf("файл не появился: %v", err)
	}
	if got := st.Mode().Perm(); got != 0o600 {
		t.Fatalf("права %o — баланс и покупки игрока стали читаемы не только владельцу", got)
	}
}

// Проверка имени неотделима от сборки пути: получить путь, не проверив имя,
// НЕЛЬЗЯ. Иначе идентификатор с «..» увёл бы запись за пределы каталога.
func TestНедопустимоеИмяНеПишетНичего(t *testing.T) {
	dir := t.TempDir()
	for _, bad := range []string{"", "../побег", "a/b", "имя с пробелом"} {
		if err := writeUserFile(dir, bad, []byte("{}")); err == nil {
			t.Fatalf("имя %q прошло — запись могла уйти не туда", bad)
		}
	}
	ents, _ := os.ReadDir(dir)
	if len(ents) != 0 {
		t.Fatalf("после отказов в каталоге появилось %d файлов", len(ents))
	}
}
