package main

import (
	"fmt"
	"testing"
)

// ЦЕНА СМЕНЫ ДОЛЕЙ, ИЗМЕРЕННАЯ, А НЕ ОПИСАННАЯ.
//
// Обещание — «долю трафика и выключатель меняют без новой сборки». Оно
// держится: правится JSON на сервере. Но у него есть цена, которую нигде не
// назвали: зерно деления включает ВЕРСИЮ (`имя#версия:игрок`), а сменить доли
// без поднятия версии validateExperiments запрещает — и правильно, иначе
// старые и новые данные смешались бы.
//
// Значит любая смена долей ПЕРЕСТАВЛЯЕТ часть игроков между вариантами. Для
// теста цвета кнопки это неважно. Для НАРРАТИВНОГО теста это значит, что игрок,
// прочитавший три главы по ветке B, может вернуться и получить ветку A.
//
// Клиентский докблок при этом обещает обратное: «игрок всегда в своей группе —
// после перезахода, перезапуска и переустановки, и история не меняется у него
// под руками». Для локального деления это правда; для серверного — нет.
//
// Тест не объявляет это дефектом: перекладка — осознанная плата за
// сравнимость данных. Он измеряет ЦЕНУ, чтобы её знали, называя число.
func TestСменаДолейПереставляетИгроков(t *testing.T) {
	const users = 2000
	before := experiment{
		Name: "tone", Version: 1, Enabled: true,
		Variants: []experimentVariant{{ID: "a", Weight: 50}, {ID: "b", Weight: 50}},
	}
	after := before
	after.Version = 2 // доли меняют, подняв версию — как требует проверка

	moved := 0
	for i := 0; i < users; i++ {
		u := fmt.Sprintf("u%04d", i)
		if before.pick(u) != after.pick(u) {
			moved++
		}
	}
	share := float64(moved) / users
	t.Logf("поднятие версии переставило %d из %d игроков (%.0f%%)", moved, users, share*100)

	if moved == 0 {
		t.Errorf("версия не влияет на деление — тогда смена долей НЕ пересобирает группы, "+
			"и старые данные молча смешаются с новыми (проверка validateExperiments теряет смысл)")
	}
	if share < 0.2 || share > 0.8 {
		t.Errorf("переставлено %.0f%% — это не похоже на честную перетасовку "+
			"при равных долях; проверьте зерно", share*100)
	}
}

// ВЫКЛЮЧЕНИЕ СВОДИТ ВСЕХ В ПЕРВЫЙ ВАРИАНТ — и это единственный ответ, при
// котором сцена продолжает играться. Но значит: КАЖДЫЙ, кто был во втором,
// переезжает. Для нарративного теста это самая резкая грань выключателя, и
// знать её надо до того, как им воспользуются на живой аудитории.
func TestВыключениеПереводитВсехИзВторогоВарианта(t *testing.T) {
	const users = 1000
	on := experiment{
		Name: "tone", Version: 1, Enabled: true,
		Variants: []experimentVariant{{ID: "a", Weight: 50}, {ID: "b", Weight: 50}},
	}
	off := on
	off.Enabled = false

	inB, moved := 0, 0
	for i := 0; i < users; i++ {
		u := fmt.Sprintf("u%04d", i)
		if on.pick(u) == "b" {
			inB++
			if off.pick(u) != "b" {
				moved++
			}
		}
	}
	t.Logf("во втором варианте было %d; выключение перевело %d", inB, moved)

	if inB == 0 {
		t.Fatal("никто не попал во второй вариант — стенд ничего не проверяет")
	}
	if moved != inB {
		t.Errorf("выключение перевело %d из %d — обещано «все в первом варианте»", moved, inB)
	}
}

// БЕЗ СМЕНЫ КОНФИГА ДЕЛЕНИЕ НЕПОДВИЖНО. Это и есть та часть обещания, которую
// клиентский докблок называет прямо: перезаход, перезапуск, переустановка —
// группа та же, потому что она вычисляется, а не хранится.
func TestБезСменыКонфигаДелениеНеподвижно(t *testing.T) {
	e := experiment{
		Name: "tone", Version: 3, Enabled: true,
		Variants: []experimentVariant{{ID: "a", Weight: 30}, {ID: "b", Weight: 70}},
	}
	for i := 0; i < 500; i++ {
		u := fmt.Sprintf("u%04d", i)
		first := e.pick(u)
		for k := 0; k < 5; k++ {
			if got := e.pick(u); got != first {
				t.Fatalf("%s: деление поплыло без смены конфига (%q → %q)", u, first, got)
			}
		}
	}
}
