package main

import (
	"os"
	"strings"
	"testing"
)

// «СОХРАНЕНО» ГОВОРЯТ ПОСЛЕ ДИСКА, А НЕ ДО НЕГО.
//
// Клиент верит ответу {saved:true} и НЕ повторяет запись. Значит порядок здесь
// не стилистика: ответь раньше записи — и падение процесса между двумя строками
// сотрёт часы игры, о которых игроку уже сказали «сохранено».
//
// Целиком это проверяется живым стендом (qa/state-durability-check.sh): сервер
// гасится и поднимается заново, документ обязан быть на месте с той же версией.
// Там же меряется гонка: 40 писателей, 655 отказов 409, потерь ноль.
//
// Здесь — порядок вызовов и наличие ветки отказа, за миллисекунды. Перестановка
// не меняет ни одного кода ответа: тесты остались бы зелёными, а обещание
// исчезло бы.
func TestStateSaysSavedOnlyAfterDisk(t *testing.T) {
	raw, err := os.ReadFile("main.go")
	if err != nil {
		t.Fatalf("обработчик состояния не прочитан: %v", err)
	}
	src := string(raw)

	const handler = "func (s *server) handleState("
	start := strings.Index(src, handler)
	if start < 0 {
		t.Fatal("обработчик состояния не найден — страж потерял предмет охраны")
	}
	body := src[start:]
	if end := strings.Index(body[len(handler):], "\nfunc "); end >= 0 {
		body = body[:len(handler)+end]
	}

	persist := strings.Index(body, "writeStateFile(")
	ok := strings.Index(body, `"saved": true`)
	conflict := strings.Index(body, "writeJSON409(")

	if persist < 0 {
		t.Fatal("запись состояния на диск исчезла — «сохранено» стало бы обещанием памяти")
	}
	if ok < 0 {
		t.Fatal("ответ об успехе не найден — страж смотрит не на тот код")
	}
	if persist > ok {
		t.Error("сервер отвечает «сохранено» ПРЕЖДЕ записи на диск: падение между " +
			"двумя строками сотрёт прогресс, о котором игроку уже сказали")
	}

	// Отказ по устаревшей версии — вторая половина обещания: без него запись со
	// второго устройства молча затирает первое. Замерено: в режиме без версий
	// 40 подтверждённых записей оставляют в документе ОДНУ.
	if conflict < 0 {
		t.Error("исчез отказ по устаревшей версии — параллельная запись со второго " +
			"устройства снова начнёт затирать чужой прогресс")
	}
	if conflict > persist {
		t.Error("проверка версии стоит ПОСЛЕ записи — она уже ничего не защищает")
	}
}
