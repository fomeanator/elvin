package main

import (
	"os"
	"strings"
	"testing"
)

// ПРАВА В ПАНЕЛИ: ЧТО ИМЕННО ЛЕГКО ПОТЕРЯТЬ.
//
// Панель правит ЖИВОЙ контент — то, что через секунду увидят играющие. Ролей
// три: смотрящий читает, редактор правит содержание, владелец распоряжается
// людьми.
//
// Замерено живьём (qa/admin-roles-check.sh, настоящий вход по паролю):
//
//	смотрящий читает        200
//	смотрящий пишет         403
//	редактор пишет          200
//	редактор заводит людей  403
//	хозяин заводит людей    200
//
// Хрупкость здесь в том, ОТКУДА берётся право по умолчанию: из МЕТОДА запроса.
// GET и HEAD — смотрящему, остальное — редактору. Значит опасное действие,
// сделанное через GET, достаётся смотрящему само собой, без единой правки прав.
// Явное право во всём сервере названо считанные разы, и оба места охраняются
// здесь: управление людьми и публикация требуют ВЛАДЕЛЬЦА.
func TestPanelRolesKeepTheirBoundaries(t *testing.T) {
	gate, err := os.ReadFile("admingate.go")
	if err != nil {
		t.Fatalf("охрана панели не прочитана: %v", err)
	}
	g := string(gate)

	// Правило по умолчанию: читать — смотрящему, менять — редактору.
	if !strings.Contains(g, "need := RoleEditor") {
		t.Error("право по умолчанию перестало требовать редактора — менять живой контент " +
			"сможет смотрящий")
	}
	if !strings.Contains(g, "MethodGet") || !strings.Contains(g, "need = RoleViewer") {
		t.Error("чтение перестало опускаться до смотрящего — либо права выведены не из метода, " +
			"либо смотрящий потерял смысл")
	}
	// Порядок разбора: сначала человек, потом ключ машины. Иначе в журнале
	// вместо имени останется «зашли токеном сборки».
	sess := strings.Index(g, "adminPeople.Session(r)")
	tok := strings.Index(g, "bearerOK(r, token)")
	if sess < 0 || tok < 0 {
		t.Fatal("исчез один из двух путей входа — страж смотрит не на тот код")
	}
	if sess > tok {
		t.Error("ключ машины проверяется раньше сессии человека — именованное действие " +
			"потеряет имя в журнале")
	}

	// Управление людьми — только владелец, и это НЕ должно выводиться из метода.
	people, err := os.ReadFile("adminusers_http.go")
	if err != nil {
		t.Fatalf("управление людьми не прочитано: %v", err)
	}
	if !strings.Contains(string(people), "s.okRole(w, r, RoleOwner)") {
		t.Error("управление людьми больше не требует владельца явно — редактор заведёт себе " +
			"учётку с любыми правами")
	}

	// Публикация — тоже владелец: она выкатывает контент играющим.
	agent, err := os.ReadFile("agent.go")
	if err != nil {
		t.Fatalf("публикация не прочитана: %v", err)
	}
	if !strings.Contains(string(agent), "adminAllowedRole(w, r, s.adminToken, RoleOwner)") {
		t.Error("публикация перестала требовать владельца — выкатить главу играющим " +
			"сможет любой редактор")
	}

	// Старшинство ролей: владелец ≥ редактор ≥ смотрящий. Перепутанный порядок
	// не падает, он просто открывает лишнее.
	users, err := os.ReadFile("adminusers.go")
	if err != nil {
		t.Fatalf("роли не прочитаны: %v", err)
	}
	u := string(users)
	for _, want := range []string{"RoleOwner", "RoleEditor", "RoleViewer"} {
		if !strings.Contains(u, want) {
			t.Errorf("роль %s исчезла — матрица прав изменилась молча", want)
		}
	}
}
