package main

import (
	"os"
	"strings"
	"testing"
)

// ПРОВЕРКА ИДЁТ ДО ПЕРВОЙ ЗАПИСИ — НА ЭТОМ ДЕРЖИТСЯ ВСЁ ОБЕЩАНИЕ.
//
// Справка API говорит автору дословно: «Структурная ошибка — кодом 422, и в этом
// случае НИЧЕГО не записано: прежняя версия игры цела». Обещание держится не на
// коде ответа, а на ПОРЯДКЕ: сперва структурный гейт, и только потом запись.
// Переставь их местами при рефакторинге — коды ответов не изменятся, тесты
// сервера останутся зелёными, а неудачная публикация начнёт затирать игру,
// которая прямо сейчас у кого-то идёт.
//
// Целиком обещание проверяется живым сервером (qa/publish-atomicity-check.sh):
// публикуем главу, публикуем битую, сверяем дерево, манифест и провод побайтово.
// Тот прогон поднимает сервер и ходит по HTTP, поэтому идёт по требованию.
// Здесь — порядок вызовов, за миллисекунды, с каждым `go test`.
func TestPublishChecksBeforeItWrites(t *testing.T) {
	raw, err := os.ReadFile("agent.go")
	if err != nil {
		t.Fatalf("обработчик публикации не прочитан: %v", err)
	}
	src := string(raw)

	const handler = "func (s *server) handleAgentPublish("
	start := strings.Index(src, handler)
	if start < 0 {
		t.Fatal("обработчик публикации не найден — страж потерял предмет охраны")
	}
	// Тело до следующего объявления верхнего уровня.
	body := src[start:]
	if end := strings.Index(body[len(handler):], "\nfunc "); end >= 0 {
		body = body[:len(handler)+end]
	}

	check := strings.Index(body, "checkLvn(")
	write := strings.Index(body, "writeContentFile(")

	// Оба якоря обязаны найтись: пропажа любого означает, что страж смотрит не
	// туда, а «нарушений ноль» стало бы пустотой, а не порядком.
	if check < 0 {
		t.Fatal("в публикации нет структурного гейта (checkLvn) — битая глава уедет игрокам")
	}
	if write < 0 {
		t.Fatal("в публикации нет записи (writeContentFile) — страж смотрит не на тот код")
	}
	if check > write {
		t.Error("публикация ПИШЕТ раньше, чем проверяет: отказ затрёт уже опубликованную главу")
	}

	// Отказ обязан быть отказом, а не успехом с жалобой в поле.
	if !strings.Contains(body, "StatusUnprocessableEntity") {
		t.Error("структурный отказ перестал отвечать 422 — автор примет неудачу за успех")
	}
}
