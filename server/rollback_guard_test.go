package main

import (
	"os"
	"strings"
	"testing"
)

// ОТКАТ: ВОЗВРАЩАЕТ, САМ ОБРАТИМ, ИЗ КОНТЕНТА НЕ ВЫХОДИТ.
//
// Это сеть безопасности под самой дорогой ошибкой. Гейт публикации ловит битое,
// но не умеет ловить ПЛОХОЕ: глава может компилироваться, проходить структурную
// проверку и всё равно оказаться не той. Тогда остаётся откат.
//
// Замерено живьём (qa/rollback-check.sh):
//
//	по проводу вернулась прежняя редакция, байт в байт
//	снимков было 1, после отката стало 2 — вернуться назад есть чем
//	путь с «..» отвергнут (400), несуществующий снимок отвергнут (404)
//
// Три свойства, и каждое теряется по-своему:
//
//	СНИМОК ПЕРЕД ЗАПИСЬЮ  откат, стирающий то, от чего откатывались, — это не
//	                      сеть, а второй обрыв: «как было минуту назад» станет
//	                      уже нечем вернуть;
//	ИМЯ ФАЙЛА ОТ КЛИЕНТА  рядом лежит весь контент, поэтому путь обязан
//	                      проверяться, а не подставляться;
//	МЕТКА ВРЕМЕНИ         тоже из запроса и тоже часть пути на диске.
func TestRollbackRestoresAndStaysReversible(t *testing.T) {
	raw, err := os.ReadFile("admin.go")
	if err != nil {
		t.Fatalf("админские ручки не прочитаны: %v", err)
	}
	src := string(raw)

	const fn = "func (s *AdminService) handleRollback("
	at := strings.Index(src, fn)
	if at < 0 {
		t.Fatal("откат не найден — страж потерял предмет охраны")
	}
	body := src[at:]
	if end := strings.Index(body[len(fn):], "\nfunc "); end >= 0 {
		body = body[:len(fn)+end]
	}

	snap := strings.Index(body, "snapshotHistory(")
	write := strings.Index(body, "atomicWrite(")
	if snap < 0 {
		t.Error("откат больше не снимает снимок перед записью — от неудачной редакции " +
			"не останется следа, и вернуться к ней будет нечем")
	}
	if write < 0 {
		t.Fatal("запись из отката исчезла — страж смотрит не на тот код")
	}
	if snap > write {
		t.Error("снимок делается ПОСЛЕ записи — сохранится уже восстановленное, " +
			"а не то, от чего откатывались")
	}

	// Оба поля приходят от клиента и оба участвуют в пути на диске.
	if !strings.Contains(body, "historyEligible(req.File)") {
		t.Error("имя файла не проверяется — откат станет записью куда угодно")
	}
	if !strings.Contains(body, "reHistoryTS.MatchString(req.TS)") {
		t.Error("метка времени не проверяется — она тоже часть пути на диске")
	}

	// Проверка пути обязана отсекать «..» и обратный слэш, а не только
	// перечислять разрешённые каталоги.
	el := strings.Index(src, "func historyEligible(")
	if el < 0 {
		t.Fatal("проверка пути не найдена")
	}
	elBody := src[el:]
	if end := strings.Index(elBody[20:], "\nfunc "); end >= 0 {
		elBody = elBody[:20+end]
	}
	if !strings.Contains(elBody, `".."`) {
		t.Error("проверка пути перестала отсекать «..» — выход из каталога контента открыт")
	}
}
