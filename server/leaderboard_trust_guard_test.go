package main

import (
	"os"
	"strings"
	"testing"
)

// ТАБЛИЦА ЛИДЕРОВ: ЧТО ЗАЩИЩЕНО, А ЧТО НЕ МОЖЕТ БЫТЬ.
//
// Очки присылает клиент, и сервер их проверить НЕ МОЖЕТ: он не симулирует игру.
// Это граница устройства, а не недосмотр, и записана она рядом с замером:
// поданный предельный int64 попадает в таблицу как есть.
//
// Защитить здесь можно ровно три вещи, и все три проверены живьём
// (qa/leaderboard-check.sh):
//
//	ЛИЧНОСТЬ   кто подал — из ВХОДА, а не из тела. Второй игрок, подавший под
//	           чужим ИМЕНЕМ, свой рекорд и получил, чужой не тронул;
//	УЛУЧШЕНИЕ  повторная подача худшего не стёрла рекорд (100 против 10);
//	КАТАЛОГ    имя доски — слаг, и отвергает его САМ сервер (400), а не
//	           нормализация пути маршрутизатором.
func TestLeaderboardTrustsOnlyWhatItCan(t *testing.T) {
	raw, err := os.ReadFile("leaderboard.go")
	if err != nil {
		t.Fatalf("таблица лидеров не прочитана: %v", err)
	}
	src := string(raw)

	const fn = "func (s *LeaderboardService) handleSubmit("
	at := strings.Index(src, fn)
	if at < 0 {
		t.Fatal("подача результата не найдена — страж потерял предмет охраны")
	}
	body := src[at:]
	if end := strings.Index(body[len(fn):], "\nfunc "); end >= 0 {
		body = body[:len(fn)+end]
	}

	// Личность — из входа. Появись здесь user в теле запроса, один игрок стал
	// бы переписывать рекорды другого, и таблица потеряла бы смысл быстрее,
	// чем от накрученных очков.
	if !strings.Contains(body, "s.auth.UserFromRequest(r)") {
		t.Error("подающий больше не берётся из входа — рекорды станут переписываемыми")
	}
	if strings.Contains(body, `json:"user"`) {
		t.Error("во входной структуре появился user — клиент называет себя сам")
	}

	// Только улучшение: клиент шлёт результат после каждой попытки, и
	// «последний победил» стирал бы достижение первым же неудачным заходом.
	if !strings.Contains(body, "req.Score > entries[i].Score") {
		t.Error("подача перестала сравнивать с прежним результатом — худший заход " +
			"сотрёт рекорд")
	}

	// Имя доски — слаг, проверяемый сервером.
	if !strings.Contains(src, "reBoard.MatchString(board)") {
		t.Error("имя доски не проверяется — ключ хранения приходит из адреса как есть")
	}
	if !strings.Contains(src, "`^[a-z0-9_-]{1,40}$`") {
		t.Error("слаг доски перестал быть консервативным — в имя пролезет разделитель пути или пробел")
	}
}
