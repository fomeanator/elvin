package main

import (
	"os"
	"strings"
	"testing"
)

// ЦИКЛ ПЕРЕЗАРЯДКИ НАЧИНАЕТСЯ С ПЕРВОГО ПОКАЗА, А НЕ С ПОСЛЕДНЕГО.
//
// У награды за рекламу нет чека, который можно сверить: клиент просто говорит
// «я посмотрел». Поэтому защита здесь — не идемпотентность, а ограничение:
// заряды на ближайшие минуты и дневной потолок на сутки.
//
// Опасность в отсчёте несимметрична — та же, что у энергии, и потому её
// стабильно видят наполовину. Веди отсчёт от ПОСЛЕДНЕЙ попытки, и игрок,
// часто жмущий кнопку, не дождётся заряда НИКОГДА: каждая попытка отодвигает
// восстановление. Жалоба прозвучит как «у меня кнопка не оживает», и искать
// будут в клиенте.
//
// Замерено живьём (qa/ads-charges-check.sh, заряды 2, цикл 3 с, попытки каждые
// 100 мс): подряд выдано ровно 2, заряд вернулся через 2,7 с, дневной потолок
// сработал, начислено ровно потолок × награду.
func TestAdChargeCycleStartsAtTheFirstWatch(t *testing.T) {
	raw, err := os.ReadFile("ads.go")
	if err != nil {
		t.Fatalf("выдача награды не прочитана: %v", err)
	}
	src := string(raw)

	const fn = "func (s *AdsService) handleReward("
	start := strings.Index(src, fn)
	if start < 0 {
		t.Fatal("выдача награды не найдена — страж потерял предмет охраны")
	}
	body := src[start:]
	if end := strings.Index(body[len(fn):], "\nfunc "); end >= 0 {
		body = body[:len(fn)+end]
	}

	set := strings.Index(body, "doc.Since[req.Placement] = now.Unix()")
	if set < 0 {
		t.Fatal("начало цикла больше не отмечается — перезарядка не сможет истечь")
	}
	// Отметка обязана стоять ПОД УСЛОВИЕМ «цикл ещё не начат». Безусловное
	// присвоение и есть отсчёт от последнего показа.
	head := body[:set]
	cut := strings.LastIndex(head, "if ")
	if cut < 0 || !strings.Contains(head[cut:], "== 0") {
		t.Error("начало цикла ставится безусловно — это отсчёт от ПОСЛЕДНЕЙ попытки: " +
			"частые нажатия отодвинут восстановление навсегда")
	}

	// Оба предела обязаны проверяться ДО выдачи, и заряды — раньше потолка: у
	// них разные причины отказа и разный разговор с игроком.
	charges := strings.Index(body, "chargesLeft(")
	cap_ := strings.Index(body, "DailyCap > 0 && doc.Counts")
	grant := strings.Index(body, "doc.Counts[req.Placement]++")
	if charges < 0 || cap_ < 0 || grant < 0 {
		t.Fatal("исчез один из пределов или сама выдача — страж смотрит не на тот код")
	}
	if charges > grant || cap_ > grant {
		t.Error("предел проверяется ПОСЛЕ выдачи — награда уже начислена, отказывать поздно")
	}
	if charges > cap_ {
		t.Error("заряды проверяются после дневного потолка: игрок услышит «на сегодня хватит» " +
			"там, где верный ответ — «ещё минуту»")
	}
}
