package main

// ВОРОТА АДМИНКИ — единственное место, где решается, пускать ли запрос.
//
// Так было не всегда. Проверка «есть ли токен» была скопирована в полтора
// десятка обработчиков: выгрузка, импорт, публикация, логи, спайн, конфликты.
// Пока проверка была одна и та же, копии не мешали — они и выглядели
// одинаково. Но стоило добавить вход по имени, как выяснилось: сессия
// работает ровно там, где её вписали, а в остальных местах человек с
// правильным паролем получает отказ, зато старый токен продолжает открывать
// всё. Про такое расхождение никто не узнает, пока не наткнётся.
//
// Поэтому проверка здесь одна. Добавили роль — она появилась везде; закрыли
// дыру — закрылась везде. Цена: обработчики больше не решают сами, кого
// пускать, и это ровно то, чего мы хотим.

import (
	"net/http"
)

// adminPeople — учётки панели. Одна на процесс: людей заводят у сервера, а не
// у отдельной службы внутри него. Хранится здесь, а не протаскивается полем
// сквозь шесть структур, потому что протаскивание кончилось бы тем же, чем
// кончились копии проверки — где-то поле забыли бы передать.
var adminPeople *AdminUsers

// adminAllowed — пускать ли. Право на чтение достаточно роли смотрящего, на
// изменение нужен редактор: разница между «посмотреть заказы» и «выдать
// покупку» и есть та разница, ради которой заводились роли.
func adminAllowed(w http.ResponseWriter, r *http.Request, token string) bool {
	need := RoleEditor
	if r.Method == http.MethodGet || r.Method == http.MethodHead {
		need = RoleViewer
	}
	return adminAllowedRole(w, r, token, need)
}

// adminAllowedRole — то же с явно названным правом, для действий, чья
// опасность не читается по методу запроса.
func adminAllowedRole(w http.ResponseWriter, r *http.Request, token, need string) bool {
	// Админка выключена целиком: ни токена, ни людей. Отвечаем «запрещено», а
	// не «неавторизован» — просить пароль там, где входа нет, значит звать
	// подбирать его.
	if token == "" && (adminPeople == nil || adminPeople.Empty()) {
		http.Error(w, "admin disabled", http.StatusForbidden)
		return false
	}

	// Сначала СЕССИЯ человека, потом ключ машины. Порядок не косметический:
	// когда у действия есть имя, в журнале должно остаться имя, а не «зашли
	// токеном сборки».
	if adminPeople != nil {
		if sess := adminPeople.Session(r); sess != nil {
			if roleAllows(sess.Role, need) {
				return true
			}
			http.Error(w, "недостаточно прав", http.StatusForbidden)
			return false
		}
	}

	if token != "" && bearerOK(r, token) {
		return true
	}

	http.Error(w, "unauthorized", http.StatusUnauthorized)
	return false
}
