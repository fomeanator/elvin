            { ""op"": ""say"", ""text"": ""своя ветка"" },
            { ""op"": ""goto"", ""label"": ""КОНЕЦ"" },
            { ""op"": ""label"", ""id"": ""X"" },
            { ""op"": ""say"", ""text"": ""чужая ветка"" },
            { ""op"": ""label"", ""id"": ""КОНЕЦ"" }
          ]
        }";

        // Развилка без цены: два даровых варианта с разными ветками. Нужна там,
        // где проверяется само нажатие, а не деньги.
        private const string ДвойноеНажатие = @"{
          ""scene"": ""двойное"",
          ""script"": [
            { ""op"": ""say"", ""text"": ""развилка"" },
            { ""op"": ""choice"", ""options"": [
              { ""text"": ""левый"", ""goto"": ""L"" },
              { ""text"": ""правый"", ""goto"": ""R"" } ] },
            { ""op"": ""label"", ""id"": ""R"" },
            { ""op"": ""say"", ""text"": ""правая ветка"" },
            { ""op"": ""goto"", ""label"": ""КОНЕЦ"" },
            { ""op"": ""label"", ""id"": ""L"" },
            { ""op"": ""say"", ""text"": ""левая ветка"" },
            { ""op"": ""label"", ""id"": ""КОНЕЦ"" }
