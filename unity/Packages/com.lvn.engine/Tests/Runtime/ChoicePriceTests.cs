        [UnitySetUp]
        public IEnumerator Стенд()
        {
            _stage = TestStage.Panel("choice-price-stage", out _go, out _panel);
            yield return null;
        }

        [TearDown]
        public void Уборка()
        {
            if (_go != null) UnityEngine.Object.Destroy(_go);
            if (_panel != null) UnityEngine.Object.Destroy(_panel);
        }

        // ── стенд ───────────────────────────────────────────────────────────

        private T Поле<T>(string имя) where T : class
            => typeof(VnStage).GetField(имя, BindingFlags.Instance | BindingFlags.NonPublic)
                ?.GetValue(_stage) as T;

        private VisualElement Корень => _go != null
            ? _go.GetComponent<UIDocument>()?.rootVisualElement : null;

        private ChoiceList Меню => Корень?.Q<ChoiceList>();

        /// <summary>Кнопка варианта — по НАДПИСИ на ней, как её видит игрок.
        /// Искать по месту в стопке значит завязаться на порядок сборки, а
        /// вопрос здесь всегда «нажали на ту, где написано вот это».</summary>
        private Button Вариант(string надпись)
        {
            var меню = Меню;
            if (меню == null) return null;
            foreach (var кнопка in меню.Query<Button>().ToList())
                foreach (var подпись in кнопка.Query<Label>().ToList())
                    if (подпись.text == надпись) return кнопка;
            return null;
        }

        /// <summary>Что произойдёт от нажатия по кнопке. Живого тапа нет:
        /// событие разносит панель по настоящим координатам, а стопка выборов
        /// стоит там, где её поставила тема. Спрашиваем саму кнопку, к чему
        /// она приведёт, — это и есть нажатие игрока.</summary>
        // Приём живёт в доме сцены: PlayMode — отдельная сборка, и копия
        // редакторного дома здесь была бы вторым правилом на один тап.
        private static Action Нажатие(Button кнопка) => TestStage.Press(кнопка);

        private bool НаВыборе
        {
            get { var p = Поле<LvnPlayer>("_player"); return p != null && p.AtChoice; }
        }

        private int ВыбраннымиВИстории()
        {
            int n = 0;
            foreach (var строка in _stage.Backlog)
                if (строка.style == "choice") n++;
            return n;
        }

        private bool ВИстории(string текст)
        {
            foreach (var строка in _stage.Backlog)
                if (строка.text == текст) return true;
            return false;
        }

        private string Подсказка() => Корень?.Q<Label>("vn-hint-text")?.text;

        private static IEnumerator Ждём(Func<bool> готово, float секунд = 6f)
        {
            float срок = Time.realtimeSinceStartup + секунд;
            while (Time.realtimeSinceStartup < срок && !готово()) yield return null;
        }

        private static IEnumerator Кадры(int сколько)
        {
            for (int i = 0; i < сколько; i++) yield return null;
        }

        private IEnumerator ДоВыбора(string надпись)
        {
            yield return Ждём(() => Вариант(надпись) != null);
            Assert.IsNotNull(Вариант(надпись),
                "вариант «" + надпись + "» так и не вышел на экран — нажимать игроку не на что");
        }

        /// <summary>Дождаться момента, когда вариант ПО-НАСТОЯЩЕМУ доступен
        /// игроку: он не только вышел на экран, но и погашенным больше не стоит.
        /// Между этими двумя моментами лежит приезд карточки и ожидание
        /// хореографии актёров — нажимать раньше значит проверять не то, что
        /// делает игрок.</summary>
        private IEnumerator ДоЖивогоВыбора(string надпись)
        {
            yield return Ждём(() => Вариант(надпись) != null && Вариант(надпись).enabledInHierarchy);
            var кнопка = Вариант(надпись);
            Assert.IsNotNull(кнопка,
                "вариант «" + надпись + "» так и не вышел на экран — нажимать игроку не на что");
            Assert.IsTrue(кнопка.enabledInHierarchy,
                "вариант «" + надпись + "» на экране, но погашен — игрок его видит и не может нажать");
        }

        // ── (а) сперва деньги, потом ветка ───────────────────────────────────

        // ДЕНЬГИ ВПЕРЁД. Между нажатием и веткой лежит поход в кошелёк, и он
        // может не вернуться вовсе — оборваться сетью, упереться в отказ банка,
        // застрять на минуту. Уведи историю сразу — и сорванная покупка оставит
        // игрока в платной ветке с полным кошельком (даровой премиум) либо, при
        // обратном порядке ошибки, спишет деньги за ветку, которой он не
        // увидел. Пока кошелёк молчит, история обязана стоять ровно там же, где
        // стояла, а меню — оставаться на экране.
        [UnityTest]
        public IEnumerator ПокаКошелёкМолчит_ИсторияСтоитНаМесте()
        {
            var касса = new TaskCompletionSource<bool>();
            var спросили = new List<(string валюта, long сумма)>();
            bool историяУшлаДоСписания = true;

            _stage.ChoiceSpend = (валюта, сумма) =>
            {
                спросили.Add((валюта, сумма));
                историяУшлаДоСписания = ВыбраннымиВИстории() > 0 || !НаВыборе;
                return касса.Task;
            };

            _stage.Play(Развилка);
            yield return ДоВыбора("платный");

            Нажатие(Вариант("платный"))?.Invoke();
            yield return Ждём(() => спросили.Count > 0);

            Assert.AreEqual(1, спросили.Count,
                "кошелёк не спросили вовсе — платная ветка досталась игроку даром");
            Assert.AreEqual("тесткоин", спросили[0].валюта,
                "списали не ту валюту, что написана в цене варианта");
            Assert.AreEqual(25L, спросили[0].сумма,
                "списали не ту сумму, что написана в цене варианта");
            Assert.IsFalse(историяУшлаДоСписания,
                "историю увели ДО списания — сорвись покупка, ветка осталась бы пройденной, "
                + "а кошелёк нетронутым");

            yield return Кадры(10);

            Assert.AreEqual(0, ВыбраннымиВИстории(),
                "выбор записан в историю, пока кошелёк ещё не ответил");
            Assert.IsTrue(НаВыборе,
                "история ушла вперёд, не дождавшись оплаты");
            Assert.IsNotNull(Вариант("платный"),
                "меню выборов сняли на время платежа — игроку нечего нажать, если платёж сорвётся");

            // Деньги взяли — и вот теперь ветка проходится.
            касса.SetResult(true);
            yield return Ждём(() => ВИстории("платная ветка"));

            Assert.IsTrue(ВИстории("платная ветка"),
                "оплата прошла, а ветка не открылась — игрок заплатил ни за что");
            Assert.AreEqual(1, ВыбраннымиВИстории(),
                "оплаченный выбор не отметился в истории — при откате игрок не поймёт, за что платил");
        }

        // Сорванная покупка — не разрешение пройти. Сеть на телефоне рвётся
        // постоянно, и обработчик кошелька падает исключением, а не ответом
        // «нет». Прими падение за успех — и премиальная ветка станет бесплатной
        // для всякого, кто нажмёт её в метро.
        [UnityTest]
        public IEnumerator СорваннаяПокупкаНеУводитПоВетке()
        {
            _stage.ChoiceSpend = (валюта, сумма) => throw new Exception("сеть оборвалась");

            _stage.Play(Развилка);
            yield return ДоВыбора("платный");

            Нажатие(Вариант("платный"))?.Invoke();
            yield return Кадры(30);

            Assert.IsFalse(ВИстории("платная ветка"),
                "покупка сорвалась, а платная ветка всё равно открылась — премиум достался даром");
            Assert.AreEqual(0, ВыбраннымиВИстории(),
                "сорванная покупка записалась в историю как сделанный выбор");
            Assert.IsTrue(НаВыборе,
                "сорванная покупка увела историю с выбора");
            Assert.IsNotNull(Вариант("даром"),
                "после сорванной покупки меню исчезло — глава встала намертво, "
                + "хотя даровой вариант рядом");
        }

        // Без подключённого кошелька платный вариант проходит ДАРОМ. Движок
        // играется и сам по себе — в редакторе, в туре, в примерах из
        // документации, — а кошелёк живёт снаружи, в продуктовом слое. Упрись
        // платный вариант в его отсутствие, и всякая новелла с ценой становилась
        // бы непроходимой у всех, кто просто открыл движок.
        [UnityTest]
        public IEnumerator БезКошелькаПлатныйВариантПроходитДаром()
        {
            _stage.ChoiceSpend = null;

            _stage.Play(Развилка);
            yield return ДоВыбора("платный");

            Нажатие(Вариант("платный"))?.Invoke();
            yield return Ждём(() => ВИстории("платная ветка"));

            Assert.IsTrue(ВИстории("платная ветка"),
                "без кошелька платный вариант никуда не ведёт — новелла с ценой "
                + "непроходима у всех, кто открыл движок без продуктового слоя");
        }

        // ── (б) отказ кошелька ──────────────────────────────────────────────

        // ОТКАЗ — НЕ ТУПИК. Денег не хватило: это обычное состояние игрока, а не
        // сбой. Меню обязано остаться на экране (рядом почти всегда есть даровой
        // вариант, и именно его игрок выберет), а причина — прозвучать СЛОВОМ
        // АВТОРА: фраза была вписана в движок по-русски, и английская новелла
        // показывала русский текст. Сумму и валюту в неё подставляет движок —
        // автору незачем знать порядок слов и разряды.
        [UnityTest]
        public IEnumerator ОтказКошельком_МенюОстаётсяИГоворитСловомАвтора()
        {
            _stage.Theme.MenuLabels = new Dictionary<string, string>
            {
                ["choice_not_enough"] = "Не хватает {amount} {currency}, заходи позже",
            };
            _stage.ChoiceSpend = (валюта, сумма) => Task.FromResult(false);

            _stage.Play(Развилка);
            yield return ДоВыбора("платный");

            Нажатие(Вариант("платный"))?.Invoke();
            yield return Ждём(() => !string.IsNullOrEmpty(Подсказка()));

            var подсказка = Подсказка();
            Assert.IsFalse(string.IsNullOrEmpty(подсказка),
                "кошелёк отказал молча — игрок жмёт вариант, ничего не происходит, "
                + "и он считает это поломкой игры");
            StringAssert.Contains("Не хватает", подсказка,
                "движок сказал своими словами вместо авторских — в новелле на чужом языке "
                + "выскочит фраза не из неё");
            StringAssert.Contains("заходи позже", подсказка,
                "авторская фраза обрезана — до игрока дошла не она");
            StringAssert.Contains("25", подсказка,
                "в отказе нет суммы — игрок не знает, сколько ему не хватило");
            StringAssert.Contains("тесткоин", подсказка,
                "в отказе нет валюты — игрок не знает, чего ему не хватило");

            Assert.IsNotNull(Вариант("платный"),
                "после отказа кошелька меню выборов пропало — глава встала намертво");
            Assert.IsNotNull(Вариант("даром"),
                "даровой вариант пропал вместе с платным — игроку некуда деться");
            Assert.IsTrue(НаВыборе,
                "отказ кошелька увёл историю дальше — игрок получил ветку, за которую не заплатил");
            Assert.AreEqual(0, ВыбраннымиВИстории(),
                "неоплаченный выбор записан в историю как сделанный");
            Assert.IsFalse(ВИстории("платная ветка"),
                "отказ кошелька всё равно открыл платную ветку");
        }

        // ── (в) второе нажатие ──────────────────────────────────────────────

        // ВТОРОЕ НАЖАТИЕ НЕ ПРОХОДИТ, ПОКА ИДЁТ ПЕРВОЕ. Между нажатием и сменой
        // кадра карточка гаснет и стопка уезжает — доли секунды, за которые
        // палец успевает соскользнуть на соседний вариант, а нетерпеливый игрок
        // — нажать ещё раз. Пропусти второе нажатие внутрь — и история уйдёт по
        // ветке, которую игрок НЕ ВЫБИРАЛ: самый обидный вид потери, потому что
        // он видел, куда нажал.
        [UnityTest]
        public IEnumerator ВтороеНажатиеНеПеребиваетПервое()
        {
            _stage.Play(ДвойноеНажатие);
            yield return ДоВыбора("левый");

            var левый = Нажатие(Вариант("левый"));
            var правый = Нажатие(Вариант("правый"));
            Assert.IsNotNull(левый, "вариант не нажимается — выбор недоступен игроку");
            Assert.IsNotNull(правый, "вариант не нажимается — выбор недоступен игроку");

            левый();
            правый();   // тот же кадр: палец соскользнул на соседний вариант

            yield return Ждём(() => ВИстории("левая ветка") || ВИстории("правая ветка"));
            yield return Кадры(20);

            Assert.IsTrue(ВИстории("левая ветка"),
                "первое нажатие потерялось — игрок нажал и не попал никуда");
            Assert.IsFalse(ВИстории("правая ветка"),
                "второе нажатие перебило первое — история ушла по варианту, "
                + "которого игрок не выбирал");
            Assert.AreEqual(1, ВыбраннымиВИстории(),
                "выбор записан в историю дважды — откат вернёт игрока не туда");
        }

        // ── (г) сверка поколения ────────────────────────────────────────────

        // ОТВЕТ КОШЕЛЬКА ПРИНАДЛЕЖИТ СВОЕЙ СЦЕНЕ. Поход в кошелёк длится
        // секунды, и за это время глава успевает смениться: игрок вышел в меню,
        // сработал переход, пришёл перезапуск. Ответ возвращается в сцену,
        // которой уже нет, — и если его не сверить с поколением, он доигрывает
        // ЧУЖОЙ выбор: номер варианта тот же, а история другая, и игрок
        // оказывается в ветке, которую здесь не выбирал.
        [UnityTest]
        public IEnumerator ВыборПрошлойСцены_НеДоигрываетсяВНовой()
        {
            var касса = new TaskCompletionSource<bool>();
            _stage.ChoiceSpend = (валюта, сумма) => касса.Task;

            _stage.Play(Развилка);
            yield return ДоВыбора("платный");
            Нажатие(Вариант("платный"))?.Invoke();
            yield return Кадры(10);
            Assert.AreEqual(0, ВыбраннымиВИстории(), "стенд: покупка ещё идёт");

            // Глава сменилась, пока платёж висел.
            _stage.Play(ВтораяСцена);
            yield return ДоВыбора("чужой");
            Assert.IsTrue(НаВыборе, "стенд: новая сцена дошла до своего выбора");

            // И только теперь кошелёк ответил — ответом ПРОШЛОЙ сцены.
            касса.SetResult(true);
            yield return Кадры(40);

            Assert.IsFalse(ВИстории("чужая ветка"),
                "выбор прошлой сцены доиграл в новой — игрока унесло в ветку, "
                + "которую он здесь не выбирал");
            Assert.IsFalse(ВИстории("платная ветка"),
                "выбор прошлой сцены доиграл её же ветку поверх новой главы");
            Assert.AreEqual(0, ВыбраннымиВИстории(),
                "чужой выбор записался в историю новой сцены");
            Assert.IsTrue(НаВыборе,
                "новая сцена ушла с выбора сама собой — игрок не успел ничего нажать");
            Assert.IsNotNull(Вариант("чужой"),
                "меню новой сцены снесло ответом из прошлой");
        }

        // ── (д) двойное списание ────────────────────────────────────────────

        // ЗА ОДНУ ВЕТКУ ПЛАТЯТ ОДИН РАЗ. Поход за деньгами идёт через сеть и
        // длится столько, сколько длится связь, — а на экране в это время
        // ничего не меняется: карточка стоит, ветка не открывается, история не
        // движется. Игрок делает единственное, что тут можно сделать, — жмёт
        // ещё раз. Не пометь выбор занятым СРАЗУ, до ответа кошелька, и второе
        // нажатие заведёт ВТОРОЙ поход: списание пройдёт дважды за одну ветку.
        // Даровой выбор так себя и вёл (метку ставит CommitChoice), а платный —
        // самый дорогой для ошибки — шёл мимо этой защиты.
        [UnityTest]
        public IEnumerator ВтороеНажатиеВоВремяОплаты_НеЗаводитВторойПоходВКошелёк()
        {
            var касса = new TaskCompletionSource<bool>();
            int походов = 0;
            _stage.ChoiceSpend = (валюта, сумма) => { походов++; return касса.Task; };

            _stage.Play(Развилка);
            yield return ДоЖивогоВыбора("платный");

            var нажать = Нажатие(Вариант("платный"));
            Assert.IsNotNull(нажать, "вариант не нажимается — выбор недоступен игроку");

            нажать();
            yield return Ждём(() => походов > 0);
            Assert.AreEqual(1, походов, "первое нажатие не дошло до кошелька");

            // Кнопки гаснут в тот же миг: игрок обязан ВИДЕТЬ, что нажатие
            // принято и идёт работа, а не жать в тишину.
            Assert.IsNotNull(Вариант("платный"),
                "меню сняли на время платежа — игроку нечего нажать, если платёж сорвётся");
            Assert.IsFalse(Вариант("платный").enabledInHierarchy,
                "во время оплаты варианты остались живыми — игрок жмёт ещё раз, потому что "
                + "на экране ничего не изменилось");

            нажать();   // нетерпеливый игрок жмёт ещё раз
            нажать();   // и ещё
            yield return Кадры(20);

            Assert.AreEqual(1, походов,
                "нажатие во время оплаты завело второй поход в кошелёк — за одну ветку списали дважды");

            касса.SetResult(true);
            yield return Ждём(() => ВИстории("платная ветка"));

            Assert.AreEqual(1, походов,
                "к концу оплаты походов в кошелёк оказалось больше одного — игрок заплатил "
                + "за ветку несколько раз");
            Assert.AreEqual(1, ВыбраннымиВИстории(),
                "оплаченный выбор записан в историю не один раз");
        }

        // ОТКАЗ ВОЗВРАЩАЕТ ВЫБОР К ЖИЗНИ. Пометка «занят» ставится до ответа
        // кошелька — значит снимать её обязан КАЖДЫЙ исход, а не только
        // успешный. Забудь снять её на отказе, и получится худшее из
        // возможного: меню на экране, подсказка «не хватает» показана, а кнопки
        // мертвы навсегда. Игрок видит выход и не может им воспользоваться —
        // глава встала, и виновата в этом не нехватка денег, а движок.
        [UnityTest]
        public IEnumerator ПослеОтказаКошелька_ВыборСноваЖивойИСледующееНажатиеИдётВКошелёк()
        {
            int походов = 0;
            _stage.ChoiceSpend = (валюта, сумма) => { походов++; return Task.FromResult(false); };

            _stage.Play(Развилка);
            yield return ДоЖивогоВыбора("платный");

            var нажать = Нажатие(Вариант("платный"));
            нажать();
            yield return Ждём(() => походов > 0
                && Вариант("платный") != null && Вариант("платный").enabledInHierarchy);

            Assert.AreEqual(1, походов, "первое нажатие не дошло до кошелька");
            Assert.IsNotNull(Вариант("платный"), "после отказа меню пропало — глава встала намертво");
            Assert.IsTrue(Вариант("платный").enabledInHierarchy,
                "после отказа кошелька варианты остались погашенными — меню на экране, "
                + "а нажать нечего");

            // Игрок пополнил счёт и жмёт снова — это обязан быть НАСТОЯЩИЙ
            // поход в кошелёк, а не тихо съеденное нажатие.
            нажать();
            yield return Ждём(() => походов > 1);
            Assert.AreEqual(2, походов,
                "нажатие после отказа не дошло до кошелька — выбор остался помеченным занятым, "
                + "и купить ветку уже нельзя никогда");

            // И даровой сосед тоже жив: чаще всего игрок уходит именно им.
            yield return Ждём(() => Вариант("даром") != null && Вариант("даром").enabledInHierarchy);
            Нажатие(Вариант("даром"))?.Invoke();
            yield return Ждём(() => ВИстории("даровая ветка"));

            Assert.IsTrue(ВИстории("даровая ветка"),
                "после отказа кошелька даровой вариант не нажимается — игроку некуда деться");
        }

        // СМЕНА СЦЕНЫ ПОСРЕДИ ОПЛАТЫ НЕ ОСТАВЛЯЕТ ПОМЕТКУ ЗАНЯТОСТИ. Пометка
        // живёт на сцене, а не на платеже: ответ кошелька от прошлой главы
        // возвращается в мир, которого уже нет, — и уйти он обязан ЧИСТО, ничего
        // за собой не оставив. Забудь снять пометку в этой ветке — и выбор
        // новой главы окажется занятым чужим, давно отменённым платежом:
        // варианты на экране есть, нажатия не проходят, глава не продолжается.
        [UnityTest]
        public IEnumerator СменаСценыПосредиОплаты_НеОставляетВыборЗанятымНавсегда()
        {
            var касса = new TaskCompletionSource<bool>();
            _stage.ChoiceSpend = (валюта, сумма) => касса.Task;

            _stage.Play(Развилка);
            yield return ДоЖивогоВыбора("платный");
            Нажатие(Вариант("платный"))?.Invoke();
            yield return Кадры(5);

            // Глава сменилась, платёж ещё висит.
            _stage.Play(ВтораяСцена);
            yield return ДоЖивогоВыбора("свой");

            // И только теперь кошелёк ответил — ответом ПРОШЛОЙ сцены.
            касса.SetResult(true);
            yield return Кадры(20);

            Assert.IsNotNull(Вариант("свой"), "меню новой сцены снесло ответом из прошлой");
            Assert.IsTrue(Вариант("свой").enabledInHierarchy,
                "варианты новой сцены погашены — их погасил платёж прошлой главы, "
                + "и включить их обратно уже некому");

            Нажатие(Вариант("свой"))?.Invoke();
            yield return Ждём(() => ВИстории("своя ветка"));

            Assert.IsTrue(ВИстории("своя ветка"),
                "выбор в новой сцене не нажимается — оплата прошлой главы оставила его "
                + "занятым навсегда, и глава дальше не идёт");
            Assert.IsFalse(ВИстории("чужая ветка"),
                "нажатие в новой сцене увело по ветке платного варианта прошлой");
        }
    }
