    /// <summary>
    /// ПЛАТНЫЙ ВЫБОР — деньги и ветка в правильном порядке.
    ///
    /// <para>Вариант с настоящей ценой (<c>wallet_cost</c>) — единственное
    /// место движка, где решение игрока стоит ДЕНЕГ, а между нажатием и веткой
    /// лежит поход на сервер: он длится, срывается и приходит с опозданием. Всё
    /// остальное здесь мгновенно, и потому ни одна из четырёх ловушек этого
    /// перехода не была закрыта проверкой.</para>
    ///
    /// <para>Ловушки такие. Уведи историю раньше списания — сорванная покупка
    /// оставит ветку пройденной, а кошелёк полным (или наоборот, если списание
    /// прошло, а ветка нет). Сними меню на отказе — игрок останется на экране
    /// без единой кнопки, и глава встанет намертво. Пропусти второе нажатие —
    /// история уйдёт по варианту, которого игрок не выбирал. Не сверь
    /// поколение — ответ кошелька от ПРОШЛОЙ сцены доиграется в новой.</para>
    ///
    /// <para>Из EditMode это недостижимо: <c>SpendThenChooseAsync</c> живёт на
    /// самой сцене, ждёт настоящих кадров и опирается на планировщик панели.
    /// Поэтому стенд здесь настоящий — панель, сцена, живые кнопки выбора.</para>
    /// </summary>
    public class ChoicePriceTests
    {
        private GameObject _go;
        private PanelSettings _panel;
        private VnStage _stage;

        // Развилка с одним ПЛАТНЫМ вариантом и одним даровым. Ветки разведены
        // так, что по истории видно, куда ушёл игрок, — «даровая» не может
        // случайно перетечь в «платную».
        private const string Развилка = @"{
          ""scene"": ""цена"",
          ""script"": [
            { ""op"": ""say"", ""text"": ""развилка"" },
            { ""op"": ""choice"", ""options"": [
              { ""text"": ""платный"", ""goto"": ""P"",
                ""wallet_cost"": { ""currency"": ""тесткоин"", ""amount"": 25 } },
              { ""text"": ""даром"", ""goto"": ""F"" } ] },
            { ""op"": ""label"", ""id"": ""F"" },
            { ""op"": ""say"", ""text"": ""даровая ветка"" },
            { ""op"": ""goto"", ""label"": ""КОНЕЦ"" },
            { ""op"": ""label"", ""id"": ""P"" },
            { ""op"": ""say"", ""text"": ""платная ветка"" },
            { ""op"": ""label"", ""id"": ""КОНЕЦ"" }
          ]
        }";

        // Вторая сцена — тоже с выбором и тоже с платным вариантом под тем же
        // номером. Именно так и ловится сверка поколения: не будь её, ответ
        // кошелька от прошлой сцены попал бы в ЭТОТ выбор как родной.
        private const string ВтораяСцена = @"{
          ""scene"": ""вторая"",
          ""script"": [
            { ""op"": ""say"", ""text"": ""вторая сцена"" },
            { ""op"": ""choice"", ""options"": [
              { ""text"": ""чужой"", ""goto"": ""X"",
                ""wallet_cost"": { ""currency"": ""тесткоин"", ""amount"": 25 } },
