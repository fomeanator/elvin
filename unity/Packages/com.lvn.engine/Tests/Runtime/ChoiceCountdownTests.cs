using System;
using System.Collections;
using System.Reflection;
using System.Threading.Tasks;
using Lvn;
using Lvn.UI;
using NUnit.Framework;
using UnityEngine;
using UnityEngine.TestTools;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// СРОК ВЫБОРА — что его останавливает.
    ///
    /// <para>Выбор со сроком (<c>timeout</c>) — единственное место движка, где
    /// история идёт ПРОТИВ игрока: не успел — ветку берёт время. Ради этого он
    /// и заводится, и потому у него есть обратная сторона: срок обязан гонять
    /// игрока, а не обстоятельства. Всё, что отняло у игрока возможность
    /// нажать, обязано остановить и отсчёт — иначе движок отбирает ветку за то,
    /// в чём игрок не виноват.</para>
    ///
    /// <para>Причин ровно три, и все три — про одно: экран занят не выбором.
    /// Открытое меню (настройки, история, лист гардероба) держит ввод; просмотр
    /// арта и катсцена убирают интерфейс целиком; оплата платного варианта
    /// уходит в сеть и возвращается когда вернётся. Первые две были описаны
    /// словами в коде, но не закреплены ничем; третья стоила самого дорогого
    /// исхода — срок истекал во время платежа, время уводило игрока по своей
    /// ветке, а пришедший следом успешный платёж уходил в никуда: деньги
    /// списаны, ветка чужая.</para>
    ///
    /// <para>Из EditMode этого не видно вовсе: отсчёт живёт на расписании
    /// панели, тикает настоящими кадрами и стартует не раньше, чем кнопки стали
    /// нажимаемы. Поэтому стенд здесь настоящий — панель, сцена, живые кнопки,
    /// живые секунды.</para>
    /// </summary>
    public class ChoiceCountdownTests
    {
        private GameObject _go;
        private PanelSettings _panel;
        private VnStage _stage;

        /// <summary>Развилка со СРОКОМ: платный вариант, даровой сосед и третья
        /// ветка, которую берёт время. Ветки разведены так, что по истории
        /// видно, кто увёл игрока — он сам, кошелёк или часы.</summary>
        private static string Развилка(string срок) => @"{
          ""scene"": ""срок"",
          ""script"": [
            { ""op"": ""say"", ""text"": ""решай быстрее"" },
            { ""op"": ""choice"", ""timeout"": @СРОК@, ""timeout_goto"": ""ПОЗДНО"", ""options"": [
              { ""text"": ""платный"", ""goto"": ""P"",
                ""wallet_cost"": { ""currency"": ""тесткоин"", ""amount"": 25 } },
              { ""text"": ""даром"", ""goto"": ""F"" } ] },
            { ""op"": ""label"", ""id"": ""F"" },
            { ""op"": ""say"", ""text"": ""даровая ветка"" },
            { ""op"": ""goto"", ""label"": ""КОНЕЦ"" },
            { ""op"": ""label"", ""id"": ""P"" },
            { ""op"": ""say"", ""text"": ""платная ветка"" },
            { ""op"": ""goto"", ""label"": ""КОНЕЦ"" },
            { ""op"": ""label"", ""id"": ""ПОЗДНО"" },
            { ""op"": ""say"", ""text"": ""время вышло"" },
            { ""op"": ""label"", ""id"": ""КОНЕЦ"" }
          ]
        }".Replace("@СРОК@", срок);

        [UnitySetUp]
        public IEnumerator Стенд()
        {
            _stage = TestStage.Panel("choice-countdown-stage", out _go, out _panel);
            yield return null;
        }

        [TearDown]
        public void Уборка()
        {
            // Причины скрытия интерфейса держит ОБЩИЙ Режиссёр, один на весь
            // процесс: забытая причина утекла бы в следующий тест и погасила
            // ему интерфейс без всякой связи с тем, что он проверяет.
            LvnScreenDirector.Current.ShowChromeAll();
            if (_go != null) UnityEngine.Object.Destroy(_go);
            if (_panel != null) UnityEngine.Object.Destroy(_panel);
        }

        // ── стенд ───────────────────────────────────────────────────────────

        private VisualElement Корень => _go != null
            ? _go.GetComponent<UIDocument>()?.rootVisualElement : null;

        /// <summary>Кнопка варианта — по НАДПИСИ на ней, как её видит игрок.</summary>
        private Button Вариант(string надпись)
        {
            var меню = Корень?.Q<ChoiceList>();
            if (меню == null) return null;
            foreach (var кнопка in меню.Query<Button>().ToList())
                foreach (var подпись in кнопка.Query<Label>().ToList())
                    if (подпись.text == надпись) return кнопка;
            return null;
        }

        /// <summary>Что произойдёт от нажатия по кнопке: живого тапа нет —
        /// событие разносит панель по настоящим координатам. Спрашиваем саму
        /// кнопку, к чему она приведёт.</summary>
        // Приём живёт в доме сцены: PlayMode — отдельная сборка, и копия
        // редакторного дома здесь была бы вторым правилом на один тап.
        private static Action Нажатие(Button кнопка) => TestStage.Press(кнопка);

        private bool НаВыборе
        {
            get
            {
                var p = typeof(VnStage).GetField("_player",
                    BindingFlags.Instance | BindingFlags.NonPublic)?.GetValue(_stage) as LvnPlayer;
                return p != null && p.AtChoice;
            }
        }

        private bool ВИстории(string текст)
        {
            foreach (var строка in _stage.Backlog)
                if (строка.text == текст) return true;
            return false;
        }

        private static IEnumerator Ждём(Func<bool> готово, float секунд)
        {
            float срок = Time.realtimeSinceStartup + секунд;
            while (Time.realtimeSinceStartup < срок && !готово()) yield return null;
        }

        /// <summary>Настоящие секунды: отсчёт выбора тикает расписанием панели,
        /// и подменить ему часы нельзя — пауза добавляет к сроку по десятой
        /// доле на каждый такт, то есть ровно столько, сколько прошло наяву.</summary>
        private static IEnumerator Пауза(float секунд)
        {
            float до = Time.realtimeSinceStartup + секунд;
            while (Time.realtimeSinceStartup < до) yield return null;
        }

        /// <summary>Дождаться момента, когда вариант ПО-НАСТОЯЩЕМУ доступен
        /// игроку. Он же и момент старта отсчёта: часы выбора заводятся не
        /// раньше, чем кнопки стали нажимаемы.</summary>
        private IEnumerator ДоЖивогоВыбора(string надпись)
        {
            yield return Ждём(() => Вариант(надпись) != null && Вариант(надпись).enabledInHierarchy, 8f);
            var кнопка = Вариант(надпись);
            Assert.IsNotNull(кнопка,
                "вариант «" + надпись + "» так и не вышел на экран — нажимать игроку не на что");
            Assert.IsTrue(кнопка.enabledInHierarchy,
                "вариант «" + надпись + "» на экране, но погашен — игрок его видит и не может нажать");
        }

        // ── оплата останавливает срок ───────────────────────────────────────

        // ОПЛАТА — ЭТО ПАУЗА. Поход за деньгами идёт через сеть: на домашнем
        // вайфае он занимает миг, в метро — секунды. Пока он идёт, игрок уже
        // всё решил и нажал, а нажать что-то ещё не может — кнопки погашены.
        // Срок при этом продолжал тикать, и на медленной связи выходило худшее
        // из всего, что умеет этот экран: время уводило игрока по СВОЕЙ ветке,
        // а пришедший следом успешный платёж уходил в никуда. Деньги списаны,
        // ветка чужая, и связать одно с другим игрок не может ничем.
        [UnityTest]
        public IEnumerator ПокаИдётОплата_СрокНеИстекаетИВеткуБерётПлатёж()
        {
            var касса = new TaskCompletionSource<bool>();
            _stage.ChoiceSpend = (валюта, сумма) => касса.Task;

            _stage.Play(Развилка("1"));           // срок — одна секунда
            yield return ДоЖивогоВыбора("платный");

            Нажатие(Вариант("платный"))?.Invoke();
            yield return Пауза(2f);               // кошелёк отвечает вдвое дольше срока

            Assert.IsFalse(ВИстории("время вышло"),
                "срок истёк, пока шла оплата — время увело игрока по своей ветке, "
                + "и заплатил он ни за что");
            Assert.IsTrue(НаВыборе,
                "выбор ушёл сам собой во время платежа — ветку взял не игрок и не кошелёк");

            касса.SetResult(true);
            yield return Ждём(() => ВИстории("платная ветка"), 6f);

            Assert.IsTrue(ВИстории("платная ветка"),
                "оплата прошла, а ветка не открылась — деньги списаны, история пошла мимо");
            Assert.IsFalse(ВИстории("время вышло"),
                "оплаченный выбор всё равно достался времени");
        }

        // ПОСЛЕ ОТКАЗА СРОК ПРОДОЛЖАЕТСЯ С ТОГО МЕСТА, ГДЕ ОСТАНОВИЛСЯ. Пауза —
        // это пауза, а не отмена и не перезапуск. Сгори остаток разом — и игрок,
        // которому не хватило денег, потеряет ветку в ту же секунду, не успев
        // даже прочитать «не хватает». Начнись срок заново — и платный вариант
        // станет способом бесконечно продлевать себе время на раздумье: жми,
        // получай отказ, думай сначала.
        [UnityTest]
        public IEnumerator ПослеОтказаКошелька_СрокПродолжаетсяСТогоМестаГдеОстановился()
        {
            var касса = new TaskCompletionSource<bool>();
            _stage.ChoiceSpend = (валюта, сумма) => касса.Task;

            _stage.Play(Развилка("4"));
            yield return ДоЖивогоВыбора("платный");

            yield return Пауза(2f);               // две секунды из четырёх игрок уже продумал
            Assert.IsTrue(НаВыборе, "стенд: до нажатия срок ещё не истёк");

            Нажатие(Вариант("платный"))?.Invoke();
            yield return Пауза(1.5f);             // кошелёк думает — срок обязан стоять

            Assert.IsTrue(НаВыборе,
                "срок истёк во время оплаты — остаток в две секунды сгорел на походе в кошелёк");

            касса.SetResult(false);               // денег не хватило
            yield return Ждём(() => Вариант("платный") != null
                                    && Вариант("платный").enabledInHierarchy, 3f);

            Assert.IsTrue(НаВыборе, "отказ кошелька увёл историю с выбора");

            // Остаток был около двух секунд — значит и после отказа его около
            // двух. Ни мгновенного срабатывания, ни полного круга заново.
            yield return Ждём(() => ВИстории("время вышло"), 0.8f);
            Assert.IsFalse(ВИстории("время вышло"),
                "после отказа кошелька срок сгорел разом — игрок не успел даже прочитать, "
                + "чего ему не хватило, а ветку уже забрало время");

            yield return Ждём(() => ВИстории("время вышло"), 2.2f);
            Assert.IsTrue(ВИстории("время вышло"),
                "после отказа срок пошёл заново — за три секунды остаток в две так и не "
                + "истёк; платный вариант превратился в кнопку «продлить раздумье»: "
                + "жми, получай отказ, думай сначала");
        }

        // ── меню и спрятанный интерфейс ─────────────────────────────────────

        // ОТКРЫТОЕ МЕНЮ ОСТАНАВЛИВАЕТ СРОК. Игрок открывает настройки, историю
        // реплик или лист гардероба прямо на выборе — чаще всего именно затем,
        // чтобы РАЗОБРАТЬСЯ в этом выборе: перечитать вопрос, разглядеть
        // варианты покрупнее, вспомнить, кто такая эта героиня. Экран в этот миг
        // занят не выбором, кнопок под пальцем нет, и продолжать отсчёт значит
        // отбирать ветку за то, в чём игрок не виноват. Возвращается он в
        // историю, которая ушла без него, — и это худший вид потери: он ничего
        // не выбирал.
        [UnityTest]
        public IEnumerator ОткрытоеМеню_ОстанавливаетСрокИНеОтдаётВеткуВремени()
        {
            _stage.Play(Развилка("4"));
            yield return ДоЖивогоВыбора("даром");

            yield return Пауза(2f);               // две секунды из четырёх продуманы
            Assert.IsTrue(НаВыборе, "стенд: до меню срок ещё не истёк");

            _stage.InputBlocked = true;           // игрок открыл меню поверх выбора
            yield return Пауза(2.5f);             // и провёл в нём больше, чем остаток срока

            Assert.IsFalse(ВИстории("время вышло"),
                "срок истёк при открытом меню — игрок вернулся в историю, которая ушла без него");
            Assert.IsTrue(НаВыборе,
                "выбор ушёл, пока игрок был в меню, — ветку взяло время, а не он");

            _stage.InputBlocked = false;          // меню закрыли — часы идут дальше

            yield return Ждём(() => ВИстории("время вышло"), 0.8f);
            Assert.IsFalse(ВИстории("время вышло"),
                "закрытие меню сожгло весь остаток разом — игрок вышел из настроек прямо "
                + "в чужую ветку");

            yield return Ждём(() => ВИстории("время вышло"), 2.4f);
            Assert.IsTrue(ВИстории("время вышло"),
                "после меню срок пошёл заново — за три секунды остаток в две так и не истёк; "
                + "любой выбор со сроком становится вечным, стоит открыть настройки");
        }

        // СПРЯТАННЫЙ ИНТЕРФЕЙС — ТОЖЕ ПАУЗА. Долгое нажатие убирает всю
        // разметку, чтобы игрок разглядел кадр; катсцена делает то же самое по
        // воле автора. Вариантов на экране в этот момент НЕТ ВООБЩЕ — их
        // спрятали вместе с диалогом, — и отдать ветку времени, пока нажимать
        // физически нечего, значит наказать игрока за то, что он посмотрел на
        // рисунок, ради которого новеллу и открыли.
        [UnityTest]
        public IEnumerator СпрятанныйИнтерфейс_ТожеОстанавливаетСрок()
        {
            _stage.Play(Развилка("1"));
            yield return ДоЖивогоВыбора("даром");

            _stage.HideChrome("тест-просмотр-арта");
            yield return Пауза(2f);               // вдвое дольше срока

            Assert.IsFalse(ВИстории("время вышло"),
                "срок истёк, пока интерфейс был спрятан, — ветку забрало время у игрока, "
                + "которому нечего было нажать");
            Assert.IsTrue(НаВыборе,
                "выбор ушёл при спрятанном интерфейсе — игрок вернулся к кадру, "
                + "а история уже за поворотом");

            _stage.ShowChrome("тест-просмотр-арта");
            yield return Ждём(() => ВИстории("время вышло"), 3f);

            Assert.IsTrue(ВИстории("время вышло"),
                "интерфейс вернули, а отсчёт не продолжился — выбор со сроком завис навсегда, "
                + "и глава дальше не идёт");
        }
    }
}
