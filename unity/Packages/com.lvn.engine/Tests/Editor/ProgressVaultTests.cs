using System.Collections.Generic;
using Lvn.Content;
using Lvn.UI;
using Lvn.UI.Screens;
using Newtonsoft.Json.Linq;
using NUnit.Framework;
using UnityEngine;

namespace Lvn.Tests
{
    /// <summary>
    /// ОБЛАЧНЫЙ СВЁРТОК ПРОГРЕССА — единственная вещь в приложении, ошибка в
    /// которой стоит игроку ПРОХОЖДЕНИЯ, а не кадра.
    ///
    /// <para>Свёрток снимают в трёх домах сразу (записная книжка устройства,
    /// файл, серверный стор) и раскладывают обратно ровно один раз — на первом
    /// подъёме после переустановки или потери настроек. Второй попытки не
    /// будет: если новелла не попала в свёрток, её прохождение просто
    /// исчезает, и игрок узнаёт об этом, увидев вместо «Продолжить» пустую
    /// карточку.</para>
    ///
    /// <para>Здесь закреплены четыре правила, каждое из которых уже стоило
    /// живой потери: КОГО класть в свёрток (дочитанная — да, непочатая — нет,
    /// и обе половины считает дом, а не звонящий), КАК искать главу при
    /// переимпорте (id, потом номер — тем же правилом, что и локальная метка),
    /// ЧТО такое «чистое устройство» и почему восстановление обязано быть
    /// АДДИТИВНЫМ: свёрток бывает старше устройства, и молча опустить живой
    /// прогресс до облачного — та же потеря, только с другой стороны.</para>
    ///
    /// <para>Ноль проходит через все четыре: ноль — законный номер главы
    /// (вводная новелла начинается с него), а «докуда дошёл» и «начинали ли
    /// вообще» жили одним числом. Каждое правило проверяется и на обычной
    /// новелле, и на новелле с нулевой главой.</para>
    /// </summary>
    public sealed class ProgressVaultTests
    {
        private const string Id = "t_vault_novel";
        private const string Ноль = "t_vault_pilot";

        private string _имяБыло;
        private string _сейфБыл;   // содержимое файлового дома до теста — или null

        /// <summary>Тот же путь, что и у дома: файловый сейф игрока рядом с
        /// остальными его данными.</summary>
        private static string ПутьСейфа =>
            System.IO.Path.Combine(Application.persistentDataPath, "lvn_progress.json");

        private static LvnTitle Title(string id, params (string id, int number)[] chapters)
        {
            var list = new List<LvnChapter>();
            foreach (var (cid, number) in chapters) list.Add(new LvnChapter { id = cid, number = number });
            return new LvnTitle { id = id, seasons = new List<LvnSeason> { new LvnSeason { chapters = list } } };
        }

        /// <summary>Обычная новелла: главы нумерованы с единицы.</summary>
        private static LvnTitle Три() => Title(Id, ("c1", 1), ("c2", 2), ("c3", 3));

        /// <summary>Вводная новелла: ОДНА глава, и её номер — ноль. Так
        /// нумерует главы импортёр, и так устроена вся воронка приложения.</summary>
        private static LvnTitle Пилот() => Title(Ноль, ("pilot", 0));

        private static LvnManifest Манифест(params LvnTitle[] titles)
            => new LvnManifest { titles = new List<LvnTitle>(titles) };

        private static LvnChapter Гл(LvnTitle t, int i) => t.ChaptersOf()[i];

        /// <summary>Запись одной новеллы в свёртке — или null, если её туда не
        /// положили.</summary>
        private static JObject Запись(JObject свёрток, string titleId)
            => свёрток?["titles"]?[titleId] as JObject;

        [SetUp]
        public void Приготовить()
        {
            _имяБыло = LvnPrefs.PlayerName;
            // Сейф на диске принадлежит стенду, а не тесту: берём его на
            // сохранение и кладём обратно, чем бы тест ни кончился.
            _сейфБыл = System.IO.File.Exists(ПутьСейфа) ? System.IO.File.ReadAllText(ПутьСейфа) : null;
            Стереть();
        }

        [TearDown]
        public void Убрать()
        {
            Стереть();
            LvnPrefs.PlayerName = _имяБыло ?? "";
            if (_сейфБыл != null) System.IO.File.WriteAllText(ПутьСейфа, _сейфБыл);
            else if (System.IO.File.Exists(ПутьСейфа)) System.IO.File.Delete(ПутьСейфа);
        }

        private static void Стереть()
        {
            LvnProgress.ResetTitle(Id);
            LvnProgress.ResetTitle(Ноль);
            LvnGalleryStore.Clear(Id);
            LvnGalleryStore.Clear(Ноль);
            LvnPrefs.PlayerName = "";
            ProgressVault.Forget();
            // Хвосты прерванных записей — не улика этого теста: убираем их
            // заранее, иначе чужой упавший прогон обвинял бы наш.
            var папка = System.IO.Path.GetDirectoryName(ПутьСейфа);
            if (System.IO.Directory.Exists(папка))
                foreach (var хвост in System.IO.Directory.GetFiles(папка, "lvn_progress.json.tmp-*"))
                    try { System.IO.File.Delete(хвост); } catch { /* чужой файл — не наша забота */ }
        }

        // ── кого класть в свёрток ───────────────────────────────────────────

        // Дочитанная новелла выглядит В ТОЧНОСТИ как непочатая: точки
        // продолжения нет — её снял финал. Отличает их только потолок. Не
        // положи такую в свёрток — и после переустановки игрок получает свою
        // пройденную новеллу нетронутой: полоса пустая, галерея заперта,
        // концовки не отмечены. Это и есть «потерянное прохождение».
        [Test]
        public void ДочитаннаяНовеллаПопадаетВСвёрток()
        {
            var t = Три();
            LvnProgress.StartChapter(t, Гл(t, 2));
            LvnProgress.FinishChapter(t, null);   // финал: точку снял, потолок оставил

            Assert.IsNull(LvnProgress.Current(t), "дочитанная новелла не держит точки — иначе проверка ни о чём");

            var свёрток = ProgressVault.Collect(Манифест(t));
            var запись = Запись(свёрток, Id);

            Assert.IsNotNull(запись, "дочитанная новелла выпала из свёртка — прохождение потеряно");
            Assert.AreEqual(3, (int)запись["reached"], "потолок в свёртке не тот, до которого дошёл игрок");
            Assert.IsNull((string)запись["cur"], "у дочитанной новеллы точки продолжения нет");
        }

        // ТА ЖЕ новелла, но её единственная глава пронумерована нулём — так
        // импортёр нумерует вводную, с которой начинается КАЖДОЕ первое
        // знакомство с приложением. Проверка «потолок больше нуля» на ней лжёт,
        // и лгала: новелла выпадала из свёртка, переустановка возвращала её
        // непочатой, и воронка игралась заново.
        [Test]
        public void ДочитаннаяНовеллаСНулевойГлавойТожеПопадаетВСвёрток()
        {
            var t = Пилот();
            LvnProgress.StartChapter(t, Гл(t, 0));
            LvnProgress.FinishChapter(t, null);

            Assert.AreEqual(0, LvnProgress.Reached(t), "потолок нулевой главы — ноль, в этом вся ловушка");
            Assert.IsTrue(LvnProgress.Finished(t), "новелла из одной нулевой главы дочитана");

            var запись = Запись(ProgressVault.Collect(Манифест(t)), Ноль);

            Assert.IsNotNull(запись,
                "новелла с нулевой главой выпала из свёртка — переустановка вернёт её непочатой");
            Assert.AreEqual(0, (int)запись["reached"], "потолок нулевой главы обязан доехать нулём, а не пропасть");
        }

        // Обратная половина того же правила: непочатую класть нельзя. Положи —
        // и свёрток начнёт объявлять початыми ВСЕ новеллы каталога: карточки
        // покажут «Продолжить» там, где игрок не открывал ни строчки, а вводная
        // перестанет включаться.
        [Test]
        public void НепочатаяНовеллаВСвёртокНеПопадает()
        {
            var свёрток = ProgressVault.Collect(Манифест(Три(), Пилот()));

            Assert.IsNull(Запись(свёрток, Id), "непочатая новелла попала в свёрток");
            Assert.IsNull(Запись(свёрток, Ноль),
                "непочатая новелла с нулевой главой попала в свёрток — «дошёл до 0» не то же, что «начинал»");
            Assert.AreEqual(0, ((JObject)свёрток["titles"]).Count, "в свёртке оказалось лишнее");
        }

        // Начатая, но не дочитанная — самый частый случай: игрок в середине.
        // В свёртке обязаны быть ОБА ключа метки: id и номер. Первый — точный,
        // второй — тот, которым метку выручают после переименования глав.
        [Test]
        public void НачатаяНовеллаВезётИIdИНомерГлавы()
        {
            var t = Три();
            LvnProgress.StartChapter(t, Гл(t, 1));

            var запись = Запись(ProgressVault.Collect(Манифест(t)), Id);

            Assert.AreEqual("c2", (string)запись["cur"], "свёрток не запомнил, где остановился игрок");
            Assert.AreEqual(2, (int)запись["num"],
                "свёрток не везёт номер главы — после переимпорта метку будет нечем выручить");
            Assert.AreEqual(2, (int)запись["reached"]);
        }

        // ── чистое устройство ───────────────────────────────────────────────

        // Свёрток раскладывают ТОЛЬКО на чистое устройство. Ошибись здесь в
        // сторону «чисто» — и облачная копия ляжет поверх живой игры. Ошибись
        // в сторону «не чисто» — и переустановка не восстановит ничего, потому
        // что дом решит, будто прогресс на месте.
        [Test]
        public void ЧистоеУстройствоУзнаётсяПравильно()
        {
            var м = Манифест(Три(), Пилот());
            Assert.IsTrue(ProgressVault.IsVirgin(м), "пустое устройство не признано чистым — восстановления не будет");

            var t = Три();
            LvnProgress.StartChapter(t, Гл(t, 0));
            Assert.IsFalse(ProgressVault.IsVirgin(м), "устройство с живой игрой признано чистым — свёрток ляжет поверх");
        }

        // Тот же вопрос на новелле с нулевой главой — и это ровно то место, где
        // «потолок больше нуля» отвечало ложью: игрок прошёл вводную, а
        // устройство считалось чистым. Свёрток (в том числе ЧУЖОЙ, приехавший
        // с сервера по тому же id) имел право лечь поверх его прогресса.
        [Test]
        public void ЧистоеУстройствоУзнаётсяИНаНовеллеСНулевойГлавой()
        {
            var t = Пилот();
            var м = Манифест(t);

            LvnProgress.StartChapter(t, Гл(t, 0));
            Assert.IsFalse(ProgressVault.IsVirgin(м),
                "игрок стоит в нулевой главе, а устройство считается чистым");

            LvnProgress.FinishChapter(t, null);   // дочитал: точки нет, потолок ноль
            Assert.IsFalse(ProgressVault.IsVirgin(м),
                "вводная пройдена, а устройство считается чистым — свёрток ляжет поверх пройденного");
        }

        // Имя игрока — тоже прогресс: его спрашивают один раз за всю жизнь
        // приложения. Устройство, где имя названо, чистым не бывает.
        [Test]
        public void УстройствоСИменемИгрокаНеЧистое()
        {
            LvnPrefs.PlayerName = "Виктория";
            Assert.IsFalse(ProgressVault.IsVirgin(Манифест(Три())),
                "имя игрока названо, а устройство считается чистым");
        }

        // ── раскладывание обратно ───────────────────────────────────────────

        // Обычное восстановление: метка ищется по id и садится ровно туда, где
        // игрок был. Промахнись — и он продолжит чужую главу.
        [Test]
        public void ApplyВосстанавливаетМеткуПоId()
        {
            var t = Три();
            LvnProgress.StartChapter(t, Гл(t, 1));
            var свёрток = ProgressVault.Collect(Манифест(t));

            LvnProgress.ResetTitle(Id);   // «переустановили»
            ProgressVault.Apply(свёрток, Манифест(Три()));

            Assert.AreEqual("c2", LvnProgress.Current(Три())?.id,
                "после восстановления игрок оказался не в своей главе");
            Assert.AreEqual(2, LvnProgress.Reached(Три()), "потолок не восстановился — список глав снова заперт");
        }

        // ПЕРЕИМПОРТ ПЕРЕИМЕНОВАЛ ГЛАВЫ: id из свёртка в живом манифесте больше
        // нет. Единственное, что осталось общего, — номер, и метку выручает он.
        // Без этого правила любая пересборка контента отбирала бы у всех игроков
        // разом всё прохождение целиком.
        [Test]
        public void ApplyВосстанавливаетМеткуПоНомеруКогдаГлавыПереименованы()
        {
            var было = Три();
            LvnProgress.StartChapter(было, Гл(было, 1));
            var свёрток = ProgressVault.Collect(Манифест(было));

            LvnProgress.ResetTitle(Id);
            // Тот же порядок глав, другие id — ровно то, что делает переимпорт.
            var стало = Title(Id, ("ch-alpha", 1), ("ch-beta", 2), ("ch-gamma", 3));
            ProgressVault.Apply(свёрток, Манифест(стало));

            Assert.AreEqual("ch-beta", LvnProgress.Current(стало)?.id,
                "переименование глав отобрало у игрока место, где он остановился");
        }

        // Правило поиска обязано быть ТЕМ ЖЕ, что у локальной метки: сначала id,
        // и только потом номер. Разойдись порядок — и на новелле, где id
        // сменились НЕ У ВСЕХ глав, свёрток и книжка устройства вернули бы
        // разные главы: игрок продолжает то одну, то другую.
        [Test]
        public void ПоискГлавыИдётСначалаПоIdИТолькоПотомПоНомеру()
        {
            var было = Три();
            LvnProgress.StartChapter(было, Гл(было, 1));   // c2, номер 2
            var свёрток = ProgressVault.Collect(Манифест(было));

            LvnProgress.ResetTitle(Id);
            // Ловушка: «c2» на месте, но НОМЕР у неё теперь другой, а номер 2
            // достался соседке. Пойди поиск от номера — игрок уехал бы в «c9».
            var стало = Title(Id, ("c1", 1), ("c9", 2), ("c2", 7));
            ProgressVault.Apply(свёрток, Манифест(стало));

            Assert.AreEqual("c2", LvnProgress.Current(стало)?.id,
                "поиск пошёл от номера раньше, чем от id — игрок продолжит чужую главу");
        }

        // ГЛАВНОЕ ПРАВИЛО ВОССТАНОВЛЕНИЯ: оно аддитивно. Свёрток лежит на
        // сервере и вполне может быть старше устройства (играли офлайн, синк не
        // дошёл). Опусти он потолок до своего — и список глав закроется у
        // игрока прямо в руках: главы, которые он уже прошёл, снова под замком.
        [Test]
        public void ВосстановлениеНеОпускаетТоЧтоНаУстройствеНовее()
        {
            var t = Три();
            LvnProgress.StartChapter(t, Гл(t, 0));                 // старый свёрток: c1
            var старый = ProgressVault.Collect(Манифест(t));

            LvnProgress.StartChapter(t, Гл(t, 2));                 // а на устройстве игрок ушёл дальше
            ProgressVault.Apply(старый, Манифест(Три()));

            Assert.AreEqual(3, LvnProgress.Reached(Три()),
                "старый свёрток опустил потолок — пройденные главы снова заперты");
            Assert.AreEqual("c3", LvnProgress.Current(Три())?.id,
                "старый свёрток отбросил игрока назад в уже пройденную главу");
        }

        // Обратная сторона той же аддитивности: если на устройстве точки НЕТ, а
        // в свёртке она есть — точка садится. Иначе восстановление возвращало бы
        // потолок, но не место, и игрок открывал бы новеллу с начала при
        // разблокированном списке глав.
        [Test]
        public void ТочкаСадитсяТолькоНаПустоеМесто()
        {
            var t = Три();
            LvnProgress.StartChapter(t, Гл(t, 1));
            var свёрток = ProgressVault.Collect(Манифест(t));

            LvnProgress.ResetTitle(Id);
            ProgressVault.Apply(свёрток, Манифест(Три()));
            Assert.AreEqual("c2", LvnProgress.Current(Три())?.id, "точка не села на пустое место");
        }

        // Дочитанная новелла с нулевой главой доезжает ДО КОНЦА пути: её кладут
        // в свёрток (см. выше) — и достают из него так, что она остаётся
        // пройденной. Ровно это игрок и увидит на карточке: полную полосу и
        // открытую галерею вместо «начать».
        [Test]
        public void ПройденнаяНовеллаСНулевойГлавойОстаётсяПройденнойПослеВосстановления()
        {
            var t = Пилот();
            LvnProgress.StartChapter(t, Гл(t, 0));
            LvnProgress.FinishChapter(t, null);
            var свёрток = ProgressVault.Collect(Манифест(t));

            LvnProgress.ResetTitle(Ноль);   // «переустановили»
            Assert.IsFalse(LvnProgress.Finished(Пилот()), "исходное состояние теста должно быть чистым");

            ProgressVault.Apply(свёрток, Манифест(Пилот()));

            Assert.IsTrue(LvnProgress.HasReached(Пилот()),
                "вводная после восстановления снова считается непочатой — воронка пойдёт по второму кругу");
            Assert.IsTrue(LvnProgress.Finished(Пилот()),
                "пройденная вводная перестала быть пройденной — игрок увидит её нетронутой");
        }

        // ── галерея и имя ───────────────────────────────────────────────────

        // Галерея ДОЛИВАЕТСЯ. Кадр — награда за прохождение, и он вручается один
        // раз: замени свёрток галерею собой, и всё, что игрок открыл после
        // последнего синка, исчезнет без следа и без второй попытки.
        [Test]
        public void ГалереяИзСвёрткаДоливаетсяАНеЗаменяет()
        {
            var t = Три();
            LvnProgress.StartChapter(t, Гл(t, 0));
            LvnGalleryStore.Unlock(Id, "cg_из_облака");
            var свёрток = ProgressVault.Collect(Манифест(t));

            LvnGalleryStore.Clear(Id);
            LvnGalleryStore.Unlock(Id, "cg_на_устройстве");   // открыт уже после синка

            ProgressVault.Apply(свёрток, Манифест(Три()));

            var открыто = LvnGalleryStore.Unlocked(Id);
            Assert.IsTrue(открыто.Contains("cg_из_облака"), "кадр из свёртка не доехал до галереи");
            Assert.IsTrue(открыто.Contains("cg_на_устройстве"),
                "свёрток стёр кадр, открытый после синка — награда исчезла без второй попытки");
        }

        // Имя спрашивают ОДИН раз за жизнь приложения, и живое всегда сильнее
        // облачного: перезапиши свёрток имя — и герой посреди игры начнёт
        // отзываться на прошлое.
        [Test]
        public void ИмяВосстанавливаетсяТолькоНаПустоеМесто()
        {
            LvnPrefs.PlayerName = "Виктория";
            var t = Три();
            LvnProgress.StartChapter(t, Гл(t, 0));
            var свёрток = ProgressVault.Collect(Манифест(t));

            LvnPrefs.PlayerName = "Ева";   // на устройстве уже другое
            ProgressVault.Apply(свёрток, Манифест(Три()));
            Assert.AreEqual("Ева", LvnPrefs.PlayerName, "свёрток переименовал героиню посреди игры");

            LvnPrefs.PlayerName = "";
            ProgressVault.Apply(свёрток, Манифест(Три()));
            Assert.AreEqual("Виктория", LvnPrefs.PlayerName, "имя не восстановилось на пустом устройстве");
        }

        // ── свёрток, которому нельзя верить ─────────────────────────────────

        // Свёрток приезжает с сервера и читается на САМОМ РАННЕМ шаге подъёма.
        // Урони он бут — игрок не попадёт в приложение вовсе, и починить это
        // изнутри игры будет нечем. Мусор обязан быть просто проигнорирован.
        [Test]
        public void БитыйСвёртокНеРоняетВосстановление()
        {
            var м = Манифест(Три());
            Assert.DoesNotThrow(() => ProgressVault.Apply(null, м));
            Assert.DoesNotThrow(() => ProgressVault.Apply(new JObject(), м));
            Assert.DoesNotThrow(() => ProgressVault.Apply(new JObject { ["titles"] = "не объект" }, м));
            Assert.DoesNotThrow(() => ProgressVault.Apply(
                new JObject { ["titles"] = new JObject { [Id] = new JObject { ["reached"] = "три" } } }, м));
            Assert.DoesNotThrow(() => ProgressVault.Apply(ProgressVault.Collect(м), null));

            Assert.IsNull(LvnProgress.Current(Три()), "мусорный свёрток всё-таки что-то записал");
        }

        // ── файловый дом свёртка ────────────────────────────────────────────
        // Свёрток живёт в ТРЁХ домах, и файл — тот, ради которого затевалась
        // вторая линия обороны: записная книжка устройства бьётся целиком, и
        // тогда единственное, что остаётся от прохождения, лежит здесь.

        // Круг «записали — прочитали» — вся ценность файлового дома. Разойдись
        // он хоть на ключ, и после сбоя настроек восстанавливать будет нечего:
        // файл на месте, а прочесть из него прогресс не выходит.
        [Test]
        public void СейфНаДискеПереживаетКругЗаписьЧтение()
        {
            var t = Три();
            LvnProgress.StartChapter(t, Гл(t, 1));
            var свёрток = ProgressVault.Collect(Манифест(t));

            ProgressVault.WriteLocal(свёрток);
            var прочитан = ProgressVault.ReadLocal();

            Assert.IsNotNull(прочитан, "сейф прогресса не прочитался с диска");
            Assert.AreEqual("c2", (string)Запись(прочитан, Id)["cur"],
                "круг «записали — прочитали» потерял точку продолжения");
            Assert.AreEqual(2, (int)Запись(прочитан, Id)["reached"],
                "круг «записали — прочитали» потерял потолок");
        }

        // «ЗАБУДЬТЕ МЕНЯ» — обещание, а не настройка. Сейф на диске — снимок
        // ВСЕГО прогресса, и он же раскладывается обратно на первом подъёме
        // «чистого» устройства. Переживи файл забвение — и стёртое игроком
        // прохождение воскреснет само, без его участия и без его согласия.
        [Test]
        public void ЗабвениеУноситСейфПрогрессаСДиска()
        {
            var t = Три();
            LvnProgress.StartChapter(t, Гл(t, 1));
            ProgressVault.WriteLocal(ProgressVault.Collect(Манифест(t)));
            Assert.IsNotNull(ProgressVault.ReadLocal(), "исходное состояние теста должно быть с сейфом");

            ProgressVault.Forget();

            Assert.IsNull(ProgressVault.ReadLocal(),
                "сейф прогресса пережил забвение — стёртое игроком прохождение воскреснет на следующем подъёме");
            Assert.DoesNotThrow(ProgressVault.Forget, "повторное забвение обязано быть тихим");
        }

        // Файл читают на САМОМ РАННЕМ шаге подъёма, до того как есть чем
        // показать ошибку. Половина файла (убили процесс на записи), чужая
        // кодировка, обрезанный диск — всё это должно читаться как «сейфа нет»,
        // а не ронять запуск: игра, которая не стартует, чинится только
        // переустановкой, то есть той самой потерей прогресса.
        [Test]
        public void БитыйФайлСейфаНеРоняетПодъём()
        {
            ProgressVault.WriteLocal(ProgressVault.Collect(Манифест(Три())));
            System.IO.File.WriteAllText(ПутьСейфа, "{\"titles\": {\"t\": ");   // обрыв на середине

            JObject прочитан = null;
            Assert.DoesNotThrow(() => прочитан = ProgressVault.ReadLocal(),
                "битый сейф уронил чтение — до меню игрок не доберётся");
            Assert.IsNull(прочитан, "битый сейф прочитался как настоящий");
        }

        // Две записи подряд — обычное дело: прогресс сводят на КАЖДОМ его ходе.
        // Постоянное имя временного файла (а именно так эта запись и была
        // написана своими руками) значит, что вторая запись наступает на
        // первую, а сорванная оставляет мусор в папке игрока навсегда.
        [Test]
        public void ДвеЗаписиПодрядНеНаступаютДругНаДругаИНеОставляютХвостов()
        {
            var t = Три();
            LvnProgress.StartChapter(t, Гл(t, 0));
            ProgressVault.WriteLocal(ProgressVault.Collect(Манифест(t)));
            LvnProgress.StartChapter(t, Гл(t, 2));
            ProgressVault.WriteLocal(ProgressVault.Collect(Манифест(t)));

            Assert.AreEqual("c3", (string)Запись(ProgressVault.ReadLocal(), Id)["cur"],
                "вторая запись сейфа не доехала — на диске остался вчерашний прогресс");

            var хвосты = System.IO.Directory.GetFiles(
                System.IO.Path.GetDirectoryName(ПутьСейфа), "lvn_progress.json.tmp-*");
            Assert.AreEqual(0, хвосты.Length,
                "после записи сейфа остался временный файл — он копится в папке игрока");
        }

        // Снимок тоже делают на живом приложении, где манифест мог не доехать
        // или приехать полупустым. Свалиться при съёмке значит потерять СИНК —
        // и следующая переустановка достанет вчерашний свёрток.
        [Test]
        public void СъёмкаПереживаетПустойМанифест()
        {
            Assert.DoesNotThrow(() => ProgressVault.Collect(null));
            Assert.DoesNotThrow(() => ProgressVault.Collect(new LvnManifest()));

            var кривой = new LvnManifest { titles = new List<LvnTitle> { null, new LvnTitle { id = "" }, Три() } };
            JObject свёрток = null;
            Assert.DoesNotThrow(() => свёрток = ProgressVault.Collect(кривой),
                "новелла без id уронила съёмку всего свёртка");
            Assert.IsNotNull(свёрток["titles"], "свёрток без раздела новелл — это не свёрток");
        }
    }
