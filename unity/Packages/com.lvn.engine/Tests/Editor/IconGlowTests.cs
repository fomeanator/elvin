using System.Reflection;
using Lvn.UI;
using NUnit.Framework;
using UnityEngine;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// СВЕЧЕНИЕ ЗНАЧКА — ПРИМЕТА ТЕМЫ, а не украшение отдельного вызова.
    ///
    /// <para>Ореол под линией иконки принадлежит теме наравне с цветом фона:
    /// «Кибер» светит в полную силу, «Романтика» вполсилы, «Полночь» не светит
    /// вовсе. Пока умолчанием был НОЛЬ, тему приходилось называть руками в
    /// каждом вызове — и называли её в двенадцати случаях из тридцати.
    /// Остальные восемнадцать значков жили без свечения не по замыслу, а по
    /// забывчивости, и в одном ряду оказывались светящиеся и тусклые: игрок
    /// читает такой ряд как «часть кнопок выключена».</para>
    ///
    /// <para>Правило поэтому такое: не сказали — берём у ДЕЙСТВУЮЩЕЙ темы;
    /// сказали ноль — значит ноль (нижняя навигация гасит ореол намеренно: её
    /// значки сами по себе приглушены, и свечение вокруг тусклого читается как
    /// грязь). И, как у всякого правила про тему: сменилась тема — сменилось
    /// свечение, а размер, цвет и толщина линии остались, потому что их
    /// называет ВЫЗЫВАЮЩИЙ, и тема не вправе их трогать.</para>
    ///
    /// <para>Свечение живёт полем нарисованного элемента — единственное место,
    /// где его видно до первой отрисовки, поэтому спрашиваем отражением. Числа
    /// тем здесь не зашиты: проверка сравнивает значок с ТЕМОЙ, а не с
    /// константой, — иначе перекраска темы красила бы тест, а не интерфейс.</para>
    /// </summary>
    public sealed class IconGlowTests
    {
        private readonly ОдолженнаяТема _тема = new ОдолженнаяТема();

        [SetUp]
        public void Запомнить() => _тема.Взять();

        [TearDown]
        public void Вернуть() => _тема.Вернуть();

        /// <summary>Свечение нарисованного значка — поле его элемента.</summary>
        private static float Свечение(VisualElement значок)
        {
            var f = значок.GetType().GetField("Glow", BindingFlags.Instance | BindingFlags.Public);
            Assert.NotNull(f, "у значка пропало поле свечения — проверка ослепла");
            return (float)f.GetValue(значок);
        }

        private static T Поле<T>(VisualElement значок, string имя)
        {
            var f = значок.GetType().GetField(имя, BindingFlags.Instance | BindingFlags.Public);
            Assert.NotNull(f, $"у значка пропало поле «{имя}»");
            return (T)f.GetValue(значок);
        }

        // ГЛАВНОЕ ПРАВИЛО: молчание вызывающего значит «как в теме», а не
        // «никак». Верни оно ноль — и любой новый значок, написанный без
        // оглядки на тему (то есть почти всякий), встанет в светящийся ряд
        // погашенным.
        [Test]
        public void БезУказанияСвечениеБерётсяУДействующейТемы()
        {
            foreach (var имя in new[] { "midnight", "cyber", "romance" })
            {
                LvnTheme.Use(имя);
                var значок = LvnIcons.Make(LvnIcon.Home, 24f, Color.white);

                Assert.AreEqual(LvnTheme.Current.IconGlow, Свечение(значок), 1e-4f,
                    $"значок не взял свечение у темы «{имя}» — в ряду соседей он выглядит выключенным");
            }
        }

        // Явный ноль — это ЗАКОННОЕ решение, а не забытый аргумент. Так гасит
        // ореол нижняя навигация: её значки приглушены сами по себе, и свечение
        // вокруг тусклого читается как грязь. Перебей умолчание темы этот ноль —
        // и правило превратилось бы в «светятся все, всегда».
        [Test]
        public void ЯвныйНольОстаётсяНулёмДажеНаСветящейсяТеме()
        {
            LvnTheme.Use("cyber");
            Assert.Greater(LvnTheme.Current.IconGlow, 0f, "тема для проверки обязана светиться");

            var погашенный = LvnIcons.Make(LvnIcon.Home, 30f, Color.white, 0f, 0f);

            Assert.AreEqual(0f, Свечение(погашенный), 1e-4f,
                "нижняя навигация просила погасить ореол, а он загорелся от темы");
        }

        // Названное свечение сильнее темы в обе стороны — не только в ноль.
        // Лавка нарочно светит вполсилы от темы; округли это до «как в теме» —
        // и её крупные эмблемы засветятся наравне с мелкими значками строки
        // состояния.
        [Test]
        public void НазванноеСвечениеСильнееТемы()
        {
            LvnTheme.Use("cyber");
            var вполсилы = LvnIcons.Make(LvnIcon.Gem, 46f, Color.white, 0f, LvnTheme.Current.IconGlow * 0.55f);

            Assert.AreEqual(LvnTheme.Current.IconGlow * 0.55f, Свечение(вполсилы), 1e-4f,
                "названное свечение подменили темой");
        }

        // И то, ради чего свечение вообще берут у темы: сменилась тема —
        // сменился ореол у следующего значка. Зашей умолчание числом — и смена
        // темы перекрасит экран наполовину: фон новый, значки светятся
        // по-старому.
        [Test]
        public void СменаТемыМеняетСвечениеУНовогоЗначка()
        {
            LvnTheme.Use("midnight");
            float полночь = Свечение(LvnIcons.Make(LvnIcon.Star, 24f, Color.white));

            LvnTheme.Use("cyber");
            float кибер = Свечение(LvnIcons.Make(LvnIcon.Star, 24f, Color.white));

            Assert.AreNotEqual(полночь, кибер,
                "значок не заметил смены темы — интерфейс перекрасился наполовину");
            Assert.AreEqual(LvnTheme.ByName("cyber").IconGlow, кибер, 1e-4f,
                "свечение после смены темы взято не у новой темы");
        }

        // Всё ОСТАЛЬНОЕ у значка называет вызывающий, и тема не вправе это
        // трогать. Поехавший от темы размер — это съехавшая раскладка строки,
        // поехавший цвет — потерянное состояние («выбранная вкладка» отличается
        // от соседних именно цветом).
        [Test]
        public void РазмерЦветИТолщинаЛинииОтТемыНеЗависят()
        {
            var цвет = new Color(0.2f, 0.7f, 0.9f, 1f);
            foreach (var имя in new[] { "midnight", "cyber", "romance" })
            {
                LvnTheme.Use(имя);
                var значок = LvnIcons.Make(LvnIcon.Gallery, 37f, цвет, 3f);

                Assert.AreEqual(37f, значок.style.width.value.value, 1e-4f,
                    $"тема «{имя}» изменила размер значка — строка съедет");
                Assert.AreEqual(37f, значок.style.height.value.value, 1e-4f,
                    $"тема «{имя}» изменила высоту значка — сетка 24×24 перестанет быть квадратной");
                Assert.AreEqual(цвет, Поле<Color>(значок, "Color"),
                    $"тема «{имя}» перекрасила значок — состояние вкладки читается по цвету");
                Assert.AreEqual(3f, Поле<float>(значок, "Stroke"), 1e-4f,
                    $"тема «{имя}» изменила толщину линии");
            }
        }

        // Значок валюты собирают тем же домом — и он обязан слушаться темы так
        // же. Кошелёк показывают минимум три места, и один тусклый кристалл
        // среди двух светящихся выглядит как ошибка загрузки.
        [Test]
        public void ЗначокВалютыТожеСветитсяПоТеме()
        {
            LvnTheme.Use("cyber");
            Assert.AreEqual(LvnTheme.Current.IconGlow, Свечение(LvnIcons.MakeCurrency("energy", 22f)), 1e-4f,
                "значок валюты не берёт свечение у темы — кошелёк выглядит по-разному в трёх местах");
        }

        // ── ПЕРЕКРАСКА НА МЕСТЕ ─────────────────────────────────────────────
        //
        // У перекраски то же умолчание, что у создания, и это не симметрия ради
        // симметрии. Значок вкладки перекрашивают КАЖДЫМ кадром перехода; будь
        // у Tint своё умолчание «ноль», всякая перекраска, написанная без
        // третьего довода, молча гасила бы ореол на светящейся теме — и вкладка
        // теряла бы свечение ровно в тот момент, когда игрок её трогает.

        [Test]
        public void ПерекраскаБезУказанияБерётСвечениеУТемы()
        {
            LvnTheme.Use("cyber");
            var значок = LvnIcons.Make(LvnIcon.Home, 24f, Color.white, 0f, 0f);

            LvnIcons.Tint(значок, Color.red);

            Assert.AreEqual(LvnTheme.Current.IconGlow, Свечение(значок), 1e-4f,
                "перекраска погасила ореол — вкладка тускнеет ровно тогда, когда её трогают");
            Assert.AreEqual(Color.red, Поле<Color>(значок, "Color"), "перекраска не перекрасила");
        }

        // Явный ноль законен и здесь: нижняя навигация гасит ореол у неактивной
        // вкладки НАМЕРЕННО и делает это именно перекраской.
        [Test]
        public void ПерекраскаЯвнымНулёмОстаётсяПогашенной()
        {
            LvnTheme.Use("cyber");
            Assert.Greater(LvnTheme.Current.IconGlow, 0f, "тема для проверки обязана светиться");
            var значок = LvnIcons.Make(LvnIcon.Home, 24f, Color.white);

            LvnIcons.Tint(значок, Color.red, 0f);

            Assert.AreEqual(0f, Свечение(значок), 1e-4f,
                "неактивную вкладку просили погасить, а она загорелась от темы");
        }

        [Test]
        public void ПерекраскаНазваннымЧисломСильнееТемы()
        {
            LvnTheme.Use("cyber");
            var значок = LvnIcons.Make(LvnIcon.Gem, 24f, Color.white);

            LvnIcons.Tint(значок, Color.red, 0.3f);

            Assert.AreEqual(0.3f, Свечение(значок), 1e-4f, "названное свечение подменили темой");
        }

        // Умолчания создания и перекраски — ОДНО И ТО ЖЕ. Разъедься они, и
        // значок менял бы свечение просто оттого, что его перекрасили: в одном
        // ряду оказались бы «только что созданный» и «уже трогали».
        [Test]
        public void УмолчанияСозданияИПерекраскиСовпадают()
        {
            foreach (var имя in new[] { "midnight", "cyber", "romance" })
            {
                LvnTheme.Use(имя);
                var созданный = LvnIcons.Make(LvnIcon.Star, 24f, Color.white);
                var перекрашенный = LvnIcons.Make(LvnIcon.Star, 24f, Color.white, 0f, 0f);

                LvnIcons.Tint(перекрашенный, Color.white);

                Assert.AreEqual(Свечение(созданный), Свечение(перекрашенный), 1e-4f,
                    $"на теме «{имя}» создание и перекраска дают разное свечение — " +
                    "значок меняет вид оттого, что его тронули");
            }
        }

        // «Полночь» не светит вовсе, и смена умолчания её не касается: на ней
        // перекраска обязана вести себя ровно как до правки — ореола нет.
        [Test]
        public void НаПолночиПерекраскаОреолаНеЗажигает()
        {
            LvnTheme.Use("midnight");
            Assert.AreEqual(0f, LvnTheme.Current.IconGlow, 1e-4f, "«Полночь» не светит — на том и держится проверка");
            var значок = LvnIcons.Make(LvnIcon.Home, 24f, Color.white);

            LvnIcons.Tint(значок, Color.red);

            Assert.AreEqual(0f, Свечение(значок), 1e-4f,
                "на «Полночи» появился ореол — тема, которая не светит, начала светиться");
        }

        // Перекрасить можно только НАРИСОВАННЫЙ значок. Чужой элемент — не
        // ошибка вызывающего: он не обязан знать, что ему досталось, и молчание
        // тут дешевле исключения посреди кадра анимации.
        [Test]
        public void ПерекраскаЧужогоЭлементаМолчит()
        {
            LvnTheme.Use("cyber");
            Assert.DoesNotThrow(() => LvnIcons.Tint(new VisualElement(), Color.red),
                "перекраска чужого элемента бросила — а зовут её каждым кадром перехода вкладок");
            Assert.DoesNotThrow(() => LvnIcons.Tint(null, Color.red));
        }

        // Значок не схлопывается в тесной строке: без этого правила иконка
        // рядом с длинной надписью просто исчезает — Yoga отдаёт ей нулевую
        // ширину, и остаётся текст без метки.
        [Test]
        public void ЗначокНеСжимаетсяВТеснойСтроке()
        {
            var значок = LvnIcons.Make(LvnIcon.Coin, 20f, Color.white);
            Assert.AreEqual(0f, значок.style.flexShrink.value, 1e-4f,
                "значок сжимается — в тесной строке он схлопнется в ноль и пропадёт");
            Assert.AreEqual(PickingMode.Ignore, значок.pickingMode,
                "значок ловит нажатия — кнопка под ним перестала нажиматься");
        }
    }
}
