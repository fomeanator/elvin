using System;
using System.Collections.Generic;
using System.Reflection;
using Lvn.Content;
using Lvn.UI;
using Lvn.UI.Screens;
using NUnit.Framework;
using UnityEngine;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// СБОРКА ОБОЛОЧКИ ИДЕМПОТЕНТНА — собрать заново значит собрать ЗАНОВО, а
    /// не поверх старого.
    ///
    /// <para>Дерево пересобирают не в теории: смена языка, смена темы, новый
    /// манифест после скачивания контента — каждый раз оболочка строит экраны с
    /// нуля. Дерево при этом чистилось (<c>_root.Clear()</c>), а НАБОР экранов —
    /// нет: в нём оставалось прошлое поколение, оторванное от дерева. Двух бед
    /// от этого две.</para>
    ///
    /// <para>Первая — набор растёт с каждой сборкой, и «убрать всё» с каждым
    /// разом обходит вдвое больше покойников. Вторая хуже: уборка зовёт УХОД у
    /// оторванных экранов, а уход у экрана конца главы имеет значение — он
    /// отпускает ждущего. То есть навигация в меню могла ответить «в меню» за
    /// цикл глав, который её не спрашивал.</para>
    ///
    /// <para>Здесь же закреплено и то, чем это чинится: набор умеет ЗАБЫТЬ
    /// состав. Забыть — не то же самое, что убрать: старое поколение уже не
    /// наше, и трогать его нельзя.</para>
    /// </summary>
    public sealed class ShellRebuildTests
    {
        // ── НАБОР УМЕЕТ ЗАБЫТЬ СОСТАВ ───────────────────────────────────────

        /// <summary>Экран, чей уход виден: если забытый состав всё-таки
        /// уберут, счётчик это покажет.</summary>
        private sealed class ЭкранСоСвоимУходом : VisualElement, ILvnHides
        {
            public int Уходов;
            public void Hide() => Уходов++;
        }

        private static DisplayStyle Показ(VisualElement el) => el.style.display.value;

        // ЗАБЫТЬ — НЕ УБРАТЬ. Состав забывают ровно тогда, когда дерево
        // пересобирают: прошлое поколение экранов больше не наше, и звать у
        // него уход нельзя — там могут висеть чужие ожидания.
        [Test]
        public void ЗабытыйСоставНеУбирают()
        {
            var набор = new LvnScreenSet();
            var свой = набор.Add(new ЭкранСоСвоимУходом());
            var простой = набор.Add(new VisualElement());
            int уходовПриВходе = свой.Уходов;      // вход в набор сам закрывает вошедшего
            простой.style.display = DisplayStyle.Flex;

            набор.Clear();

            Assert.AreEqual(0, набор.Count, "набор помнит состав, который его просили забыть");
            Assert.IsFalse(набор.Has(свой), "забытый экран всё ещё числится своим");
            Assert.IsFalse(набор.Has(простой));
            Assert.AreEqual(уходовПриВходе, свой.Уходов,
                "«забыть» обернулось «убрать» — у чужого экрана позвали уход, " +
                "а уход бывает со значением: он отпускает того, кто ждёт ответа");
        }

        [Test]
        public void УборкаПослеЗабытьНикогоНеТрогает()
        {
            var набор = new LvnScreenSet();
            var свой = набор.Add(new ЭкранСоСвоимУходом());
            var простой = набор.Add(new VisualElement());
            набор.Clear();
            int уходовБыло = свой.Уходов;
            простой.style.display = DisplayStyle.Flex;

            набор.HideAll();

            Assert.AreEqual(уходовБыло, свой.Уходов, "уборка достала забытый экран");
            Assert.AreEqual(DisplayStyle.Flex, Показ(простой),
                "уборка погасила экран, который набору больше не принадлежит");
        }

        [Test]
        public void НаборПослеЗабытьСноваПринимаетЭкраны()
        {
            var набор = new LvnScreenSet();
            набор.Add(new VisualElement());
            набор.Clear();

            var новый = набор.Add(new VisualElement());

            Assert.AreEqual(1, набор.Count, "после «забыть» набор перестал набираться заново");
            Assert.IsTrue(набор.Has(новый));
        }

        [Test]
        public void ПовторноеЗабытьНикогоНеРоняет()
        {
            var набор = new LvnScreenSet();
            набор.Add(new VisualElement());
            набор.Clear();

            Assert.DoesNotThrow(() => набор.Clear(), "второе «забыть» уронило набор");
            Assert.AreEqual(0, набор.Count);
        }

        [Test]
        public void ЗабытьУПустогоНабораНикогоНеРоняет()
        {
            var набор = new LvnScreenSet();

            Assert.DoesNotThrow(() => набор.Clear());
            Assert.AreEqual(0, набор.Count);
        }

        // ── ОБОЛОЧКА СОБИРАЕТСЯ ЗАНОВО ──────────────────────────────────────

        private readonly Мусор _мусор = new Мусор();
        private readonly ОдолженнаяТема _тема = new ОдолженнаяТема();

        [SetUp]
        public void Запомнить() => _тема.Взять();

        [TearDown]
        public void Прибрать()
        {
            _тема.Вернуть();   // хаб выбирает тему на сборке — вернём чужим тестам их
            _мусор.Убрать();
        }

        private static LvnManifest Манифест() => new LvnManifest
        {
            ui = new LvnUiConfig
            {
                auth = new AuthConfig(),
                chapter_end = new ChapterEndConfig(),
            },
        };

        private NovelShell Оболочка()
        {
            var shell = NovelShell.Create();
            _мусор.Беречь(shell.gameObject);
            shell.Build(Манифест(), new TestAssets());
            return shell;
        }

        private static LvnScreenSet Набор(NovelShell об)
            => Внутренности.Достать<LvnScreenSet>(об, typeof(NovelShell), "_screens",
                "оболочка держит экраны не набором — единого правила уборки больше нет");

        /// <summary>Позвать уборку оболочки — ту же, что стоит на каждой
        /// навигации по меню.</summary>
        private static void УбратьВсё(NovelShell об) =>
            Внутренности.Способ(typeof(NovelShell), "ShowOnly").Invoke(об, null);

        // Пересборка — обычное дело: смена языка, смена темы, новый манифест.
        // Набор обязан остаться НАБОРОМ ОДНОГО поколения, иначе уборка каждой
        // навигации обходит вдвое больше экранов, половина из которых давно
        // оторвана от дерева.
        [Test]
        public void ВтораяСборкаНеУдваиваетНабор()
        {
            var об = Оболочка();
            var набор = Набор(об);
            int послеПервой = набор.Count;
            Assert.Greater(послеПервой, 0, "оболочка собралась без экранов — проверять нечего");

            об.Build(Манифест(), new TestAssets());

            Assert.AreEqual(послеПервой, набор.Count,
                $"после второй сборки в наборе {набор.Count} экранов вместо {послеПервой}: " +
                "прошлое поколение осталось в нём, и уборка каждой навигации будет обходить покойников");
        }

        [Test]
        public void ТретьяСборкаТожеНеУдваиваетНабор()
        {
            var об = Оболочка();
            var набор = Набор(об);
            int послеПервой = набор.Count;

            об.Build(Манифест(), new TestAssets());
            об.Build(Манифест(), new TestAssets());

            Assert.AreEqual(послеПервой, набор.Count,
                "набор растёт с каждой сборкой — значит, чистится он не там, где собирается дерево");
        }

        // В наборе после пересборки — НОВОЕ поколение, а не старое: экран,
        // которого нет в дереве, уборкой не убрать, а показать его нельзя
        // вовсе.
        [Test]
        public void ПослеПересборкиВНабореНовоеПоколениеЭкранов()
        {
            var об = Оболочка();
            var прошлаяВитрина = об.Browse?.View;

            об.Build(Манифест(), new TestAssets());
            var набор = Набор(об);

            Assert.AreNotSame(прошлаяВитрина, об.Browse?.View, "пересборка не собрала экраны заново — проверять нечего");
            Assert.IsTrue(набор.Has(об.Browse?.View), "новый экран не попал в набор — уборка его пропустит");
            Assert.IsFalse(набор.Has(прошлаяВитрина),
                "в наборе остался экран прошлого поколения: его нет в дереве, " +
                "и уборка каждой навигации будет ходить к нему");
        }

        // СУТЬ. Уход экрана бывает СО ЗНАЧЕНИЕМ: конец главы, уходя, отвечает
        // ждущему «в меню». Останься прошлое поколение в наборе — обычная
        // навигация по меню ответила бы за цикл глав, который её не спрашивал:
        // игрок открыл профиль, а игра решила, что он попросился в меню.
        [Test]
        public void УборкаПослеПересборкиНеОтпускаетЖдущегоПрошлогоПоколения()
        {
            var об = Оболочка();
            var прошлыйКонецГлавы = об.ChapterEnd;
            Assert.NotNull(прошлыйКонецГлавы, "экран конца главы не собран — проверять нечего");
            var ждём = прошлыйКонецГлавы.ShowAsync("Глава 1", hasNext: true);

            об.Build(Манифест(), new TestAssets());
            УбратьВсё(об);

            Assert.IsFalse(ждём.IsCompleted,
                "уборка НОВОГО поколения дотянулась до экрана СТАРОГО и ответила за его ждущего — " +
                "любая навигация по меню становится ответом «в меню» за чужой цикл глав");
        }

        // Пересобранная оболочка убирается как обычно: новое поколение уборка
        // накрывает целиком.
        [Test]
        public void УборкаПослеПересборкиУбираетНовоеПоколение()
        {
            var об = Оболочка();
            об.Build(Манифест(), new TestAssets());
            об.Browse.View.style.display = DisplayStyle.Flex;
            об.Profile.style.display = DisplayStyle.Flex;

            УбратьВсё(об);

            Assert.AreEqual(DisplayStyle.None, Показ(об.Browse.View), "уборка не убрала пересобранную витрину");
            Assert.AreEqual(DisplayStyle.None, Показ(об.Profile), "уборка не убрала пересобранный профиль");
        }
    }
}
