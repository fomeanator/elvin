using System.Collections.Generic;
using Lvn.UI;
using NUnit.Framework;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// ВЪЕЗД ИЗ-ЗА КРОМКИ — <see cref="LvnMotion.Enter"/>.
    ///
    /// <para>Так приходят верхняя полоса, нижнее меню и страница главной. Всё,
    /// что здесь можно сломать, ломается ОДИНАКОВО на глаз: поверхность
    /// показывается на своём месте, а уже потом дёргается, — и вместо «приехало»
    /// читается «перерисовалось».</para>
    ///
    /// <para>ПРО ЗАВЕРШЕНИЕ. Анимации UI Toolkit крутит панель, а в EditMode её
    /// нет вовсе: ни один кадр не тикает и <c>OnCompleted</c> не наступает.
    /// Поэтому здесь закреплено то, что видно СИНХРОННО, в кадре вызова, — а
    /// это ровно тот кадр, в котором дефект и виден игроку.</para>
    /// </summary>
    public class MotionEnterTests
    {
        private bool _спокойноБыло;

        [SetUp]
        public void Запомнить() => _спокойноБыло = LvnPrefs.ReduceMotion;

        [TearDown]
        public void Вернуть() => LvnPrefs.ReduceMotion = _спокойноБыло;

        /// <summary>Поверхность, записывающая каждую долю пути, которую ей
        /// назвали. Ставить себя — работа звонящего, и вот он.</summary>
        private static List<float> Записать(VisualElement el, int ms)
        {
            var путь = new List<float>();
            LvnMotion.Enter(el, ms, p => путь.Add(p));
            return путь;
        }

        [Test]
        public void ПоверхностьУходитЗаКромкуВТомЖеКадре()
        {
            // Ради этого одного вызов и стоит первой строкой. Отложи расстановку
            // до первого тика анимации — и полоса меню успевает нарисоваться НА
            // МЕСТЕ, а следующим кадром прыгает за кромку и приезжает обратно.
            // Со стороны это не въезд, а мигание интерфейса при каждом открытии
            // экрана.
            var полоса = new VisualElement();

            var путь = Записать(полоса, LvnMotion.Curtain);

            Assert.IsNotEmpty(путь, "поверхность не расставили вовсе — она нарисуется на месте");
            Assert.AreEqual(0f, путь[0], 1e-4f,
                "первый же кадр показал поверхность не за кромкой — въезд читается как рывок");
            foreach (var доля in путь)
                Assert.Less(доля, 1f,
                    "поверхность доехала до места в том же кадре — движения не будет вовсе");
        }

        [Test]
        public void ВъездНеСтавитПоверхностьСам()
        {
            // Место поверхности знает только звонящий: у полосы это ПРОЦЕНТЫ
            // собственной высоты (пиксели в первом кадре ещё не посчитаны, и
            // выезд шёл бы из ниоткуда), у страницы — ширина экрана влево.
            // Возьмись въезд ставить смещение сам, он бы выбрал единицы за них
            // и подрался бы с той расстановкой, которую они уже сделали.
            var страница = new VisualElement();

            LvnMotion.Enter(страница, LvnMotion.Normal, _ => { });

            Assert.AreEqual(StyleKeyword.Null, страница.style.translate.keyword,
                "въезд сам сдвинул поверхность — звонящий считает место в своих единицах");
            Assert.AreEqual(StyleKeyword.Null, страница.style.opacity.keyword,
                "въезд подмешал проявление: полоса обязана ПРИЕХАТЬ, а не проступить на месте");
        }

        [Test]
        public void СпокойныйРежимСокращаетВъезд_АНеОтменяетЕго()
        {
            // Настройка «меньше движения» убирает РАЗМАХ, а не связность.
            // Пропусти въезд начальную расстановку в спокойном режиме — и
            // поверхность просто возникнет на месте: для человека, который эту
            // настройку и включил, мгновенная подмена читается как сбой
            // отрисовки, то есть хуже исходного движения.
            LvnPrefs.ReduceMotion = true;

            var меню = new VisualElement();
            var путь = Записать(меню, LvnMotion.Curtain);

            Assert.IsNotEmpty(путь, "в спокойном режиме поверхность не расставили — она возникнет на месте");
            Assert.AreEqual(0f, путь[0], 1e-4f, "спокойный режим отменил въезд вместо того, чтобы его укоротить");
            Assert.Greater(LvnMotion.Ms(LvnMotion.Curtain), 0,
                "срок сократился в ноль — анимация нулевой длины не доедет до конца и не поставит поверхность на место");
        }

        [Test]
        public void ПустотаНеРоняетВъезд()
        {
            // Въезд зовут из сборки экрана — там, где половины ссылок ещё нет:
            // документ пересоздают на смене темы, полосу выключили манифестом,
            // страницу сносят прямо в переходе. Урони это сборку — игрок
            // остаётся не без анимации, а без экрана.
            var живая = new VisualElement();
            int звали = 0;

            Assert.DoesNotThrow(() => LvnMotion.Enter(null, LvnMotion.Normal, _ => звали++),
                "въезд несуществующей поверхности уронил сборку экрана");
            Assert.AreEqual(0, звали, "расставляли поверхность, которой нет");

            Assert.DoesNotThrow(() => LvnMotion.Enter(живая, LvnMotion.Normal, null),
                "въезд без расстановки уронил сборку экрана");
        }
    }
}
