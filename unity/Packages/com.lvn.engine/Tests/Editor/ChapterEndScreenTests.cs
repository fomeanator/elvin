using System;
using System.Reflection;
using System.Threading.Tasks;
using Lvn.Content;
using Lvn.UI.Screens;
using NUnit.Framework;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// ЭКРАН КОНЦА ГЛАВЫ УМЕЕТ УЙТИ — и, уходя, ОТПУСКАЕТ ЖДУЩЕГО.
    ///
    /// <para>Экран этот не украшение: пока он на виду, цикл глав стоит и ждёт
    /// от него ответа — «дальше» или «в меню». Своего ухода у него не было
    /// вовсе, и потому «убрать всё» гасило ему показ мимо него: экран исчезал с
    /// глаз, а ожидание оставалось висеть. Для игрока это выглядело так —
    /// дочитал главу, экран моргнул и пропал, и дальше не происходит НИЧЕГО:
    /// ни следующей главы, ни меню. Выход один — убить приложение.</para>
    ///
    /// <para>Отсюда правило: у ухода экрана есть ЗНАЧЕНИЕ. Убрали молча —
    /// значит, продолжать некуда, и ждущий получает «в меню» (false). Это не
    /// вкус: любой другой ответ либо подвешивает цикл, либо запускает главу,
    /// которую никто не просил.</para>
    /// </summary>
    public sealed class ChapterEndScreenTests
    {
        private static ChapterEndScreen Экран()
            => new ChapterEndScreen(new ChapterEndConfig(), new TestAssets());

        private static DisplayStyle Показ(VisualElement el) => el.style.display.value;

        /// <summary>Кнопки экрана в порядке их появления: «продолжить», «в
        /// меню». Кто есть кто — закреплено отдельной проверкой ниже (на
        /// последней главе первая прячется), поэтому порядок здесь не догадка.</summary>
        private static Button[] Кнопки(ChapterEndScreen экран)
        {
            var кнопки = экран.Query<Button>().ToList();
            Assert.AreEqual(2, кнопки.Count,
                "у экрана конца главы должно быть ровно два выхода — дальше и в меню");
            return кнопки.ToArray();
        }

        /// <summary>НАЖАТЬ без панели и кадров — вопрос к дому
        /// (<see cref="Нажатие"/>). Запасной путь через приватный Invoke пришёл
        /// отсюда: три соседние копии его не знали.</summary>
        private static void Нажать(Button кнопка) => Нажатие.Жать(кнопка);

        // ── показ: экран держит цикл глав ───────────────────────────────────

        // Пока игрок не ответил, ответа нет. Задача, завершённая сразу, — это
        // глава, промотанная без спроса.
        [Test]
        public void ПоказЖдётОтветаИгрока()
        {
            var экран = Экран();

            var ждём = экран.ShowAsync("Глава 1. Агентство", hasNext: true);

            Assert.IsFalse(ждём.IsCompleted,
                "экран ответил за игрока — цикл глав поехал дальше, пока экран ещё на виду");
            Assert.AreEqual(DisplayStyle.Flex, Показ(экран), "экран показали, а его не видно");
        }

        // Кто из двух кнопок кто — не догадка: на последней главе продолжать
        // некуда, и первая кнопка прячется. Заодно это правило самой последней
        // главы: единственный выход из неё — в меню.
        [Test]
        public void БезСледующейГлавыПродолжитьНеПоказывают()
        {
            var экран = Экран();
            var кнопки = Кнопки(экран);

            экран.ShowAsync("Глава последняя", hasNext: false);

            Assert.AreEqual(DisplayStyle.None, Показ(кнопки[0]),
                "продолжать некуда, а кнопку «дальше» показали — игрок нажмёт её в пустоту");
            Assert.AreEqual(DisplayStyle.Flex, Показ(кнопки[1]),
                "с последней главы убрали единственный выход — игрок заперт на экране");
        }

        // ── ответ игрока ────────────────────────────────────────────────────

        [Test]
        public void КнопкаДальшеДаётСледующуюГлаву()
        {
            var экран = Экран();
            var кнопки = Кнопки(экран);
            var ждём = экран.ShowAsync("Глава 1", hasNext: true);

            Нажать(кнопки[0]);

            Assert.IsTrue(ждём.IsCompleted, "нажали «дальше», а цикл глав ответа не получил");
            Assert.IsTrue(ждём.Result, "«дальше» обязано значить следующую главу, а не возврат в меню");
            Assert.AreEqual(DisplayStyle.None, Показ(экран),
                "экран остался поверх начавшейся главы");
        }

        [Test]
        public void КнопкаВМенюВозвращаетВМеню()
        {
            var экран = Экран();
            var кнопки = Кнопки(экран);
            var ждём = экран.ShowAsync("Глава 1", hasNext: true);

            Нажать(кнопки[1]);

            Assert.IsTrue(ждём.IsCompleted, "нажали «в меню», а цикл глав ответа не получил");
            Assert.IsFalse(ждём.Result, "«в меню» обернулось запуском следующей главы");
            Assert.AreEqual(DisplayStyle.None, Показ(экран));
        }

        // ── СУТЬ ДОМА: уход отпускает ждущего ───────────────────────────────

        // ЖИВОЙ ДЕФЕКТ. Экран убирали не его способом — просто гасили показ, —
        // и ждущий оставался ждать вечно. Игрок дочитывал главу, экран моргал и
        // пропадал, и дальше не происходило ничего: ни главы, ни меню.
        [Test]
        public void УходОтпускаетЖдущегоВМеню()
        {
            var экран = Экран();
            var ждём = экран.ShowAsync("Глава 1", hasNext: true);

            экран.Hide();

            Assert.IsTrue(ждём.IsCompleted,
                "экран ушёл молча — цикл глав ждёт ответа от экрана, которого больше нет: " +
                "для игрока это игра, которая просто перестала продолжаться");
            Assert.IsFalse(ждём.Result,
                "убранный экран значит «продолжать некуда» — иначе он сам запускает главу, " +
                "которую игрок не выбирал");
        }

        [Test]
        public void ПослеУходаЭкранаНеВидно()
        {
            var экран = Экран();
            экран.ShowAsync("Глава 1", hasNext: true);

            экран.Hide();

            Assert.AreEqual(DisplayStyle.None, Показ(экран),
                "экран отпустил ждущего, но остался на виду поверх меню");
        }

        // Уход зовётся на каждой уборке набора, а уборка — на каждой навигации.
        // «Уйти с того, с чего уже ушли» обязано быть будничным делом.
        [Test]
        public void ПовторныйУходНикогоНеРоняет()
        {
            var экран = Экран();
            var ждём = экран.ShowAsync("Глава 1", hasNext: true);
            экран.Hide();

            Assert.DoesNotThrow(() => экран.Hide(),
                "второй уход уронил экран — уборка набора зовётся на каждой навигации");
            Assert.IsFalse(ждём.Result, "второй уход переписал уже данный ответ");
        }

        [Test]
        public void УходСНеПоказанногоЭкранаНикогоНеРоняет()
        {
            var экран = Экран();

            Assert.DoesNotThrow(() => экран.Hide(),
                "экран убрали, ни разу не показав, — обычное дело для «убрать всё» при старте");
        }

        // Ответ даётся ОДИН раз: экран, ушедший после нажатия, не имеет права
        // переписать выбор игрока на «в меню».
        [Test]
        public void УходПослеОтветаОтветаНеМеняет()
        {
            var экран = Экран();
            var кнопки = Кнопки(экран);
            var ждём = экран.ShowAsync("Глава 1", hasNext: true);
            Нажать(кнопки[0]);

            экран.Hide();

            Assert.IsTrue(ждём.Result,
                "игрок выбрал следующую главу, а уход экрана увёл его в меню");
        }

        // Прошлый показ не имеет права пережить новый: TCS отдаёт результат
        // один раз, и висящий с прошлой главы ждущий подвесил бы цикл навсегда.
        [Test]
        public void НовыйПоказОтпускаетЖдущегоСПрошлойГлавы()
        {
            var экран = Экран();
            var прошлый = экран.ShowAsync("Глава 1", hasNext: true);

            var новый = экран.ShowAsync("Глава 2", hasNext: true);

            Assert.IsTrue(прошлый.IsCompleted, "ждущий с прошлого показа остался висеть");
            Assert.IsFalse(прошлый.Result);
            Assert.IsFalse(новый.IsCompleted, "новый показ ответил за игрока");
        }

        // ── и то же самое ЧЕРЕЗ НАБОР ЭКРАНОВ ───────────────────────────────

        // РАДИ ЧЕГО ЭКРАН И ПОМЕТИЛИ. Набор закрывает всех разом и знать
        // поимённо, у кого уход особый, не обязан: метка ILvnHides — весь
        // способ ему об этом сказать. Не будь её, набор погасил бы показ мимо
        // экрана — то есть ровно так, как и подвешивал цикл глав.
        [Test]
        public void НаборЭкрановУбираетЭкранЕгоЖеУходом()
        {
            var экран = Экран();
            var ждём = экран.ShowAsync("Глава 1", hasNext: true);

            LvnScreenSet.Shut(экран);

            Assert.IsTrue(ждём.IsCompleted,
                "набор погасил показ мимо экрана — метка «умею уходить сам» до него не доехала, " +
                "и цикл глав повис на экране, которого уже не видно");
            Assert.IsFalse(ждём.Result);
            Assert.AreEqual(DisplayStyle.None, Показ(экран));
        }

        [Test]
        public void УборкаНабораОтпускаетЖдущего()
        {
            var набор = new LvnScreenSet();
            var экран = набор.Add(Экран());
            var ждём = экран.ShowAsync("Глава 1", hasNext: true);

            набор.HideAll();

            Assert.IsTrue(ждём.IsCompleted,
                "«убрать всё» прошло мимо экрана конца главы — он и есть тот экран, " +
                "который теряли в ручном перечне");
            Assert.IsFalse(ждём.Result);
        }
    }
}
