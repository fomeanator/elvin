using System;
using System.IO;
using System.Reflection;
using System.Threading;
using System.Threading.Tasks;
using Lvn.Content;
using NUnit.Framework;
using UnityEngine.Networking;

namespace Lvn.Tests
{
    /// <summary>
    /// ОДИН ЗАХОД ЗА БАЙТАМИ — общий вход в сеть у всего загрузчика контента
    /// (<c>ContentLoader.GetAsync</c>).
    ///
    /// <para>Правила захода были записаны ТРИЖДЫ — у тихой предзагрузки, у
    /// одиночного захода и у пакетного; отличались они только тем, что считать
    /// по дороге. Расхождение в любом читалось бы как «иногда офлайн не
    /// определяется» или «иногда качает вечно», то есть как плавающий дефект,
    /// который ищут неделями.</para>
    ///
    /// <para>ЗДЕСЬ ПРОВЕРЯЕТСЯ ТО, ЧТО НЕ ТРЕБУЕТ ПРОВОДА: отказ, случающийся
    /// ДО запроса, и место в очереди загрузок, которое обязано вернуться на
    /// любом выходе. Оба правила про поведение загрузчика, когда всё идёт не
    /// так, — а именно тогда его никто и не проверяет руками.</para>
    ///
    /// <para>ЧЕГО ЗДЕСЬ НЕТ. Успешный ответ — тело, код, докачка с байта N,
    /// отказ на не-двухсотом коде — требует живого сервера и прокрутки кадров:
    /// EditMode не даёт ни того, ни другого (блокирующее ожидание кладёт
    /// главный поток, покадровое не двигается без кадров). Поднимать «почти
    /// сеть» на заглушках здесь незачем: проверялась бы заглушка.</para>
    /// </summary>
    public class ContentFetchTests
    {
        private static readonly MethodInfo ЗаходЗаБайтами =
            typeof(ContentLoader).GetMethod("GetAsync", BindingFlags.Instance | BindingFlags.NonPublic);

        private static readonly FieldInfo ПолеОчереди =
            typeof(ContentLoader).GetField("_downloadSlots", BindingFlags.Static | BindingFlags.NonPublic);

        /// <summary>Очередь загрузок: сколько заходов ещё пустят на провод
        /// одновременно. Общая на весь процесс — потому её утечка и стоит
        /// дорого.</summary>
        private static SemaphoreSlim Очередь => (SemaphoreSlim)ПолеОчереди.GetValue(null);

        private ContentLoader _loader;
        private string _root;
        private bool _силойОфлайн;

        [SetUp]
        public void SetUp()
        {
            Assert.IsNotNull(ЗаходЗаБайтами, "общий заход за байтами переименован — правила ниже проверять нечем");
            Assert.IsNotNull(ПолеОчереди, "очередь загрузок переименована — правила ниже проверять нечем");

            _root = Path.Combine(Path.GetTempPath(), "lvn-fetch-" + Guid.NewGuid().ToString("N"));
            // Порт 9 (discard) — адрес, на который никто не ответит: если тест
            // всё-таки уйдёт на провод, это будет видно по зависанию, а не по
            // случайно удачному ответу.
            _loader = new ContentLoader("http://127.0.0.1:9/", _root);
            _силойОфлайн = LvnNetworkStatus.ForceOffline;
        }

        [TearDown]
        public void TearDown()
        {
            // Признак связи общий на процесс: оставить его сбитым — значит
            // покрасить чужие тесты.
            LvnNetworkStatus.ForceOffline = _силойОфлайн;
            if (!_силойОфлайн) LvnNetworkStatus.MarkOnline("конец теста");
            if (Directory.Exists(_root)) Directory.Delete(_root, true);
        }

        /// <summary>Заход за байтами. <paramref name="подготовить"/> — то, что
        /// заход добавляет к запросу перед отправкой (докачка ставит там
        /// заголовок Range).</summary>
        private Task Зайти(string url, CancellationToken ct = default,
                           Action<UnityWebRequest> подготовить = null)
            => (Task)ЗаходЗаБайтами.Invoke(_loader, new object[] { url, ct, null, подготовить });

        // ── отказ ДО провода ────────────────────────────────────────────────

        // Когда уже известно, что связи нет, идти на провод незачем: звонящий
        // обязан немедленно упасть на дисковый кэш. Пойди заход всё равно — и
        // каждый файл главы отстоит свой сокетный таймаут: в самолёте игрок
        // увидит бесконечный загрузочный экран вместо главы, которая целиком
        // лежит у него на диске.
        //
        // Код отказа именно «network», а не «сервер ответил ошибкой»: по нему
        // циклы повторов понимают, что повторять бессмысленно, и отдают
        // управление кэшу вместо десяти заходов с нарастающей паузой.
        [Test]
        public void ЗнаяЧтоСвязиНетЗаходНеИдётНаПровод()
        {
            LvnNetworkStatus.ForceOffline = true;

            var заход = Зайти("/content/bg/city.jpg");

            Assert.IsTrue(заход.IsCompleted,
                "заход ушёл на провод, зная, что связи нет, — глава будет ждать сокетный таймаут на каждый файл");
            var отказ = заход.Exception?.InnerException as LvnFetchException;
            Assert.IsNotNull(отказ, "офлайн не отказ, а что-то другое: " + заход.Exception?.InnerException);
            Assert.AreEqual("network", отказ.Code,
                "отказ выдан за ответ сервера — цикл повторов будет десять раз ломиться в мёртвую сеть");
            Assert.AreEqual(0, отказ.Status, "у отказа без ответа не может быть кода ответа");
        }

        // Отказ, случившийся ДО очереди, места в ней не занимает. Занял бы —
        // и офлайн стал бы самоподдерживающимся: связь вернулась, а качать
        // нечем, потому что все двенадцать мест раздали отказам.
        [Test]
        public void ОтказПоОфлайнуОчередьНеТрогает()
        {
            LvnNetworkStatus.ForceOffline = true;
            int было = Очередь.CurrentCount;

            for (int i = 0; i < 15; i++)
            {
                var заход = Зайти("/content/bg/city.jpg");
                Assert.IsNotNull(заход.Exception, "офлайн прошёл молча — звонящий не узнает, что байтов не будет");
            }

            Assert.AreEqual(было, Очередь.CurrentCount,
                "отказы съели очередь загрузок — вернувшаяся связь уже ничего не скачает");
        }

        // ── место в очереди возвращается на ЛЮБОМ выходе ────────────────────

        // Очередь — двенадцать мест на весь процесс, и берут их ВСЕ загрузки:
        // скрипт главы, фоны, актёры, музыка. Место занимают перед заходом и
        // отпускают в finally — именно потому, что заход падает чаще, чем
        // удаётся: обрыв, битый ответ, сорванная докачка.
        //
        // Отпусти его только на удачном пути — и двенадцати сбоев (одна глава
        // на плохом вайфае) хватит, чтобы загрузки встали НАВСЕГДА. Игра при
        // этом не падает и ничего не сообщает: прогресс просто перестаёт
        // двигаться, до перезапуска приложения.
        [Test]
        public void МестоВОчередиВозвращаетсяИКогдаЗаходСорвался()
        {
            LvnNetworkStatus.ForceOffline = false;
            LvnNetworkStatus.MarkOnline("тест");
            int было = Очередь.CurrentCount;

            // Сбоев больше, чем мест в очереди: если место не возвращать,
            // последние заходы уже не с чем будет отправлять.
            for (int i = 0; i < 15; i++)
            {
                var заход = Зайти("/content/bg/city.jpg",
                    подготовить: _ => throw new InvalidOperationException("сорвалось по дороге"));
                Assert.IsTrue(заход.IsFaulted, "сорвавшийся заход не сообщил о сбое");
                _ = заход.Exception;   // сбой замечен — иначе он всплывёт чужим тестом
            }

            Assert.AreEqual(было, Очередь.CurrentCount,
                "сорвавшиеся заходы не вернули места — очередь загрузок встала до перезапуска приложения");
        }

        // Отмена — это не сбой, а обычный конец жизни загрузки: игрок вышел из
        // главы, и всё, что она качала, снимают разом. Такой выход обязан
        // оставить очередь ровно такой, какой взял: иначе каждый выход из главы
        // отъедает от неё по куску, и к третьей новелле за сеанс загружать
        // становится нечем.
        [Test]
        public void ОтменённыйЗаходОчередьВозвращает()
        {
            LvnNetworkStatus.ForceOffline = false;
            LvnNetworkStatus.MarkOnline("тест");
            int было = Очередь.CurrentCount;

            using var снято = new CancellationTokenSource();
            снято.Cancel();
            for (int i = 0; i < 15; i++)
            {
                var заход = Зайти("/content/bg/city.jpg", снято.Token);
                Assert.IsTrue(заход.IsCanceled || заход.IsFaulted,
                    "снятая загрузка продолжает качать — глава, из которой вышли, тянет сеть за собой");
                _ = заход.Exception;
            }

            Assert.AreEqual(было, Очередь.CurrentCount,
                "снятые загрузки не вернули места — очередь тает с каждым выходом из главы");
        }
    }
}
