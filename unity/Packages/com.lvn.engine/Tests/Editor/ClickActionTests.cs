using System.Collections.Generic;
using Lvn.UI;
using Newtonsoft.Json.Linq;
using NUnit.Framework;

namespace Lvn.Tests
{
    /// <summary>
    /// ЧТО ЗНАЧИТ НАЖАТИЕ — <see cref="LvnClick"/>, один ответ на всю игру.
    ///
    /// <para>Автор пишет <c>on_click</c> двумя записями: одним словом — метка
    /// перехода, — или объектом, который заодно правит переменные. Записи
    /// равноправны и обязаны работать всюду: у фигуры на сцене, у предмета и в
    /// дереве <c>ui</c>. Раньше их знала только сцена, а дерево <c>ui</c>
    /// приводило поле к строке напрямую — и на объекте БРОСАЛО. Дерево не
    /// строилось вовсе: у игрока на этом шаге пропадал весь интерфейс, хотя
    /// написал он ровно то, что стоит в документации движка.</para>
    ///
    /// <para>Здесь закреплены правила этого дома. Каждое стоит игроку чего-то
    /// видимого: пропавшего интерфейса, мёртвой кнопки, ветки, читающей вчерашние
    /// переменные, или главы, упавшей из-за опечатки в одном символе.</para>
    /// </summary>
    public class ClickActionTests
    {
        /// <summary>Журнал одного нажатия: что случилось и В КАКОМ ПОРЯДКЕ.
        /// Порядок здесь — не отчётность, а само проверяемое правило.</summary>
        private sealed class Журнал
        {
            public readonly List<string> Шаги = new List<string>();
            public string Метка;
            public bool Переходили;
            public JObject Переменные;

            public void Идти(string label) { Переходили = true; Метка = label; Шаги.Add("переход"); }
            public void Писать(JObject ops) { Переменные = ops; Шаги.Add("переменные"); }
        }

        // ── обе записи ведут по метке ───────────────────────────────────────

        // Ровно тот дефект, ради которого дом и появился: объектную запись
        // знала сцена, а дерево `ui` — нет, и падало на ней приведением к
        // строке. Обе записи описывают ОДНО намерение автора, и переход по
        // метке обязан случиться в обеих.
        [Test]
        public void ОбеЗаписиВедутПоНазваннойМетке()
        {
            var словом = new Журнал();
            var объектом = new Журнал();

            LvnClick.From(new JValue("bag"), словом.Идти, словом.Писать)();
            LvnClick.From(new JObject { ["goto"] = "bag" }, объектом.Идти, объектом.Писать)();

            Assert.AreEqual("bag", словом.Метка, "нажатие одним словом никуда не привело");
            Assert.AreEqual("bag", объектом.Метка,
                "объектная запись не сработала — а именно на ней дерево ui и роняло весь интерфейс");
        }

        // ── переменные раньше перехода ──────────────────────────────────────

        // Ветка, в которую ведёт метка, обычно и ЧИТАЕТ эти переменные: «нашёл
        // ключ» ставят нажатием, а проверяют первой же строкой найденной ветки.
        // Поменяй порядок — и первая реплика новой ветки увидит вчерашние
        // значения: игрок подобрал предмет и слышит, что предмета у него нет.
        [Test]
        public void ПеременныеПишутсяДоПерехода()
        {
            var журнал = new Журнал();

            LvnClick.From(
                new JObject { ["goto"] = "found", ["set"] = new JObject { ["key"] = true } },
                журнал.Идти, журнал.Писать)();

            CollectionAssert.AreEqual(new[] { "переменные", "переход" }, журнал.Шаги,
                "переход случился раньше записи — ветка прочитает состояние ДО нажатия");
        }

        // Приёмнику отдают ровно тот блок, который написал автор: он и есть
        // список правок. Отдай не его — нажатие «сработает», а переменные
        // останутся прежними, и ошибку будут искать в сценарии.
        [Test]
        public void ПриёмникуОтдаютАвторскийБлокПравок()
        {
            var журнал = new Журнал();
            var правки = new JObject { ["found"] = true, ["mood"] = 3 };

            LvnClick.From(new JObject { ["goto"] = "next", ["set"] = правки },
                журнал.Идти, журнал.Писать)();

            Assert.IsNotNull(журнал.Переменные, "правки до приёмника не доехали");
            Assert.AreEqual(true, (bool)журнал.Переменные["found"], "правка автора потерялась по дороге");
            Assert.AreEqual(3, (int)журнал.Переменные["mood"], "правка автора потерялась по дороге");
        }

        // Объект без `set` — это просто переход, записанный длинно. Беспокоить
        // приёмник переменных пустотой значит гнать пересчёт статов и перерисовку
        // интерфейса на каждое нажатие, которое ничего не меняет.
        [Test]
        public void ОбъектБезПравокПриёмникаНеБеспокоит()
        {
            var журнал = new Журнал();

            LvnClick.From(new JObject { ["goto"] = "map" }, журнал.Идти, журнал.Писать)();

            CollectionAssert.AreEqual(new[] { "переход" }, журнал.Шаги,
                "нажатие без правок всё равно позвало приёмник переменных");
        }

        // ── пустая метка: две записи, два разных смысла ─────────────────────

        // Объектная запись — это ДЕЙСТВИЕ, даже когда переход никуда не ведёт:
        // «поставить флаг и остаться на месте» — законный сценарий. Звонящий
        // всё равно обязан снять ожидание и шагнуть дальше, а сделать это он
        // может только изнутри действия. Верни здесь null — и элемент станет
        // мёртвым: игрок жмёт, переменная не ставится, сцена стоит.
        [Test]
        public void ОбъектСПустымПереходомВсёРавноДействие()
        {
            var журнал = new Журнал();
            var правки = new JObject { ["seen"] = true };

            var действие = LvnClick.From(
                new JObject { ["set"] = правки }, журнал.Идти, журнал.Писать);

            Assert.IsNotNull(действие,
                "объект без метки объявлен «нажатием без действия» — переменная не встанет, а сцена не шагнёт");
            действие();
            CollectionAssert.AreEqual(new[] { "переменные", "переход" }, журнал.Шаги,
                "звонящему не дали шагнуть — ожидание останется висеть");
            Assert.IsTrue(string.IsNullOrEmpty(журнал.Метка),
                "пустой переход обязан остаться пустым, а не увести по выдуманной метке");
        }

        // А запись ОДНИМ СЛОВОМ ничего, кроме перехода, не описывает: пустая
        // строка в ней — это «нажатие не назначено». Дай на неё действие — и
        // элемент станет кликабельным без единого последствия: игрок жмёт по
        // подсвеченной области и решает, что игра сломана.
        [Test]
        public void ПустаяМеткаСловомОставляетЭлементНеактивным()
        {
            var журнал = new Журнал();

            Assert.IsNull(LvnClick.From(new JValue(""), журнал.Идти, журнал.Писать),
                "пустая метка сделала элемент кликабельным впустую");
            Assert.IsNull(LvnClick.From(JValue.CreateNull(), журнал.Идти, журнал.Писать),
                "null в поле нажатия сделал элемент кликабельным впустую");
        }

        // ── опечатка автора — не повод ронять главу ─────────────────────────

        // `on_click: 42` и `on_click: true` пишут случайно (кавычки съел
        // редактор, поле заполнили не тем). Это ошибка сценария, и сообщить о
        // ней должен ЧТЕЦ — «нет такой метки», по имени, с местом. Упасть здесь
        // значит обменять понятную жалобу на упавшую главу посреди сцены.
        [Test]
        public void ЧислоИлиДаВПолеМеткиГлавуНеРоняют()
        {
            var число = new Журнал();
            var да = new Журнал();

            Assert.DoesNotThrow(() => LvnClick.From(new JValue(42), число.Идти, число.Писать)(),
                "опечатка автора уронила главу вместо жалобы чтеца");
            Assert.AreEqual("42", число.Метка, "метку взяли не так, как её написал автор");

            Assert.DoesNotThrow(() => LvnClick.From(new JValue(true), да.Идти, да.Писать)(),
                "опечатка автора уронила главу вместо жалобы чтеца");
            Assert.IsTrue(да.Переходили, "переход не состоялся — чтецу не на что пожаловаться");
            Assert.IsFalse(string.IsNullOrEmpty(да.Метка),
                "метка стала пустой: элемент просто промолчит, и автор не узнает про опечатку");
        }

        // Жалоба чтеца называет метку СЛОВАМИ АВТОРА, а не .NET. У логического
        // значения `ToString` даёт «True» с прописной — и сообщение «нет метки
        // True» отправляет автора искать в сценарии слово, которого он никогда
        // не писал. Искать он будет глазами, по всему файлу, и не найдёт:
        // понятная жалоба превращается в тупик. Язык пишет согласие строчными,
        // ими же оно и называется.
        [Test]
        public void ЛогическоеВПолеМеткиНазываетсяСловомЯзыка_АНеДотнета()
        {
            var да = new Журнал();
            var нет = new Журнал();

            LvnClick.From(new JValue(true), да.Идти, да.Писать)();
            LvnClick.From(new JValue(false), нет.Идти, нет.Писать)();

            Assert.AreEqual("true", да.Метка,
                "метка названа по-дотнетовски — автор пойдёт искать в сценарии слово, которого не писал");
            Assert.AreEqual("false", нет.Метка,
                "метка названа по-дотнетовски — жалоба чтеца указывает не на то, что написано");
        }

        // ── неполная оснастка звонящего ─────────────────────────────────────

        // Переменные умеют писать не все: у дерева `ui` приёмник есть, у
        // предмета на сцене может не быть. Отсутствие приёмника — не отказ от
        // нажатия: переход обязан состояться, иначе объектная запись перестанет
        // работать в половине мест, и автор будет искать, чем эти места
        // отличаются.
        [Test]
        public void БезПриёмникаПеременныхОстаётсяПереход()
        {
            var журнал = new Журнал();

            var действие = LvnClick.From(
                new JObject { ["goto"] = "bag", ["set"] = new JObject { ["x"] = 1 } },
                журнал.Идти);

            Assert.IsNotNull(действие, "нажатие пропало вместе с приёмником переменных");
            Assert.DoesNotThrow(() => действие(), "нажатие упало там, где переменные писать некому");
            Assert.AreEqual("bag", журнал.Метка, "переход не состоялся — кнопка мертва");
        }

        // Нет поля — нет нажатия: элемент остаётся неактивным, а не «нажимается
        // в никуда». А если некуда вести (перехода не дали), то и обе записи
        // одинаково молчат: действие, которое ничего не может, — это ловушка
        // для пальца.
        [Test]
        public void БезПоляИлиБезПереходаНажатияНет()
        {
            var журнал = new Журнал();

            Assert.IsNull(LvnClick.From(null, журнал.Идти, журнал.Писать),
                "нажатие появилось там, где автор его не назначал");
            Assert.IsNull(LvnClick.From(new JValue("bag"), null, журнал.Писать),
                "нажатие обещает переход, а вести его некуда");
            Assert.IsNull(LvnClick.From(new JObject { ["goto"] = "bag" }, null, журнал.Писать),
                "нажатие обещает переход, а вести его некуда");
        }
    }
}
