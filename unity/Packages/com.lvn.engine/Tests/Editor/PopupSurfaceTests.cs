using System;
using Lvn.Content;
using Lvn.UI;
using Lvn.UI.Screens;
using NUnit.Framework;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// АЛЕРТ — ПОВЕРХНОСТЬ РЕЖИССЁРА, а не частное дело попапа.
    ///
    /// <para>«Кто сейчас наверху» знает Режиссёр — он же отвечает, что закроет
    /// «назад». Про алерт он не знал ничего: открыт тот или нет, помнил только
    /// сам экран, и спрашивали его, заглядывая снаружи в стиль показа. Стоило
    /// поднять вопрос поверх сюжетной панели — и верхней у Режиссёра оставалась
    /// ПАНЕЛЬ: «назад» закрывал её из-под заданного над ней вопроса. То же
    /// самое когда-то стоил Escape, слепой к модалям оболочки.</para>
    ///
    /// <para>На уровне Режиссёра правило закреплено в <c>ScreenDirectorTests</c>
    /// («Алерт…»). Здесь — уровень ЭКРАНА: что попап действительно объявляет о
    /// себе Режиссёру, а уходя — снимает объявление. Пишется это в одном месте
    /// (свойство «алерт открыт»), и именно это одно место здесь и проверяется.</para>
    ///
    /// <para>ЧЕГО ЗДЕСЬ НЕТ. Ответ КНОПКОЙ в EditMode не докручивается: нажатие
    /// отдаёт результат ожиданию, а поверхность снимается в <c>finally</c> —
    /// уже после того, как продолжение ожидания вернётся на главный поток. Ни
    /// кадров, ни прокачки контекста в EditMode нет (та же причина, по которой
    /// модальный виток не проверяется в <c>OverlayScreenTests</c>), поэтому
    /// закрытие проверяется через уход экрана — тот самый путь, которым его
    /// закрывает набор.</para>
    /// </summary>
    public sealed class PopupSurfaceTests
    {
        private Func<float> _часыБыли;
        private float _тик;

        [SetUp]
        public void Setup()
        {
            // ЧАСЫ, КОТОРЫЕ ВСЕГДА УЖЕ ПРОШЛИ: появление попапа — затухание, а
            // затухание в EditMode ждёт кадров, которых нет. С такими часами
            // оно кончается на первом же замере, и показ доходит до места, где
            // ждёт ответа игрока, — не выходя за пределы одного вызова.
            _часыБыли = LvnClock.Now;
            _тик = 0f;
            LvnClock.Now = () => (_тик += 10f);
            LvnScreenDirector.Current.Reset();
        }

        [TearDown]
        public void TearDown()
        {
            LvnClock.Now = _часыБыли;
            LvnScreenDirector.Current.Reset();
        }

        private static PopupScreen Попап() => new PopupScreen(new PopupConfig());

        private static string Верхний => LvnScreenDirector.Current.BackTarget;

        // ── показ объявляет о себе Режиссёру ────────────────────────────────

        // ГЛАВНОЕ ПРАВИЛО. Вопрос на экране — значит, наверху вопрос. Пока это
        // знал только сам попап, «назад» уводил игрока из-под заданного ему
        // вопроса, закрывая то, что стояло ниже.
        [Test]
        public void ПоказАлертаСтавитЕгоНаверхЭкрана()
        {
            var попап = Попап();

            попап.ShowAsync("Внимание", "Не хватает валюты", null);

            Assert.IsTrue(попап.IsOpen, "попап показали, а он себя открытым не считает");
            Assert.AreEqual(LvnScreenDirector.Alert, Верхний,
                "вопрос на экране, а Режиссёр про него не знает — «назад» закроет то, " +
                "что стоит под вопросом, и игрок ответит на него не глядя");
            Assert.IsTrue(LvnScreenDirector.Current.AnyOpen);
        }

        // Живой путь: в магазине не хватило валюты, поверх него встал вопрос
        // «пополнить?». Верхним обязан стать вопрос, а не магазин.
        [Test]
        public void АлертВстаётПоверхОткрытойМодалиОболочки()
        {
            LvnScreenDirector.Current.Open(LvnScreenDirector.ShellModal);
            var попап = Попап();

            попап.ShowAsync("Не хватает", "Пополнить?", null);

            Assert.AreEqual(LvnScreenDirector.Alert, Верхний,
                "магазин остался верхним под заданным поверх него вопросом");
        }

        // ── уход снимает поверхность ────────────────────────────────────────

        [Test]
        public void УходСнимаетПоверхностьАлерта()
        {
            var попап = Попап();
            попап.ShowAsync("Внимание", "Текст", null);

            попап.Hide();

            Assert.IsFalse(попап.IsOpen, "попап убрали, а он считает себя открытым");
            Assert.IsFalse(LvnScreenDirector.Current.IsOpen(LvnScreenDirector.Alert),
                "вопроса на экране нет, а у Режиссёра он всё ещё наверху — " +
                "«назад» перестанет работать вовсе, потому что закрывать он будет призрак");
            Assert.IsFalse(LvnScreenDirector.Current.AnyOpen);
            Assert.AreEqual(DisplayStyle.None, попап.style.display.value);
        }

        // Снимается СВОЯ поверхность, а не верхняя: под вопросом остаётся
        // открытый магазин, и ответ на вопрос обязан вернуть игрока в него.
        [Test]
        public void УходАлертаНеУноситЧужуюПоверхность()
        {
            LvnScreenDirector.Current.Open(LvnScreenDirector.ShellModal);
            var попап = Попап();
            попап.ShowAsync("Не хватает", "Пополнить?", null);

            попап.Hide();

            Assert.AreEqual(LvnScreenDirector.ShellModal, Верхний,
                "ответили на вопрос — и магазин под ним тоже закрылся: " +
                "игрок вылетел из магазина, ничего для этого не сделав");
        }

        // Уход зовётся на каждой уборке набора — то есть на любой навигации, и
        // почти всегда у экрана, который никто не открывал. Он не имеет права
        // оставить после себя поверхность, которой не было.
        [Test]
        public void УходСНеОткрытогоАлертаПоверхностиНеОставляет()
        {
            var попап = Попап();

            попап.Hide();

            Assert.IsFalse(LvnScreenDirector.Current.IsOpen(LvnScreenDirector.Alert),
                "закрытый попап объявил о себе Режиссёру — на экране ничего нет, " +
                "а «назад» уже занят несуществующим вопросом");
            Assert.IsFalse(LvnScreenDirector.Current.AnyOpen);
        }

        [Test]
        public void ПовторныйУходПоверхностиНеВоскрешает()
        {
            var попап = Попап();
            попап.ShowAsync("Внимание", "Текст", null);
            попап.Hide();

            Assert.DoesNotThrow(() => попап.Hide());
            Assert.IsFalse(LvnScreenDirector.Current.AnyOpen, "второй уход вернул поверхность на экран");
        }

        // Попап один на всё приложение, и второй вопрос его ПЕРЕЗАНИМАЕТ, а не
        // добавляет. Поверхность при этом одна: иначе одного ухода не хватило
        // бы, чтобы её снять, и «назад» остался бы занят навсегда.
        [Test]
        public void ВторойВопросНеДобавляетВторойПоверхности()
        {
            var попап = Попап();
            попап.ShowAsync("Первый", "Текст", null);

            попап.ShowAsync("Второй", "Текст", null);
            попап.Hide();

            Assert.IsFalse(LvnScreenDirector.Current.IsOpen(LvnScreenDirector.Alert),
                "второй вопрос лёг на стопку вторым слоем — одного ухода не хватило снять оба, " +
                "и «назад» навсегда занят вопросом, которого нет");
            Assert.IsFalse(LvnScreenDirector.Current.AnyOpen);
        }

        // ── и то же самое ЧЕРЕЗ НАБОР ЭКРАНОВ ───────────────────────────────

        // Уборку зовёт набор, и зовёт он её ЕГО ЖЕ уходом — попап помечен как
        // умеющий уходить сам. Погаси набор показ мимо экрана, и на экране
        // вопроса нет, а у Режиссёра он наверху.
        [Test]
        public void НаборЭкрановСнимаетПоверхностьАлерта()
        {
            var попап = Попап();
            попап.ShowAsync("Внимание", "Текст", null);

            LvnScreenSet.Shut(попап);

            Assert.IsFalse(LvnScreenDirector.Current.IsOpen(LvnScreenDirector.Alert),
                "набор погасил попапу показ мимо него — поверхность осталась висеть у Режиссёра");
            Assert.IsFalse(попап.IsOpen);
        }
    }
}
