using System;
using System.Collections.Generic;
using Lvn.Content;
using Lvn.UI.Screens;
using NUnit.Framework;

namespace Lvn.Tests
{
    /// <summary>
    /// ГЛАГОЛЫ ПРОГРЕССА — пять поводов сдвинуть точку продолжения и то, что у
    /// каждого из них СВОЁ.
    ///
    /// <para>Точку двигают пятеро: игрок выбрал главу в списке, попросил
    /// переиграть, глава началась сама, загрузилось сохранение, глава дочитана
    /// до конца. Общий <c>SetCurrent</c> закрыт наружу намеренно — по нему не
    /// видно, ЧТО произошло, а от этого зависят два решения: снимать ли
    /// ожидающий перезапуск и считать ли главу достигнутой. Пока эти решения
    /// принимали экраны, карусель делала одну пару своими руками, а карточка
    /// новеллы — другую.</para>
    ///
    /// <para>Здесь проверяется то, что обязано быть общим у ВСЕХ пяти
    /// (достигнутая глава не падает, точка переезжает, неполные данные не роняют
    /// игру), и то, чем они друг от друга отличаются. Отдельные правила метки и
    /// счёта пройденного стоят в <see cref="ProgressMarkerTests"/> и
    /// <see cref="ProgressCountTests"/>; здесь — сами глаголы.</para>
    /// </summary>
    public sealed class ProgressVerbsTests
    {
        private const string Id = "t_progress_verbs";
        private const string Сосед = "t_progress_verbs_сосед";

        private static LvnTitle Title(string id, params (string id, int number)[] chapters)
        {
            var list = new List<LvnChapter>();
            foreach (var (cid, number) in chapters) list.Add(new LvnChapter { id = cid, number = number });
            return new LvnTitle { id = id, seasons = new List<LvnSeason> { new LvnSeason { chapters = list } } };
        }

        private static LvnTitle Three() => Title(Id, ("c1", 1), ("c2", 2), ("c3", 3));

        private static LvnChapter Гл(LvnTitle t, int i) => t.ChaptersOf()[i];

        /// <summary>Четыре глагола, которым глава ОБЯЗАТЕЛЬНА: без неё
        /// переезжать некуда.</summary>
        private static readonly (string имя, Action<LvnTitle, LvnChapter> зови)[] Переезды =
        {
            ("выбрал главу в списке", LvnProgress.ChooseChapter),
            ("просит переиграть",     LvnProgress.RestartChapter),
            ("глава началась",        LvnProgress.StartChapter),
            ("загрузил сохранение",   LvnProgress.ResumeFromSave),
        };

        [SetUp]
        [TearDown]
        public void Clean()
        {
            LvnProgress.ResetTitle(Id);
            LvnProgress.ResetTitle(Сосед);
        }

        // ── общее у всех пяти ───────────────────────────────────────────────

        // «Достигнутая глава» — это ПОТОЛОК, а не текущая позиция: по ней
        // список глав решает, какие из них открыты. Дай любому из пяти
        // глаголов опустить её — и игрок, переигравший первую главу или
        // загрузивший старое сохранение, обнаружит, что поздние главы снова
        // заперты, а прохождение как будто отобрали. Возврат назад в новелле —
        // штатное действие, а не сброс прогресса.
        [Test]
        public void НиОдинГлаголНеОпускаетДостигнутуюГлаву()
        {
            var все = new List<(string, Action<LvnTitle, LvnChapter>)>(Переезды)
            {
                ("дочитал предыдущую", LvnProgress.FinishChapter),
            };

            foreach (var (имя, зови) in все)
            {
                LvnProgress.ResetTitle(Id);
                var t = Three();
                LvnProgress.StartChapter(t, Гл(t, 2));     // потолок = третья глава

                зови(t, Гл(t, 0));                          // а игрок вернулся в первую

                Assert.AreEqual(3, LvnProgress.Reached(t),
                    $"«{имя}» опустил достигнутую главу — поздние главы снова заперты в списке");
                Assert.AreEqual("c1", LvnProgress.Current(t).id,
                    $"«{имя}» не подвинул точку продолжения — «Продолжить» ведёт не туда, где игрок");
            }
        }

        // Зеркальное правило: движение ВПЕРЁД потолок поднимает, каким бы
        // глаголом оно ни пришло. Пропусти это у одного из пяти — и главы,
        // куда игрок уже попал, останутся закрытыми в списке: он их проходит,
        // а список показывает замок.
        [Test]
        public void ЛюбойГлаголВперёдПоднимаетДостигнутуюГлаву()
        {
            var все = new List<(string, Action<LvnTitle, LvnChapter>)>(Переезды)
            {
                ("дочитал предыдущую", LvnProgress.FinishChapter),
            };

            foreach (var (имя, зови) in все)
            {
                LvnProgress.ResetTitle(Id);
                var t = Three();
                LvnProgress.StartChapter(t, Гл(t, 0));

                зови(t, Гл(t, 2));

                Assert.AreEqual(3, LvnProgress.Reached(t),
                    $"«{имя}» не поднял потолок — глава, в которой игрок стоит, заперта в списке");
            }
        }

        // Глаголы зовут из игрового цикла и из экранов, где манифест мог не
        // доехать, а глава — не найтись. Ответ «ничего не меняю» тут законен,
        // падение — нет: это чёрный экран вместо новеллы. И, что важнее, ни
        // одного побочного действия: «выбрал главу» без главы не имеет права
        // отменить ожидающий перезапуск — иначе сорванная отрисовка списка
        // тихо превратит «переиграть» в «продолжить».
        [Test]
        public void ГлаголБезНовеллыИлиБезГлавыНичегоНеМеняет()
        {
            var t = Three();
            LvnProgress.RestartChapter(t, Гл(t, 1));       // точка на c2, ждёт перезапуск

            foreach (var (имя, зови) in Переезды)
            {
                Assert.DoesNotThrow(() => зови(t, null),
                    $"«{имя}» без главы уронил экран вместо честного «ничего не меняю»");
                Assert.DoesNotThrow(() => зови(null, Гл(t, 0)),
                    $"«{имя}» без новеллы уронил экран");
                Assert.DoesNotThrow(() => зови(null, null), $"«{имя}» без всего уронил экран");

                Assert.AreEqual("c2", LvnProgress.Current(t).id,
                    $"«{имя}» с пустыми данными всё-таки сдвинул точку продолжения");
                Assert.AreEqual("c2", LvnProgress.PendingRestart(Id),
                    $"«{имя}» с пустыми данными снял ожидающий перезапуск — глава сядет на чужие статы");
            }

            // У финала главы null — законный ответ «дальше глав нет», поэтому
            // ему проверяют только отсутствие новеллы.
            Assert.DoesNotThrow(() => LvnProgress.FinishChapter(null, Гл(t, 0)),
                "финал главы без новеллы уронил игровой цикл");
        }

        // ── чем глаголы отличаются друг от друга ────────────────────────────

        // ЗАГРУЗКА СОХРАНЕНИЯ — пятый повод сдвинуть точку, и до появления
        // глагола он единственный двигал её мимо остальных, прямым вызовом из
        // загрузчика. Игрок прыгает сохранением НАЗАД чаще, чем вперёд (хочет
        // переиграть развилку), и это не должно стоить ему открытых глав.
        [Test]
        public void ЗагрузкаСохраненияВедётТочкуЗаИгроком_ВОбеСтороны()
        {
            var t = Three();
            LvnProgress.StartChapter(t, Гл(t, 2));

            LvnProgress.ResumeFromSave(t, Гл(t, 0));
            Assert.AreEqual("c1", LvnProgress.Current(t).id,
                "загрузили сохранение первой главы, а «Продолжить» осталось на третьей");
            Assert.AreEqual(3, LvnProgress.Reached(t),
                "прыжок сохранением назад запер главы, до которых игрок уже дошёл");

            // Сохранение может приехать и из будущего — из облака, с другого
            // устройства: там игрок дальше, и список глав обязан это признать.
            LvnProgress.ResumeFromSave(t, Гл(t, 2));
            Assert.AreEqual(3, LvnProgress.Reached(t));
        }

        // Ожидающий перезапуск — одноразовый флаг «следующий вход в эту главу
        // начинается с её входного чекпойнта». Попроси переиграть другую главу,
        // не погасив первый флаг, — и он сработает на ЧУЖОЙ главе: игрок
        // выбрал третью, а её посадят на переменные второй.
        [Test]
        public void ВтораяПросьбаПереигратьПерецеливаетФлагАНеКопитЕго()
        {
            var t = Three();
            LvnProgress.RestartChapter(t, Гл(t, 1));
            LvnProgress.RestartChapter(t, Гл(t, 2));

            Assert.AreEqual("c3", LvnProgress.PendingRestart(Id),
                "перезапуск ждёт прежнюю главу — выбранную посадят на чужой чекпойнт");
            Assert.AreEqual("c3", LvnProgress.Current(t).id);
            Assert.IsTrue(LvnProgress.TakeRestart(Id, "c3"), "флаг не достался той главе, которую выбрали");
        }

        // Обратная сторона правила «сознательный выбор сильнее отложенного
        // перезапуска»: сам ВЫБОР главы в списке перезапуска не заводит. Заведи
        // его — и обычный переход по списку каждый раз откатывал бы переменные
        // ко входу в главу, то есть тихо стирал бы всё, что игрок набрал после.
        [Test]
        public void ВыборГлавыВСпискеПерезапускаНеПросит()
        {
            var t = Three();
            LvnProgress.ChooseChapter(t, Гл(t, 1));

            Assert.AreEqual("", LvnProgress.PendingRestart(Id),
                "переход по списку глав объявлен перезапуском — набранное после входа откатится");
            Assert.AreEqual("c2", LvnProgress.Current(t).id);
        }

        // ГЛАВА НАЧАЛАСЬ САМА — обычное продолжение чтения, и оно тоже не
        // перезапуск: игровой цикл двигает точку на каждом переходе, и заводи
        // он при этом флаг — каждая следующая глава садилась бы на чекпойнт
        // вместо накопленного прохождения.
        [Test]
        public void НачаласьГлава_ЭтоНеПерезапуск()
        {
            var t = Three();
            LvnProgress.StartChapter(t, Гл(t, 1));
            LvnProgress.FinishChapter(t, Гл(t, 2));

            Assert.AreEqual("", LvnProgress.PendingRestart(Id),
                "штатный переход к следующей главе объявлен перезапуском");
        }

        // ── пройдена или нет ────────────────────────────────────────────────

        // «Пройдена» стоит на ДВУХ ногах: дошли до последней главы И точки
        // продолжения больше нет. Здесь проверяется вторая нога: игрок дошёл до
        // финальной главы, но стоит В НЕЙ — концовку он ещё не видел. Спроси
        // только про достигнутую — и карточка объявит новеллу пройденной за
        // главу до конца, а витрина предложит «пройти заново» тому, кто её не
        // дочитал.
        [Test]
        public void СтояВПоследнейГлавеНовеллаЕщёНеПройдена()
        {
            var t = Three();
            LvnProgress.StartChapter(t, Гл(t, 2));

            Assert.IsFalse(LvnProgress.Finished(t),
                "новелла объявлена пройденной, пока игрок стоит в последней главе");
            Assert.Less(LvnProgress.Fraction(t), 1f,
                "полоса заполнилась целиком, а концовки игрок ещё не видел");
        }

        // А это первая нога. Точку снимает финал главы, у которой нет
        // следующей, — и такое случается не только в конце: переимпорт вырезал
        // главу, ветка кончилась раньше. Спроси только про снятую точку — и
        // новелла объявится пройденной на середине: галочка «пройдено» на
        // карточке, полная полоса и предложение начать заново тому, кто прочёл
        // треть.
        [Test]
        public void СнятаяТочкаБезПоследнейГлавыПройденнойНовеллуНеДелает()
        {
            var t = Three();
            LvnProgress.StartChapter(t, Гл(t, 0));
            LvnProgress.FinishChapter(t, null);

            Assert.IsNull(LvnProgress.Current(t), "финал главы обязан снять точку продолжения");
            Assert.IsFalse(LvnProgress.Finished(t),
                "новелла объявлена пройденной после первой же главы");
            Assert.Less(LvnProgress.Fraction(t), 1f,
                "полоса на карточке полна, а прочитана одна глава из трёх");
        }

        // НОМЕРА ГЛАВ — НЕ ПОРЯДКОВЫЕ НОМЕРА. У импортированных новелл они идут
        // не с единицы и не подряд, поэтому пройденное считают ПО СПИСКУ.
        // Посчитай по номеру («достиг десятой — значит девять позади») — и
        // полоса на карточке упрётся в край на второй главе из трёх: игрок
        // читает её как сведения о себе, а она врёт в его пользу и обесценивает
        // остаток новеллы.
        [Test]
        public void ДоляСчитаетсяПоСпискуГлавАНеПоИхНомерам()
        {
            var t = Title(Id, ("пролог", 0), ("середина", 10), ("финал", 20));
            LvnProgress.StartChapter(t, Гл(t, 1));         // игрок в «середине», номер 10

            Assert.AreEqual(1, LvnProgress.Done(t),
                "пройденные посчитаны по номеру главы, а не по их списку");
            Assert.AreEqual(1f / 3f, LvnProgress.Fraction(t), 0.001f,
                "полоса на карточке показывает не долю прочитанного, а номер главы");
        }

        // Манифест живой: переимпорт вырезает главы, и достигнутая может
        // оказаться больше всего, что осталось в списке. Доля — это доля, у неё
        // есть край: пусти счёт за него — и полоса нарисуется длиннее дорожки,
        // а число пройденных глав окажется больше, чем глав вообще.
        [Test]
        public void СжавшийсяМанифестНеПереполняетПолосу()
        {
            var t = Three();
            LvnProgress.RestoreMarker(Id, "c3", number: 3, reached: 99);

            Assert.LessOrEqual(LvnProgress.Done(t), t.ChaptersOf().Count,
                "пройденных глав насчитали больше, чем их есть");
            Assert.LessOrEqual(LvnProgress.Fraction(t), 1f, "полоса вылезла за свой край");
            Assert.GreaterOrEqual(LvnProgress.Fraction(t), 0f, "полоса ушла в минус");
        }

        // НОЛЬ — ЗАКОННЫЙ НОМЕР ГЛАВЫ, и на нём начинается воронка приложения.
        // Пока потолок и «ничего не начинали» жили одним числом, потолок
        // нулевой главы не записывался вовсе («ноль не больше нуля»), и
        // новелла, целиком состоящая из пилота, НЕ становилась пройденной
        // никогда: игрок дочитал её до конца, а карточка каждый раз показывает
        // пустую полосу и не ставит «пройдено».
        [Test]
        public void ПройденнаяГлаваНольСчитаетсяПройденной()
        {
            var пилот = Title(Id, ("пролог", 0));
            LvnProgress.StartChapter(пилот, Гл(пилот, 0));
            LvnProgress.FinishChapter(пилот, null);

            Assert.IsTrue(LvnProgress.Finished(пилот),
                "новелла из одной главы под номером 0 дочитана до конца, а «пройдено» не встало");
            Assert.AreEqual(1, LvnProgress.Done(пилот), "дочитанная нулевая глава не засчитана");
            Assert.AreEqual(1f, LvnProgress.Fraction(пилот), 0.001f,
                "полоса пустая у полностью прочитанной новеллы");
        }

        // Обратная сторона того же: «начинали» и «докуда дошли» — РАЗНЫЕ
        // вопросы, и на чистом устройстве первый обязан отвечать «нет». Слей их
        // обратно в одно число — и непочатая новелла станет неотличима от той,
        // где игрок стоит в нулевой главе: воронка либо не включится ни разу,
        // либо включится у того, кто её уже прошёл.
        [Test]
        public void НачиналиЛи_ИДокудаДошли_ЭтоРазныеВопросы()
        {
            var пилот = Title(Id, ("пролог", 0), ("первая", 1));

            Assert.IsFalse(LvnProgress.HasReached(пилот),
                "на чистом устройстве новелла объявлена начатой");
            Assert.AreEqual(0, LvnProgress.Reached(пилот));

            LvnProgress.StartChapter(пилот, Гл(пилот, 0));

            Assert.IsTrue(LvnProgress.HasReached(пилот),
                "игрок стоит в нулевой главе, а новелла считается непочатой");
            Assert.AreEqual(0, LvnProgress.Reached(пилот), "потолок — по-прежнему нулевая глава");
            Assert.IsFalse(LvnProgress.Finished(пилот),
                "новелла объявлена пройденной на её первой же главе");
        }

        // ── прогресс говорит о себе сам ─────────────────────────────────────

        // Точка продолжения живёт в ТРЁХ местах: книжка устройства, облачный
        // свёрток и серверные переменные. Держать их в согласии полагалось
        // звонящему — и экраны этого не делали: игрок выбирал главу в списке,
        // приложение закрывали, а облачная копия оставалась со старой точкой.
        // Восстановление возвращало его туда, откуда он уже ушёл. Поэтому о
        // ходе говорит сам дом, и молчать не вправе НИ ОДИН глагол.
        [Test]
        public void КаждыйХодПрогрессаСлышенСнаружи()
        {
            var t = Three();
            int ходов = 0;
            System.Action слушатель = () => ходов++;
            LvnProgress.Moved += слушатель;
            try
            {
                foreach (var (имя, зови) in Переезды)
                {
                    ходов = 0;
                    зови(t, Гл(t, 1));
                    Assert.GreaterOrEqual(ходов, 1,
                        $"«{имя}» сдвинул прогресс молча — облачная копия останется со старой точкой");
                }

                ходов = 0;
                LvnProgress.FinishChapter(t, null);
                Assert.GreaterOrEqual(ходов, 1, "финал новеллы прошёл молча");

                ходов = 0;
                LvnProgress.ResetTitle(Id);
                Assert.GreaterOrEqual(ходов, 1,
                    "«начать заново» прошло молча — свёрток вернёт стёртое прохождение");
            }
            finally { LvnProgress.Moved -= слушатель; }
        }

        // А ВОССТАНОВЛЕНИЕ ИЗ СВЁРТКА МОЛЧИТ НАМЕРЕННО: оно и есть тот, кто
        // раскладывает свёрток обратно. Заговори оно — и раскладка тут же
        // попросила бы сложить свёрток заново, по разу на каждую новеллу
        // каталога, прямо на подъёме приложения.
        [Test]
        public void ВосстановлениеИзВолтаОСебеНеОбъявляет()
        {
            int ходов = 0;
            System.Action слушатель = () => ходов++;
            LvnProgress.Moved += слушатель;
            try
            {
                LvnProgress.RestoreMarker(Id, "c2", number: 2, reached: 2);
                Assert.AreEqual(0, ходов,
                    "раскладка свёртка объявила ход — подъём приложения начнёт складывать его обратно");
            }
            finally { LvnProgress.Moved -= слушатель; }
        }

        // Слушатель хода — чужой код (сведение с сервером, а оно ходит в сеть).
        // Урони он ход прогресса — и запись, которая УЖЕ сделана, останется
        // недосказанной: глава началась, а вызвавший её игровой цикл получил
        // исключение вместо продолжения.
        [Test]
        public void УпавшийСлушательНеЛомаетХодПрогресса()
        {
            var t = Three();
            System.Action падучий = () => throw new System.InvalidOperationException("нарочно");
            LvnProgress.Moved += падучий;
            try
            {
                Assert.DoesNotThrow(() => LvnProgress.StartChapter(t, Гл(t, 1)),
                    "упавший слушатель уронил игровой цикл на переходе к главе");
                Assert.AreEqual("c2", LvnProgress.Current(t).id,
                    "ход прогресса не записан — «Продолжить» поведёт в прежнюю главу");
            }
            finally { LvnProgress.Moved -= падучий; }
        }

        // ── волт и сброс ────────────────────────────────────────────────────

        // Бэкап прогресса помнит две разные вещи: ГДЕ игрок стоит и ДОКУДА он
        // дошёл. У пройденной новеллы первого нет вовсе — точку снял финал.
        // Восстанови «где стоит» из пустоты — и пройденная новелла откроется
        // «в середине»; не восстанови «докуда дошёл» — и список глав захлопнется
        // на человеке, который прочёл всё.
        [Test]
        public void ВолтБезПозицииВосстанавливаетТолькоПотолок()
        {
            var t = Three();

            LvnProgress.RestoreMarker(Id, null, number: 0, reached: 3);

            Assert.AreEqual(3, LvnProgress.Reached(t),
                "бэкап пройденной новеллы не вернул открытые главы");
            Assert.IsNull(LvnProgress.Current(t),
                "бэкап выдумал позицию там, где её не было, — пройденная новелла откроется с середины");
        }

        // «Начать заново» нажимают на КАРТОЧКЕ ОДНОЙ новеллы. Сотри лишнее — и
        // игрок, решивший перечитать первую историю, потеряет прохождение
        // второй, о которой его никто не спрашивал.
        [Test]
        public void СбросНовеллыНеТрогаетСоседнюю()
        {
            var t = Three();
            var сосед = Title(Сосед, ("s1", 1), ("s2", 2));
            LvnProgress.StartChapter(t, Гл(t, 1));
            LvnProgress.StartChapter(сосед, Гл(сосед, 1));
            LvnProgress.RequestRestart(Сосед, "s2");

            LvnProgress.ResetTitle(Id);

            Assert.IsNull(LvnProgress.Current(t), "своя новелла не сброшена");
            Assert.AreEqual("s2", LvnProgress.Current(сосед).id,
                "сброс одной новеллы отобрал прохождение соседней");
            Assert.AreEqual(2, LvnProgress.Reached(сосед), "и запер её главы");
            Assert.AreEqual("s2", LvnProgress.PendingRestart(Сосед),
                "и погасил её ожидающий перезапуск");
        }

        // Сброс зовут из карточки, куда идентификатор новеллы приезжает из
        // манифеста, — а тот бывает недогружен. Падение здесь означает, что
        // кнопка «начать заново» роняет экран.
        [Test]
        public void СбросБезИмениНовеллыНеРоняетЭкран()
        {
            Assert.DoesNotThrow(() => LvnProgress.ResetTitle(null));
            Assert.DoesNotThrow(() => LvnProgress.ResetTitle(""));
        }
    }
