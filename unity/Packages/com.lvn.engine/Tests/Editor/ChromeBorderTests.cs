using Lvn.UI;
using NUnit.Framework;
using UnityEngine;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// КРОМКА ТЕМЫ ВПОЛСИЛЫ — <see cref="LvnChrome.BorderSoft"/> и
    /// <see cref="LvnChrome.BorderTone"/>.
    ///
    /// <para>«Обвести доп-цветом темы, но потише» — самая частая огранка
    /// оболочки: карточки профиля, строки списков, плитки лавки. Записывалась
    /// она восемь раз одинаковой пятёрней — взять токен, разобрать на
    /// составляющие, собрать обратно с умноженной прозрачностью, — и в этой
    /// пятёрне терялось единственное, что различает места: САМА ДОЛЯ. Она и
    /// разъехалась молча: одна и та же роль обведена то на 0.55, то на 0.64,
    /// то на 0.7.</para>
    ///
    /// <para>Здесь закрепляется то, ради чего дом заводился: доля УМНОЖАЕТ
    /// прозрачность темы, а не подменяет её. Подмена выглядит рабочей на всех
    /// сегодняшних темах (у них рамка непрозрачная или почти) и ломается ровно
    /// там, где это замечает игрок: на теме с прозрачной рамкой, которую
    /// выбирает новелла, экран получил бы обводку, которой тема не просила.</para>
    /// </summary>
    public sealed class ChromeBorderTests
    {
        private readonly ОдолженнаяТема _тема = new ОдолженнаяТема();

        [SetUp]
        public void Запомнить() => _тема.Взять();

        [TearDown]
        public void Вернуть() => _тема.Вернуть();

        // Полная сила — это РОВНО кромка темы, без поправок «на глаз». Разойдись
        // она с темой хоть на волос — и элемент, обведённый «во всю силу», уже
        // не совпадёт с соседом, обведённым штатной рамкой: два одинаковых по
        // замыслу края с разной плотностью в одном экране.
        [Test]
        public void ПолнаяСилаДаётРовноКромкуТемы()
        {
            foreach (var тема in new[] { "midnight", "cyber", "romance" })
            {
                LvnTheme.Use(тема);
                Assert.AreEqual(LvnTokens.Border, LvnChrome.BorderTone(1f),
                    $"кромка во всю силу разошлась с рамкой темы «{тема}»");
            }
        }

        // ГЛАВНОЕ ПРАВИЛО: доля умножает прозрачность темы, а не заменяет её.
        // Тема вправе сказать «рамки не рисовать» — и экран, попросивший
        // «потише», обязан остаться без рамки, а не получить её на 70%.
        // Подмена ведёт себя правильно на всех нынешних темах и врёт только на
        // той, ради которой правило и записано.
        [Test]
        public void ДоляУмножаетПрозрачностьТемы_АНеЗаменяетЕё()
        {
            LvnTheme.Use("cyber");
            var темы = LvnTokens.Border;

            var вполсилы = LvnChrome.BorderTone(0.5f);
            Assert.AreEqual(темы.a * 0.5f, вполсилы.a, 1e-4f,
                "доля не умножила прозрачность темы — кромка перестала слушаться темы");
            Assert.AreEqual(темы.r, вполсилы.r, 1e-4f, "кромка вполсилы поменяла цвет темы");
            Assert.AreEqual(темы.g, вполсилы.g, 1e-4f, "кромка вполсилы поменяла цвет темы");
            Assert.AreEqual(темы.b, вполсилы.b, 1e-4f, "кромка вполсилы поменяла цвет темы");

            // Тема БЕЗ рамки — тот единственный случай, где умножение и подмена
            // расходятся видимо.
            var безРамки = LvnTheme.ByName("midnight");
            безРамки.Border = new Color(безРамки.Border.r, безРамки.Border.g, безРамки.Border.b, 0f);
            LvnTheme.Use(безРамки);

            Assert.AreEqual(0f, LvnChrome.BorderTone(0.7f).a, 1e-4f,
                "тема просила не рисовать рамку, а экран получил обводку на 70%");
        }

        // Ноль — это «не обводить», и он обязан работать: экран гасит кромку
        // выключенного элемента тем же вызовом, что и зажигает.
        [Test]
        public void НулеваяДоляГаситКромкуСовсем()
        {
            LvnTheme.Use("cyber");
            Assert.AreEqual(0f, LvnChrome.BorderTone(0f).a, 1e-4f,
                "погашенная кромка всё равно видна");
        }

        // Тот же цвет отдельным вызовом — не удобство, а обязательство: у
        // выделенной карточки верх акцентный, а остальные три стороны красят
        // руками. Разойдись два вызова — и у карточки будет три «тихих» стороны
        // одной плотности и одна другой, чего никто не заказывал.
        [Test]
        public void ОтдельныйЦветИЦелаяОбводкаГоворятОдноИТоЖе()
        {
            LvnTheme.Use("cyber");
            var el = new VisualElement();

            LvnChrome.BorderSoft(el, 0.64f);

            var тон = LvnChrome.BorderTone(0.64f);
            Assert.AreEqual(тон, el.style.borderTopColor.value, "обводка и отдельный тон разошлись");
            Assert.AreEqual(тон, el.style.borderBottomColor.value, "обводка и отдельный тон разошлись");
            Assert.AreEqual(тон, el.style.borderLeftColor.value, "обводка и отдельный тон разошлись");
            Assert.AreEqual(тон, el.style.borderRightColor.value, "обводка и отдельный тон разошлись");
        }

        // Толщина по умолчанию — ОДИН пиксель, и одинаковая со всех четырёх
        // сторон: тихая кромка тем и тиха, что её видно как линию, а не как
        // раму. Разъедься стороны — и карточка станет выглядеть перекошенной,
        // хотя ни один её угол не сдвинулся.
        [Test]
        public void ТолщинаТихойКромкиОднаПиксельнаяСоВсехСторон()
        {
            LvnTheme.Use("cyber");
            var el = new VisualElement();

            LvnChrome.BorderSoft(el, 0.7f);

            Assert.AreEqual(1f, el.style.borderTopWidth.value, 1e-4f, "тихая кромка потолстела");
            Assert.AreEqual(1f, el.style.borderBottomWidth.value, 1e-4f, "стороны кромки разной толщины");
            Assert.AreEqual(1f, el.style.borderLeftWidth.value, 1e-4f, "стороны кромки разной толщины");
            Assert.AreEqual(1f, el.style.borderRightWidth.value, 1e-4f, "стороны кромки разной толщины");

            // Толщину можно назвать — там, где кромка нарочно заметнее.
            var толстая = new VisualElement();
            LvnChrome.BorderSoft(толстая, 0.7f, 2f);
            Assert.AreEqual(2f, толстая.style.borderTopWidth.value, 1e-4f,
                "названную толщину не услышали");
        }

        // Огранку зовут при сборке экрана, где элемент приезжает из поиска по
        // дереву и вполне может не найтись. Дом обязан промолчать: обводка —
        // украшение, и ронять из-за неё весь экран нельзя.
        [Test]
        public void ПустойЭлементКромкуНеРоняет()
        {
            Assert.DoesNotThrow(() => LvnChrome.BorderSoft(null, 0.64f));
            Assert.DoesNotThrow(() => LvnChrome.BorderSoft(null, 0.64f, 2f));
        }

        // И то, ради чего цвет вообще берут у темы: сменилась тема — сменилась
        // кромка. Зашей её числом (а именно так она и была записана восемь раз)
        // — и смена темы перекрасит экран наполовину: фон новый, обводки
        // старые.
        [Test]
        public void СменаТемыМеняетКромку()
        {
            LvnTheme.Use("midnight");
            var полночь = LvnChrome.BorderTone(0.64f);

            LvnTheme.Use("cyber");
            var кибер = LvnChrome.BorderTone(0.64f);

            Assert.AreNotEqual(полночь, кибер,
                "кромка не заметила смены темы — экран перекрасился наполовину");
        }
    }
}
