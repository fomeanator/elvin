using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using Lvn.Content;
using Lvn.UI;
using Lvn.UI.Screens;
using NUnit.Framework;
using UnityEngine;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// НАБОР ЭКРАНОВ ВЕДЁТ СЕБЯ САМ.
    ///
    /// <para>Перечень экранов оболочки был написан от руки в двух местах сразу:
    /// в «убрать всё» и в «спрятать сразу после создания». Дописать новый экран
    /// надо было в оба, и трижды не дописали — таблица лидеров, экран конца
    /// главы и гардеробная вкладка не попали в уборку вовсе. Игрок видел это
    /// как экран, оставшийся поверх другого.</para>
    ///
    /// <para>Здесь закреплены правила ОДНОЙ двери: кто вошёл — тот уже закрыт,
    /// а закрывается он ТЕМ СПОСОБОМ, который есть у него самого. Второе
    /// важнее первого: у экранов оболочки <c>Hide()</c> делает больше, чем
    /// гасит показ, — возвращает непрозрачность (иначе экран всплывёт
    /// полупрозрачным), закрывает просмотрщик картинки, снимает ожидание
    /// ответа. Набор обязан отдать уход экрану, а не гасить его показ мимо
    /// него.</para>
    /// </summary>
    public sealed class ScreenSetTests
    {
        /// <summary>Экран, чей уход — НЕ «выключить показ». Он нарочно не
        /// трогает display: если набор закроет его сам, а не его же способом,
        /// проверка это увидит.</summary>
        private sealed class ЭкранСоСвоимУходом : VisualElement, ILvnHides
        {
            public int Уходов;
            public void Hide() => Уходов++;
        }

        private static VisualElement Показанный()
        {
            var el = new VisualElement();
            el.style.display = DisplayStyle.Flex;
            return el;
        }

        private static DisplayStyle Показ(VisualElement el) => el.style.display.value;

        // ── ПРАВИЛО УХОДА ───────────────────────────────────────────────────

        // У кого своего ухода нет — тому и гасят показ. Это вся его жизнь на
        // экране, и трогать больше нечего.
        [Test]
        public void ЭлементБезСвоегоУходаПростоГаснет()
        {
            var el = Показанный();

            LvnScreenSet.Shut(el);

            Assert.AreEqual(DisplayStyle.None, Показ(el),
                "обычный элемент обязан просто исчезнуть с раскладки");
        }

        // СУТЬ ВСЕГО ДОМА. У экрана оболочки уход свой, и он делает больше, чем
        // гасит показ: возвращает непрозрачность, закрывает просмотрщик, снимает
        // ожидание ответа. Погаси набор показ напрямую — экран исчез бы с виду,
        // но остался бы открытым внутри: следующий показ всплыл бы прозрачным, а
        // тот, кто ждал ответа, ждал бы вечно.
        [Test]
        public void УходЭкранаСоСвоимHideОтдаётсяЕмуЖе()
        {
            var экран = new ЭкранСоСвоимУходом();
            экран.style.display = DisplayStyle.Flex;

            LvnScreenSet.Shut(экран);

            Assert.AreEqual(1, экран.Уходов,
                "у экрана есть свой уход, а его закрыли мимо — прозрачность, " +
                "просмотрщик и ожидание ответа остались как были");
            Assert.AreEqual(DisplayStyle.Flex, Показ(экран),
                "набор погасил показ САМ вместо того, чтобы отдать уход экрану");
        }

        [Test]
        public void УходПустотыНикогоНеРоняет()
        {
            Assert.DoesNotThrow(() => LvnScreenSet.Shut(null),
                "экран, которого новелла не заказала (авторизация, конец главы), — обычное дело");
        }

        // ── ДВЕРЬ ОДНА: ОНА ЖЕ ЗАПИСЫВАЕТ И ЗАКРЫВАЕТ ───────────────────────

        // Экран поднимается СКРЫТЫМ, показывает его тот, кто его открывает.
        // Пока «внести» и «спрятать» были двумя действиями, второе забывали — и
        // экран стоял поверх всего с первого кадра приложения.
        [Test]
        public void ВходВНаборСразуЗакрываетВошедшего()
        {
            var набор = new LvnScreenSet();
            var простой = Показанный();
            var свой = new ЭкранСоСвоимУходом();
            свой.style.display = DisplayStyle.Flex;

            Assert.AreSame(простой, набор.Add(простой),
                "дверь обязана вернуть вошедшего — иначе её не поставить в одну строку с созданием");
            набор.Add(свой);

            Assert.AreEqual(2, набор.Count);
            Assert.IsTrue(набор.Has(простой));
            Assert.IsTrue(набор.Has(свой));
            Assert.AreEqual(DisplayStyle.None, Показ(простой),
                "вошедший остался на виду — он покажется поверх всего с первого кадра");
            Assert.AreEqual(1, свой.Уходов,
                "вошедшего закрыли не его способом — правило входа и правило уборки разъехались");
        }

        // Половина экранов необязательна (авторизация, конец главы), и место
        // вызова спокойно передаёт сюда пустоту. Она не экран: ни в набор, ни в
        // счёт.
        [Test]
        public void ПустотаВНаборНеВходит()
        {
            var набор = new LvnScreenSet();

            Assert.IsNull(набор.Add<VisualElement>(null));

            Assert.AreEqual(0, набор.Count, "пустота попала в набор и будет закрываться каждую уборку");
            Assert.IsFalse(набор.Has(null));
            Assert.DoesNotThrow(() => набор.HideAll());
        }

        [Test]
        public void ЧужойЭкранВНабореНеЧислится()
        {
            var набор = new LvnScreenSet();
            набор.Add(Показанный());

            Assert.IsFalse(набор.Has(Показанный()),
                "набор признал своим экран, которого в него не вносили");
        }

        // ── УБОРКА ──────────────────────────────────────────────────────────

        // ТО, РАДИ ЧЕГО НАБОР И ЗАВЕЛИ. Ручной перечень отставал от жизни:
        // экран, дописанный позже, в уборку не попадал и оставался на виду
        // поверх следующего. Набор обязан пройти ВЕСЬ себя, включая тех, кто
        // вошёл уже после первой уборки.
        [Test]
        public void УборкаПроходитВесьНаборВключаяВнесённыхПозже()
        {
            var набор = new LvnScreenSet();
            var ранний = Показанный();
            набор.Add(ранний);
            набор.HideAll();

            var поздний = Показанный();   // дописан ПОСЛЕ первой уборки
            набор.Add(поздний);
            ранний.style.display = DisplayStyle.Flex;
            поздний.style.display = DisplayStyle.Flex;

            набор.HideAll();

            Assert.AreEqual(DisplayStyle.None, Показ(ранний), "уборка потеряла экран, внесённый первым");
            Assert.AreEqual(DisplayStyle.None, Показ(поздний),
                "уборка не заметила экрана, внесённого позже, — ровно так теряли " +
                "таблицу лидеров, конец главы и гардероб");
            Assert.AreEqual(2, набор.Count);
        }

        // Уборка зовётся на каждой навигации, и «убрать уже убранное» обязано
        // быть будничным делом, а не вторым, другим состоянием.
        [Test]
        public void ПовторнаяУборкаНичегоНеМеняет()
        {
            var набор = new LvnScreenSet();
            var простой = Показанный();
            var свой = new ЭкранСоСвоимУходом();
            набор.Add(простой);
            набор.Add(свой);

            набор.HideAll();
            var послеПервой = Показ(простой);

            Assert.DoesNotThrow(() => набор.HideAll());

            Assert.AreEqual(DisplayStyle.None, послеПервой);
            Assert.AreEqual(послеПервой, Показ(простой),
                "вторая уборка привела экран в другое состояние, чем первая");
            Assert.AreEqual(2, набор.Count, "уборка изменила состав набора");
        }

        // ── НАБОР ОБОЛОЧКИ: НАКРЫТЫ ЛИ ИМ ВСЕ ЭКРАНЫ ────────────────────────

        private readonly List<GameObject> _мусор = new List<GameObject>();
        private string _темаБыла;

        [SetUp]
        public void Запомнить() => _темаБыла = LvnTheme.Current.Name;

        [TearDown]
        public void Прибрать()
        {
            LvnTheme.Use(_темаБыла);   // хаб выбирает тему на сборке — вернём чужим тестам их
            foreach (var go in _мусор) if (go != null) UnityEngine.Object.DestroyImmediate(go);
            _мусор.Clear();
        }

        /// <summary>Оболочка со ВСЕМИ экранами: авторизацию и конец главы
        /// заказывает новелла, и без этих двух блоков их просто не создадут.</summary>
        private NovelShell Оболочка(ILvnAssets assets)
        {
            var shell = NovelShell.Create();
            _мусор.Add(shell.gameObject);
            shell.Build(new LvnManifest
            {
                ui = new LvnUiConfig
                {
                    auth = new AuthConfig(),
                    chapter_end = new ChapterEndConfig(),
                },
            }, assets);
            return shell;
        }

        /// <summary>Экраны оболочки ПОИМЁННО — канон этой проверки. Список
        /// здесь затем, чтобы новый экран нельзя было завести молча: он либо
        /// попадёт в набор и в этот перечень, либо проверка скажет, что кого-то
        /// не назвали.</summary>
        private static (string имя, VisualElement экран)[] Экраны(NovelShell об) => new (string, VisualElement)[]
        {
            ("Boot", об.Boot), ("Carousel", об.Carousel), ("Hub", об.Hub),
            ("Loading", об.Loading), ("Title", об.Title), ("Hud", об.Hud),
            ("Auth", об.Auth), ("Settings", об.Settings), ("Detail", об.Detail),
            ("Gallery", об.Gallery), ("Profile", об.Profile), ("Daily", об.Daily),
            ("Leaderboard", об.Leaderboard), ("SkinShop", об.SkinShop),
            ("PackShop", об.PackShop), ("PackShopModal", об.PackShopModal),
            ("Popup", об.Popup), ("WardrobeTab", об.WardrobeTab),
            ("ChapterEnd", об.ChapterEnd),
        };

        private static LvnScreenSet НаборОболочки(NovelShell об)
        {
            var поле = typeof(NovelShell).GetField("_screens", BindingFlags.Instance | BindingFlags.NonPublic);
            Assert.NotNull(поле, "набор экранов у оболочки переименован — проверка ослепла");
            var набор = поле.GetValue(об) as LvnScreenSet;
            Assert.NotNull(набор, "оболочка держит экраны не набором — единого правила уборки больше нет");
            return набор;
        }

        // Приложение поднимается НА ЧИСТОМ: собрали дерево — на экране ничего.
        // Показывает экран тот, кто его открывает; экран, забывший спрятаться
        // при рождении, стоит поверх всего с первого кадра — и это не «мелькнуло
        // при старте», а живой экран, ловящий нажатия.
        [Test]
        public void ПослеСборкиНиОдинЭкранНеВиден()
        {
            var об = Оболочка(new TestAssets());

            foreach (var (имя, экран) in Экраны(об))
            {
                Assert.NotNull(экран, $"экран {имя} не собран — правило проверять не на чем");
                Assert.AreEqual(DisplayStyle.None, Показ(экран),
                    $"экран {имя} поднялся видимым — он встанет поверх меню с первого кадра " +
                    "и будет ловить нажатия, предназначенные не ему");
            }
        }

        // Набор — ЕДИНСТВЕННЫЙ перечень экранов оболочки. Прежде их было два, и
        // они расходились: экран есть в дереве, но не в уборке, — значит,
        // остаётся на виду поверх следующего.
        [Test]
        public void НаборНакрываетКаждыйЭкранОболочки()
        {
            var об = Оболочка(new TestAssets());
            var набор = НаборОболочки(об);
            var экраны = Экраны(об);

            foreach (var (имя, экран) in экраны)
                Assert.IsTrue(набор.Has(экран),
                    $"экран {имя} не в наборе — «убрать всё» его пропустит, и он останется поверх следующего");

            Assert.AreEqual(экраны.Length, набор.Count,
                "в наборе есть экран, которого нет в перечне выше. Это не ошибка набора — " +
                "это новый экран, который надо назвать здесь: перечень и есть канон того, " +
                "какие экраны у оболочки бывают");
        }

        // ОСНА́СТКА ПЕРЕЖИВАЕТ «УБРАТЬ ВСЁ». Верхний бар — единый верх
        // приложения, кружок загрузок показывает качанное из любого места, даже
        // из-под алерта (живой репорт «закрыл — и остановилось»: батч жил, но
        // был невидим). Попади они в набор — уборка гасила бы их вместе с
        // экранами.
        [Test]
        public void ОснасткаВНаборНеВходитИУборкуПереживает()
        {
            var кэш = Path.Combine(Path.GetTempPath(), "lvn-screenset-" + Guid.NewGuid().ToString("N"));
            // Порт 9 (discard) — адрес, на который никто не ответит: уйди
            // сборка на провод, это было бы видно, а не случайно удачно.
            var об = Оболочка(new CachingAssets(new ContentLoader("http://127.0.0.1:9/", кэш)));
            var набор = НаборОболочки(об);

            Assert.NotNull(об.TopBar, "верхний бар не собран");
            Assert.NotNull(об.DownloadHud, "кружок загрузок не собран — а загрузчик умеет качать");
            Assert.IsFalse(набор.Has(об.TopBar),
                "верхний бар попал в набор экранов — уборка погасит единый верх приложения");
            Assert.IsFalse(набор.Has(об.DownloadHud),
                "кружок загрузок попал в набор — качание станет невидимым из любого места, " +
                "кроме того экрана, где его завели");

            var барБыл = Показ(об.TopBar);
            набор.HideAll();

            Assert.AreEqual(барБыл, Показ(об.TopBar), "уборка экранов погасила верхний бар");
            Assert.AreEqual(DisplayStyle.None, Показ(об.Hub), "уборка не убрала сами экраны");

            try { Directory.Delete(кэш, true); } catch (Exception) { }
        }
    }
