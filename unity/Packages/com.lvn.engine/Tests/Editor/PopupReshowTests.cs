using System;
using System.Collections.Generic;
using System.Reflection;
using System.Threading;
using System.Threading.Tasks;
using Lvn.Content;
using Lvn.UI;
using Lvn.UI.Screens;
using NUnit.Framework;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// ВТОРОЙ ВОПРОС ПОВЕРХ ПЕРВОГО — попап один на всё приложение, и вопросы
    /// приходят подряд.
    ///
    /// <para>ЖИВОЙ ДЕФЕКТ. Правило «последний вызов побеждает» было записано
    /// только наполовину: отменённый показ доживал до своей уборки уже ПОСЛЕ
    /// того, как экран занял второй вопрос, — и убирал ЗА НИМ. Гасил показ,
    /// снимал поверхность у Режиссёра и обнулял ЧУЖОЕ ожидание: кнопки
    /// становились мертвы, карточка вопроса невидима, а тот, кто ждал ответа,
    /// не получал его никогда. Два вопроса подряд — а по тапу на запертую
    /// карточку они и идут подряд — вешали игру намертво в том самом месте,
    /// где она ждала ответа. Единственный выход был убить приложение.</para>
    ///
    /// <para>Здесь закреплено правило, а не его запись: уборка принадлежит
    /// ТОМУ показу, который сейчас на экране. Чужую уборку не делает никто —
    /// ни отменённый первый вопрос, ни показ, переживший уход экрана.</para>
    ///
    /// <para>Соседний файл (<c>PopupSurfaceTests</c>) закрепляет другую
    /// половину: что попап вообще объявляет себя Режиссёру. Здесь — что он не
    /// снимает объявление за чужой спиной.</para>
    ///
    /// <para>КАДРЫ ЗДЕСЬ РУЧНЫЕ. Ответ доезжает до ждущего продолжением, а
    /// продолжения у попапа намеренно асинхронные
    /// (<c>RunContinuationsAsynchronously</c>): в живой игре их прокручивает
    /// кадр, в EditMode кадров нет. Поэтому на время теста ставится
    /// СИНХРОНИЗАЦИОННЫЙ КОНТЕКСТ, который прокручивается вручную — это те же
    /// кадры, только по требованию, и без них не проверить ровно то, ради чего
    /// дефект и чинили.</para>
    /// </summary>
    public sealed class PopupReshowTests
    {
        /// <summary>КАДРЫ ПО ТРЕБОВАНИЮ: очередь продолжений, которую тест
        /// прокручивает сам. В игре её прокручивает Unity на каждом кадре.</summary>
        private sealed class РучныеКадры : SynchronizationContext
        {
            private readonly Queue<KeyValuePair<SendOrPostCallback, object>> _очередь
                = new Queue<KeyValuePair<SendOrPostCallback, object>>();

            public override void Post(SendOrPostCallback дело, object груз)
                => _очередь.Enqueue(new KeyValuePair<SendOrPostCallback, object>(дело, груз));

            public override void Send(SendOrPostCallback дело, object груз) => дело(груз);

            /// <summary>Прокрутить всё, что накопилось (и всё, что появится по
            /// ходу). Потолок — страховка от вечного круга, а не ожидание.</summary>
            public void Прокрутить()
            {
                for (int шаг = 0; шаг < 128 && _очередь.Count > 0; шаг++)
                {
                    var дело = _очередь.Dequeue();
                    дело.Key(дело.Value);
                }
                Assert.AreEqual(0, _очередь.Count, "продолжения не кончаются — показ зациклился");
            }
        }

        private Func<float> _часыБыли;
        private SynchronizationContext _контекстБыл;
        private РучныеКадры _кадры;
        private float _тик;

        [SetUp]
        public void Setup()
        {
            // ЧАСЫ, КОТОРЫЕ ВСЕГДА УЖЕ ПРОШЛИ: появление и уход попапа —
            // затухания, а они ждут кадров. С такими часами затухание кончается
            // на первом же замере, и показ доходит до места, где ждёт ответа.
            _часыБыли = LvnClock.Now;
            _тик = 0f;
            LvnClock.Now = () => (_тик += 10f);

            _контекстБыл = SynchronizationContext.Current;
            _кадры = new РучныеКадры();
            SynchronizationContext.SetSynchronizationContext(_кадры);

            LvnScreenDirector.Current.Reset();
        }

        [TearDown]
        public void TearDown()
        {
            SynchronizationContext.SetSynchronizationContext(_контекстБыл);
            LvnClock.Now = _часыБыли;
            LvnScreenDirector.Current.Reset();
        }

        private static PopupScreen Попап() => new PopupScreen(new PopupConfig());

        private static string Верхний => LvnScreenDirector.Current.BackTarget;

        private static string Заголовок(PopupScreen попап) => попап.Q<Label>("popup-title")?.text;

        private static bool НаЭкране(PopupScreen попап) => попап.style.display.value == DisplayStyle.Flex;

        private static PopupScreen.Button[] ДаНет => new[]
        {
            new PopupScreen.Button("Нет"),
            new PopupScreen.Button("Да", primary: true),
        };

        /// <summary>НАЖАТЬ без панели и кадров: настоящий указатель до кнопки в
        /// EditMode не доходит (нет ни панели, ни раскладки), а правило живёт
        /// именно на нажатии — дёргаем обработчик напрямую.</summary>
        private static void Нажать(PopupScreen попап, int номер)
        {
            var кнопки = попап.Query<Button>().ToList();
            Assert.Greater(кнопки.Count, номер, "кнопки, на которую отвечают, на экране нет");
            Нажатие.Жать(кнопки[номер]);
        }

        private static int Ответ(Task<int> показ, string почему)
        {
            Assert.IsTrue(показ.IsCompleted, почему);
            return показ.Result;
        }

        // ── второй вопрос занимает экран ────────────────────────────────────

        // ГЛАВНОЕ ПРАВИЛО. Отменённый вопрос отвечает «−1» своему ждущему и на
        // этом кончается: экран уже не его, и трогать он на нём не вправе
        // ничего.
        [Test]
        public void ВторойВопросОтменяетПервыйНоСамОстаётсяНаЭкране()
        {
            var попап = Попап();

            var первый = попап.ShowAsync("Первый", "Текст", null);
            var второй = попап.ShowAsync("Второй", "Текст", null);
            _кадры.Прокрутить();

            Assert.AreEqual(-1, Ответ(первый, "отменённый вопрос не отпустил своего ждущего — " +
                                              "тот, кто его задал, стоит на ответе, которого уже не будет"),
                "у отменённого вопроса один честный ответ — «никак»");

            Assert.IsFalse(второй.IsCompleted, "за игрока ответил кто-то другой");
            Assert.IsTrue(попап.IsOpen,
                "первый вопрос убрал за вторым: на экране висит вопрос, который попап считает закрытым");
            Assert.IsTrue(НаЭкране(попап),
                "вопрос погашен вместе с отменённым — игрок отвечает на невидимую карточку");
            Assert.AreEqual("Второй", Заголовок(попап), "на экране остался текст отменённого вопроса");
            Assert.AreEqual(LvnScreenDirector.Alert, Верхний,
                "поверхность вопроса снял ЧУЖОЙ показ — «назад» уводит из-под заданного игроку вопроса");
        }

        // ЖИВОЙ ПУТЬ ДЕФЕКТА. Ответ на второй вопрос обязан дойти до того, кто
        // его ждёт: именно здесь игра и вставала — кнопки нажимались, а вызов,
        // задавший вопрос, не возвращался никогда.
        [Test]
        public void ОтветНаВторойВопросДоходитДоТогоКтоЕгоЖдал()
        {
            var попап = Попап();
            var первый = попап.ShowAsync("Первый", "Текст", null);
            var второй = попап.ShowAsync("Второй", "Купить?", ДаНет);
            _кадры.Прокрутить();

            Нажать(попап, 1);   // «Да»
            _кадры.Прокрутить();

            Assert.AreEqual(1, Ответ(второй, "нажали кнопку, а тот, кто задал вопрос, ответа не получил: " +
                                             "игра стоит на месте, и выход один — убить приложение"),
                "ответ пришёл не той кнопкой, на которую нажали");
            Assert.AreEqual(-1, Ответ(первый, "отменённый вопрос так и не отпустил своего ждущего"));

            Assert.IsFalse(попап.IsOpen, "ответили, а попап всё ещё считает себя открытым");
            Assert.IsFalse(НаЭкране(попап), "отвеченный вопрос остался поверх экрана");
            Assert.IsFalse(LvnScreenDirector.Current.AnyOpen,
                "поверхность вопроса не снята — «назад» навсегда занят вопросом, которого нет");
        }

        // Под вопросом обычно стоит открытая модаль оболочки: «не хватает
        // валюты» задают поверх магазина. Смена вопроса не имеет права её
        // унести — иначе игрок вылетает из магазина, ничего для этого не сделав.
        [Test]
        public void СменаВопросаНеУноситЧужуюПоверхность()
        {
            LvnScreenDirector.Current.Open(LvnScreenDirector.ShellModal);
            var попап = Попап();

            попап.ShowAsync("Первый", "Текст", null);
            var второй = попап.ShowAsync("Второй", "Текст", ДаНет);
            _кадры.Прокрутить();

            Assert.AreEqual(LvnScreenDirector.Alert, Верхний);

            Нажать(попап, 0);
            _кадры.Прокрутить();

            Assert.AreEqual(0, Ответ(второй, "ответ на второй вопрос потерялся"));
            Assert.AreEqual(LvnScreenDirector.ShellModal, Верхний,
                "ответили на вопрос — и магазин под ним закрылся вместе с ним");
        }

        // Третий вопрос подряд — то же правило: уборка всегда у того, кто на
        // экране сейчас. Проверяется отдельно, потому что метка поколения — это
        // счётчик, и «работает для двух» не значит «работает для трёх».
        [Test]
        public void ТретийВопросОтменяетДваПредыдущихИОстаётсяНаЭкране()
        {
            var попап = Попап();

            var первый = попап.ShowAsync("Первый", "Текст", null);
            var второй = попап.ShowAsync("Второй", "Текст", null);
            var третий = попап.ShowAsync("Третий", "Текст", ДаНет);
            _кадры.Прокрутить();

            Assert.AreEqual(-1, Ответ(первый, "первый вопрос не отпустил ждущего"));
            Assert.AreEqual(-1, Ответ(второй, "второй вопрос не отпустил ждущего"));
            Assert.IsFalse(третий.IsCompleted);
            Assert.AreEqual("Третий", Заголовок(попап));
            Assert.AreEqual(LvnScreenDirector.Alert, Верхний);

            Нажать(попап, 1);
            _кадры.Прокрутить();

            Assert.AreEqual(1, Ответ(третий, "до третьего вопроса ответ не дошёл"));
        }

        // ── уход экрана ─────────────────────────────────────────────────────

        // Уход зовётся уборкой набора — то есть на любой навигации. Он обязан
        // отпустить ждущего (иначе сцена стоит на ответе, которого не будет) и
        // снять СВОЮ поверхность — ровно её, ровно один раз.
        [Test]
        public void УходВоВремяПоказаОтпускаетЖдущегоИСнимаетСвоюПоверхность()
        {
            LvnScreenDirector.Current.Open(LvnScreenDirector.ShellModal);
            var попап = Попап();
            var показ = попап.ShowAsync("Вопрос", "Текст", ДаНет);

            попап.Hide();
            _кадры.Прокрутить();

            Assert.AreEqual(-1, Ответ(показ, "экран ушёл молча — тот, кто задал вопрос, ждёт ответа " +
                                             "от экрана, которого больше нет"),
                "уход экрана значит «ответа не будет», а не выбор за игрока");
            Assert.IsFalse(попап.IsOpen);
            Assert.IsFalse(НаЭкране(попап));
            Assert.AreEqual(LvnScreenDirector.ShellModal, Верхний,
                "уход вопроса унёс с собой и модаль под ним");
        }

        // ТО ЖЕ ПРАВИЛО С ДРУГОЙ СТОРОНЫ: показ, переживший уход экрана, не
        // имеет права убрать за вопросом, заданным ПОСЛЕ него. Здесь «уборка
        // ровно один раз» и видна: второй раз её делать было бы уже некому и не
        // за кем.
        [Test]
        public void ПоказПережившийУходНеУбираетЗаСледующимВопросом()
        {
            var попап = Попап();
            var первый = попап.ShowAsync("Первый", "Текст", null);

            попап.Hide();
            var второй = попап.ShowAsync("Второй", "Текст", ДаНет);
            _кадры.Прокрутить();

            Assert.AreEqual(-1, Ответ(первый, "убранный экран не отпустил ждущего"));
            Assert.IsTrue(попап.IsOpen,
                "показ, убранный минуту назад, закрыл заданный после него вопрос");
            Assert.IsTrue(НаЭкране(попап), "новый вопрос погашен уборкой прошлого");
            Assert.AreEqual("Второй", Заголовок(попап));
            Assert.AreEqual(LvnScreenDirector.Alert, Верхний,
                "поверхность нового вопроса снята уборкой прошлого показа");

            Нажать(попап, 1);
            _кадры.Прокрутить();
            Assert.AreEqual(1, Ответ(второй, "ответ на новый вопрос не дошёл: " +
                                             "его ожидание обнулила уборка прошлого показа"));
        }

        // ЧЕГО ЗДЕСЬ НЕТ. Тап по затемнению (тот, что отвечает «−1», когда это
        // разрешено) в EditMode недостижим: событие разносит панель, а панели
        // без открытого окна редактора нет — SendEvent на отвязанном элементе
        // не доходит ни до кого. Правило про «закрывать мимо кнопок нельзя»
        // проверялось бы вокруг события, которого не было, то есть зеленело бы
        // всегда. Отмена по токену — та же история с другой стороны: её путь
        // сходится с уходом экрана, который проверен выше.
    }
}
