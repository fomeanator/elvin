using System.Collections.Generic;
using Lvn.Content;
using Lvn.UI;
using NUnit.Framework;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// ПОДПИСЬ ПОМНИТ, ОТКУДА ОНА ВЗЯЛАСЬ — <see cref="LvnRedress"/>.
    ///
    /// <para>Текст ставится строкой, и на этом связь со словарём кончается:
    /// экран знал, как собрать подпись, но по готовому <c>Label</c> этого уже
    /// не узнать. Игрок переключал язык — и открытый гардероб, нижнее меню,
    /// шапка настроек оставались на прежнем. Решал он это однозначно:
    /// переключатель сломан.</para>
    ///
    /// <para>Здесь закреплены правила, каждое из которых было живым дефектом:
    /// привязка отдаёт элемент обратно (иначе её негде поставить), ставит текст
    /// СРАЗУ (иначе экран рождается пустым), перечитывается по просьбе (иначе
    /// текст живёт в экране дважды и расходится), и переодевание доходит до
    /// вложенных экранов — до 28.08 не доходило, и «Профиль», «Магазин» и
    /// «Играть» оставались на прежнем языке под уже переключившимся списком.</para>
    /// </summary>
    public class RedressTests
    {
        /// <summary>Экран, умеющий переодеться: считает просьбы и, если попросили,
        /// делает по ним свою работу (в том числе роняет её).</summary>
        private sealed class Экран : VisualElement, ILvnRedress
        {
            private readonly System.Action _работа;
            public int Спросили;
            public Экран(System.Action работа = null) { _работа = работа; }
            public void Redress() { Спросили++; _работа?.Invoke(); }
        }

        /// Корни регистрируются в доме навсегда — но живыми ссылками он их не
        /// держит и выбрасывает отвязанные. Отвязываем свои, чтобы соседний тест,
        /// сменивший язык, не переодевал наши мёртвые деревья.
        private readonly List<VisualElement> _мои = new List<VisualElement>();

        [TearDown]
        public void Убрать()
        {
            foreach (var el in _мои) el.RemoveFromHierarchy();
            _мои.Clear();
            LvnWords.Learn(null);
            LvnWords.Translate(null);
        }

        // ── привязка ────────────────────────────────────────────────────────

        [Test]
        public void ПривязкаОтдаётЭлементОбратно()
        {
            // Привязку ставят НА МЕСТЕ СОЗДАНИЯ: `var кнопка = Bind(new Button(), …)`.
            // Верни она что-нибудь другое — обёртка стала бы двумя строками, а
            // двухстрочную обёртку в сотне мест забывают ровно там, где подпись
            // и оставалась непереведённой.
            var кнопка = new Button();
            Assert.AreSame(кнопка, LvnRedress.Bind(кнопка, () => "Играть"),
                "привязка вернула не тот элемент — её негде поставить одной строкой");

            // Экран собирают и на пустом месте: подписи нет, источника нет.
            // Уронить на этом сборку значит потерять весь экран ради одной
            // строки текста.
            Assert.IsNull(LvnRedress.Bind<Label>(null, () => "x"));
            var безИсточника = new Label { text = "Гость" };
            Assert.AreSame(безИсточника, LvnRedress.Bind(безИсточника, null));
            Assert.AreEqual("Гость", безИсточника.text, "привязка без источника стёрла подпись");
            Assert.IsFalse(LvnRedress.TrySource(безИсточника, out _),
                "пустой источник записан как настоящий — переодевание поставит null");
        }

        [Test]
        public void ПривязкаСтавитТекстСразу_АНеСоСледующегоПереодевания()
        {
            // Экран собирается и показывается ЗАДОЛГО до первой смены языка.
            // Ставь привязка текст только при переодевании — игрок увидел бы
            // пустую шапку и пустые кнопки на всём, что открыто первым.
            var подпись = LvnRedress.Bind(new Label(), () => "Профиль");

            Assert.AreEqual("Профиль", подпись.text,
                "привязанная подпись родилась пустой — экран показан без слов");
        }

        [Test]
        public void ПовторнаяПривязкаЗаменяетИсточник_АНеДобавляетВторой()
        {
            // Один и тот же элемент привязывают дважды: экран пересобрал шапку
            // поверх прежней, роль переодела кнопку, наследник уточнил подпись
            // предка. Второй источник рядом с первым — это либо срыв на месте
            // (таблица со слабыми ключами не принимает второй ключ), либо
            // подпись, которая перечитывается в СТАРОЕ слово.
            var кнопка = new Button();
            LvnRedress.Bind(кнопка, () => "Старое");

            Assert.DoesNotThrow(() => LvnRedress.Bind(кнопка, () => "Новое"),
                "вторая привязка уронила сборку экрана");
            Assert.AreEqual("Новое", кнопка.text, "вторая привязка не поставила своё слово");

            Assert.IsTrue(LvnRedress.TrySource(кнопка, out var источник));
            Assert.AreEqual("Новое", источник(), "у подписи остался прежний источник");

            кнопка.text = "затёрто на месте";
            LvnRedress.Refresh(кнопка);
            Assert.AreEqual("Новое", кнопка.text, "перечитался первый источник, а не последний");
        }

        [Test]
        public void НепривязаннаяПодписьОтвечаетЧтоИсточникаНет()
        {
            // Переодевание спрашивает про КАЖДЫЙ узел дерева — а привязан там
            // один из сотни. Ответь непривязанный «да» с пустым источником, и
            // обход поставил бы ему null вместо текста: экран потерял бы
            // подписи ровно в момент смены языка.
            Assert.IsFalse(LvnRedress.TrySource(new Label { text = "Гость" }, out var нет));
            Assert.IsNull(нет, "у непривязанной подписи выдали источник");
            Assert.IsFalse(LvnRedress.TrySource(null, out _), "спросили про пустое место — ответили «есть»");
        }

        // ── перечитать одну ─────────────────────────────────────────────────

        [Test]
        public void ПеречитатьОдну_БерётСловоЗаново()
        {
            // Так живут кнопки, чья надпись зависит от СОСТОЯНИЯ: взведённая
            // кнопка удаления («Точно удалить?»), забранная награда
            // («Получено»), карточка новеллы («Играть» / «Продолжить»).
            //
            // Без этого экран держит текст ДВАЖДЫ — привязкой для языка и
            // присваиванием для состояния, — и они расходятся ровно тогда,
            // когда игрок сменил язык на открытой карточке.
            bool взведена = false;
            var удалить = LvnRedress.Bind(new Button(), () => взведена ? "Точно удалить?" : "Удалить");
            Assert.AreEqual("Удалить", удалить.text);

            взведена = true;
            LvnRedress.Refresh(удалить);

            Assert.AreEqual("Точно удалить?", удалить.text,
                "кнопка не перечитала себя — игрок жмёт «Удалить» и стирает сейв без подтверждения");
        }

        [Test]
        public void ПеречитатьОдну_БезПривязкиНичегоНеПортит()
        {
            // Экран зовёт «спроси заново» по всему ряду — а привязан там не
            // каждый. Затри непривязанную подпись пустотой, и ряд наполовину
            // опустеет при первом же обновлении состояния.
            var своимиРуками = new Label { text = "12 из 30" };
            Assert.DoesNotThrow(() => LvnRedress.Refresh(своимиРуками));
            Assert.AreEqual("12 из 30", своимиРуками.text, "непривязанную подпись стёрли перечитыванием");

            Assert.DoesNotThrow(() => LvnRedress.Refresh(null));
            Assert.DoesNotThrow(() => LvnRedress.Refresh(new VisualElement()),
                "перечитывание не-текста уронило экран");
        }

        // ── обход дерева ────────────────────────────────────────────────────

        [Test]
        public void ПереодеваниеДоходитДоСамойГлубокойПодписи()
        {
            // Экран — это не два уровня. Карточка внутри полосы внутри
            // прокрутки внутри вкладки: остановись обход на первом ярусе, и
            // переключилась бы только шапка.
            string слово = "Играть";
            var корень = new VisualElement();
            var ярус = корень;
            for (int i = 0; i < 4; i++) { var ниже = new VisualElement(); ярус.Add(ниже); ярус = ниже; }
            var глубоко = LvnRedress.Bind(new Label(), () => слово);
            ярус.Add(глубоко);

            слово = "Play";
            LvnRedress.All(корень);

            Assert.AreEqual("Play", глубоко.text, "обход не дошёл до подписи на пятом ярусе");
        }

        [Test]
        public void ВложенныеЭкраныПересобираютсяРовноПоРазу()
        {
            // Обход НАМЕРЕННО заходит внутрь уже переодевшегося экрана: там,
            // в шапке и кнопках, собранных в конструкторе, и живут привязки
            // (дефект 28.08). Плата за этот заход — риск позвать вложенный
            // экран дважды, а пересборка списка вдвое дороже всей смены языка:
            // на большом гардеробе это видимый провал кадра ровно в момент
            // переключения.
            var корень = new VisualElement();
            var вкладка = new Экран();
            var внутренний = new Экран();
            вкладка.Add(внутренний);
            корень.Add(вкладка);

            LvnRedress.All(корень);

            Assert.AreEqual(1, вкладка.Спросили, "вкладку пересобрали не один раз");
            Assert.AreEqual(1, внутренний.Спросили,
                "вложенный экран пересобрали дважды за один обход — смена языка стоит двух сборок");
        }

        [Test]
        public void ПереодеваниеМеняетПодписи_АНеМигаетЭкраномЦеликом()
        {
            // Проявлять панель целиком значит мигать фоном, плашками и
            // картинками — со стороны это белая вспышка, а не смена языка.
            // Меняются ТОЛЬКО подписи, они и проступают.
            var корень = new VisualElement();
            var экран = new Экран();
            экран.style.opacity = 1f;
            var картинка = new VisualElement();
            картинка.style.opacity = 1f;
            экран.Add(картинка);
            экран.Add(new Label { text = "Магазин" });
            корень.Add(экран);

            LvnRedress.All(корень);

            Assert.AreEqual(1f, экран.style.opacity.value, 1e-4f,
                "экран проявился целиком — со стороны это вспышка, а не смена языка");
            Assert.AreEqual(1f, картинка.style.opacity.value, 1e-4f,
                "обложка мигнула вместе с текстом");
        }

        // ── одна беда не уносит весь экран ──────────────────────────────────

        [Test]
        public void УпавшийИсточникНеОставляетСоседейНаПрежнемЯзыке()
        {
            // Источник — чужой код: он лезет в манифест, в кошелёк, в каталог
            // главы, которой уже нет. Урони он обход — переключение языка
            // остановилось бы на первой битой подписи, и ВЕСЬ остальной экран
            // остался бы на прежнем.
            string слово = "Купить";
            bool главаПропала = false;
            var корень = new VisualElement();
            корень.Add(LvnRedress.Bind(new Label(),
                () => главаПропала ? throw new System.InvalidOperationException("нет главы") : "Купить"));
            var сосед = LvnRedress.Bind(new Label(), () => слово);
            корень.Add(сосед);

            главаПропала = true;   // главу выгрузили, пока экран стоял открытым
            слово = "Buy";
            Assert.DoesNotThrow(() => LvnRedress.All(корень), "битая подпись уронила смену языка");

            Assert.AreEqual("Buy", сосед.text, "после битой подписи соседи остались на прежнем языке");
        }

        [Test]
        public void УпавшийЭкранНеОставляетОстальныеНаПрежнемЯзыке()
        {
            // То же самое ярусом выше: пересборка экрана лезет в данные и
            // падает. Один упавший экран не имеет права оставить непереодетой
            // всю оболочку.
            var корень = new VisualElement();
            корень.Add(new Экран(() => throw new System.NullReferenceException("нет списка")));
            var целый = new Экран();
            корень.Add(целый);

            Assert.DoesNotThrow(() => LvnRedress.All(корень), "упавший экран уронил смену языка");

            Assert.AreEqual(1, целый.Спросили, "после упавшего экрана остальных переодевать не стали");
        }

        // ── ради чего дом существует ────────────────────────────────────────

        [Test]
        public void СменаЯзыка_ПривязаннаяПодписьМеняется_СвояОстаётся()
        {
            // Ключевой сценарий. Игрок переключает язык — и обязан увидеть
            // новое слово ТАМ, ГДЕ ЭКРАН СКАЗАЛ, ОТКУДА ОНО БЕРЁТСЯ. Подпись,
            // поставленную строкой, дом не трогает: угадывать, какой Label
            // словарный, а какой — имя игрока или название главы, он не вправе,
            // и «умный» обход переводил бы имена персонажей.
            var хозяин = new VisualElement();
            var корень = new VisualElement();
            хозяин.Add(корень);          // отвязанный корень дом выбрасывает как мёртвый
            _мои.Add(корень);

            LvnWords.Learn(new Dictionary<string, string> { ["play"] = "Играть" });
            var словарная = LvnRedress.Bind(new Label(), () => LvnWords.Of("play", "Play"));
            var своя = new Label { text = "Виктория" };
            корень.Add(словарная);
            корень.Add(своя);
            Assert.AreEqual("Играть", словарная.text);

            LvnRedress.Register(корень);
            LvnWords.Translate(new Dictionary<string, string> { ["play"] = "Play" });

            Assert.AreEqual("Play", словарная.text,
                "язык переключён, а подпись прежняя — для игрока это сломанный переключатель");
            Assert.AreEqual("Виктория", своя.text,
                "переодевание залезло в подпись без источника — так переводятся имена героев");
        }

        [Test]
        public void ОбъявленныйКореньПереодеваетсяБезОболочки()
        {
            // Подписка на смену языка жила в оболочке: работа общая, а держал
            // её один жилец. Сцена в песочнице, демо без оболочки, витрина
            // отдельным документом — язык менялся в настройках и не доезжал
            // никуда, хотя корни были честно объявлены. Слушает дом.
            var хозяин = new VisualElement();
            var корень = new VisualElement();
            хозяин.Add(корень);
            _мои.Add(корень);

            var экран = new Экран();
            корень.Add(экран);
            LvnRedress.Register(корень);
            LvnRedress.Register(корень);   // повторное объявление безвредно

            LvnWords.Translate(new Dictionary<string, string> { ["play"] = "Play" });

            Assert.AreEqual(1, экран.Спросили,
                "корень объявлен, а переодеться его не попросили — или попросили дважды");
        }
