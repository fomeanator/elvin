            LvnTheme тема = null;

            var жалобы = Жалобы(() => тема = LvnTheme.ByName("cyberpank"));

            Assert.AreEqual("midnight", тема.Name,
                "неизвестная тема обязана дать «Полночь», а не пустой экран");
