            StringAssert.Contains("ui.browse.theme", жалобы[0], "жалоба не назвала поле манифеста");
        }

        // Манифест пишут руками: «Cyber» с заглавной и с пробелом после
        // двоеточия — не опечатка, а обычная запись.
        [Test]
        public void РегистрИПробелыВИмениТемыНеМешают()
