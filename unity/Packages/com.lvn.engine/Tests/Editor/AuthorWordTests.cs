        public void НезаданноеПоявлениеЭтоNoneБезЖалобы()
        {
            var жалобы = Жалобы(() =>
            {
                Assert.AreEqual(LvnAppearKind.None, LvnAppear.Parse(null));
                Assert.AreEqual(LvnAppearKind.None, LvnAppear.Parse(""));
                Assert.AreEqual(LvnAppearKind.None, LvnAppear.Parse("   "));
            });

            Assert.IsEmpty(жалобы, "элемент без вида появления получает ругань — " +
                string.Join(" | ", жалобы));
        }

        // ── ПОТРЕБИТЕЛЬ: РЕЖИМ ИГРОВОГО HUD ─────────────────────────────────

        private readonly List<GameObject> _мусор = new List<GameObject>();
        private readonly ОдолженнаяТема _тема = new ОдолженнаяТема();

        /// <summary>Оболочка с заданным режимом HUD. Тема запоминается: хаб
        /// выбирает её на сборке, и без возврата чужие тесты досталась бы
        /// наша.</summary>
        private NovelShell Оболочка(string режим, bool безРаздела = false)
        {
            _тема.Взять();   // лениво: тему меняет сама сборка оболочки
            var shell = NovelShell.Create();
            _мусор.Add(shell.gameObject);
            shell.Build(new LvnManifest
            {
                ui = new LvnUiConfig { hud = безРаздела ? null : new HudConfig { mode = режим } },
            }, new TestAssets());
            return shell;
        }

        // «choices» — минимальная поверхность чтения: полоса прячется на
        // обычной реплике и выходит только на выборе, где цена и баланс важны.
        [Test]
        public void СловоChoicesВключаетРежимВыборов()
        {
            Assert.IsTrue(Оболочка("choices").HudChoicesOnly,
                "слово «choices» не включило режим выборов — новелла получит полную полосу " +
                "поверх каждой реплики");
            Assert.IsTrue(Оболочка("  Choices ").HudChoicesOnly,
                "режим читают мимо дома: регистр и пробелы решили за автора, что он ошибся");
        }

        // Умолчание — полный HUD, и оно берётся ДВУМЯ путями: словом «full» и
        // отсутствием настройки. Оба обязаны привести в одно место.
        [Test]
        public void ПолноеСловоИОтсутствиеРазделаДаютПолныйHud()
        {
            Assert.IsFalse(Оболочка("full").HudChoicesOnly, "«full» — это полный HUD");
            Assert.IsFalse(Оболочка(null).HudChoicesOnly, "незаданный режим — это полный HUD");
            Assert.IsFalse(Оболочка("").HudChoicesOnly, "пустой режим — это полный HUD");
            Assert.IsFalse(Оболочка(null, безРаздела: true).HudChoicesOnly,
                "новелла без раздела hud обязана получить полный HUD, а не падение");
        }

        // Всё, что не «choices», молча означало полный HUD — включая опечатку в
        // самом «choices». Автор просил минимальную поверхность чтения, получал
        // полосу поверх каждой реплики и не имел ни одной подсказки почему.
        [Test]
        public void ОпечаткаВРежимеHudДаётПолныйHudИЖалобу()
        {
            NovelShell об = null;

            var жалобы = Жалобы(() => об = Оболочка("choise"));

            Assert.IsFalse(об.HudChoicesOnly,
                "неизвестный режим обязан дать полный HUD, а не пустой интерфейс");
            var проРежим = жалобы.FindAll(ж => ж.Contains("ui.hud.mode"));
            Assert.AreEqual(1, проРежим.Count,
                "опечатка в режиме HUD прошла молча: автор просил минимальный интерфейс, " +
                "получил полный и не узнал почему — " + string.Join(" | ", жалобы));
            StringAssert.Contains("choise", проРежим[0], "жалоба не назвала слово автора");
            StringAssert.Contains("choices", проРежим[0],
                "в жалобе нет допустимого значения — автор не узнает, как надо было");
