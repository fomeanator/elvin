            Assert.IsEmpty(жалобы, "дом ругается на имена из собственного набора — " +
                string.Join(" | ", жалобы));
        }

        [Test]
        public void ОпечаткаВПоявленииДаётNoneИЖалобу()
        {
            LvnAppearKind вид = LvnAppearKind.Fade;

            var жалобы = Жалобы(() => вид = LvnAppear.Parse("rize"));

            Assert.AreEqual(LvnAppearKind.None, вид,
                "неизвестный вид появления обязан быть «никак», а не случайной анимацией");
            Assert.AreEqual(1, жалобы.Count,
                "«панель просто возникла» — самая необъяснимая для автора беда, " +
                "и она снова прошла молча");
            StringAssert.Contains("appear", жалобы[0], "жалоба не назвала настройку");
            StringAssert.Contains("rize", жалобы[0], "жалоба не назвала слово автора");
        }

        // Появление не задали — панель появляется без анимации, и это норма:
        // вид появления есть далеко не у каждого элемента.
