        }

        // ── ПОТРЕБИТЕЛЬ: ВИД ПОЯВЛЕНИЯ ──────────────────────────────────────

        // Набор имён объявлен отдельно от разбора (LvnAppear.Names уходит в
        // жалобу как «известны: …»), и разъехаться им ничего не мешает: слово
        // числилось бы допустимым, разбор давал бы None, а панель — молча
        // возникала. Проверяется КАЖДОЕ имя набора, включая короткие синонимы.
        [Test]
        public void КаждоеИмяПоявленияИзНабораРазбирается()
        {
            var жалобы = Жалобы(() =>
            {
                foreach (var имя in LvnAppear.Names)
                    Assert.AreNotEqual(LvnAppearKind.None, LvnAppear.Parse(имя),
                        $"«{имя}» числится допустимым видом появления, но разбор даёт «никак»: " +
