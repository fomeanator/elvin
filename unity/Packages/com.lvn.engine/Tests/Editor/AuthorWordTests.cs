using System;
using System.Collections.Generic;
using Lvn.Content;
using Lvn.UI;
using Lvn.UI.Screens;
using NUnit.Framework;
using UnityEngine;

namespace Lvn.Tests
{
    /// <summary>
    /// ЗАКРЫТОЕ СЛОВО АВТОРА — настройка, у которой есть список допустимых
    /// значений, и голос, который говорит, когда слово в этот список не попало.
    ///
    /// <para>Раньше каждая такая настройка читалась своим <c>switch</c> с
    /// молчаливым <c>default</c>. Опечатка в <c>ui.browse.theme</c> отдавала
    /// «Полночь», и киберпанковая игра открывалась в облике по умолчанию;
    /// опечатка в виде появления отдавала «никак», и панель просто возникала.
    /// Манифест не проходит через структурный гейт — ни компилятор, ни
    /// валидатор его не читают, — поэтому сказать об опечатке больше НЕКОМУ,
    /// кроме того, кто исполняет.</para>
    ///
    /// <para>Здесь закреплено ПОВЕДЕНИЕ дома, а не его текст: страж в
    /// <c>vocabulary_guard_test.go</c> уже следит, что потребители зовут
    /// <see cref="LvnAuthorWord.Pick"/>, но зовут они его или впустую — читается
    /// только отсюда. Правил четыре: известное слово приводится к канону,
    /// пустое — не опечатка (настройку просто не задали) и потому молчит, чужое
    /// даёт умолчание И жалобу, а жалоба звучит РОВНО ОДИН РАЗ на пару
    /// «поле + слово» — настройку читают на каждой пересборке экрана, и повтор
    /// превратил бы журнал в шум.</para>
    ///
    /// <para>Отдельно проверены три живых потребителя. Дом можно позвать и не
    /// воспользоваться ответом; проверка потребителя ловит именно это — тему
    /// сверяем с той, что вернулась, вид появления с набором его же имён, режим
    /// HUD собранной оболочкой.</para>
    ///
    /// <para>Жалобы ловятся напрямую через <see cref="Application.logMessageReceived"/>,
    /// а не через <c>LogAssert.Expect</c>: проверять надо не только факт
    /// жалобы, но и её содержимое — названы ли ПОЛЕ, СЛОВО и весь допустимый
    /// набор. Без набора автор видит «так нельзя» и не видит, как можно.</para>
    /// </summary>
    public sealed class AuthorWordTests
    {
        // Дом помнит, о чём уже жаловался, на весь запуск. Между проверками
        // память сбрасывается в обе стороны: иначе соседний тест либо съел бы
        // нашу жалобу, либо мы съели бы его.
        [SetUp]
        public void ЗабытьЖалобыПеред() => LvnAuthorWord.ForgetComplaints();

        [TearDown]
        public void ЗабытьЖалобыПосле()
        {
            LvnAuthorWord.ForgetComplaints();
            foreach (var go in _мусор) if (go != null) UnityEngine.Object.DestroyImmediate(go);
            _мусор.Clear();
            _тема.Вернуть();
        }

        /// <summary>Голос дома у жалобы один — метка <c>[lvn-cfg]</c>. По ней
        /// жалобы и отбираются: сборка оболочки шумит и о своём, а нас
        /// интересует ровно этот дом.</summary>
        private static List<string> Жалобы(Action действие)
        {
            var собрано = new List<string>();
            Application.LogCallback ловец = (текст, стек, вид) =>
            {
                if (вид == LogType.Warning && текст != null && текст.Contains("[lvn-cfg]"))
                    собрано.Add(текст);
            };
            Application.logMessageReceived += ловец;
            try { действие(); }
            finally { Application.logMessageReceived -= ловец; }
            return собрано;
        }

        // ── ДОМ ─────────────────────────────────────────────────────────────

        // Слово приводится к канону: дальше по коду его сравнивают с набором
        // строчными, и «Cyber» с хвостом пробелов обязан дойти до сравнения
        // тем же «cyber». Автор пишет манифест руками — регистр и края там
        // будут.
        [Test]
        public void ИзвестноеСловоВозвращаетсяПриведённымИМолча()
        {
            string прямое = null, крупно = null, скраями = null;

            var жалобы = Жалобы(() =>
            {
                прямое = LvnAuthorWord.Pick("cyber", "поле", "midnight", "midnight", "cyber");
                крупно = LvnAuthorWord.Pick("CYBER", "поле", "midnight", "midnight", "cyber");
                скраями = LvnAuthorWord.Pick("  Cyber\t", "поле", "midnight", "midnight", "cyber");
            });

            Assert.AreEqual("cyber", прямое);
            Assert.AreEqual("cyber", крупно, "регистр решил за автора, что он ошибся");
            Assert.AreEqual("cyber", скраями, "пробел по краям решил за автора, что он ошибся");
            Assert.IsEmpty(жалобы, "дом ругается на слово, которое сам же и знает: " +
                "автор пойдёт искать несуществующую ошибку — " + string.Join(" | ", жалобы));
        }

        // ПУСТОЕ — НЕ ОПЕЧАТКА. Настройку просто не задали, и это самый частый
        // случай на свете: в манифесте таких полей десятки, и почти все пустые.
        // Пожалуйся дом здесь — журнал каждого запуска стал бы стеной ругани, и
        // настоящая жалоба утонула бы в ней.
        [Test]
        public void ПустоеСловоМолчаБерётУмолчание()
        {
            var результаты = new List<string>();

            var жалобы = Жалобы(() =>
            {
                результаты.Add(LvnAuthorWord.Pick(null, "поле", "умолчание", "cyber"));
                результаты.Add(LvnAuthorWord.Pick("", "поле", "умолчание", "cyber"));
                результаты.Add(LvnAuthorWord.Pick("   ", "поле", "умолчание", "cyber"));
                результаты.Add(LvnAuthorWord.Pick("\t\n ", "поле", "умолчание", "cyber"));
            });

            foreach (var р in результаты)
                Assert.AreEqual("умолчание", р, "незаданная настройка обязана дать умолчание");
            Assert.IsEmpty(жалобы, "жалоба на НЕЗАПОЛНЕННОЕ поле — это ругань на каждый " +
                "пустой ключ манифеста: настоящая опечатка утонет в ней — " + string.Join(" | ", жалобы));
        }

        // СУТЬ ДОМА. Чужое слово даёт умолчание — посреди главы падать нельзя, —
        // но МОЛЧА его давать нельзя тем более: автор увидит не ошибку, а
        // «почему-то не так», и пойдёт искать причину глазами по всему проекту.
        //
        // В жалобе обязаны быть все три части. Поле — чтобы знать, ГДЕ искать
        // (одно и то же слово пишут в десятке настроек). Само слово — как его
        // написал автор, иначе он не найдёт его поиском по файлу. И весь
        // допустимый набор — без него автор знает, что нельзя, и не знает, как
        // можно.
        [Test]
        public void ЧужоеСловоДаётУмолчаниеИЖалобуСПолемСловомИНабором()
        {
            string взято = null;

            var жалобы = Жалобы(() => взято = LvnAuthorWord.Pick(
                "CyberPank", "ui.browse.theme", "midnight", "midnight", "cyber", "cyberpunk", "romance"));

            Assert.AreEqual("midnight", взято, "чужое слово обязано дать умолчание, а не пустоту");
            Assert.AreEqual(1, жалобы.Count, "чужое слово прошло молча — автор ищет причину глазами");
            StringAssert.Contains("ui.browse.theme", жалобы[0],
                "жалоба не назвала поле — автор не знает, ГДЕ он ошибся");
            StringAssert.Contains("CyberPank", жалобы[0],
                "жалоба не назвала слово так, как его написал автор, — поиском по файлу его не найти");
            foreach (var известное in new[] { "midnight", "cyber", "cyberpunk", "romance" })
                StringAssert.Contains(известное, жалобы[0],
                    $"в жалобе нет допустимого значения «{известное}»: автор узнал, что нельзя, " +
                    "и не узнал, как можно");
        }

        // Настройку читают на КАЖДОЙ пересборке экрана — смена языка, смена
        // темы, новый манифест после скачивания. Жалуйся дом каждый раз, журнал
        // за один сеанс наполнился бы сотней копий одной строки, и следующая
        // жалоба — про другую беду — прошла бы незамеченной.
        [Test]
        public void ПовторТогоЖеСловаВТомЖеПолеМолчит()
        {
            var жалобы = Жалобы(() =>
            {
                for (int i = 0; i < 5; i++)
                    LvnAuthorWord.Pick("рома", "ui.browse.theme", "midnight", "midnight", "romance");
            });

            Assert.AreEqual(1, жалобы.Count,
                $"о той же беде сказано {жалобы.Count} раз(а): пересборка экрана превращает " +
                "журнал в стену копий, и следующая жалоба в ней утонет");
        }

        // А вот ЭТО прятать нельзя. Одно и то же слово в двух разных настройках —
        // две разные беды: автор поправит тему и не узнает, что тем же словом
        // ошибся в появлении. Ключ памяти — пара «поле + слово», а не слово.
        [Test]
        public void ТоЖеСловоВДругомПолеЖалуетсяОтдельно()
        {
            var жалобы = Жалобы(() =>
            {
                LvnAuthorWord.Pick("рома", "ui.browse.theme", "midnight", "midnight", "romance");
                LvnAuthorWord.Pick("рома", "appear", "", "fade", "rise");
            });

            Assert.AreEqual(2, жалобы.Count,
                "вторая беда спряталась за первой: автор поправит одно поле и не узнает, " +
                "что тем же словом ошибся в другом");
            CollectionAssert.IsNotEmpty(жалобы.FindAll(ж => ж.Contains("ui.browse.theme")));
            CollectionAssert.IsNotEmpty(жалобы.FindAll(ж => ж.Contains("appear")));
        }

        // Зеркальное правило: две опечатки в ОДНОМ поле — тоже две беды. Память
        // по одному только полю замолчала бы про вторую.
        [Test]
        public void РазныеСловаВОдномПолеЖалуютсяКаждое()
        {
            var жалобы = Жалобы(() =>
            {
                LvnAuthorWord.Pick("cybber", "ui.browse.theme", "midnight", "midnight", "cyber");
                LvnAuthorWord.Pick("romace", "ui.browse.theme", "midnight", "midnight", "cyber");
            });

            Assert.AreEqual(2, жалобы.Count, "вторая опечатка в том же поле прошла молча");
            CollectionAssert.IsNotEmpty(жалобы.FindAll(ж => ж.Contains("cybber")));
            CollectionAssert.IsNotEmpty(жалобы.FindAll(ж => ж.Contains("romace")));
        }

        // Забывание — не украшение, а то, на чём стоит независимость проверок:
        // память дома живёт весь запуск, и без сброса порядок тестов решал бы,
        // прозвучит жалоба или нет.
        [Test]
        public void ПослеЗабыванияЖалобаЗвучитСнова()
        {
            var первые = Жалобы(() =>
                LvnAuthorWord.Pick("cybber", "ui.browse.theme", "midnight", "midnight", "cyber"));
            Assert.AreEqual(1, первые.Count);

            LvnAuthorWord.ForgetComplaints();

            var вторые = Жалобы(() =>
                LvnAuthorWord.Pick("cybber", "ui.browse.theme", "midnight", "midnight", "cyber"));
            Assert.AreEqual(1, вторые.Count,
                "память дома не сбрасывается — порядок тестов начинает решать, " +
                "услышана жалоба или нет");
        }

        // ── ПОТРЕБИТЕЛЬ: ТЕМА ОБОЛОЧКИ ──────────────────────────────────────

        // Дом можно позвать и не воспользоваться ответом. Здесь проверяется
        // именно результат: каждое известное слово доходит до СВОЕЙ темы,
        // включая синоним «cyberpunk».
        [Test]
        public void ИмяТемыДоходитДоСвоейТемы()
        {
            var жалобы = Жалобы(() =>
            {
                Assert.AreEqual("cyber", LvnTheme.ByName("cyber").Name);
                Assert.AreEqual("cyber", LvnTheme.ByName("cyberpunk").Name,
                    "синоним «cyberpunk» перестал вести в киберпанк");
                Assert.AreEqual("romance", LvnTheme.ByName("romance").Name);
                Assert.AreEqual("midnight", LvnTheme.ByName("midnight").Name);
            });

            Assert.IsEmpty(жалобы, "дом ругается на собственные известные слова темы — " +
                string.Join(" | ", жалобы));
        }

        // Тот самый случай, ради которого дом и заводили: киберпанковая игра
        // открывалась в облике по умолчанию, и автор видел не ошибку.
        [Test]
        public void ОпечаткаВТемеДаётПолночьИЖалобу()
