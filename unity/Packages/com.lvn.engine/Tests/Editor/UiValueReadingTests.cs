using Lvn.UI;
using Newtonsoft.Json.Linq;
using NUnit.Framework;

namespace Lvn.Tests
{
    /// <summary>
    /// КАК ЧИТАЕТСЯ ЗНАЧЕНИЕ АВТОРСКОЙ ЗАПИСИ — <see cref="LvnUiValues"/>:
    /// отступ, кегль, цвет, «да/нет», имя значка.
    ///
    /// <para>Разбор жил вперемешку со сборкой дерева <c>ui</c>, и каждое его
    /// правило успело стоить дефекта: <c>pad=3</c> значило три пикселя вместо
    /// третьей ступени шкалы темы, а свой разбор цвета делал так, что один и
    /// тот же <c>accent</c> означал разное в разных слоях — экран выходил
    /// наполовину перекрашенным.</para>
    ///
    /// <para>Общее у всех этих поломок одно: автор пишет ровно то, что стоит в
    /// документации движка, ошибки не получает НИГДЕ — ни в компиляторе, ни в
    /// логе, — а на экране выходит не то. Длину (<c>w</c>, <c>h</c>, <c>auto</c>,
    /// проценты) закрепляет <see cref="UiLayerTests"/> на живом слое; здесь —
    /// остальные виды значений и то, чем разбор разметки НАМЕРЕННО отличается
    /// от общих домов движка.</para>
    /// </summary>
    public class UiValueReadingTests
    {
        // ── отступ ──────────────────────────────────────────────────────────

        // Отступы держит ШКАЛА темы, а не глазомер автора: одинаковые вещи на
        // разных экранах обязаны отстоять одинаково, иначе интерфейс выглядит
        // собранным из кусков. `pad=3` — третья ступень этой шкалы; когда оно
        // значило три пикселя, панель прижималась к тексту вплотную, и автор
        // «чинил» это, подбирая числа руками, — то есть навсегда уходил из
        // темы, и смена темы его экран больше не трогала.
        [Test]
        public void ЦелоеОтДоШести_ЭтоСтупеньШкалыТемы_АНеПиксели()
        {
            Assert.AreEqual(LvnTokens.Space1, LvnUiValues.Step((JToken)"1", out _), 0.001f, "pad=1 — не один пиксель");
            Assert.AreEqual(LvnTokens.Space2, LvnUiValues.Step((JToken)"2", out _), 0.001f, "pad=2 — не два пикселя");
            Assert.AreEqual(LvnTokens.Space3, LvnUiValues.Step((JToken)"3", out _), 0.001f, "pad=3 — не три пикселя");
            Assert.AreEqual(LvnTokens.Space4, LvnUiValues.Step((JToken)"4", out _), 0.001f, "pad=4 — не четыре пикселя");
            Assert.AreEqual(LvnTokens.Space5, LvnUiValues.Step((JToken)"5", out _), 0.001f, "pad=5 — не пять пикселей");
            Assert.AreEqual(LvnTokens.Space6, LvnUiValues.Step((JToken)"6", out _), 0.001f, "pad=6 — не шесть пикселей");

            // Ступень выбирается и когда число пришло числом, а не строкой:
            // `pad: 3` и `pad: "3"` — одна и та же авторская запись, и разница
            // между ними не должна значить ничего.
            Assert.AreEqual(LvnTokens.Space3, LvnUiValues.Step((JToken)3, out _), 0.001f,
                "числовая запись отступа прошла мимо шкалы — тот же pad, а результат другой");
        }

        // Ступени — удобство, а не клетка: за пределами шкалы и с явной единицей
        // автор говорит точным числом, и его слушают дословно. Иначе «pad=12»
        // пришлось бы писать как-то ещё, а «pad=3%» — резиновый отступ, который
        // держится на узком экране, — стал бы недоступен вовсе.
        [Test]
        public void ЯвнаяЕдиницаИЧислоВнеШкалы_РаботаютДословно()
        {
            var процент = LvnUiValues.Step((JToken)"3%", out var u1);
            Assert.AreEqual(LvnUiValues.Unit.Percent, u1, "«3%» съело единицу и стало ступенью шкалы");
            Assert.AreEqual(3f, процент, 0.001f, "резиновый отступ подменён числом темы");

            Assert.AreEqual(12f, LvnUiValues.Step((JToken)"12", out var u2), 0.001f,
                "число вне шкалы 1…6 — это пиксели автора");
            Assert.AreEqual(LvnUiValues.Unit.Px, u2);

            Assert.AreEqual(0f, LvnUiValues.Step((JToken)"0", out _), 0.001f,
                "ноль — это «без отступа», а не нулевая ступень шкалы");
        }

        // Шкала — правило ОТСТУПА, и только его. `w=3` — это три пикселя, а
        // `pad=3` — восемнадцать: числа одинаковые, смысл разный. Свести их
        // «для единообразия» — значит либо раздуть трёхпиксельную полоску до
        // размера отступа, либо вернуть отступам глазомер, ради ухода от
        // которого шкала и заводилась.
        [Test]
        public void ШкалаСтупенейПринадлежитОтступу_АНеРазмеру()
        {
            Assert.AreEqual(3f, LvnUiValues.Len((JToken)"3", out _), 0.001f,
                "ширина «3» уехала на ступень шкалы — тонкая полоска станет толщиной с отступ");
            Assert.AreNotEqual(LvnUiValues.Len((JToken)"3", out _), LvnUiValues.Step((JToken)"3", out _),
                "размер и отступ прочитали одно и то же число одинаково — одно из двух правил потерялось");
        }

        // ── кегль ───────────────────────────────────────────────────────────

        // Размер шрифта берут ИМЕНЕМ ступени по той же причине, что и отступ:
        // заголовок на одном экране и заголовок на другом обязаны совпасть.
        // Число тоже принимается — но тогда за разнобой отвечает автор, а не
        // тема, и это его осознанный выбор, а не побочный эффект.
        [Test]
        public void КегльПоИмениСтупени_ЧислоТожеПринимается()
        {
            Assert.AreEqual(LvnTokens.TextXs, LvnUiValues.TextSize((JToken)"xs"), 0.001f, "ступень xs потерялась");
            Assert.AreEqual(LvnTokens.TextSm, LvnUiValues.TextSize((JToken)"sm"), 0.001f, "ступень sm потерялась");
            Assert.AreEqual(LvnTokens.TextBase, LvnUiValues.TextSize((JToken)"base"), 0.001f, "ступень base потерялась");
            Assert.AreEqual(LvnTokens.TextLg, LvnUiValues.TextSize((JToken)"lg"), 0.001f, "ступень lg потерялась");
            Assert.AreEqual(LvnTokens.TextXl, LvnUiValues.TextSize((JToken)"xl"), 0.001f, "ступень xl потерялась");
            Assert.AreEqual(LvnTokens.TextDisplay, LvnUiValues.TextSize((JToken)"display"), 0.001f,
                "витринная ступень потерялась");

            Assert.AreEqual(42f, LvnUiValues.TextSize((JToken)42), 0.001f, "число кегля не приняли");
        }

        // Опечатка в имени ступени не должна давать НОЛЬ: нулевой кегль — это
        // невидимый текст, и автор будет искать пропавшую реплику где угодно,
        // только не в одной букве. Умолчание — основной кегль: не тот размер
        // виден сразу, отсутствие текста — нет.
        [Test]
        public void НеизвестнаяСтупеньКегля_ОсновнойРазмер_АНеНоль()
        {
            Assert.AreEqual(LvnTokens.TextBase, LvnUiValues.TextSize((JToken)"хl"), 0.001f,
                "опечатка в ступени дала невидимый текст вместо основного кегля");
            Assert.AreEqual(LvnTokens.TextBase, LvnUiValues.TextSize(null), 0.001f,
                "кегль не назван — берётся основной, а не ноль");
        }

        // ── цвет ────────────────────────────────────────────────────────────

        // Цвет читается ОБЩИМ домом, и это не про экономию строк: своя копия
        // разбора здесь и была тем, из-за чего один и тот же `accent` означал
        // разное в разных слоях. Экран выходил наполовину перекрашенным — хуже,
        // чем не перекрашенным вовсе. Поэтому проверяется не «hex
        // разбирается», а «имя токена доходит до ДЕЙСТВУЮЩЕЙ темы».
        [Test]
        public void ЦветПоИмениТокена_ЭтоЦветДействующейТемы()
        {
            Assert.AreEqual(LvnTokens.Accent, LvnUiValues.Color("accent", UnityEngine.Color.black),
                "accent в дереве ui разошёлся с accent темы");
            Assert.AreEqual(LvnTokens.Text, LvnUiValues.Color("text", UnityEngine.Color.black),
                "text в дереве ui разошёлся с текстом темы");
            Assert.AreEqual(LvnTokens.Scrim, LvnUiValues.Color("veil", UnityEngine.Color.black),
                "затемнение в дереве ui разошлось с затемнением темы");

            Assert.AreEqual(UnityEngine.Color.red, LvnUiValues.Color("#ff0000", UnityEngine.Color.black),
                "литеральный цвет перестал работать — им пишут то, чего в теме нет");
        }

        // ── «да/нет» ────────────────────────────────────────────────────────

        // РАСХОЖДЕНИЕ С ОБЩИМ ДОМОМ, и оно намеренное. В разметке непустая
        // строка исторически значит «свойство задано»: `hide=1`, `hide=да`,
        // `hide=yes` — и `hide=точно` тоже. Общий дом на незнакомом слове
        // отвечает «не понял» и отдаёт умолчание поля; здесь умолчание —
        // согласие. Сведи их — и разметка, годами работавшая, начнёт молча
        // показывать спрятанное.
        [Test]
        public void НезнакомоеСловоВРазметке_ЭтоСогласие()
        {
            Assert.IsTrue(LvnUiValues.Truthy("точно"), "незнакомое слово в разметке — «свойство задано»");
            Assert.IsNull(Lvn.LvnBool.Parse("точно"),
                "общий дом на этом слове обязан отвечать «не понял» — иначе расхождение исчезло не там");

            Assert.IsTrue(LvnUiValues.Truthy("yes"));
            Assert.IsTrue(LvnUiValues.Truthy((JToken)true));
        }

        // А вот отказ разметка понимает как все: `hide=no` обязано ПОКАЗАТЬ.
        // Иначе автор пишет отказ словом — и получает согласие, потому что
        // строка непустая; в разметке это самая дорогая из возможных ошибок,
        // потому что выглядит как «поле не работает».
        [Test]
        public void ЯвныйОтказ_ОстаётсяОтказом()
        {
            Assert.IsFalse(LvnUiValues.Truthy("no"), "«no» в разметке спрятало элемент");
            Assert.IsFalse(LvnUiValues.Truthy("нет"), "русский отказ в разметке не понят");
            Assert.IsFalse(LvnUiValues.Truthy("off"));
            Assert.IsFalse(LvnUiValues.Truthy("0"));
            Assert.IsFalse(LvnUiValues.Truthy((JToken)false));
        }

        // Пустое и отсутствующее — не согласие: поля-то нет. Считай пустоту
        // согласием — и каждый узел без `hide` спрятался бы сам собой.
        [Test]
        public void ПустоеИОтсутствующее_НеСогласие()
        {
            Assert.IsFalse(LvnUiValues.Truthy(""), "пустая строка — это не «да»");
            Assert.IsFalse(LvnUiValues.Truthy((string)null), "ничего не написано — это не «да»");
            Assert.IsFalse(LvnUiValues.Truthy((JToken)null), "поля нет — это не «да»");
            Assert.IsFalse(LvnUiValues.Truthy(JValue.CreateNull()), "явный null — это не «да»");
        }

        // ── значок ──────────────────────────────────────────────────────────

        // Набор значков закрыт намеренно, и опечатка в имени — обычное дело.
        // Падение здесь стоит ВСЕГО дерева `ui`: у игрока пропадает интерфейс
        // целиком из-за одной буквы в названии картинки. Звезда — видимая
        // заглушка: «значок не тот» автор заметит сразу.
        [Test]
        public void НеизвестноеИмяЗначка_Звезда_АНеПадение()
        {
            Assert.AreEqual(LvnIcon.Star, LvnUiValues.IconByName("bannana"),
                "опечатка в имени значка обязана давать видимую заглушку, а не ронять дерево");
            Assert.AreEqual(LvnIcon.Star, LvnUiValues.IconByName(""), "имя не названо — заглушка");
            Assert.AreEqual(LvnIcon.Star, LvnUiValues.IconByName(null), "имени нет — заглушка");

            Assert.AreEqual(LvnIcon.Home, LvnUiValues.IconByName("home"),
                "регистр в имени значка автору не диктуют");
        }

        // ЧИСЛО ИМЕНЕМ НЕ СЧИТАЕТСЯ. Разбор перечисления принимает и числа, и
        // от этого `icon name=5` молча давал ПЯТЫЙ ПО СЧЁТУ значок — не тот,
        // что имел в виду автор, но похожий на настоящий, так что ошибку никто
        // не искал. `name=999` хуже: такого значения в перечислении нет вовсе,
        // рисовать нечего, и на экране оставалась ДЫРКА в ряду — ни значка, ни
        // заглушки, ни жалобы. Порядок значков в коде движка — не язык автора:
        // он вправе меняться, а имена — нет.
        [Test]
        public void ЧислоВместоИмениЗначка_Заглушка_АНеПорядковыйНомер()
        {
            Assert.AreEqual(LvnIcon.Star, LvnUiValues.IconByName("5"),
                "число прошло как имя — автор получил значок по порядковому номеру, а не по названию");
            Assert.AreEqual(LvnIcon.Star, LvnUiValues.IconByName("0"),
                "ноль прошёл как имя — на его месте пусто, и в ряду останется дырка");
            Assert.AreEqual(LvnIcon.Star, LvnUiValues.IconByName("999"),
                "число вне перечисления стало значком, которого нет: в ряду останется дырка");
            Assert.AreEqual(LvnIcon.Star, LvnUiValues.IconByName("-3"),
                "отрицательное число стало значком, которого нет");

            // И при этом настоящие имена работают как работали — заглушка не
            // должна расползтись на весь набор.
            Assert.AreEqual(LvnIcon.Gem, LvnUiValues.IconByName("GEM"),
                "настоящее имя перестало работать — на экране вместо валюты звёзды");
            Assert.AreEqual(LvnIcon.Energy, LvnUiValues.IconByName("energy"),
                "настоящее имя перестало работать");
        }
    }
}
