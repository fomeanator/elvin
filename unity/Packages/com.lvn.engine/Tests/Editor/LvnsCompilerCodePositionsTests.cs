using Lvn.Editor;
using Newtonsoft.Json.Linq;
using NUnit.Framework;

namespace Lvn.Tests
{
    /// <summary>
    /// ЧТО В СТРОКЕ КОД, А ЧТО ТЕКСТ.
    ///
    /// <para>Внутри кавычек и внутри «шевронов» символы ничего не значат:
    /// фигурная скобка в реплике не открывает блок, запятая в тексте не делит
    /// аргументы, две косые в адресе не начинают комментарий. Правило было
    /// написано ЧЕТЫРЕЖДЫ — у поиска скобки, у поиска парной, у срезания
    /// комментария и у деления аргументов — и сведено в один сканер.</para>
    ///
    /// <para>Проверки ниже написаны не на сканер (он закрытый), а на то, ради
    /// чего он существует: автор пишет обычный текст, а компилятор не находит в
    /// нём синтаксиса. Разойдись копии на одном символе — и место разберётся
    /// двумя способами, а автор увидит не ошибку в логе, а МОЛЧА НЕ ТО на
    /// экране.</para>
    /// </summary>
    public sealed class LvnsCompilerCodePositionsTests
    {
        [Test]
        public void СкобкаВРепликеНеОткрываетБлок()
        {
            var текст = Реплика("scene t\nАня: Он сказал «заходи в 18:00 {если успеешь}» и ушёл.");

            Assert.AreEqual("Он сказал «заходи в 18:00 {если успеешь}» и ушёл.", текст,
                "скобка внутри шевронов принята за начало блока — реплика доехала обрезанной");
        }

        [Test]
        public void ДвеКосыеВАдресеНеНачинаютКомментарий()
        {
            var сценарий = LvnsCompiler.Compile("scene t\nbg https://example.org/a/bg.png\nАня: Тут.");

            Assert.IsTrue(сценарий.Contains("https://example.org/a/bg.png"),
                "адрес обрезан на «//» — фон не найдётся, и сцена молча останется пустой");
        }

        [Test]
        public void ЗапятаяВТекстеНеДелитАргументы()
        {
            var текст = Реплика("scene t\nАня: Ну, знаешь, как бывает.");

            Assert.AreEqual("Ну, знаешь, как бывает.", текст,
                "запятые внутри реплики приняты за разделители аргументов");
        }

        // ── помощники ───────────────────────────────────────────────────────

        private static string Реплика(string src)
        {
            foreach (var cmd in (JArray)JToken.Parse(LvnsCompiler.Compile(src))["script"])
                if ((string)cmd["op"] == "say") return (string)cmd["text"];
            Assert.Fail("в сценарии нет ни одной реплики");
            return null;
        }
    }
}
