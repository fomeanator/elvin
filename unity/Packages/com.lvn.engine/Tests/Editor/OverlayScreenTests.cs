using Lvn.UI;
using Lvn.UI.Screens;
using NUnit.Framework;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// НАКЛАДНОЙ ЭКРАН — <see cref="LvnOverlayScreen"/>, общий жизненный цикл
    /// восьми разделов (профиль, настройки, магазин, наборы, скины, лидерборд,
    /// награды, деталь новеллы).
    ///
    /// <para>Пока цикла не было, у каждого экрана заводилась собственная его
    /// версия — и однажды одна из них расходилась. Здесь закреплено то, что
    /// наследник больше НЕ ОБЯЗАН помнить: зачин (растянуться и спрятаться),
    /// переодевание шапки вместе с телом и уборка наложения на любом выходе.</para>
    ///
    /// <para>ЧЕГО ЗДЕСЬ НЕТ. Модальный виток (<c>ShowAsync</c> → закрытие →
    /// ответ) в EditMode не прокручивается: он ждёт кадров, а кадров нет —
    /// блокирующее ожидание кладёт главный поток, покадровое не двигается.
    /// Поэтому закрытие проверяется по тому, что видно на самом экране, а не
    /// по возвращённому ответу.</para>
    /// </summary>
    public class OverlayScreenTests
    {
        /// <summary>Наследник, который ведёт себя как настоящий раздел: имеет
        /// лист, кладёт поверх него карточку подтверждения и считает, о чём его
        /// просили.</summary>
        private sealed class Раздел : LvnOverlayScreen
        {
            public int ШапкуПеречитали, ТелоСобрали, Прибрались;

            protected override void RedressChrome() => ШапкуПеречитали++;
            public override void Rebuild() => ТелоСобрали++;
            protected override void OnClosed() => Прибрались++;

            public VisualElement ПоставитьЛист() => Sheet();
            public void ПоложитьПоверх(VisualElement el) => PutOverlay(el);
            public bool ЧтоТоПоверхЛиста => HasOverlay;
        }

        /// <summary>Наследник, у которого переодеться — НЕ значит пересобрать:
        /// живая гардеробная вкладка. Умеет и то и другое, чтобы было видно,
        /// что именно из двух его попросили.</summary>
        private sealed class Вкладка : LvnOverlayScreen
        {
            public int ШапкуПеречитали, ТелоСобрали, РостерПереспросили;

            protected override void RedressChrome() => ШапкуПеречитали++;
            public override void Rebuild() => ТелоСобрали++;
            protected override void RedressBody() => РостерПереспросили++;
        }

        /// <summary>Экран без списка: попап, подтверждение, лист с двумя
        /// кнопками. Переодевать в нём нечего, и он не переопределяет ничего.</summary>
        private sealed class Простой : LvnOverlayScreen { }

        // ── зачин ───────────────────────────────────────────────────────────

        [Test]
        public void ЭкранРождаетсяРастянутымИСпрятанным()
        {
            // Три строки зачина стояли в конструкторе КАЖДОГО из восьми
            // наследников, и это не вкус. Экран, забывший спрятаться, виден
            // поверх всего с первого кадра приложения — игрок запускает игру и
            // попадает в магазин. Забывший растянуться схлопывается в нулевой
            // размер: его скрим не ловит тапы, и нажатия проваливаются в игру
            // под открытым окном.
            var раздел = new Раздел();

            Assert.AreEqual(Position.Absolute, раздел.style.position.value,
                "экран встал в поток родителя — он больше не накладной");
            Assert.AreEqual(0f, раздел.style.left.value.value, 1e-4f, "экран не растянут по левому краю");
            Assert.AreEqual(0f, раздел.style.right.value.value, 1e-4f, "экран не растянут по правому краю");
            Assert.AreEqual(0f, раздел.style.top.value.value, 1e-4f, "экран не растянут сверху");
            Assert.AreEqual(0f, раздел.style.bottom.value.value, 1e-4f, "экран не растянут снизу");
            Assert.AreEqual(0f, раздел.style.opacity.value, 1e-4f,
                "экран родился видимым — он мигнёт на первом кадре приложения");
            Assert.AreEqual(DisplayStyle.None, раздел.style.display.value,
                "экран родился в раскладке — он виден поверх всего до первого открытия");
        }

        // ── переодевание ────────────────────────────────────────────────────

        [Test]
        public void ПереодеваниеДоходитИДоШапки_ИДоТелаНаследника()
        {
            // Переопределяли сам Redress, и правил вышло ТРИ: одни звали и
            // шапку, и пересборку, другие только пересборку (шапка оставалась
            // на прежнем языке), третьи только шапку (на прежнем оставался
            // список). Заголовок раздела игрок видит первым — расхождение
            // читается сразу.
            var раздел = new Раздел();

            раздел.Redress();

            Assert.AreEqual(1, раздел.ШапкуПеречитали,
                "шапку не перечитали — заголовок и крестик остались на прежнем языке");
            Assert.AreEqual(1, раздел.ТелоСобрали,
                "тело не пересобрали — список остался на прежнем языке");
        }

        [Test]
        public void НаследникуНеНужноОбъявлятьСебяПереодевающимся()
        {
            // Семь экранов из восьми написали ILvnRedress руками, а восьмой
            // (гардеробная вкладка) забыл — и его подписи не меняли язык, пока
            // экран не пересоздадут. Правило, которое надо ПОМНИТЬ, помнят не
            // все; теперь оно у общего предка, и обход находит раздел сам.
            var корень = new VisualElement();
            var раздел = new Раздел();
            корень.Add(раздел);

            LvnRedress.All(корень);

            Assert.AreEqual(1, раздел.ТелоСобрали,
                "общий обход не нашёл накладной экран — смена языка его не касается");
            Assert.AreEqual(1, раздел.ШапкуПеречитали, "обход дошёл до экрана, но шапку тот не перечитал");
        }

        [Test]
        public void СвоёПереодеваниеТелаЗаменяетПересборку_АНеДополняетЕё()
        {
            // ДВЕ СТОРОНЫ ОДНОГО ПРАВИЛА.
            //
            // Умолчание: переодеть тело — это пересобрать его. Семь экранов
            // писали эту работу под именем `Rebuild` и ОТДЕЛЬНОЙ строкой
            // связывали её с переодеванием — семь одинаковых строк, каждую из
            // которых полагалось не забыть. Восьмой забыл, и смена языка на
            // его открытом экране тело не трогала: заголовок уже по-английски,
            // список всё ещё по-русски.
            //
            // Исключение: у гардеробной вкладки переодеться — значит
            // ПЕРЕСПРОСИТЬ РОСТЕР. Имена персонажей уходят в лист готовыми
            // строками, и пересборка собрала бы его из тех же прежних строк —
            // то есть на прежнем языке. Добавь база пересборку к своему
            // способу — экран делал бы обе работы, и вторая отменяла бы первую.
            var раздел = new Раздел();
            var вкладка = new Вкладка();

            раздел.Redress();
            вкладка.Redress();

            Assert.AreEqual(1, раздел.ТелоСобрали,
                "переодевание не дошло до пересборки — экрану снова придётся связывать их своей строкой");
            Assert.AreEqual(1, вкладка.РостерПереспросили,
                "свой способ переодеть тело не позвали — ростер остался на прежнем языке");
            Assert.AreEqual(0, вкладка.ТелоСобрали,
                "поверх своего способа сделали ещё и пересборку — лист вернулся к прежним именам");
            Assert.AreEqual(1, раздел.ШапкуПеречитали, "шапку перечитывает база — независимо от того, как переодето тело");
            Assert.AreEqual(1, вкладка.ШапкуПеречитали,
                "экран со своим переодеванием тела остался без шапки: заголовок на прежнем языке");
        }

        [Test]
        public void ЭкранБезСпискаПереодеваетсяМолча()
        {
            // Смена языка идёт ОДНИМ обходом по всему дереву, и накладные
            // экраны в нём все до единого. Попапу переодевать нечего — но
            // упади он здесь, и обход оборвётся на нём: экраны, стоящие в
            // дереве дальше, останутся на прежнем языке, а игрок увидит
            // наполовину переключённое приложение.
            var простой = new Простой();

            Assert.DoesNotThrow(() => простой.Redress(), "переодевание уронило экран, которому нечего переодевать");
            Assert.DoesNotThrow(() => простой.Rebuild(), "пересборка уронила экран, которому нечего пересобирать");
        }

        // ── наложение поверх листа ──────────────────────────────────────────

        [Test]
        public void СменаГлавыТожеСнимаетНаложение()
        {
            // ПЯТЫЙ ВЫХОД. Про наложение знали четыре: «отмена» внутри самой
            // карточки, оба ответа модального витка и уход по вкладке. А
            // <c>Hide</c> — «убрать немедленно», смена главы и выход в меню, —
            // не знал; роутер оболочки зовёт его на КАЖДОЙ навигации, так что
            // это не край, а половина переходов.
            //
            // Экран гас, а карточка оставалась его невидимым ребёнком и
            // всплывала при следующем открытии — уже поверх ДРУГОЙ новеллы:
            // пересборка страницы чистит ленту, а не корень экрана.
            var раздел = new Раздел();
            var подтверждение = new VisualElement();
            var лист = раздел.ПоставитьЛист();
            раздел.ПоложитьПоверх(подтверждение);

            раздел.Hide();

            Assert.IsNull(подтверждение.parent,
                "смена главы погасила экран, а подтверждение осталось на нём — оно всплывёт над другой новеллой");
            Assert.IsFalse(раздел.ЧтоТоПоверхЛиста);
            Assert.AreEqual(DisplayStyle.None, раздел.style.display.value, "экран не убрался с раскладки");
            Assert.AreEqual(0f, раздел.style.opacity.value, 1e-4f, "экран остался видимым поверх новой главы");
            Assert.AreSame(раздел, лист.parent,
                "вместе с наложением снесли и лист — вернувшийся раздел окажется пустым");
        }
    }
}
