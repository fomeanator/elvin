using Lvn.UI;
using NUnit.Framework;

namespace Lvn.Tests
{
    /// <summary>
    /// ВАЖЕН ТОЛЬКО САМЫЙ НОВЫЙ (<see cref="LvnNewest"/>).
    ///
    /// <para>Проверяется то, чем очередь отличается от отсутствия очереди:
    /// обогнанный узнаёт об этом и уходит, ничего не тронув. Цена отсутствия —
    /// не лишняя работа, а НЕВЕРНЫЙ ИТОГ: две загрузки, начатые подряд,
    /// приходят в любом порядке, и победивший последним ставит своё — то есть
    /// старое. Ни исключения, ни строки в логе при этом нет.</para>
    ///
    /// <para>Отдельно проверяется, что номера не обнуляются. Обнули — и
    /// опоздавший однажды снова окажется «новейшим», потому что счётчик
    /// вернулся к его номеру; единственная защита от него в том, что его номер
    /// уже не повторится.</para>
    /// </summary>
    public class NewestTests
    {
        private const string Линия = "manifest";

        [Test]
        public void ПоследнийВошедшийОтменяетПрежнего()
        {
            var q = new LvnNewest();
            int первый = q.Claim(Линия);
            int второй = q.Claim(Линия);

            Assert.IsFalse(q.Mine(Линия, первый), "первого обогнали — трогать экран нельзя");
            Assert.IsTrue(q.Mine(Линия, второй), "второй новейший");
            Assert.AreNotEqual(первый, второй);
        }

        /// <summary>Линии независимы: приёмка каталога не отменяет показ актёра
        /// оттого, что случилась позже.</summary>
        [Test]
        public void ЛинииНеЗадеваютДругДруга()
        {
            var q = new LvnNewest();
            int каталог = q.Claim("manifest");
            q.Claim("actor:hill");
            Assert.IsTrue(q.Mine("manifest", каталог), "чужая линия отменила нашу работу");
        }

        /// <summary>Номер, взятый до сброса, не имеет права снова стать
        /// новейшим. Обнуление счётчика — единственный способ это сломать, и
        /// поэтому его здесь нет вовсе: правило проверяется тем, что номера
        /// только растут.</summary>
        [Test]
        public void НомераТолькоРастут()
        {
            var q = new LvnNewest();
            int давний = q.Claim(Линия);
            for (int i = 0; i < 50; i++) q.Claim(Линия);
            Assert.IsFalse(q.Mine(Линия, давний), "давний номер снова стал новейшим");
            Assert.Greater(q.Claim(Линия), давний + 50);
        }

        /// <summary>Отмена никого не начинает: «этот таймер больше не наш».
        /// После неё прежний владелец обогнан, а нового владельца нет.</summary>
        [Test]
        public void ОтменаОбгоняетНикогоНеНачиная()
        {
            var q = new LvnNewest();
            int мой = q.Claim(Линия);
            q.Supersede(Линия);
            Assert.IsFalse(q.Mine(Линия, мой));
        }

        /// <summary>
        /// НЕЗНАКОМАЯ ЛИНИЯ ОТВЕЧАЕТ «ДА».
        ///
        /// <para>Правило не должно ОТМЕНЯТЬ работу там, где его не заводили:
        /// иначе новая линия, где номер ещё никто не брал, молча выключала бы
        /// весь свой тракт — и выключала бы тихо, как всё в этой теме.</para>
        /// </summary>
        [TestCase("линии такой нет", 7)]
        [TestCase(null, 1)]
        [TestCase("", 1)]
        public void НезнакомаяЛинияНеОтменяет(string линия, int номер)
        {
            var q = new LvnNewest();
            Assert.IsTrue(q.Mine(линия, номер));
        }

        /// <summary>Безымянная линия и номера не выдаёт: иначе её «номер»
        /// стал бы нулём у всех сразу, и все были бы друг другу новейшими.</summary>
        [Test]
        public void БезымяннаяЛинияНомеровНеВыдаёт()
        {
            var q = new LvnNewest();
            Assert.AreEqual(0, q.Claim(null));
            Assert.AreEqual(0, q.Claim(""));
        }
    }
}
