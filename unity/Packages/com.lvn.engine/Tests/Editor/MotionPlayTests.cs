using System.Threading.Tasks;
using Lvn.UI;
using NUnit.Framework;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// ОЖИДАНИЕ КОНЦА ДВИЖЕНИЯ ВСЕГДА ЗАВЕРШАЕТСЯ.
    ///
    /// <para>Приём «завести обещание, разрешить его на последнем кадре, ждать»
    /// стоял дважды и оба раза без предохранителя. Движение обрывается —
    /// поверхность вынули из дерева, документ пересобрали, сменили тему, — и
    /// последнего кадра не будет никогда.</para>
    ///
    /// <para>У вкладок это хуже всего: на время перехода поднят флаг «занято», а
    /// снимается он ПОСЛЕ ожидания. Оборванная анимация оставила бы флаг
    /// поднятым навсегда, и вкладки перестали бы переключаться до
    /// перезапуска.</para>
    /// </summary>
    public sealed class MotionPlayTests
    {
        // Поверхности вне живого документа UI Toolkit не анимирует вовсе: её
        // ход не начнётся, последнего кадра не будет. Ровно тот случай, ради
        // которого заведён предохранитель.
        [Test]
        public async Task ДвижениеВнеДокументаНеОставляетЖдущегоНавсегда()
        {
            var el = new VisualElement();
            var ход = LvnMotion.PlayAsync(el, 10, (_, __) => { });

            var сторож = Task.Delay(5000);
            var первый = await Task.WhenAny(ход, сторож);

            Assert.AreSame(ход, первый,
                "ожидание конца движения не завершилось: вызывающий останется висеть, "
                + "а у вкладок вместе с ним останется поднятым флаг «занято»");
        }

        // Пустая поверхность — не повод повиснуть: вызывающий получает ответ
        // сразу и доводит состояние сам, как и после настоящего движения.
        [Test]
        public async Task ПустаяПоверхностьЗавершаетОжиданиеСразу()
        {
            var ход = LvnMotion.PlayAsync(null, 100, (_, __) => { });
            var первый = await Task.WhenAny(ход, Task.Delay(2000));
            Assert.AreSame(ход, первый, "ожидание по пустой поверхности не завершилось");
        }
    }
}
