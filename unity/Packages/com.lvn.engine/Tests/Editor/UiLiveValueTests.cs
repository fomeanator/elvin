using System.Collections.Generic;
using Lvn.UI;
using Newtonsoft.Json.Linq;
using NUnit.Framework;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// ЖИВОЕ ЗНАЧЕНИЕ ДЕРЕВА <c>ui</c> — <see cref="LvnUiLive"/>: «{hp}/{hp_max}»
    /// в подписи, доля в полосе, цвет по переменной.
    ///
    /// <para>Дом не знает, что нарисовано, — только что вот этот элемент
    /// показывает вот это выражение и обязан меняться следом за переменными.
    /// Через слой (<see cref="UiLayerTests"/>) проверено, что опрос доходит до
    /// элемента, не трогает неизменившееся и двигает заливку полосы. Здесь —
    /// правила, которые из слоя не видны: КОГО вообще берут в опрос, чем
    /// кончается упавшее выражение соседа и куда именно ложится значение по
    /// имени поля.</para>
    /// </summary>
    public class UiLiveValueTests
    {
        private static Dictionary<string, JToken> Пер(params (string имя, JToken знач)[] пары)
        {
            var d = new Dictionary<string, JToken>();
            foreach (var p in пары) d[p.имя] = p.знач;
            return d;
        }

        /// <summary>Полоса такая же, какую строит слой: рамка с классом полосы
        /// и заливка внутри. Ширину двигают у заливки, а не у рамки.</summary>
        private static VisualElement Полоса()
        {
            var рамка = new VisualElement();
            рамка.AddToClassList(LvnUiLayer.BarClass);
            var заливка = new VisualElement();
            заливка.style.width = Length.Percent(0f);
            рамка.Add(заливка);
            return рамка;
        }

        // ── кого берут в опрос ──────────────────────────────────────────────

        // Статическую подпись не опрашивает НИКТО: привязки у неё нет, и
        // другого случая поставить ей текст не будет. Не поставь его в момент
        // объявления — и «Инвентарь» над списком не появится вовсе, хотя автор
        // его написал.
        [Test]
        public void СтатическоеЗначениеСтавитсяВМоментОбъявления()
        {
            var подпись = new Label();

            new LvnUiLive().Bind(подпись, "text", (JToken)"Инвентарь");

            Assert.AreEqual("Инвентарь", подпись.text,
                "неизменная подпись осталась пустой — поставить её больше некому");
        }

        // Привязка заводится ТОЛЬКО на значение с {…}. Завести её на «Инвентарь»
        // значит каждый такт считать выражение, сравнивать строки и трогать
        // элемент — за то, что измениться не может. Таких подписей в дереве
        // десятки, а такт у них общий с игрой.
        [Test]
        public void ВОпросБерутТолькоТоЧтоМожетИзмениться()
        {
            var неизменное = new LvnUiLive();
            неизменное.Bind(new Label(), "text", (JToken)"Инвентарь");
            Assert.IsFalse(неизменное.Any,
                "неизменная подпись попала в опрос — движок будет пересчитывать её шестнадцать раз в секунду");

            var живое = new LvnUiLive();
            живое.Bind(new Label(), "text", (JToken)"{hp}");
            Assert.IsTrue(живое.Any, "живое значение мимо опроса — оно замрёт на первом кадре");
        }

        // ── принудительный опрос ────────────────────────────────────────────

        // Обычный опрос НЕ ТРОГАЕТ неизменившееся — иначе он затирал бы всё, что
        // живёт на элементе между тактами. Ровно из-за этого и нужен `force`:
        // после пересборки узла элемент новый, на нём умолчание, а дом помнит,
        // что «уже показано 10», и по своему правилу промолчит. Без
        // принудительного опроса пересобранное дерево остаётся с пустыми
        // подписями и схлопнутыми полосами до первого изменения переменной —
        // то есть иногда навсегда.
        [Test]
        public void ПринудительныйОпросСтавитЗановоДажеНеизменившееся()
        {
            var подпись = new Label();
            var живое = new LvnUiLive();
            var перем = Пер(("hp", 10));

            живое.Bind(подпись, "text", (JToken)"{hp}");
            живое.Refresh(перем, force: false);
            Assert.AreEqual("10", подпись.text, "первый опрос не подставил значение переменной");

            подпись.text = "";              // узел пересобрали: на экране умолчание
            живое.Refresh(перем, force: false);
            Assert.AreEqual("", подпись.text,
                "обычный опрос полез в неизменившееся — тогда `force` был бы не нужен вовсе");

            живое.Refresh(перем, force: true);
            Assert.AreEqual("10", подпись.text,
                "принудительный опрос не поставил значение — пересобранный интерфейс останется пустым");
        }

        // Выражение пишет автор, а опрос идёт СПИСКОМ. Упади он на одном
        // выражении наружу — всё, что стояло за ним, перестанет обновляться:
        // счётчики, полосы, цены. Одна опечатка гасит остальной интерфейс, и
        // связь между ней и погасшим экраном не видна ниоткуда.
        [Test]
        public void СломанноеВыражениеНеГаситСоседние()
        {
            var битая = new Label();
            var соседняя = new Label();
            var живое = new LvnUiLive();
            var перем = Пер(("герой", new JObject { ["имя"] = "Вика" }), ("hp", 7));

            живое.Bind(битая, "text", (JToken)"{герой.имя[}");   // незакрытая скобка в пути
            живое.Bind(соседняя, "text", (JToken)"{hp}");

            Assert.DoesNotThrow(() => живое.Refresh(перем, force: false),
                "опечатка автора в выражении уронила опрос всего дерева");
            Assert.AreEqual("7", соседняя.text,
                "соседняя привязка не обновилась — одна опечатка погасила остальной интерфейс");
        }

        // ── куда ложится значение ───────────────────────────────────────────

        // `text` — одно авторское поле, а элемент под ним движок выбирает сам:
        // узел с нажатием становится кнопкой, без него — подписью. Автор про
        // это различие не знает и знать не должен. Пропусти кнопку — и надписи
        // на ней не будет вовсе: текст у кнопки лежит в своём поле.
        [Test]
        public void ТекстДоходитИДоКнопки_АНеТолькоДоПодписи()
        {
            var подпись = new Label();
            var кнопка = new Button();

            LvnUiLive.Set(подпись, "text", "Взять");
            LvnUiLive.Set(кнопка, "text", "Взять");

            Assert.AreEqual("Взять", подпись.text, "текст не дошёл до подписи");
            Assert.AreEqual("Взять", кнопка.text,
                "текст не дошёл до кнопки — она останется безымянной, хотя автор надпись написал");
        }

        // Непонятая прозрачность — ВИДИМЫЙ элемент, а не ноль. Невидимая кнопка
        // продолжает ловить нажатия и выглядит как пустое место: игрок жмёт
        // мимо, автор ищет ошибку в сценарии.
        [Test]
        public void НепонятаяПрозрачность_ЭлементВидим()
        {
            var эл = new VisualElement();

            LvnUiLive.Set(эл, "opacity", "почти");

            Assert.AreEqual(1f, эл.style.opacity.value, 0.001f,
                "опечатка в прозрачности сделала элемент невидимым, но нажимаемым");
        }

        // ── полоса ──────────────────────────────────────────────────────────

        // У полосы красить нужно ЗАЛИВКУ. Рамка — это её пустой след; покрасив
        // рамку, получаешь «цвет вроде применился», пока не посмотришь на
        // заполненную часть. Цвет полосы чаще всего и есть живое значение —
        // зелёный к красному по остатку здоровья, — то есть красится он на
        // каждом такте, и ошибка тут не разовая.
        [Test]
        public void ЦветПолосыКраситЗаливку()
        {
            var полоса = Полоса();

            LvnUiLive.Set(полоса, "color", "accent");

            Assert.AreEqual(LvnTokens.Accent, полоса[0].style.backgroundColor.value,
                "покрасился пустой след полосы, а заполненная часть осталась прежней");
        }

        // Долю пишут и процентом: «50%» — та же половина, что «0.5». Формы
        // равноправны во всём языке, и шкала не имеет права быть исключением —
        // иначе автор пишет привычное «{hp*100/max}%» и получает полоску в
        // полпроцента.
        [Test]
        public void ДоляПолосыПишетсяИПроцентом()
        {
            var полоса = Полоса();

            LvnUiLive.Set(полоса, "value", "50%");

            Assert.AreEqual(50f, полоса[0].style.width.value.value, 0.001f,
                "процент в доле полосы понят не как половина");
        }

        // Непонятая доля оставляет полосу КАК БЫЛА. Выражение на кадр вернёт
        // «{hp}» (переменной ещё нет в этой главе) или пустоту — обнулить по
        // такому поводу шкалу значит показать игроку смерть на ровном месте, а
        // потом вернуть здоровье обратно.
        [Test]
        public void НепонятаяДоляОставляетПолосуКакБыла()
        {
            var полоса = Полоса();
            LvnUiLive.Set(полоса, "value", "0.5");

            LvnUiLive.Set(полоса, "value", "{hp}");

            Assert.AreEqual(50f, полоса[0].style.width.value.value, 0.001f,
                "нечитаемая доля обнулила шкалу — игрок увидит пустую полосу здоровья");
        }

        // Переход у заливки заводится ОДИН раз. Доля меняется каждый такт, а
        // списки свойств перехода накопительные: переписывай их на каждом
        // кадре — и они растут без конца, а переход перестаёт быть переходом.
        [Test]
        public void ПереходЗаливкиЗаводитсяОдинРаз()
        {
            var полоса = Полоса();

            LvnUiLive.Set(полоса, "value", "0.9");
            LvnUiLive.Set(полоса, "value", "0.6");
            LvnUiLive.Set(полоса, "value", "0.3");

            var длительность = полоса[0].style.transitionDuration.value;
            Assert.IsNotNull(длительность, "у заливки нет перехода — потеря здоровья будет прыжком");
            Assert.AreEqual(1, длительность.Count,
                "переход переписывается на каждом такте — список свойств растёт без конца");
            Assert.AreEqual(1, полоса[0].style.transitionProperty.value.Count,
                "список свойств перехода вырос — заливка едет уже не только шириной");
        }

        // ── живой размер ────────────────────────────────────────────────────

        /// <summary>Схлопнут ли узел в невидимую точку: длина ЗАДАНА и равна
        /// нулю. «auto» и незаданная длина схлопыванием не считаются — там
        /// размер решает раскладка, и узел остаётся на экране.</summary>
        private static bool СхлопнутВНоль(StyleLength длина)
            => длина.keyword != StyleKeyword.Auto
               && длина.keyword != StyleKeyword.Null
               && длина.value.value == 0f;

        // ЖИВОЙ РАЗМЕР НАЧИНАЕТ ЖИЗНЬ ВИДИМЫМ — та же беда, что у живого
        // скрытия, и тем же корнем. Значение кладётся сразу, до первого опроса,
        // а сырым шаблоном `{cardW}` оно разбирается КАК ДЛИНА и даёт ноль:
        // узел схлопывается в невидимую точку. Опрос это чинит через миг — но
        // только если переменная уже есть. Нет её (глава объявит позже, или
        // автор опечатался в имени) — и карточка, которую автор написал и видит
        // в дереве, не появится НИКОГДА: ни пустого места, ни жалобы, ни следа.
        // Безопасное умолчание у размера одно: пусть до первого опроса действует
        // то, что поставила раскладка.
        [Test]
        public void ЖивойРазмерНеСхлопываетУзелДоПервогоОпроса()
        {
            var карточка = new VisualElement();
            var живое = new LvnUiLive();

            живое.Bind(карточка, "w", (JToken)"{cardW}");

            Assert.IsFalse(СхлопнутВНоль(карточка.style.width),
                "сырой шаблон разобран как длина и дал ноль — узел схлопнулся в невидимую точку "
                + "ещё до того, как выражение кто-нибудь посчитал");

            живое.Refresh(Пер(("cardW", 120)), force: false);
            Assert.AreEqual(120f, карточка.style.width.value.value, 0.001f,
                "живая ширина не доехала до узла на первом же опросе");
        }

        // ПЕРЕМЕННОЙ ЕЩЁ НЕТ — ЭТО НЕ ПОВОД УБРАТЬ УЗЕЛ. Опрос без переменных
        // пропускается целиком, а опрос с чужими переменными возвращает сырое
        // «{cardH}»: обе дороги ведут к нулю, если ноль вообще разрешено
        // ставить. Переменная появляется позже — на третьей реплике главы, — и
        // до тех пор панель обязана стоять на экране, а не ждать невидимой
        // точкой, из которой она может и не вернуться.
        [Test]
        public void ЖивойРазмерБезПеременнойНеПрячетУзелНавсегда()
        {
            var карточка = new VisualElement();
            var живое = new LvnUiLive();
            живое.Bind(карточка, "h", (JToken)"{cardH}");

            живое.Refresh(null, force: false);          // переменных в главе ещё нет вовсе
            Assert.IsFalse(СхлопнутВНоль(карточка.style.height),
                "без переменных узел схлопнулся — опрашивать его больше нечем, и он пропал навсегда");

            живое.Refresh(Пер(("gold", 10)), force: true);   // переменные есть, этой среди них нет
            Assert.IsFalse(СхлопнутВНоль(карточка.style.height),
                "нечитаемая высота обнулила узел — карточка исчезла с экрана, хотя автор её написал");

            живое.Refresh(Пер(("cardH", 64)), force: false); // глава объявила её только сейчас
            Assert.AreEqual(64f, карточка.style.height.value.value, 0.001f,
                "переменная появилась, а высота за ней не пошла");
        }

        // НЕПОНЯТАЯ ДЛИНА ОСТАВЛЯЕТ УЗЕЛ КАК БЫЛ — то же правило, что у доли
        // полосы. Выражение живёт всю главу и на каком-то такте вернёт не число:
        // переменную сбросили, ветка ушла в другую сцену, автор написал «{hp}»
        // там, где hp ещё не заведена. Схлопнуть узел по такому поводу значит
        // мигнуть игроку пропавшей панелью посреди сцены и вернуть её обратно —
        // ровно так выглядит поломка отрисовки.
        [Test]
        public void НепонятаяЖиваяДлинаОставляетУзелКакБыл()
        {
            var карточка = new VisualElement();

            LvnUiLive.Set(карточка, "w", "120");
            LvnUiLive.Set(карточка, "w", "{cardW}");

            Assert.AreEqual(120f, карточка.style.width.value.value, 0.001f,
                "нечитаемая ширина обнулила узел — панель мигнула схлопнутой посреди сцены");
        }

        // ── живое скрытие ───────────────────────────────────────────────────

        // ЖИВОЕ СКРЫТИЕ НАЧИНАЕТ ЖИЗНЬ ВИДИМЫМ. Значение кладётся сразу, до
        // первого опроса, — и сырым шаблоном оно выглядит как непустая
        // незнакомая строка, а такая в разметке НАМЕРЕННО значит согласие.
        // Поэтому узел с `hide="{gold < 10}"` уходил в невидимость ещё до того,
        // как кто-то посчитал выражение; а если переменных в этой главе ещё
        // нет, опрос молчит вовсе — и панель, которую автор написал и видит в
        // дереве, не появляется НИКОГДА. Безопасное умолчание у скрытия одно:
        // показать. Лишняя видимая панель — заметный пустяк, пропавшая — час
        // поисков в сценарии.
        [Test]
        public void ЖивоеСкрытиеНачинаетЖизньВидимым()
        {
            var эл = new VisualElement();
            var живое = new LvnUiLive();

            живое.Bind(эл, "hide", (JToken)"{gold < 10}");

            Assert.AreEqual(DisplayStyle.Flex, эл.style.display.value,
                "узел спрятался по сырому шаблону — игрок не увидит панель, которую автор написал");

            // Переменных ещё нет (глава их не объявила) — опрос пропускается
            // целиком, и это НЕ повод оставить узел спрятанным.
            живое.Refresh(null, force: false);
            Assert.AreEqual(DisplayStyle.Flex, эл.style.display.value,
                "без переменных узел так и остался спрятанным — панель не появится до конца главы");
        }

        // После опроса скрытие слушается выражения В ОБЕ СТОРОНЫ. Условие на то
        // и живое, что меняется по ходу сцены: подсказка «не хватает золота»
        // обязана и появиться, когда денег мало, и уйти, когда их стало
        // достаточно. Односторонний переход — это либо вечная подсказка, либо
        // подсказка, которую нельзя показать второй раз.
        [Test]
        public void ПослеОпросаЖивоеСкрытиеСлушаетсяВыраженияВОбеСтороны()
        {
            var эл = new VisualElement();
            var живое = new LvnUiLive();
            живое.Bind(эл, "hide", (JToken)"{gold < 10}");

            живое.Refresh(Пер(("gold", 5)), force: false);
            Assert.AreEqual(DisplayStyle.None, эл.style.display.value,
                "условие сошлось, а узел на экране остался — скрытие по выражению не работает вовсе");

            живое.Refresh(Пер(("gold", 50)), force: false);
            Assert.AreEqual(DisplayStyle.Flex, эл.style.display.value,
                "условие разошлось, а узел не вернулся — спрятанное живым условием уже не показать");
        }

        // Статическое `hide=true` прячет СРАЗУ и без всякого опроса: живого в
        // нём нет, привязки не будет, и другого случая спрятать этот узел не
        // представится. Показать его на первом кадре значит показать навсегда.
        [Test]
        public void СтатическоеСкрытиеПрячетСразу()
        {
            var спрятанный = new VisualElement();
            var видимый = new VisualElement();
            var живое = new LvnUiLive();

            живое.Bind(спрятанный, "hide", (JToken)"true");
            живое.Bind(видимый, "hide", (JToken)"false");

            Assert.AreEqual(DisplayStyle.None, спрятанный.style.display.value,
                "`hide=true` не спрятал узел — прятать его больше некому");
            Assert.AreEqual(DisplayStyle.Flex, видимый.style.display.value,
                "`hide=false` спрятал узел — автор написал обратное");
            Assert.IsFalse(живое.Any,
                "неизменное скрытие попало в опрос — движок будет пересчитывать его всю главу");
        }
    }
}
