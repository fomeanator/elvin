using Lvn;
using Lvn.Services;
using NUnit.Framework;

namespace Lvn.Tests
{
    /// <summary>
    /// ЧАСЫ ИГРОКА НЕ ДВИГАЮТ ВОСПОЛНЕНИЕ.
    ///
    /// <para>Энергия копится по часам СЕРВЕРА: он присылает абсолютную метку
    /// следующего начисления. «Сколько осталось» считалось вычитанием
    /// локального «сейчас» — то есть по часам, которые принадлежат игроку.
    /// Замер 05.09 на живом сервере: до начисления 7199 с, а та же формула при
    /// часах, переведённых на сутки вперёд, даёт −79201 с — интерфейс говорит
    /// «готово», а сервер на трату отвечает отказом (409). Обратный случай тише
    /// и вреднее: отставшие часы заставляют ждать лишнее при уже начисленной
    /// энергии.</para>
    ///
    /// <para>Починка: сервер называет своё «сейчас» (поле <c>now</c>), клиент
    /// держит поправку, а бег времени между ответами берёт у МОНОТОННЫХ часов
    /// приложения — тогда перевод системных часов прямо во время игры тоже
    /// ничего не сдвигает.</para>
    /// </summary>
    public class RefillClockTests
    {
        private const string Валюта = "энергия";

        private static void Ответ(long серверСейчас, long следующее)
        {
            LvnWallet.Apply(@"{""balances"":{""" + Валюта + @""":0},""inventory"":{},""regen"":{""" + Валюта + @""":{"
                + @"""balance"":0,""cap"":3,""interval_seconds"":7200,""next_refill_unix"":" + следующее + "}},"
                + @"""now"":" + серверСейчас + "}");
        }

        [TearDown]
        public void Уборка() => LvnClock.Wall = () => UnityEngine.Time.realtimeSinceStartup;

        [Test]
        public void ПереводСистемныхЧасовНеДвигаетОтсчёт()
        {
            float ход = 1000f;
            LvnClock.Wall = () => ход;
            long серверСейчас = 1_800_000_000;
            Ответ(серверСейчас, серверСейчас + 7200);

            Assert.AreEqual(7200, LvnWallet.SecondsUntilRefill(Валюта),
                "сразу после ответа ждать ровно столько, сколько сказал сервер");

            // Игрок перевёл часы устройства на сутки вперёд: системное время
            // изменилось, монотонные часы приложения — нет. Ответ не меняется.
            Assert.AreEqual(7200, LvnWallet.SecondsUntilRefill(Валюта),
                "перевод системных часов сдвинул отсчёт — счётчик скажет «готово», а сервер откажет");

            ход += 200f;   // а настоящее ожидание отсчёт двигать обязано
            Assert.AreEqual(7000, LvnWallet.SecondsUntilRefill(Валюта),
                "прошло двести настоящих секунд, а счётчик стоит");
        }

        [Test]
        public void ОтсчётИдётПоСерверномуВремениАНеПоУстройству()
        {
            float ход = 500f;
            LvnClock.Wall = () => ход;
            long серверСейчас = 1_800_000_000;   // заведомо не совпадает с часами машины
            Ответ(серверСейчас, серверСейчас + 60);

            Assert.AreEqual(60, LvnWallet.SecondsUntilRefill(Валюта),
                "отсчёт считается по чужим часам — при расхождении игрок ждёт не то, что сервер");

            ход += 60f;
            Assert.AreEqual(0, LvnWallet.SecondsUntilRefill(Валюта),
                "время вышло, а счётчик всё ещё показывает ожидание");
        }

        [Test]
        public void СтарыйСерверБезПоляВремениНеЛомаетОтсчёт()
        {
            LvnClock.Wall = () => 0f;
            // Клиент, НИКОГДА не видевший серверного времени: поправки нет.
            LvnWallet.ForgetServerClock();
            LvnWallet.Apply(@"{""balances"":{""" + Валюта + @""":0},""inventory"":{},""regen"":{""" + Валюта + @""":{"
                + @"""balance"":0,""cap"":3,""interval_seconds"":7200,""next_refill_unix"":"
                + (System.DateTimeOffset.UtcNow.ToUnixTimeSeconds() + 120) + "}}}");

            Assert.That(LvnWallet.SecondsUntilRefill(Валюта), Is.InRange(100, 130),
                "без серверного времени отсчёт обязан падать на прежнее поведение, а не обнуляться");
        }

        [Test]
        public void ПолныйКошелёкНичегоНеЖдёт()
        {
            LvnClock.Wall = () => 0f;
            long серверСейчас = 1_800_000_000;
            LvnWallet.Apply(@"{""balances"":{""" + Валюта + @""":3},""inventory"":{},""regen"":{""" + Валюта + @""":{"
                + @"""balance"":3,""cap"":3,""interval_seconds"":7200,""next_refill_unix"":0}},"
                + @"""now"":" + серверСейчас + "}");

            Assert.AreEqual(0, LvnWallet.SecondsUntilRefill(Валюта),
                "на полном кошельке счётчик обязан молчать");
        }
    }
}
