using System.Globalization;

namespace Lvn.Content
{
    /// <summary>
    /// ОБРЕЗАТЬ ДЛИННОЕ — так, чтобы обрезок остался текстом.
    ///
    /// <para>Правило «взять первые N символов и приписать многоточие» стояло
    /// тремя реализациями и с разными числами. Превью автосейва — той же
    /// строки! — резалось по 40 в карусели и по 46 в меню сцены: два экрана
    /// показывали одну запись по-разному, и совпадение это или нет, знал только
    /// тот, кто писал оба.</para>
    ///
    /// <para>Наивная обрезка портит текст тремя способами, и все три видны
    /// игроку:</para>
    ///
    /// <list type="bullet">
    /// <item><b>Рвёт пару.</b> Эмодзи и редкие буквы записаны ДВУМЯ символами;
    /// разрез между ними даёт «□» — знак, которого в тексте не было.</item>
    /// <item><b>Оставляет хвост.</b> «Привет, » + «…» читается как опечатка:
    /// пробел и запятая перед многоточием — мусор, а не сокращение.</item>
    /// <item><b>Режет ради ничего.</b> Строка длиннее предела на один символ
    /// превращается в обрезанную — хотя целиком она короче, чем обрезок с
    /// многоточием.</item>
    /// </list>
    /// </summary>
    public static class LvnClip
    {
        /// <summary>Многоточие одним символом: три точки подряд выглядят как
        /// опечатка и занимают втрое больше места.</summary>
        public const string Ellipsis = "…";

        /// <summary>Обрезать до <paramref name="max"/> символов вместе с
        /// многоточием. Короткая строка возвращается как есть.</summary>
        public static string Text(string s, int max)
        {
            if (string.IsNullOrEmpty(s) || max <= 0) return s ?? "";
            if (s.Length <= max) return s;
            // Обрезок с многоточием обязан ПОМЕСТИТЬСЯ в предел, иначе смысл
            // предела теряется: подпись всё равно выедет за отведённое место.
            int cut = max - 1;
            if (cut <= 0) return Ellipsis;
            // Не рвём суррогатную пару: половина пары — это «□».
            if (cut > 0 && char.IsHighSurrogate(s[cut - 1])) cut--;
            // И не рвём составной символ (буква с диакритикой, эмодзи с
            // модификатором): граница берётся по ТЕКСТОВОМУ элементу.
            cut = SafeBoundary(s, cut);
            var head = s.Substring(0, cut).TrimEnd();
            head = head.TrimEnd(',', ';', ':', '-', '—', '–', '.', '!', '?', ' ');
            return head.Length == 0 ? Ellipsis : head + Ellipsis;
        }

        /// <summary>Сколько символов превью сохранения помещается в строку
        /// списка. Число здесь, а не у каждого экрана: превью одной и той же
        /// записи, обрезанное по-разному, читается как разные сохранения.</summary>
        public const int PreviewMax = 46;

        /// <summary>Короткий идентификатор для экрана: «u_e25fc02ed2…». Правило
        /// одно на профиль и настройки — раньше его писали дважды, и разойтись
        /// им мешала только память автора.</summary>
        public static string Id(string id, int max = 13) => Text(id, max);

        // Ближайшая граница текстового элемента слева: разрез внутри составного
        // символа рисуется как отдельные точки и палочки.
        private static int SafeBoundary(string s, int cut)
        {
            if (cut <= 0 || cut >= s.Length) return cut;
            var e = StringInfo.GetTextElementEnumerator(s);
            int last = 0;
            while (e.MoveNext())
            {
                int i = e.ElementIndex;
                if (i > cut) return last;
                last = i;
            }
            return cut;
        }
    }
}
