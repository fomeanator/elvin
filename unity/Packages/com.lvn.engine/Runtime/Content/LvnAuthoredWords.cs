using System.Collections.Generic;

namespace Lvn.Content
{
    /// <summary>
    /// ПОДПИСИ, ЗАДАННЫЕ ПОЛЯМИ МАНИФЕСТА, — переведённые в ключи словаря.
    ///
    /// <para>Автор задаёт слово двумя способами: словарём (<c>ui.words</c>,
    /// ключ → слово) и ПОЛЕМ секции (<c>ui.wardrobe.equip_text</c>). Первый —
    /// нынешний, второй — прежний, и живы оба. Экран, знающий про поле, зовёт
    /// <c>LvnWords.Pick(ключ, поле, англ.)</c>; экран, не знающий, — просто
    /// <c>Of(ключ, англ.)</c>. Разница невидима глазом и решается тем, вспомнил
    /// ли автор строки поле в момент, когда писал экран.</para>
    ///
    /// <para>Чем это кончалось: в живом манифесте стояли «Надеть», «Надето»,
    /// «Снять» и «+{0} бонусом», а игрок видел Equip, Equipped, None и
    /// «+300 bonus» — четыре английских слова посреди русской игры. Поле было
    /// написано правильно; его просто никто не спрашивал.</para>
    ///
    /// <para>Поэтому перевод «поле → ключ» собран ЗДЕСЬ, один раз, и вливается
    /// в словарь при загрузке манифеста. Экраны остаются при одном вызове
    /// <c>Of</c>, а новое поле-подпись достаточно вписать в таблицу ниже —
    /// вместо того чтобы протаскивать секцию конфига через полэкрана.</para>
    ///
    /// <para>СЛОЙ САМЫЙ НИЖНИЙ: словарь новеллы и подписи меню сильнее поля
    /// (автор, вписавший слово дважды, имел в виду то, что ближе к словарю), а
    /// перевод сильнее всех — язык выбирает игрок, а не автор.</para>
    /// </summary>
    public static class LvnAuthoredWords
    {
        /// <summary>Слова из полей секций — ключами словаря. Пустой словарь,
        /// если автор не задал ни одного.</summary>
        public static Dictionary<string, string> Fold(LvnUiConfig ui)
        {
            var map = new Dictionary<string, string>(System.StringComparer.OrdinalIgnoreCase);
            if (ui == null) return map;

            // Гардероб. Пункт «снять» в полосе примерки — тот же выбор, что
            // надеть, поэтому авторское remove_text ложится на его ключ.
            //
            // Первые два ключа принадлежат ВИТРИНЕ СКИНОВ, у которой сегодня
            // нет точки входа (`NovelShell.OpenSkinShopAsync` объявлен НЕ
            // ПОДКЛЮЧЁННЫМ). Слова автора там не пропадут, но и не покажутся,
            // пока витрину не приведут к настоящим данным. Убирать поля из-за
            // этого не за что: автор написал их правильно.
            Put(map, "skinshop.equip", ui.wardrobe?.equip_text);
            Put(map, "skinshop.equipped", ui.wardrobe?.equipped_text);
            Put(map, "wardrobe.none", ui.wardrobe?.remove_text);

            // Магазин. Шаблон с числом («+{0} бонусом») подставляется словарём
            // так же, как перевод: место числа автор указывает сам.
            Put(map, "shop.bonus", ui.store?.bonus_text);

            return map;
        }

        private static void Put(Dictionary<string, string> map, string key, string word)
        {
            if (!string.IsNullOrEmpty(word)) map[key] = word;
        }
    }
}
