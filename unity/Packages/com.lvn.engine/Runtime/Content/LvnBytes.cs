namespace Lvn.Content
{
    /// <summary>
    /// СКОЛЬКО ЭТО ЗАНИМАЕТ — размер, каким его видит игрок.
    ///
    /// <para>Перевод байтов в подпись стоял восемью экземплярами и по ТРЁМ
    /// разным правилам. Центр загрузок считал по-умному: до ста мегабайт — с
    /// десятыми, дальше — целыми. Настройки и ворота главы рубили целыми через
    /// сдвиг, подставляя <c>Max(1, …)</c>, чтобы четыреста килобайт не стали
    /// «0 МБ». Логи писали своё.</para>
    ///
    /// <para>Один и тот же объём получал разные подписи на соседних экранах:
    /// центр загрузок говорил «0,4 МБ», настройки про него же — «1 МБ», ворота
    /// главы — «≈1 МБ». Игрок складывает эти числа (сколько скачано, сколько
    /// осталось, сколько весит глава) и не может свести — а решает по ним,
    /// хватит ли трафика.</para>
    ///
    /// <para>Правила записаны здесь, и каждое — про игрока, а не про
    /// арифметику:</para>
    ///
    /// <list type="bullet">
    /// <item><b>Никогда не «0»</b>. Округление вниз превращает «есть что
    /// качать» в «нечего»: игрок жмёт кнопку, которая по её же подписи не
    /// нужна.</item>
    /// <item><b>Мелкое — с десятыми</b>. «0,4 МБ» честнее, чем «1 МБ», и
    /// заметно меньше — а это ровно то, ради чего он смотрит на число.</item>
    /// <item><b>Крупное — целыми</b>. «117,3 МБ» не помогает решить ничего,
    /// зато делает подпись длиннее и шумнее.</item>
    /// <item><b>От гигабайта — в гигабайтах</b>. «1400 МБ» человек всё равно
    /// переводит в уме, и переводит с ошибкой.</item>
    /// </list>
    ///
    /// <para>Единицы — слова новеллы (<c>unit.mb</c>, <c>unit.gb</c>),
    /// разделитель дроби — из <see cref="LvnNumberFormat"/>: подпись обязана
    /// читаться одинаково на любом телефоне.</para>
    /// </summary>
    public static class LvnBytes
    {
        private const long Mb = 1L << 20;
        private const long Gb = 1L << 30;

        /// <summary>Размер с единицей: «0,4 МБ», «117 МБ», «1,4 ГБ».</summary>
        public static string Short(long bytes)
        {
            if (bytes < 0) bytes = 0;
            if (bytes >= Gb)
                return LvnNumberFormat.Decimals(bytes / (float)Gb) + " " + LvnWords.Of("unit.gb", "GB");
            string mb = LvnWords.Of("unit.mb", "MB");
            if (bytes >= 100 * Mb) return (bytes / Mb) + " " + mb;
            // Ноль показываем ТОЛЬКО у настоящего нуля: «0,1 МБ» у ста
            // килобайт — правда, «0 МБ» у них же — неправда.
            if (bytes == 0) return "0 " + mb;
            float value = bytes / (float)Mb;
            if (value < 0.1f) value = 0.1f;
            return LvnNumberFormat.Decimals(value) + " " + mb;
        }

        /// <summary>
        /// СКОРОСТЬ: «1,4 МБ/с» или «860 КБ/с».
        ///
        /// <para>Скорость — другая величина, и правило у неё своё: килобайты в
        /// секунду осмысленны (это реальная скорость на слабой сети), а «0,1
        /// МБ/с» — нет. Дробная часть остаётся только у мегабайтов: в
        /// килобайтах она дрожит на каждом кадре и мешает читать.</para>
        /// </summary>
        public static string Speed(float bytesPerSec)
        {
            if (bytesPerSec < 0f) bytesPerSec = 0f;
            if (bytesPerSec >= Mb)
                return LvnNumberFormat.Decimals(bytesPerSec / Mb) + " " + LvnWords.Of("unit.mbs", "MB/s");
            return UnityEngine.Mathf.RoundToInt(bytesPerSec / 1024f) + " " + LvnWords.Of("unit.kbs", "KB/s");
        }

        /// <summary>Оценка: «≈117 МБ». Знак приблизительности ставится ЗДЕСЬ,
        /// чтобы он стоял одинаково — раньше половина мест писала его, половина
        /// нет, и игрок читал одно и то же число как точное и как примерное.</summary>
        public static string Approx(long bytes) => "≈" + Short(bytes);
    }
}
