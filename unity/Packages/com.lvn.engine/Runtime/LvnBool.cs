using Newtonsoft.Json.Linq;

namespace Lvn
{
    /// <summary>
    /// ЧТЕЦ «ДА-НЕТ» — что считать согласием, когда автор пишет его словом.
    ///
    /// <para>Компилятор булевых значений НЕ приводит: <c>show=no</c> доезжает до
    /// рантайма строкой «no», <c>show=0</c> — числом. Решает рантайм, и решал он
    /// ШЕСТЬЮ разными способами: команды сцены понимали <c>true/1/yes</c>,
    /// звук — только настоящее <c>true</c>, переменные плеера — тоже,
    /// UI-слой знал ещё <c>off</c> и русское <c>нет</c>, кадровая модель
    /// приводила голым <c>(bool)</c>, а сервисные операции держали самый полный
    /// словарь — приватным у себя.</para>
    ///
    /// <para>Для автора это тихий отказ в чистом виде: он пишет <c>no</c>, как
    /// написал строкой выше у актёра, и получает молча не то — музыка
    /// зацикливается, потому что «no» её чтец не понял и взял умолчание. Ошибки
    /// при этом нет нигде: ни в компиляторе, ни в логе.</para>
    ///
    /// <para>Ответственность: один словарь согласия и отказа на весь движок.
    /// Что делать с непонятым значением — решает вызывающий, потому что ответ
    /// разный: полю команды правильнее взять умолчание, а UI-слою — считать
    /// непустое незнакомое значение согласием (там оно исторически значит
    /// «свойство задано»).</para>
    ///
    /// <para>Это НЕ истинность выражения. <c>if flag</c> считает истиной любую
    /// непустую строку (см. <c>LvnExpression</c>) — это семантика языка, общая
    /// с JS-рантаймом, и сводить её с чтением поля нельзя: «no» как значение
    /// поля — отказ, а как строка в выражении — непустая строка.</para>
    /// </summary>
    public static class LvnBool
    {
        /// <summary>
        /// РАЗОБРАТЬ. <c>null</c> — значение не из словаря: не «нет», а «не
        /// понял», и различать это обязан вызывающий.
        ///
        /// <para>Словарь взят самый широкий из шести бывших — тот, что вырос у
        /// сервисных операций: сузить его значило бы отнять у авторов формы,
        /// которые уже работают в живых новеллах.</para>
        /// </summary>
        public static bool? Parse(JToken t)
        {
            if (t == null || t.Type == JTokenType.Null) return null;
            if (t.Type == JTokenType.Boolean) return t.Value<bool>();
            if (t.Type == JTokenType.Integer || t.Type == JTokenType.Float) return t.Value<double>() != 0d;
            return Parse(t.ToString());
        }

        /// <summary>Та же работа для голой строки — их читают темы и разметка,
        /// где до JSON дело не доходит.</summary>
        public static bool? Parse(string s)
        {
            if (string.IsNullOrEmpty(s)) return null;
            switch (s.Trim().ToLowerInvariant())
            {
                case "1": case "true": case "yes": case "y": case "on": case "да":
                    return true;
                case "0": case "false": case "no": case "n": case "off": case "нет":
                    return false;
                default:
                    return null;
            }
        }

        /// <summary>ЗНАЧЕНИЕ ПОЛЯ. Не понял — берём умолчание: незнакомое слово
        /// вернее считать опечаткой автора, чем его решением.</summary>
        public static bool Of(JToken t, bool fallback) => Parse(t) ?? fallback;

        /// <summary>ПОЛЕ-ПРИЗНАК: присутствует и не отменено словом.
        ///
        /// <para>Часть полей команды — не значения, а флаги: <c>fx off</c>,
        /// <c>sfx off</c>. Компилятор кладёт в них <c>true</c>, и рантайм
        /// читал их ПЯТЬЮ местами как «поле вообще есть» (<c>cmd["off"] !=
        /// null</c>), а одним — как «значение истинно».</para>
        ///
        /// <para>Расхождение спит, пока значение приходит от компилятора. Но
        /// сырой <c>.lvn</c> пишут и руками, и там <c>"off": false</c> или
        /// <c>"off": 0</c> означает ровно обратное — а четыре из пяти мест
        /// всё равно выключат. Автор написал «не выключать» и получил
        /// выключено, без единой жалобы в логе.</para>
        ///
        /// <para>Правило одно: нет поля — признака нет; есть поле — признак
        /// есть, если слово в нём не отменяет его явно.</para></summary>
        public static bool Flag(JToken t) => t != null && Of(t, true);


        /// <summary>То же для строки.</summary>
        public static bool Of(string s, bool fallback) => Parse(s) ?? fallback;

        /// <summary>ЯВНОЕ СОГЛАСИЕ. Отсутствие поля — не согласие.</summary>
        public static bool On(JToken t) => Parse(t) == true;

        /// <summary>ЯВНЫЙ ОТКАЗ — отдельный вопрос, а не отрицание согласия:
        /// у полей вроде <c>wait</c> умолчание «да», и отличить «написано нет»
        /// от «не написано ничего» обязательно.</summary>
        public static bool Off(JToken t) => Parse(t) == false;
    }
}
