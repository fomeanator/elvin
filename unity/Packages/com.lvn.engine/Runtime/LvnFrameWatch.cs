namespace Lvn
{
    /// <summary>
    /// РЫВКИ КАДРА — сколько раз игра запнулась и насколько сильно.
    ///
    /// <para>Порог и сам вопрос «это уже рывок?» жили строкой внутри цикла
    /// сцены, и ответ был только в логе: строка на каждый долгий кадр. По логу
    /// видно ЧТО случилось, но не видно, СТАЛО ЛИ ЛУЧШЕ — а именно это и
    /// спрашивают после каждой правки («приложение прям очень плавное стало» —
    /// проверить это было нечем).</para>
    ///
    /// <para>Здесь счёт: сколько запинок и какая худшая. Числа снимаются вместе
    /// с концом главы и уходят в отчёт свойствами события — так «плавнее» из
    /// ощущения становится величиной, которую видно в воронке.</para>
    ///
    /// <para>Порог 150 мс — не «просело до 6 кадров», а «глаз заметил остановку»:
    /// ниже него глаз считает движение непрерывным, выше — видит рывок.</para>
    /// </summary>
    public static class LvnFrameWatch
    {
        public const float HitchSeconds = 0.15f;

        /// <summary>Первые кадры после загрузки сцены тяжелы всегда и о плавности
        /// ничего не говорят.</summary>
        public const int WarmupFrames = 10;

        private static int _hitches;
        private static float _worst;

        /// <summary>
        /// ДЛИНА ПОСЛЕДНЕГО ПРОЖИТОГО КАДРА, мс.
        ///
        /// <para>Нужна не плавности, а ЗАМЕРАМ ОЖИДАНИЯ. Всё, чего движок ждёт
        /// через событие Unity (загрузка, распаковка, расшифровка кода),
        /// узнаёт о готовности на главном потоке, в покадровой обработке, —
        /// то есть не раньше следующей границы кадра. На буте кадры по
        /// полсекунды, и измеренное «ждали» оказывается длиной кадра, а не
        /// стоимостью работы.</para>
        ///
        /// <para>Живой пример 02.09: пять разных файлов дали 917, 925, 929,
        /// 932 и 936 мс при кадре в 955 мс. Работа так не совпадает —
        /// совпадает ожидание. Поставив это число рядом в логе, мы даём
        /// замеру объяснить себя самому.</para>
        ///
        /// <para>Пишется ДО раннего выхода: обычный кадр запинкой не считается,
        /// но длину имеет.</para>
        /// </summary>
        public static int LastFrameMs { get; private set; }

        /// <summary>Сколько запинок с прошлого снятия и какая была худшей.</summary>
        public static int Hitches => _hitches;
        public static int WorstMs => (int)(_worst * 1000f);

        /// <summary>
        /// ЧЕМ ЗАНЯТ ДВИЖОК — пояснение к запинке от того, кто это знает.
        ///
        /// <para>Кадры считает ОДНО место, живущее с первого кадра (наблюдатель
        /// панели, см. LvnPanel). Сцена знает то, чего он не знает — сборки
        /// скелетов в полёте, — и отдаёт это сюда, пока жива. Раньше сцена
        /// считала кадры сама, и на витрине, где грузится полотно, счётчик
        /// стоял: «кадр 0 мс» рядом с «wall=6451 мс» отвечал на другой вопрос.
        /// Спрашивается ТОЛЬКО у запинки.</para>
        /// </summary>
        public static System.Func<string> Busy { get; set; }

        /// <summary>Кадр прожит. <paramref name="note"/> — чем движок был занят
        /// (по умолчанию — <see cref="Busy"/>); спрашивается ТОЛЬКО когда кадр
        /// оказался рывком, чтобы обычный кадр не платил за диагностику.</summary>
        public static void Frame(float dt, int frameCount, System.Func<string> note = null)
        {
            LastFrameMs = (int)(dt * 1000f);
            if (dt <= HitchSeconds || frameCount <= WarmupFrames) return;
            _hitches++;
            if (dt > _worst) _worst = dt;
            note ??= Busy;
            LvnLog.Trace($"[lvn-perf] FRAME HITCH {(dt * 1000f):F0}ms at frame {frameCount}"
                                  + (note != null ? note() : ""));
        }

        /// <summary>Снять счёт и начать заново — конец главы, конец сессии.</summary>
        public static (int hitches, int worstMs) Take()
        {
            var r = (_hitches, WorstMs);
            _hitches = 0; _worst = 0f;
            return r;
        }
    }
}
