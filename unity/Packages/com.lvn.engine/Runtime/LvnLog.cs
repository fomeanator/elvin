using UnityEngine;

namespace Lvn
{
    /// <summary>
    /// ЖУРНАЛ ДВИЖКА с одним рубильником.
    ///
    /// <para>Диагностика копится не от любви к логам, а от охоты: чтобы поймать
    /// «белый прямоугольник вместо героини», в тракт сцены пришлось расставить
    /// десяток строк, каждая из которых печатается на КАЖДЫЙ показ меню. Баг
    /// ловится и уходит, строки остаются — и живая сборка сыплет в консоль
    /// подробностями, за которыми не видно настоящих ошибок.</para>
    ///
    /// <para>Отсюда разделение по адресату. <see cref="Trace"/> — разговор
    /// движка с собой, нужный, пока что-то ищут: в редакторе он слышен, в
    /// собранной игре молчит. <see cref="Info"/> — вехи, которые важны и в
    /// поле (что за сборка, какой контент, куда пошли деньги). <see cref="Warn"/>
    /// и <see cref="Error"/> звучат всегда: это уже не разговор, а происшествие.</para>
    ///
    /// <para>Живёт в ЯДРЕ. Пока дом стоял в сборке интерфейса, рубильника не
    /// было у трёх слоёв разом — контента, сервисов и самого ядра, — а шумит
    /// как раз контент: скачивание, кэш, вытеснение спрайтов. Рубильник,
    /// который не достаёт до самого громкого, ничего не выключает.</para>
    ///
    /// <para>Тег остаётся в самой строке (<c>[lvn-menu] …</c>) — по нему
    /// фильтруют консоль и отгружаемый лог.</para>
    /// </summary>
    public static class LvnLog
    {
        /// <summary>Слышна ли подробная диагностика. По умолчанию — в редакторе
        /// и в отладочной сборке: там её и читают. В релизной игре выключена,
        /// но включается на лету (настройки, отладочное меню, удалённая
        /// поддержка живого игрока).</summary>
        public static bool Verbose = Application.isEditor || Debug.isDebugBuild;

        /// <summary>Разговор движка с собой: шаги тракта, состояния, дампы.
        /// Строка собирается ТОЛЬКО когда её будут слышать — интерполяция в
        /// молчащем логе стоит ровно столько же, сколько в слышимом.</summary>
        public static void Trace(string message)
        {
            if (Verbose) Debug.Log(message);
        }

        /// <summary>Веха, важная и в поле: штамп сборки, выбранный контент,
        /// покупка, вход в главу.</summary>
        public static void Info(string message) => Debug.Log(message);

        /// <summary>Происшествие: что-то не сошлось, но игра продолжается.</summary>
        public static void Warn(string message) => Debug.LogWarning(message);

        /// <summary>Отказ: дальше этот тракт не работает.</summary>
        public static void Error(string message) => Debug.LogError(message);
    }
}
