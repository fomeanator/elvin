using System;
using UnityEngine;

namespace Lvn
{
    /// <summary>
    /// ВРЕМЯ ИНТЕРФЕЙСА — один ответ на «сколько прошло».
    ///
    /// <para>Источников было два, и стояли они вперемешку:
    /// <c>Time.unscaledTime</c> у таймера выбора, ожидания сцены и экранных
    /// затуханий, <c>Time.realtimeSinceStartup</c> у печати реплики и
    /// автопродвижения. Разница между ними невелика ровно до одного случая —
    /// приложение СВЕРНУЛИ.</para>
    ///
    /// <para>Кадровое время в фоне стоит: кадров нет, значит и время не идёт.
    /// Реальное идёт всегда. Игрок, свернувший игру на минуту, возвращается — и
    /// автопродвижение считает, что реплику читали минуту, и листает её сразу,
    /// а таймер выбора рядом ведёт себя правильно. Один экран, два ответа на
    /// вопрос «сколько игрок здесь пробыл».</para>
    ///
    /// <para>Взято кадровое: интерфейс живёт кадрами, и «пока игры не было на
    /// экране, время для неё не шло» — то поведение, которого игрок ждёт.</para>
    ///
    /// <para>НЕ ПУТАТЬ с <c>LvnStageClock</c>: тот про ПОРЯДОК событий сцены
    /// (эпохи, дорожки, барьеры), а не про длительности, и ему нужна
    /// монотонность, не совпадающая с ожиданиями игрока.</para>
    ///
    /// <para>ЖИВЁТ В КОРНЕВОЙ СБОРКЕ, а не среди интерфейса. Сначала он стоял в
    /// <c>Lvn.Engine.UI</c> — и слой контента, который видит только
    /// <c>Lvn.Engine</c>, дотянуться до него не мог: сроки жизни кэша и
    /// «не найдено» брали время сами. Время — инфраструктура, как разбор чисел
    /// и хранилище настроек, и стоять должно там же.</para>
    /// </summary>
    public static class LvnClock
    {
        /// <summary>Подменяется в тестах: длительности проверяются без ожидания
        /// настоящих секунд.</summary>
        public static Func<float> Now = () => Time.unscaledTime;

        /// <summary>Сколько прошло с отметки. Отрицательного не бывает: часы
        /// могли подменить между отметкой и замером.</summary>
        public static float Since(float mark) => Mathf.Max(0f, Now() - mark);

        /// <summary>ПОТОЛОК ШАГА ПО УМОЛЧАНИЮ: десятая доля секунды — несколько
        /// кадров. Больше этого «прошедшее время» уже не про плавность, а про
        /// паузу, которой на экране не было.</summary>
        public const float StepCap = 0.1f;

        /// <summary>
        /// СКОЛЬКО ПРОШЛО С ПРОШЛОГО КАДРА — но не больше потолка. Отметка
        /// времени двигается сама, поэтому зовущему остаётся одна строка.
        ///
        /// <para>Потолок нужен не для красоты. Свернули приложение на минуту и
        /// вернули — кадровые часы отдадут эту минуту одним куском, и всё, что
        /// движется по шагу, ПРЫГНЕТ: частицы окажутся за краем экрана, вспышка
        /// от касания доживёт до конца в первом же кадре. Без потолка это
        /// выглядит как сбой отрисовки, а не как возвращение из фона.</para>
        ///
        /// <para>Само правило стояло двумя копиями с разными потолками (0,1 у
        /// поля частиц и 0,05 у вспышек). Потолок и вправе отличаться — он про
        /// характер эффекта, — а вот «взять шаг и подвинуть отметку» одно на
        /// всех, и в копиях легко забыть вторую половину.</para>
        /// </summary>
        public static float Step(ref float last, float cap = StepCap)
        {
            float now = Now();
            float dt = Mathf.Min(cap, Mathf.Max(0f, now - last));
            last = now;
            return dt;
        }

        /// <summary>
        /// ВРЕМЯ, КОТОРОЕ ИДЁТ И В ФОНЕ — для страховочных сроков, а не для
        /// того, что видит игрок.
        ///
        /// <para>Кадровое время (<see cref="Now"/>) в свёрнутом приложении
        /// стоит, и это правильно для всего, что игрок ВИДИТ: пока игры нет на
        /// экране, реплику он не читает. Но ровно это свойство губит
        /// СТРАХОВКИ — «ждём готовности не дольше десяти секунд», «запись
        /// „не найдено“ живёт минуту», «не спрашивать сервер чаще раза в
        /// секунду». Свернул игру на минуту — и страховка не сработает никогда,
        /// потому что её время не шло.</para>
        ///
        /// <para>Оба ответа законны, и до сих пор выбор между ними делался
        /// молча: двадцать девять мест брали <c>Time.realtimeSinceStartup</c>
        /// напрямую, и по коду нельзя было отличить осознанное решение от
        /// первого попавшегося. Отдельное имя — это подпись под выбором, как
        /// <c>LvnQuiet.Try</c> под молчанием.</para>
        /// </summary>
        public static Func<float> Wall = () => Time.realtimeSinceStartup;
    }
}
