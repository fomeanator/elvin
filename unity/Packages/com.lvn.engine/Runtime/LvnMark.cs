using System;
using UnityEngine;

namespace Lvn
{
    /// <summary>
    /// ПАСПОРТИСТ — кто выдаёт метки: этому устройству, этому запуску, этой
    /// операции. Метка сама по себе бессмысленна, смысл ей даёт правило,
    /// по которому она выдана, а правил было три и жили они врозь.
    ///
    /// <para><b>Метка запуска стояла двумя экземплярами.</b> Аналитика
    /// порождала свою (16 знаков, уезжала в событии как <c>props.sid</c>),
    /// отправщик логов — свою (12 знаков, уезжала при пачке как
    /// <c>device.session</c>). Оба звались «сессия», оба жили ровно один
    /// запуск, и оба говорили о ТОМ ЖЕ запуске — но разными словами. Значит
    /// событие «сбой» и лог этого сбоя сшить было нельзя: отчёт видел долю
    /// сессий со сбоем, а спуститься от такой сессии к её строкам лога — уже
    /// нет. Сервер, между прочим, об этом прямо просил: в совете отчёта
    /// (<c>analytics_report.go</c>) стояло «штампуй на события ТУ ЖЕ метку
    /// сессии, что и отправщик логов». Обещание было записано, исполнено — не
    /// было.</para>
    ///
    /// <para><b>Постоянная метка выдавалась по трём рецептам.</b> Идентификатор
    /// игрока — 32 знака и ДВА дома, книжка и файл рядом с ней: «испорченный
    /// prefs не должен осиротить сейвы». Секрет состояния и идентификатор
    /// устройства — 64 знака и один дом каждый. Урок про второй дом выучили
    /// один раз и не разнесли, хотя цена потери у всех трёх одинаковая и даже
    /// выше: без секрета состояния сервер не отдаст блоб (ключ заявлен при
    /// первой записи), без метки устройства следующий старт зарегистрирует
    /// НОВУЮ учётку — с чужим кошельком и пустыми покупками.</para>
    ///
    /// <para>Правила теперь записаны здесь:</para>
    ///
    /// <list type="bullet">
    /// <item><b>Запуск метится один раз</b> — <see cref="Run"/>. Одна метка на
    /// процесс, её берут все, кто рассказывает о запуске наружу. Связывать
    /// запуски между собой не нужно, нужно их различать И уметь сойтись на
    /// одном.</item>
    /// <item><b>Постоянная метка живёт в двух домах</b> —
    /// <see cref="Steady"/>. Книжка теряется (сброс данных, кривой бэкап,
    /// переезд), файл теряется (чистка кэша) — но редко одновременно.</item>
    /// <item><b>Разовая метка не хранится</b> — <see cref="Once"/>. Она нужна
    /// ровно на одну операцию: повтор запроса с той же меткой сервер считает
    /// тем же начислением, а не вторым.</item>
    /// </list>
    ///
    /// <para>Чего здесь НЕТ: смысла меток. Что значит «учётка», когда её
    /// сбрасывать и кому показывать — дело владельцев. Паспортист не знает,
    /// кому выдаёт.</para>
    /// </summary>
    public static class LvnMark
    {
        /// <summary>
        /// МЕТКА ЭТОГО ЗАПУСКА. Одна на процесс — её ставит и аналитика (в
        /// событие), и отправщик логов (на пачку), и потому строку лога можно
        /// поднять по событию, а событие — по строке лога.
        ///
        /// <para>Шестнадцать знаков: этого хватает, чтобы за отчётный месяц
        /// две сессии не совпали, и мало настолько, чтобы метка читалась
        /// глазами в двух разных отчётах рядом.</para>
        /// </summary>
        public static readonly string Run = Hex(16);

        /// <summary>
        /// ПОСТОЯННАЯ МЕТКА под именем <paramref name="name"/> — та же при
        /// каждом запуске, пока жив хоть один её дом.
        ///
        /// <para>Домов два: запись в книжке и файл <c>&lt;имя&gt;.id</c> рядом
        /// с сохранениями. Читается тот, который уцелел; после чтения оба
        /// приводятся к одному значению — то есть уцелевший дом чинит
        /// потерянный, и следующая потеря снова окажется не смертельной.</para>
        ///
        /// <para>Порождается ОДИН раз, 64 знака. Метка — ключ ко всему, что
        /// сервер помнит об игроке, поэтому подобрать её должно быть нельзя, а
        /// не просто «маловероятно».</para>
        /// </summary>
        public static string Steady(string name)
        {
            if (string.IsNullOrEmpty(name)) throw new ArgumentException("метке нужно имя", nameof(name));

            var value = LvnKeep.Get(name, "");
            string fromFile = null;
            if (string.IsNullOrEmpty(value))
            {
                fromFile = ReadFile(name);
                value = fromFile;
            }
            if (string.IsNullOrEmpty(value)) value = Hex(64);

            // Оба дома приводим к одному значению ВСЕГДА, а не только при
            // порождении: уцелевший чинит потерянный ровно в тот момент, когда
            // метку впервые спросили после потери.
            LvnKeep.Put(name, value);
            if (fromFile != value) WriteFile(name, value);
            return value;
        }

        /// <summary>
        /// ЗАБЫТЬ постоянную метку — оба дома сразу. Половинчатое забывание
        /// хуже, чем никакого: переживший дом вернёт игрока в удалённую учётку
        /// следующим стартом, и он не поймёт, почему «удалил всё», а оно тут.
        /// </summary>
        public static void Forget(string name)
        {
            if (string.IsNullOrEmpty(name)) return;
            LvnKeep.Drop(name);
            try
            {
                var path = FilePath(name);
                if (System.IO.File.Exists(path)) System.IO.File.Delete(path);
            }
            catch (Exception e) { Debug.LogWarning($"[mark] не стёрся файл метки '{name}': {e.Message}"); }
        }

        /// <summary>
        /// РАЗОВАЯ метка — на одну операцию, не хранится. Её смысл в том, что
        /// повтор запроса с той же меткой сервер обязан счесть тем же
        /// действием: сеть роняет ответ чаще, чем запрос, и без такой метки
        /// повтор начисляет второй раз.
        /// </summary>
        public static string Once() => Hex(32);

        // ── как это устроено ─────────────────────────────────────────────────

        // Guid даёт 32 шестнадцатеричных знака; для 64 берём два подряд, для
        // более коротких — начало. Обрезка начала законна: знаки Guid v4
        // случайны все, кроме версии и варианта, а они стоят в середине.
        private static string Hex(int length)
        {
            var s = Guid.NewGuid().ToString("N");
            while (s.Length < length) s += Guid.NewGuid().ToString("N");
            return s.Length == length ? s : s.Substring(0, length);
        }

        private static string FilePath(string name) =>
            System.IO.Path.Combine(Application.persistentDataPath, name + ".id");

        private static string ReadFile(string name)
        {
            try
            {
                var path = FilePath(name);
                if (System.IO.File.Exists(path)) return System.IO.File.ReadAllText(path).Trim();
            }
            catch { /* нечитаемый второй дом — считаем, что его нет */ }
            return null;
        }

        private static void WriteFile(string name, string value)
        {
            try { System.IO.File.WriteAllText(FilePath(name), value); }
            catch { /* остаётся копия в книжке */ }
        }
    }
}
