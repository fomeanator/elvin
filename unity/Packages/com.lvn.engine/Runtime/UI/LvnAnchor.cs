using UnityEngine.UIElements;

namespace Lvn.UI
{
    /// <summary>
    /// ЯКОРЬ — какой точкой поверхность держится за своё место.
    ///
    /// <para>Автор пишет словом: <c>top-left</c>, <c>bottom-right</c>,
    /// <c>center</c>. Слово превращается в сдвиг самой поверхности в процентах
    /// её размера: прижатая слева не сдвигается, прижатая справа уезжает на
    /// свою ширину, посередине — на половину.</para>
    ///
    /// <para>Правило стояло ДВАЖДЫ, слово в слово, — у подписи на сцене и у
    /// окна реплики, — и различались копии только умолчанием. Умолчание и есть
    /// единственное, что тут вправе отличаться: у подписи это «сверху слева»
    /// (тогда авторские x/y читаются как отступ от угла), у окна — «по центру».
    /// Поэтому оно и осталось у зовущего.</para>
    /// </summary>
    public static class LvnAnchor
    {
        /// <summary>СТОРОНА ПОПЕРЁК ЭКРАНА — то же правило, что у якоря, но
        /// для раскладки: слово автора превращается в выравнивание ряда.
        ///
        /// <para>Стояло дважды и РАЗЛИЧАЛОСЬ не только умолчанием. Список
        /// выборов знал «left» и «right», всё прочее считая серединой; окно
        /// реплики знало «center» и «right», всё прочее — левым краем. Одно и
        /// то же авторское слово вне этих коротких списков разводило два
        /// элемента экрана в разные стороны, и заметить это можно было только
        /// глазами.</para>
        ///
        /// <para>Разбор слова теперь один. Умолчание осталось у зовущего — оно
        /// и вправду разное по смыслу: выборы стоят посередине, окно реплики
        /// прижато влево, и это решение экрана, а не разбора.</para>
        /// </summary>
        public static Align Across(string word, Align fallback)
        {
            switch (word)
            {
                case "left": return Align.FlexStart;
                case "right": return Align.FlexEnd;
                case "center": return Align.Center;
                default: return fallback;
            }
        }

        /// <summary>Сдвиг поверхности в процентах её размера. Незнакомое слово
        /// считается серединой: автор написал что-то своё, и лучше показать
        /// по центру, чем не показать вовсе.</summary>
        public static (float x, float y) Percent(string anchor, string fallback)
        {
            string a = (string.IsNullOrEmpty(anchor) ? fallback : anchor).ToLowerInvariant();
            float x = a.Contains("left") ? 0f : a.Contains("right") ? -100f : -50f;
            float y = a.Contains("top") ? 0f : a.Contains("bottom") ? -100f : -50f;
            return (x, y);
        }
    }
}
