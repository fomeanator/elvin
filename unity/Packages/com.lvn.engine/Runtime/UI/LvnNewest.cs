using System.Collections.Generic;

namespace Lvn.UI
{
    /// <summary>
    /// ВАЖЕН ТОЛЬКО САМЫЙ НОВЫЙ — очередь, где выигрывает последний вошедший.
    ///
    /// <para>Правило простое: начинающий работу берёт номер, а закончив —
    /// спрашивает, не обогнали ли его. Обогнанный тихо уходит, ничего не
    /// тронув. Оно нужно везде, где работа идёт через ожидание, а поводов
    /// начать её несколько: показ актёра, смена фона, принятие свежего
    /// каталога, смена языка.</para>
    ///
    /// <para>ЦЕНА ОТСУТСТВИЯ НЕ «ЛИШНЯЯ РАБОТА», А НЕВЕРНЫЙ ИТОГ. Две загрузки,
    /// начатые подряд, приходят в любом порядке: сеть не обещает очерёдности.
    /// Победивший последним ставит СВОЁ — и это старое. На экране остаётся то,
    /// что игрок уже отменил, и ни исключения, ни строки в логе при этом
    /// нет.</para>
    ///
    /// <para>Номера только РАСТУТ и никогда не обнуляются. Обнули — и работа,
    /// начатая до сброса, однажды снова окажется «новейшей», потому что
    /// счётчик вернулся к её номеру. Единственная защита от опоздавшего в том,
    /// что его номер уже не повторится.</para>
    ///
    /// <para>Линии названы строками, а не полями: их столько, сколько
    /// одновременных работ, и часть имён собирается на лету («actor:hill»).
    /// Отдельным домом — потому что правило одно, а слоёв, где оно нужно, два:
    /// сцена (<see cref="LvnStageClock"/> держит линии здесь) и приложение
    /// (принятие каталога). Второй экземпляр той же логики разошёлся бы
    /// молча.</para>
    /// </summary>
    public sealed class LvnNewest
    {
        private readonly Dictionary<string, int> _lines = new Dictionary<string, int>();

        /// <summary>Взять номер — объявить себя новейшим на этой линии.
        /// Прежний владелец узнает об этом по <see cref="Mine"/>.</summary>
        public int Claim(string line)
        {
            if (string.IsNullOrEmpty(line)) return 0;
            int next = (_lines.TryGetValue(line, out var cur) ? cur : 0) + 1;
            _lines[line] = next;
            return next;
        }

        /// <summary>Моя работа всё ещё самая новая на этой линии? Безымянная
        /// линия и неизвестная линия отвечают «да»: правило не должно
        /// ОТМЕНЯТЬ работу там, где его не заводили.</summary>
        public bool Mine(string line, int ticket)
            => string.IsNullOrEmpty(line)
               || !_lines.TryGetValue(line, out var cur) || cur == ticket;

        /// <summary>Отменить всё, что идёт по линии, никого не начиная —
        /// «этот таймер больше не наш».</summary>
        public void Supersede(string line) => Claim(line);
    }
}
