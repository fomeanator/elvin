using Newtonsoft.Json.Linq;

namespace Lvn.UI
{
    /// <summary>
    /// РОСТОМЕР — единственная мера роста в кадре: МЕТРЫ.
    ///
    /// <para>До него рост был долей экрана, и её называл каждый по-своему:
    /// сценарий писал <c>h=1.06</c>, меню ставило куклу своей высотой,
    /// гардероб — своей (0.92×1.06), тема добавляла множитель. Один и тот же
    /// человек получал три разных числа за один переход, и рост скакал (Илья,
    /// 27.08). Доля экрана вообще не про рост: она отвечает на вопрос «сколько
    /// занять», а не «какого ты роста».</para>
    ///
    /// <para>Здесь мера общая и физическая. Сцена объявляет, сколько метров
    /// помещается в кадр по высоте (<see cref="SceneMeters"/>, по умолчанию
    /// 2 — потолок комнаты), персонаж объявляет свой рост
    /// (<c>sprites.&lt;id&gt;.meters</c>, героиня 1.7), и высота на экране
    /// получается делением. Кто бы ни ставил куклу — сценарий, меню, гардероб,
    /// катсцена, — рост выходит один и тот же, потому что считается из одних и
    /// тех же двух чисел.</para>
    ///
    /// <para>Рост меряется по ФИГУРЕ, а не по холсту: у художника вокруг
    /// персонажа воздух, и его доля у разных героев разная (см.
    /// <c>LvnSpriteEntity.content</c>). Поэтому метры честны между героями —
    /// 1.7 и 1.9 встанут рядом с настоящей разницей в 20 сантиметров.</para>
    /// </summary>
    public static class LvnScale
    {
        /// <summary>Сколько метров помещается в кадр по высоте, если сцена не
        /// сказала иначе. 2 метра — потолок комнаты: человек в 1.7 занимает
        /// 85% кадра, над головой остаётся ладонь воздуха.</summary>
        public const float DefaultSceneMeters = 2f;

        /// <summary>Высота кадра в метрах (<c>ui.stage.meters</c>). Меньше —
        /// камера ближе, все фигуры крупнее; больше — общий план.</summary>
        public static float SceneMeters { get; set; } = DefaultSceneMeters;

        /// <summary>Есть ли у сцены разумная шкала. Ноль или мусор в настройке
        /// не должен превращать всех в бесконечность.</summary>
        public static bool Sane => SceneMeters > 0.05f;

        /// <summary>МЕТРЫ → ДОЛЯ ВЫСОТЫ КАДРА. Единственное место, где живёт это
        /// деление: рост 1.7 при потолке 2 — это 0.85 кадра, и так везде.</summary>
        public static float Fraction(float meters)
            => !Sane || meters <= 0f ? 0f : meters / SceneMeters;

        /// <summary>Рост, названный в самой команде: <c>meters=</c> (или
        /// <c>height_m=</c> — то же поле длинным именем). 0 — не назван.</summary>
        public static float MetersIn(JObject cmd)
        {
            if (cmd == null) return 0f;
            var tok = cmd["meters"] ?? cmd["height_m"];
            if (tok == null) return 0f;
            try { return (float)tok; } catch { return 0f; }
        }
    }
}
