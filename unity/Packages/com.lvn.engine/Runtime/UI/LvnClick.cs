using System;
using Newtonsoft.Json.Linq;

namespace Lvn.UI
{
    /// <summary>
    /// ЧТО ЗНАЧИТ <c>on_click</c> — одно решение на всю игру.
    ///
    /// <para>Автор пишет нажатие двумя способами: одним словом — метка
    /// перехода (<c>on_click="bag"</c>), — или объектом, который заодно правит
    /// переменные (<c>on_click={ goto: "bag", set: { found: true } }</c>).
    /// Формы равноправны и работают у фигуры на сцене, у предмета и у дерева
    /// <c>ui</c>.</para>
    ///
    /// <para>ТАК БЫЛО НЕ ВСЕГДА. Сцена знала обе записи, а дерево <c>ui</c> —
    /// только первую, и не мирно: оно приводило поле к строке напрямую, а
    /// приведение объекта к строке в Newtonsoft БРОСАЕТ. Исключение уходило
    /// наверх, дерево не строилось вовсе — у игрока на этом шаге пропадал весь
    /// интерфейс. Автор при этом написал ровно то, что написано в документации
    /// движка, просто не в том операторе.</para>
    ///
    /// <para>Порядок закреплён здесь же и он не косметический: СНАЧАЛА
    /// переменные, ПОТОМ переход. Ветка, в которую ведёт метка, обычно и
    /// читает эти переменные — поставь их после перехода, и первая же реплика
    /// новой ветки увидит старые значения.</para>
    /// </summary>
    public static class LvnClick
    {
        /// <summary>
        /// Собрать действие нажатия. Null — автор нажатия не назначил (или
        /// назначил пустую метку), и элемент остаётся неактивным.
        /// </summary>
        /// <param name="field">поле <c>on_click</c> команды</param>
        /// <param name="go">переход по метке; пустая метка означает «никуда»,
        /// но остальное (снять ожидание, шагнуть) звонящий делает всё равно</param>
        /// <param name="set">записать переменные; null у того, кто их писать не
        /// умеет — тогда объектная форма отработает одним переходом</param>
        public static Action From(JToken field, Action<string> go, Action<JObject> set = null)
        {
            if (field == null || go == null) return null;

            if (field.Type == JTokenType.Object)
            {
                var o = (JObject)field;
                var target = (string)o["goto"];
                var ops = o["set"] as JObject;
                return () =>
                {
                    if (ops != null) set?.Invoke(ops);
                    go(target);
                };
            }

            // Число или true в поле метки — опечатка автора, а не повод ронять
            // главу: берём как написано и уходим по несуществующей метке, что
            // уже умеет сообщать сам чтец.
            var label = field.Type == JTokenType.String ? (string)field : field.ToString();
            if (string.IsNullOrEmpty(label)) return null;
            return () => go(label);
        }
    }
}
