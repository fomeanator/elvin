namespace Lvn.UI
{
    /// <summary>
    /// ВЗВОД — два положения и три перехода, отдельно от кнопки.
    ///
    /// <para>Обряд опасного действия — это состояние, а не оформление:
    /// первое нажатие взводит, второе делает, время и уход с экрана
    /// разоружают. Кнопка — одна из его шкур; вторая когда-нибудь будет
    /// пунктом меню или жестом.</para>
    ///
    /// <para>Отдельным домом ещё и потому, что иначе правило нечем
    /// проверить: щелчок UITK не рождается без панели, а панели в
    /// EditMode нет. Проверка, которую невозможно написать, — это правило,
    /// которое однажды тихо перестанет работать.</para>
    /// </summary>
    public sealed class LvnArming
    {
        /// <summary>Взведён ли сейчас.</summary>
        public bool Armed { get; private set; }

        /// <summary>Нажали. <c>true</c> — это было ПОДТВЕРЖДЕНИЕ (второе
        /// нажатие); после него взвод снимается сам.</summary>
        public bool Press()
        {
        if (!Armed) { Armed = true; return false; }
        Armed = false;
        return true;
        }

        /// <summary>Разоружить (время вышло, ушли с экрана).
        /// <c>true</c> — состояние изменилось.</summary>
        public bool Disarm()
        {
        if (!Armed) return false;
        Armed = false;
        return true;
        }
    }
}
