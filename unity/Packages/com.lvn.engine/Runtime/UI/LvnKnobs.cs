using UnityEngine;

namespace Lvn.UI
{
    /// <summary>
    /// СТУПЕНИ РУЧЕК ИГРОКА — какие значения вообще предлагаются и где предел.
    ///
    /// <para>Размер текста и размер интерфейса игрок выбирает НЕ долей на
    /// полоске, а именованной ступенью: у читаемости нет «чуть-чуть», есть
    /// «читается» и «не читается», и пять названных ступеней проходятся за
    /// пять нажатий вместо ловли доли пальцем.</para>
    ///
    /// <para>ПРЕДЕЛ ВЫВОДИТСЯ ИЗ СТУПЕНЕЙ, а не пишется рядом. Пока он был
    /// отдельным числом, ступени и зажим успели разойтись: настройка размера
    /// реплик обещала в документации и в зажиме верхнюю границу 1,4, а ступеней
    /// выше 1,3 не существовало — четверть обещанного диапазона была
    /// недостижима, и понять это по коду было нельзя. Теперь крайние ступени и
    /// есть границы: разойтись нечему.</para>
    ///
    /// <para>Ступени были записаны ДВАЖДЫ — в меню главы и в настройках
    /// оболочки, — и это два экрана одной настройки. Числа переехали сюда; вид
    /// (ряд кнопок, карточка, образец текста) остаётся за экраном, он у них
    /// разный намеренно.</para>
    /// </summary>
    public static class LvnKnobs
    {
        /// <summary>Одна ступень: множитель, ключ слова и английское
        /// умолчание. Ключ короткий («size_l»): куда его класть — в словарь
        /// новеллы или в раздел настроек оболочки — решает тот, кто
        /// спрашивает.</summary>
        public readonly struct Step
        {
            public readonly float K;
            public readonly string Key;
            public readonly string En;

            public Step(float k, string key, string en) { K = k; Key = key; En = en; }
        }

        /// <summary>Ступени размера — общие у текста реплик и у интерфейса.
        ///
        /// <para>Мельче 0,85 кнопки перестают попадать под палец, крупнее 1,3
        /// списки перестают помещаться в экран — и то и другое читается как
        /// поломка, а не как настройка.</para></summary>
        public static readonly Step[] Scale =
        {
            new Step(0.85f, "size_xs", "XS"),
            new Step(0.92f, "size_s",  "S"),
            new Step(1f,    "size_m",  "M"),
            new Step(1.15f, "size_l",  "L"),
            new Step(1.3f,  "size_xl", "XL"),
        };

        /// <summary>Нижняя граница масштаба — первая ступень.</summary>
        public static float ScaleMin => Scale[0].K;

        /// <summary>Верхняя граница масштаба — последняя ступень.</summary>
        public static float ScaleMax => Scale[Scale.Length - 1].K;

        /// <summary>Зажать множитель в предлагаемый игроку диапазон.</summary>
        public static float ClampScale(float v) => Mathf.Clamp(v, ScaleMin, ScaleMax);

        /// <summary>Стоит ли ручка на этой ступени.
        ///
        /// <para>Допуск нужен потому, что значение возвращается из настроек
        /// через запись и чтение float, а сравнивать доли на равенство нельзя.
        /// Он был выписан по месту в каждом из четырёх экранов — здесь он
        /// один, и подсветка текущей ступени не может разойтись между
        /// экранами.</para></summary>
        public static bool At(float value, in Step s) => Mathf.Abs(value - s.K) < 0.01f;
    }
}
