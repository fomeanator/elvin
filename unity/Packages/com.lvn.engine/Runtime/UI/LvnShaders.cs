using System.Collections.Generic;
using UnityEngine;

namespace Lvn.UI
{
    /// <summary>
    /// ВЗЯТЬ ШЕЙДЕР ЭФФЕКТА — и сказать, если его нет.
    ///
    /// <para>Пять мест грузили шейдер одинаково и реагировали на пропажу
    /// ПО-РАЗНОМУ: стекло, размытие и эффекты кадра молча поднимали флаг
    /// «шейдера нет» и дальше рисовали без эффекта; композит слоёв и грим актёра
    /// писали предупреждение — на разных языках и разными словами.</para>
    ///
    /// <para>Молчание тут дороже, чем кажется. Шейдер пропадает не «иногда, у
    /// кого-то»: он не попадает в сборку, если его забыли в списке всегда
    /// включённых, и не поддерживается на части устройств. Игрок при этом видит
    /// не поломку, а РОВНУЮ картинку без эффекта — и жалуется на «скучно
    /// выглядит», а не на ошибку. В логе, куда посмотрели бы первым делом, нет
    /// ничего.</para>
    ///
    /// <para>Материал заводится тут же: временный материал эффекта обязан нести
    /// <c>HideAndDontSave</c>, иначе он попадает в сцену и переживает
    /// её. Правило повторялось шестью строками подряд и держалось на
    /// внимательности.</para>
    /// </summary>
    public static class LvnShaders
    {
        private static readonly HashSet<string> _told = new HashSet<string>();

        /// <summary>Шейдер из ресурсов пакета; <c>null</c>, если его нет или он
        /// не поддержан. Жалуется ОДИН раз на имя: доклад раз в кадр превратил
        /// бы лог в шум ровно там, где его читают.</summary>
        public static Shader Load(string name)
        {
            var shader = Resources.Load<Shader>(name);
            if (shader != null && shader.isSupported) return shader;
            if (_told.Add(name))
                Debug.LogWarning($"[lvn-fx] шейдер «{name}» "
                                 + (shader == null ? "не найден в сборке" : "не поддержан этим устройством")
                                 + " — эффект выключен, картинка останется без него");
            return null;
        }

        /// <summary>Материал по шейдеру, спрятанный от сцены. <c>null</c>, если
        /// шейдера нет — вызывающий обязан это пережить.</summary>
        public static Material Material(string name)
        {
            var shader = Load(name);
            return shader == null ? null : new Material(shader) { hideFlags = HideFlags.HideAndDontSave };
        }
    }

    /// <summary>
    /// МЕСТО ПОД МАТЕРИАЛ ЭФФЕКТА — взять один раз и запомнить, что не вышло.
    ///
    /// <para>Эффект не может просить материал каждый кадр: <see
    /// cref="LvnShaders.Material"/> заводит НОВЫЙ материал на каждый вызов, а
    /// у пропавшего шейдера ответ всегда один и тот же. Поэтому у каждого
    /// эффекта было по ДВЕ памяти — сам материал и флажок «уже не вышло» — и
    /// один и тот же обряд из четырёх строк: если материала нет и мы ещё не
    /// пробовали, попробовать; не вышло — поднять флажок.</para>
    ///
    /// <para>Написан он был трижды (матовое стекло, размытие фона, стопка
    /// эффектов кадра) слово в слово. Две памяти об одном факте — это форма, в
    /// которой ошибка становится вопросом времени: достаточно один раз
    /// проверить материал, забыв про флажок, и эффект начнёт заводить новый
    /// материал каждый кадр — молча, без падения, просто расходуя память.</para>
    ///
    /// <para>Здесь факт один: «материал либо есть, либо его не будет».</para>
    /// </summary>
    public struct LvnShaderSlot
    {
        private Material _mat;
        private bool _tried;

        /// <summary>Материал эффекта или <c>null</c>, если шейдера нет. Попытка
        /// ровно одна за жизнь ячейки — жалобу дом шейдеров уже произнёс.</summary>
        public Material Of(string shaderName)
        {
            if (_mat != null) return _mat;
            if (_tried) return null;
            _tried = true;
            _mat = LvnShaders.Material(shaderName);
            return _mat;
        }

        /// <summary>
        /// ОТПУСТИТЬ МАТЕРИАЛ — эффект уходит вместе со своим объектом.
        ///
        /// <para>Материал заведён с <c>HideAndDontSave</c>: сцена его не
        /// уберёт, это обязан сделать тот, кто завёл. Пока материал жил полем
        /// эффекта, уничтожение писали по месту тремя копиями — и каждая
        /// проверяла на null своими руками.</para>
        ///
        /// <para>Ячейка после этого «не пробовала»: следующий показ соберёт
        /// материал заново, а не будет вечно помнить, что его уже нет.</para>
        /// </summary>
        public void Release()
        {
            if (_mat != null) Object.Destroy(_mat);
            _mat = null;
            _tried = false;
        }

        /// <summary>Шейдера нет и не будет — эффект пропускает кадр целиком.
        /// Спрашивать это ДО <see cref="Of"/> бессмысленно: пока не пробовали,
        /// ответ «не знаем».</summary>
        public bool Missing => _tried && _mat == null;
    }
}
