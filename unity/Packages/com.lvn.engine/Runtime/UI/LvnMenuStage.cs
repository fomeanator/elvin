using UnityEngine;

namespace Lvn.UI
{
    /// <summary>
    /// ВИТРИНА МЕНЮ — сцена, которая стоит ЗА интерфейсом хаба: широкое полотно
    /// и кукла героини перед ним.
    ///
    /// <para>Числа этой сцены — рост куклы, где стоит камера полотна, сколько
    /// она проезжает за вкладку — подбирались на глаз и оседали прямо в коде
    /// оболочки: «width 1.26», «0.35 + 0.14 × вкладка». Каждая следующая
    /// правка означала поиск нужной строки среди тысячи и подстановку нового
    /// числа наугад. Здесь у них дом: движковые значения покрывают обычную
    /// портретную игру, новелла перекрывает нужное через <c>ui.browse</c>, а
    /// поменять их можно и на лету.</para>
    ///
    /// <para>Граница с соседями простая: <see cref="VnTheme"/> — постановка
    /// НОВЕЛЛЫ, <see cref="LvnMotion"/> — время и физика движения, здесь —
    /// сцена под меню.</para>
    /// </summary>
    public static class LvnMenuStage
    {
        // ── кукла ─────────────────────────────────────────────────────────────

        /// <summary>Рост куклы: доля высоты кадра. 0.91 — фигура почти во весь
        /// экран, ногами на нижней кромке, головой под строкой состояния.</summary>
        public static float DollHeight = 0.91f;

        /// <summary>Ширина, в которую вписывается фигура (доля кадра). Единица
        /// означает «шире экрана не станет, но и не ужмётся ради полей»: ширину
        /// мерит сама фигура, а не холст её файла (см. Placement.ContentW).</summary>
        public static float DollWidth = 1f;

        // Где кукла стоит — см. HomeDollSlot / SideDollSlot ниже: только
        // стандартные слоты сцены, своей доли ширины у витрины больше нет.

        // ── полотно ───────────────────────────────────────────────────────────

        /// <summary>Где стоит камера на полотне при открытии меню (0 — левый
        /// край картины, 1 — правый). Первая вкладка живёт левее центра: справа
        /// остаётся место, куда полотно поедет.</summary>
        public static float PanStart = 0f;

        /// <summary>Сколько полотна проезжает камера за одну вкладку. Шаг
        /// прямо виден игроку: маленький — фон кажется неподвижным, большой —
        /// вкладки читаются как разные комнаты.</summary>
        public static float PanStep = 0.34f;

        /// <summary>Насколько приближено полотно витрины. Единственный способ
        /// удлинить переезд: вертикальная картина на экране телефона даёт всего
        /// четверть ширины запаса, и панорама проходит её целиком. 1.5 — предел
        /// чёткости для картины 1529px на экране 1080 (окно 1019px, ещё не
        /// растянуто), и она же даёт ход, который ВИДНО: 60% картины по ширине
        /// и треть по высоте между крайними вкладками («сильно его туда-сюда
        /// двигать для крутого эффекта» — Илья 08.09). Дальше ход растёт до ×4,
        /// но картина мылится.</summary>
        public static float PanZoom = 1.5f;

        /// <summary>БЛУЖДАНИЕ ПОЛОТНА: насколько кадр гуляет вокруг своей
        /// точки (доли картины) и за сколько секунд обходит круг. Мало и
        /// медленно — иначе не «съёмка с рук», а дёрганье: 1.5% ширины за 18
        /// секунд глаз читает как дыхание, а не как движение.</summary>
        public static float Drift = 0.015f;
        public static float DriftSeconds = 18f;

        /// <summary>Автор задал свой переезд — тогда его числа и работают, а
        /// движок не пересчитывает ход под число вкладок.</summary>
        private static bool _panAuthored;

        // ── КОМПОЗИЦИЯ: ПОЛОТНО ПОВТОРЯЕТ ГЕОМЕТРИЮ МЕНЮ ─────────────────────
        // Переезд считался по НОМЕРУ вкладки — по истории их появления, а не по
        // тому, где кнопка стоит у игрока под пальцем. У облика «сцена» ряд —
        // гардероб слева, ГЛАВНАЯ по центру и выше, магазин справа, — и номера
        // (главная 0, магазин 1, гардероб 2) прогоняли полотно СЛЕВА НАПРАВО
        // ровно наоборот тому, что видно на экране. Формула переехала на МЕСТО
        // кнопки: «фон отражает положение вкладки» (Илья 08.09).

        /// <summary>Сколько картины проходит полотно между крайними вкладками
        /// (1 — весь запас кроя целиком). Меньше единицы — сдержанный ход,
        /// больше — упор в края: дальше запаса всё равно не уедешь.</summary>
        public static float PanSpread = 1f;

        /// <summary>То же по высоте: насколько полотно поднимается над
        /// приподнятой вкладкой. Вертикальный запас берётся из приближения
        /// (<see cref="PanZoom"/>) — без него ходить некуда.</summary>
        public static float LiftSpread = 1f;

        /// <summary>ТОЧКА ПОЛОТНА ПО КОМНАТЕ ВКЛАДКИ. Комната — в ЭКРАННЫХ
        /// осях (<paramref name="roomX"/> 0 левый край … 1 правый,
        /// <paramref name="roomY"/> 0 верх … 1 низ). Возвращает точку кадра
        /// в осях КАРТИНЫ: x по ширине, y по высоте снизу вверх — к верхней
        /// комнате камера показывает верх картины.</summary>
        public static Vector2 CanvasPointFor(float roomX, float roomY)
            => new Vector2(
                Mathf.Clamp01(0.5f + (Mathf.Clamp01(roomX) - 0.5f) * PanSpread),
                Mathf.Clamp01(0.5f + (0.5f - Mathf.Clamp01(roomY)) * LiftSpread));

        // ── КОМПОЗИЦИЯ: ГЕРОИНЯ УСТУПАЕТ МЕСТО ───────────────────────────────

        // МЕСТА У ФИГУРЫ — ТОЛЬКО СТАНДАРТНЫЕ СЛОТЫ СЦЕНЫ. Здесь стояли свои
        // доли (0.32 / 0.5) и «сдвиг слоя фигур» поверх них — третья система
        // координат для одного и того же: у актёров давно есть семь
        // именованных слотов (Placement.StandingSlotXs), по которым их
        // расставляет глава и разводит арбитр. Сдвиг слоя считался от
        // авторской доли как от данности и разъезжался с тем, где фигура
        // стоит НА САМОМ ДЕЛЕ: на боковой вкладке героиня уходила вправо за
        // край (живой скрин 08.09). Витрина обязана говорить на языке сцены:
        // героиню СТАВЯТ В СЛОТ позой, а плавный переезд между слотами делает
        // сама сцена — так же, как для любого актёра главы («у нас же есть
        // стандартные слоты героев, именно их надо юзать и ничего кроме» —
        // Илья 08.09).

        /// <summary>Слот героини на ГЛАВНОЙ: «left» (четверть ширины) —
        /// правую половину занимают карточки. «center_left» (0.38) читался
        /// глазом как центр («ну вот героиня не слева же» — Илья 08.09):
        /// с планом 0.9 фигура вставала на 0.39, а авторское место, которое
        /// помнили как «слева», было 0.32. Автор может назвать другой стоячий
        /// слот через <c>ui.browse.doll_place</c>.</summary>
        public static string HomeDollSlot = "left";

        /// <summary>…и на боковых вкладках: центр кадра, к которому привязаны
        /// наезды гардероба на причёску и наряд.</summary>
        public static string SideDollSlot = "center";

        /// <summary>…и в МАГАЗИНЕ: снова слева — справа встают витрины
        /// товаров, как на главной карточки («в магазине героиня наоборот
        /// слева» — Илья 08.09).</summary>
        public static string StoreDollSlot = "left";

        /// <summary>КОМНАТА ВИТРИНЫ — какая у вкладки композиция. Три рода, а
        /// не «главная / не главная»: у магазина свои место и план. Какая
        /// вкладка какого рода — знает оболочка (вкладки её), витрина знает
        /// только числа рода.</summary>
        public enum Room { Home, Store, Side }

        /// <summary>Слот героини для комнаты — словом сцены.</summary>
        public static string DollSlot(Room room)
        {
            switch (room)
            {
                case Room.Home:  return HomeDollSlot;
                case Room.Store: return StoreDollSlot;
                default:         return SideDollSlot;
            }
        }

        /// <summary>Слот комнаты долей ширины кадра.</summary>
        public static float DollSlotX(Room room) => Placement.SlotX(DollSlot(room));

        /// <summary>ПЕРЕЛЁТ МЕЖДУ ВКЛАДКАМИ — одно время на всех: страницы
        /// интерфейса, полотно и героиня летят одной кривой и приходят
        /// вместе. Число живёт здесь, а не в оболочке, потому что сцена тоже
        /// его знает: фигура переезжает между слотами своим ходом и обязана
        /// успеть ровно к концу переезда кадра.</summary>
        public static int TravelMs = 680;   // 420 → 480 («на 15 %») → 680 («ещё на 200 мс») — Илья 08.09

        /// <summary>ПЛАН ГЕРОИНИ НА ГЛАВНОЙ — ПРИБЛИЖЕНИЕ НА ПЯТНАДЦАТУЮ.
        /// Путь к числу за один день: 0.9 («карточка спорит с фигурой»),
        /// потом полный рост («не уменьшать», «она выше на процентов 10»),
        /// потом «сделай приближение 15 процентов на главной» — Илья 08.09.
        /// Камера фигур масштабирует от ног (WorldCameraRig, pivot снизу):
        /// героиня растёт вверх, а не всплывает над лентой.
        ///
        /// <para>Место фигуре освобождает КОМПОЗИЦИЯ, а не масштаб: панели
        /// вкладок стоят столбиком справа, левая половина кадра — её.
        /// Соседние комнаты считаются ОТ этого числа
        /// (см. <see cref="StoreCastGain"/>): правка здесь двигает витрину
        /// разом, а не расходится по вкладкам.</para></summary>
        public static float HomeCastZoom = 1.15f;

        /// <summary>План боковых вкладок: героиню разглядывают ВБЛИЗИ —
        /// гардероб мерит наряды и причёски, и фигура там подаётся вперёд.</summary>
        public static float SideCastZoom = 1f;

        /// <summary>Насколько магазин крупнее ОБЫЧНОГО роста героини (того,
        /// в котором её видят на главной): «больше на 5 процентов, чем
        /// обычно» — Илья 08.09. Доля, а не свой план: подвинется рост на
        /// главной — магазин поедет за ним, оставшись «на пять процентов
        /// крупнее», а не разъедется молча.</summary>
        public static float StoreCastGain = 1.05f;

        /// <summary>Отдаление фигур для комнаты.</summary>
        public static float CastZoomFor(Room room)
        {
            switch (room)
            {
                case Room.Home:  return HomeCastZoom;
                case Room.Store: return HomeCastZoom * StoreCastGain;
                default:         return SideCastZoom;
            }
        }

        /// <summary>Точка полотна для вкладки — единственная формула переезда,
        /// вместо повторения «0.35 + 0.14 × N» в двух местах оболочки.</summary>
        public static float PanFor(int tab, int tabs = 4)
        {
            int last = Mathf.Max(1, tabs - 1);
            // ВЕСЬ ФОН, А НЕ ЕГО ТРЕТЬ. Прежние 0.35 + 0.14×вкладка прогоняли
            // 42% картины: между крайними вкладками полотно смещалось меньше
            // чем на полкадра и читалось как неподвижное. Без авторских чисел
            // ход считаем от числа вкладок — крайние встают ровно на края.
            float start = _panAuthored ? PanStart : 0f;
            float step = _panAuthored ? PanStep : 1f / last;
            return Mathf.Clamp01(start + step * Mathf.Clamp(tab, 0, last));
        }

        // ── самолечение ───────────────────────────────────────────────────────
        // Сцену меню собирает асинхронный тракт (сеть, декод, поколения), и
        // любое его звено может не доехать. Сторож сверяется с ФАКТОМ на
        // экране, а не с флагом «мы вроде поставили» — три бага 26–27.08 были
        // ровно про это. Числа здесь — терпение сторожа, не украшение.

        /// <summary>Как часто сторож смотрит на сцену, секунды.</summary>
        public static float GuardPeriodSeconds = 1f;

        /// <summary>Сколько сторож ждёт, прежде чем счесть пустое полотно
        /// поломкой, а не ещё-не-доехавшей загрузкой, секунды.</summary>
        public static float GuardPatienceSeconds = 2f;

        /// <summary>Сколько бут-вуаль ждёт первого кадра сцены, прежде чем
        /// открыть меню как есть, миллисекунды. Без ожидания игрок видел чёрный
        /// экран под интерфейсом; с бесконечным — висел бы на вуали.</summary>
        public static int VeilWaitMs = 1200;

        /// <summary>За сколько секунд вуаль растворяется, открывая меню.</summary>
        public static float VeilFadeSeconds = 0.4f;

        /// <summary>Применить настройки новеллы (<c>ui.browse</c>). Пустые поля
        /// оставляют движковый дефолт: манифест не обязан знать про эту
        /// механику, чтобы игра выглядела правильно.</summary>
        public static void Apply(float? dollHeight, float? dollWidth,
                                 float? panStart, float? panStep, string dollPlace = null)
        {
            if (dollHeight.HasValue) DollHeight = Mathf.Clamp(dollHeight.Value, 0.1f, 3f);
            if (dollWidth.HasValue) DollWidth = Mathf.Clamp(dollWidth.Value, 0.1f, 3f);
            // Предел шага 1f и признак авторского пана — наши; место куклы
            // (dollPlace) пришло с обликом «сцена». Нужны обе половины.
            if (panStart.HasValue) { PanStart = Mathf.Clamp01(panStart.Value); _panAuthored = true; }
            if (panStep.HasValue) { PanStep = Mathf.Clamp(panStep.Value, 0f, 1f); _panAuthored = true; }
            // Место куклы принимается ТОЛЬКО стоячим слотом сцены. Доля
            // ширины («0.32») была своей системой координат витрины и
            // разъезжалась с тем, где фигура стоит на самом деле; такое поле
            // не ломает композицию — оно объявляется вслух и не действует.
            if (!string.IsNullOrEmpty(dollPlace))
            {
                if (Placement.IsStandingSlot(dollPlace)) HomeDollSlot = dollPlace;
                else LvnLog.Trace($"[lvn-doll] ui.browse.doll_place=«{dollPlace}» — не слот сцены "
                                + $"({string.Join("|", Placement.SlotNames)}); героиня стоит в «{HomeDollSlot}»");
            }
        }
    }
}
