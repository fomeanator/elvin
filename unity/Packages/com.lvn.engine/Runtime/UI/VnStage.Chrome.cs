namespace Lvn.UI
{
    /// <summary>
    /// УБРАНСТВО СЦЕНЫ — окно реплики и стопка выборов: как их собирают и как
    /// отпускают.
    ///
    /// <para>Собирают их ДВАЖДЫ: при рождении сцены и заново при каждой смене
    /// темы — новая глава, другая новелла, доехавшие картинки рамок. Оба раза
    /// это одна и та же работа: создать по теме, подписать на события,
    /// применить настройки игрока, связать геометрию выборов с окном.</para>
    ///
    /// <para>Пока она была расписана в двух местах, списки разошлись по
    /// порядку и держались на записке в коде: «подписки принадлежат этим
    /// экземплярам и должны быть привязаны заново». Записка читателю — это
    /// ручная синхронизация, и цена ей известна: новое поле у окна реплики
    /// вспомнят в одном месте из двух, и разница вылезет не там, где её
    /// завели, — при живой смене темы посреди главы.</para>
    ///
    /// <para>Где положить собранное — НЕ здесь: при рождении хром просто
    /// добавляют в безопасную область, при пересборке вставляют по индексу,
    /// чтобы сохранить порядок слоёв. Это решение места, а не механизма.</para>
    /// </summary>
    public partial class VnStage
    {
        /// <summary>Собрать убранство по текущей теме и привязать его.
        ///
        /// <para>Порядок внутри не случаен: связь геометрии выборов ищет окно
        /// реплики, поэтому окно создаётся первым. Вызывающему об этом знать
        /// не надо — ровно затем оба и собраны здесь.</para></summary>
        private void MakeChrome()
        {
            ResolveFont();

            _dialogue = new DialogueBox(Theme);
            _dialogue.RevealingChanged += OnDialogueRevealing; // луп клавиатуры
            _dialogue.SetUserOpacity(LvnPrefs.DialogOpacity);
            // Пустая рамка в теме не должна стоять на голой сцене — ни при
            // рождении, ни при перекраске между репликами.
            SetSayVisible(SayOnScreen);

            _choices = new ChoiceList(Theme);
            _choices.OnSelected += OnChoiceSelected;
            _choices.VisibleChanged += OnChoicesVisibleChanged;
            // Окно растёт вместе с текстом — стопка выборов сторонится его в
            // реальном времени, а не по одному замеру на реплику.
            WireChoiceGeometrySync();
        }

        /// <summary>Отпустить прежнее убранство: снять всё, что навязал
        /// <see cref="MakeChrome"/>. Зеркало обязано оставаться зеркалом —
        /// подписка, которую забыли снять, переживает свой экземпляр.</summary>
        private void DropChrome()
        {
            if (_dialogue != null) _dialogue.RevealingChanged -= OnDialogueRevealing;
            if (_choices == null) return;
            _choices.OnSelected -= OnChoiceSelected;
            _choices.VisibleChanged -= OnChoicesVisibleChanged;
        }
    }
}
