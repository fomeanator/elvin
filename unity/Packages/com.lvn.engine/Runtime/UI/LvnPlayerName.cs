namespace Lvn.UI
{
    /// <summary>
    /// КАК ЗОВУТ ИГРОКА — одна правда для всех, кто это показывает.
    ///
    /// <para>Хранилище было одно (<see cref="LvnPrefs.PlayerName"/>), а вот
    /// ПОКАЗ разъезжался: подпись для безымянного игрока — «Гость» — стояла
    /// русским словом в двух экранах движка (профиль и шапка хаба), то есть
    /// любая другая игра получала её насильно, вопреки правилу «подписи на
    /// экране принадлежат автору» (docs/language-policy.md). Само имя при этом
    /// копировалось вручную в поля экранов (<c>Hub.PlayerName</c>,
    /// <c>Profile.PlayerName</c>) и обновлялось отдельными вызовами после
    /// каждой смены — четвёртый признак пропущенного владельца: если A после
    /// записи обязан не забыть толкнуть B, между ними некого спросить.</para>
    ///
    /// <para>Ответственность: назвать игрока. Имя — из настроек устройства,
    /// подпись безымянного — из манифеста; движок держит только английское
    /// умолчание, как и для прочих своих подписей.</para>
    ///
    /// <para>Границы: нормализация ввода (длина, запрещённые символы) — у
    /// <c>PlayerNameInput</c>, синхронизация с аккаунтом — у хранилища
    /// прогресса. Здесь только «как его зовут прямо сейчас».</para>
    /// </summary>
    public static class LvnPlayerName
    {
        /// <summary>Подпись безымянного игрока, пока новелла не назвала свою.
        /// Английская — по тому же правилу, что «Equip»/«Choose» в гардеробе:
        /// умолчания движка системны, слова игры приходят из манифеста.</summary>
        public const string DefaultGuest = "Guest";

        /// <summary>Как новелла зовёт безымянного игрока. Отдельное поле
        /// манифеста (<c>ui.guest_name</c>) старше словаря и потому уважается
        /// первым; пусто — слово спрашивается у СЛОВАРЯ по ключу
        /// «player.guest». Роль знает ПРАВИЛО «имя или подпись», слово ей даёт
        /// Словарь.</summary>
        public static string GuestLabel;

        /// <summary>Имя, которое игрок ввёл. Пусто — он ещё не назвался.</summary>
        public static string Current => LvnPrefs.PlayerName;

        /// <summary>Что показать: имя игрока, а без него — подпись безымянного.
        /// Единственный ответ на вопрос «что писать в этом месте».</summary>
        public static string Display
            => string.IsNullOrEmpty(LvnPrefs.PlayerName)
                ? (string.IsNullOrEmpty(GuestLabel)
                       ? Lvn.Content.LvnWords.Of("player.guest", DefaultGuest) : GuestLabel)
                : LvnPrefs.PlayerName;

        /// <summary>Игрок назвался — имя сохраняется, и все, кто его
        /// показывает, увидят новое при следующей отрисовке.</summary>
        public static void Set(string name) => LvnPrefs.PlayerName = name ?? string.Empty;
    }
}
