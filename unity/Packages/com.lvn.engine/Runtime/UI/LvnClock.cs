using System;
using UnityEngine;

namespace Lvn.UI
{
    /// <summary>
    /// ВРЕМЯ ИНТЕРФЕЙСА — один ответ на «сколько прошло».
    ///
    /// <para>Источников было два, и стояли они вперемешку:
    /// <c>Time.unscaledTime</c> у таймера выбора, ожидания сцены и экранных
    /// затуханий, <c>Time.realtimeSinceStartup</c> у печати реплики и
    /// автопродвижения. Разница между ними невелика ровно до одного случая —
    /// приложение СВЕРНУЛИ.</para>
    ///
    /// <para>Кадровое время в фоне стоит: кадров нет, значит и время не идёт.
    /// Реальное идёт всегда. Игрок, свернувший игру на минуту, возвращается — и
    /// автопродвижение считает, что реплику читали минуту, и листает её сразу,
    /// а таймер выбора рядом ведёт себя правильно. Один экран, два ответа на
    /// вопрос «сколько игрок здесь пробыл».</para>
    ///
    /// <para>Взято кадровое: интерфейс живёт кадрами, и «пока игры не было на
    /// экране, время для неё не шло» — то поведение, которого игрок ждёт.</para>
    ///
    /// <para>НЕ ПУТАТЬ с <see cref="LvnStageClock"/>: тот про ПОРЯДОК событий
    /// сцены (эпохи, дорожки, барьеры), а не про длительности, и ему нужна
    /// монотонность, не совпадающая с ожиданиями игрока.</para>
    /// </summary>
    public static class LvnClock
    {
        /// <summary>Подменяется в тестах: длительности проверяются без ожидания
        /// настоящих секунд.</summary>
        public static Func<float> Now = () => Time.unscaledTime;

        /// <summary>Сколько прошло с отметки. Отрицательного не бывает: часы
        /// могли подменить между отметкой и замером.</summary>
        public static float Since(float mark) => Mathf.Max(0f, Now() - mark);
    }
}
