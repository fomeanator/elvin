namespace Lvn
{
    /// <summary>
    /// СКОЛЬКО ЖДЁМ СЕТЬ — сроки названы в одном месте.
    ///
    /// <para>Их было три и все по-разному: загрузчик контента держал две
    /// объяснённые константы, хранилище состояния — свою восьмёрку без единого
    /// слова почему, а сервисный клиент вписывал десятку числом прямо в двух
    /// вызовах. Спросить «сколько игра ждёт мёртвую сеть» было не у кого:
    /// ответов три, и два из них не назывались.</para>
    ///
    /// <para>Сроки РАЗНЫЕ по существу, и в этом смысл дома: он не сводит их к
    /// одному числу, а объясняет, почему их два.</para>
    /// </summary>
    public static class LvnNetPatience
    {
        /// <summary>
        /// ОТВЕТ ЦЕЛИКОМ: короткий запрос, у которого тело мало (вход, кошелёк,
        /// манифест, скрипт главы).
        ///
        /// <para>Нарочно короткий: мёртвый сокет обязан упасть быстро, чтобы
        /// глава сползла на кэш, а не висела. Офлайн UnityWebRequest иначе
        /// досиживает срок целиком. Общий флаг сети — быстрый путь; этот срок —
        /// живая подстраховка на случай, когда флаг устарел (вайфай отвалился
        /// посреди сессии).</para>
        /// </summary>
        public const int RequestSeconds = 10;

        /// <summary>
        /// МОЛЧАНИЕ В ПЕРЕДАЧЕ: для файлов срок считается не с начала, а с
        /// последнего пришедшего байта.
        ///
        /// <para>Фон в 5 МБ на медленной соте законно едет дольше десяти секунд,
        /// и обрыв посреди тела превращал один медленный файл в бурю «сеть
        /// пропала — сеть вернулась» на всю сессию (живой случай на BlueStacks:
        /// «Request timeout» каждые несколько секунд). Передача жива, пока
        /// счётчик байтов движется; мёртв только ЗАМЕРШИЙ счётчик.</para>
        /// </summary>
        public const int StallSeconds = 15;
    }
}
