using System;
using System.Text;

namespace Lvn
{
    /// <summary>
    /// СРАВНЕНИЕ ИМЁН ПО СМЫСЛУ, а не по буквам.
    ///
    /// <para>«Ноэль де Флёр», «noel_de_fleur» и «Noel De Fleur» — для автора
    /// одно и то же имя, для словаря — три разных ключа. Приведение к общему
    /// виду жило двумя копиями (сцена и трёхмерный мир); разойдись они — и
    /// персонаж, найденный на плоской сцене, не находился бы в наборе.</para>
    /// </summary>
    public static class LvnKey
    {
        /// <summary>
        /// Только буквы и цифры, в нижнем регистре. Пробелы, дефисы и
        /// подчёркивания выбрасываются: разделитель — вопрос вкуса автора, а не
        /// часть имени.
        ///
        /// <para>СНАЧАЛА ЮНИКОДНАЯ СБОРКА (NFC). «Й» и «ё» записываются двумя
        /// способами: одним знаком или буквой плюс отдельным надстрочным. Второй
        /// способ — не экзотика: так отдаёт имена файловая система macOS, и так
        /// приходят имена, прошедшие через путь на диске. Без сборки надстрочный
        /// знак не проходил проверку «буква или цифра» и просто ВЫБРАСЫВАЛСЯ:
        /// «Майя» превращалась в «маия», «Алёна» — в «алена». Ключи расходились,
        /// и актёр, найденный по имени из манифеста, не находился по тому же
        /// имени из пути.</para>
        ///
        /// <para>Тот же приём применён у каталога переводов
        /// (<c>LvnPlayer.Lookup</c>) — там его добавили, когда реплика молча
        /// осталась непереведённой. Здесь цена промаха такая же тихая: реплика
        /// просто говорится «в никуда», без единого сообщения.</para>
        /// </summary>
        public static string Normalize(string s)
        {
            if (string.IsNullOrEmpty(s)) return "";
            // Битую суррогатную пару .NET считает поводом бросить — а имя
            // персонажа не повод ронять главу: берём как есть.
            try { s = s.Normalize(NormalizationForm.FormC); }
            catch (ArgumentException) { }
            var sb = new StringBuilder(s.Length);
            foreach (var c in s.ToLowerInvariant())
                if (char.IsLetterOrDigit(c)) sb.Append(c);
            return sb.ToString();
        }
    }
}
