namespace Lvn
{
    /// <summary>
    /// КТО ОТДАЁТ КОМАНДУ СЦЕНЕ — подпись под каждой командой.
    ///
    /// <para>Живёт в ядре, а не в слое интерфейса, потому что подписывается и
    /// сам плеер: история — такой же отправитель, как остальные, просто главный
    /// по смыслу. Разрешает споры <c>LvnStageManager</c> (Помреж).</para>
    ///
    /// <para>До подписи спор двух отправителей за один предмет разрешался тем,
    /// чей <c>await</c> вернулся позже. Отсюда рос целый класс дефектов: рост
    /// героини скакал (три отправителя — три доли экрана), кукла прыгала при
    /// возврате в меню, реплика висела поверх катсцены, поза витрины
    /// подмешивалась к авторской.</para>
    /// </summary>
    public enum LvnSender
    {
        /// <summary>Сценарий автора — то, ради чего всё остальное.</summary>
        Story = 0,

        /// <summary>Восстановление кадра после загрузки: те же авторские
        /// команды, но игрок их не видел. Старшинство то же, что у истории.</summary>
        Replay = 1,

        /// <summary>Катсцена: приход в главу, уход в меню, гардеробный фокус.
        /// Пока играет — кадр принадлежит ей целиком.</summary>
        Cutscene = 2,

        /// <summary>Гардероб: игрок прямо сейчас крутит примерку и ждёт отклика
        /// на своё действие.</summary>
        Wardrobe = 3,

        /// <summary>Витрина меню: кукла на главной, полотно, створ. Оформление,
        /// а не событие, — поэтому младше истории.</summary>
        Menu = 4,

        /// <summary>Страж-самолечение: полотно опустело, слои куклы умерли.
        /// Чинит только то, о чём никто не спорит.</summary>
        Guard = 5,
    }
}
