using System;
using System.Threading;

namespace Lvn
{
    /// <summary>
    /// ПОГАСИТЬ ИСТОЧНИК ОТМЕНЫ — отменить и отпустить, не споткнувшись.
    ///
    /// <para>Связка повторялась у планировщика ассетов и у синхронизатора
    /// контента слово в слово: снять ссылку, отменить, освободить. Порядок в ней
    /// не украшение — он и есть смысл:</para>
    ///
    /// <list type="bullet">
    /// <item>ссылку снимают ПЕРВОЙ, иначе тот, кто заглянет между отменой и
    /// обнулением, увидит источник живым и подпишется на уже мёртвый токен;</item>
    /// <item><c>Cancel</c> оборачивают, потому что на уже освобождённом
    /// источнике он бросает — а «остановить дважды» бывает штатно: снос сцены и
    /// смена главы приходят почти одновременно;</item>
    /// <item><c>Dispose</c> обязателен: источник держит регистрации отмены, и
    /// без него они переживают того, кто их завёл.</item>
    /// </list>
    ///
    /// <para>Снятие ссылки остаётся у владельца — он один знает, нужен ли для
    /// этого замок. Общим стало то, что идёт после: гасить и отпускать.</para>
    /// </summary>
    public static class LvnCancel
    {
        /// <summary>Отменить и освободить снятый источник. <c>null</c> и
        /// повторный вызов безвредны.</summary>
        public static void Retire(CancellationTokenSource cts)
        {
            if (cts == null) return;
            try { cts.Cancel(); }
            catch (ObjectDisposedException) { /* уже погашен — это не ошибка */ }
            catch (AggregateException) { /* чей-то обработчик отмены упал; гасим дальше */ }
            cts.Dispose();
        }
    }
}
