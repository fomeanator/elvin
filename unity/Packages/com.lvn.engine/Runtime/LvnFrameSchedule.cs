using System.Collections.Generic;
using Newtonsoft.Json.Linq;

namespace Lvn
{
    /// <summary>
    /// НЕ ПОДКЛЮЧЁН: в игре состояние кадра ведёт Рамка (<see cref="LvnFrame"/>)
    /// — она собирает его ПО ХОДУ и этого хватает всем нынешним потребителям.
    /// Расписание отвечает на более сильный вопрос («что на сцене в ЛЮБОЙ точке
    /// сценария, не проходя его»), нужный перемотке и предпросмотру; включать
    /// его значит менять модель сцены, а не добавлять функцию. Тесты держат его
    /// рабочим до этого решения.
    ///
    /// РАСПИСАНИЕ КАДРА — кто в каком месте чем является, для КАЖДОЙ точки
    /// сценария.
    ///
    /// <para>Управление сценой идёт через сценарий, и это правильно: автор
    /// пишет историю, а не расставляет спрайты руками. Но пока состояние кадра
    /// было только СЛЕДОМ от последовательности команд, оно оставалось
    /// непредсказуемым — «что сейчас на сцене» знал лишь тот, кто прошёл весь
    /// путь, и любое вмешательство со стороны (катсцена, витрина, гардероб)
    /// делало ответ неизвестным даже сценарию.</para>
    ///
    /// <para>Здесь тот же сценарий читается как ГРАФ и превращается в
    /// расписание: для каждой команды известно, кто в кадре, где стоит и в
    /// каком облике. Дальше это просто данные, и с ними можно делать то, чего
    /// со следом сделать нельзя:</para>
    /// <list type="bullet">
    ///   <item>восстановить сохранение — взять кадр по индексу, а не
    ///   переигрывать сотню команд с их побочными эффектами;</item>
    ///   <item>вернуть кадр после катсцены — он записан, а не «запомнен на
    ///   всякий случай»;</item>
    ///   <item>проверить сценарий до запуска: где герой говорит, не будучи
    ///   показанным, где остался в кадре забытым, где двое стоят в одной
    ///   точке.</item>
    /// </list>
    ///
    /// <para><b>Ветвления.</b> Кадр зависит от пути: после выбора ветви
    /// приходят к одной команде с разными людьми на сцене. Расписание считает
    /// это честно — состояние узла хранится, только если оно ОДИНАКОВО по всем
    /// входящим путям (<see cref="Certain"/>); иначе узел помечается
    /// «зависит от пути», и точный кадр берётся по трассе исполнения, которую
    /// сохранение и так хранит. Врать про кадр хуже, чем признать
    /// неоднозначность.</para>
    /// </summary>
    public static class LvnFrameSchedule
    {
        /// <summary>Кадр в точке сценария плюс честность этого знания.</summary>
        public struct Stop
        {
            /// <summary>Состояние сцены ПОСЛЕ выполнения этой команды.</summary>
            public LvnFrame Frame;

            /// <summary>Одинаков ли кадр по всем путям, приводящим сюда. False —
            /// узел лежит после схождения ветвей с разной сценой, и точный ответ
            /// даёт только трасса.</summary>
            public bool Certain;
        }

        /// <summary>
        /// ПРОЙТИ ПО СЦЕНАРИЮ И РАСПИСАТЬ КАДР для каждой команды.
        ///
        /// <para>Обход идёт по фактическим переходам (<c>jump</c>, ветви выбора,
        /// конец блока), а не по порядку строк: линейный проход соврал бы на
        /// первом же ветвлении. Узел, к которому пришли двумя путями с разной
        /// сценой, помечается неопределённым и дальше несёт эту пометку — ложь
        /// в расписании опаснее пустого места.</para>
        /// </summary>
        /// <param name="script">команды сценария по порядку</param>
        /// <param name="edges">куда ведёт команда i: список индексов-наследников</param>
        public static Stop[] Build(IReadOnlyList<JObject> script,
                                   System.Func<int, IReadOnlyList<int>> edges)
        {
            int n = script?.Count ?? 0;
            var stops = new Stop[n];
            if (n == 0) return stops;

            var seen = new bool[n];
            var queue = new Queue<(int at, LvnFrame frame)>();
            queue.Enqueue((0, new LvnFrame()));

            while (queue.Count > 0)
            {
                var (at, incoming) = queue.Dequeue();
                if (at < 0 || at >= n) continue;

                var frame = incoming.Clone();
                frame.Absorb(script[at]);

                if (!seen[at])
                {
                    seen[at] = true;
                    stops[at] = new Stop { Frame = frame, Certain = true };
                }
                else
                {
                    // Сюда уже приходили. Совпало — знание подтверждено; не
                    // совпало — узел неоднозначен, и это надо СКАЗАТЬ, а не
                    // выбрать один из вариантов молча.
                    bool same = stops[at].Frame.SameAs(frame);
                    if (!same && stops[at].Certain)
                        stops[at] = new Stop { Frame = stops[at].Frame, Certain = false };
                    continue;   // дальше по этой ветке уже ходили
                }

                var next = edges?.Invoke(at);
                if (next == null) continue;
                foreach (var to in next) queue.Enqueue((to, frame));
            }
            return stops;
        }

        /// <summary>
        /// КАДР ПО ТРАССЕ — точный ответ там, где расписание неоднозначно.
        ///
        /// <para>Сохранение хранит путь, которым игрок реально шёл. Пройти по
        /// нему — значит получить кадр без единой догадки и без побочных
        /// эффектов: ни звука, ни ожиданий, ни переходов, только состояние.</para>
        /// </summary>
        public static LvnFrame At(IReadOnlyList<JObject> script, IReadOnlyList<int> trace)
        {
            var frame = new LvnFrame();
            if (script == null || trace == null) return frame;
            foreach (var i in trace)
                if (i >= 0 && i < script.Count) frame.Absorb(script[i]);
            return frame;
        }
    }
}
