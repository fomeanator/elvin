using System.Threading;
using System.Threading.Tasks;
using Lvn.Content;
using UnityEngine.UIElements;

namespace Lvn.UI.Screens
{
    /// <summary>
    /// ВИТРИНА — экран, на котором игрок выбирает новеллу. Витрин у движка две
    /// (карусель и хаб), выбирает манифест, а вопрос к ним один: КАКУЮ НОВЕЛЛУ
    /// ВЫБРАЛ ИГРОК.
    ///
    /// <para>Раньше вопрос был один, а ответов два. Хаб отвечал одним
    /// <c>await</c>, а у карусели тот же ответ собирался в цикле оболочки:
    /// подписка на событие, снятие подписки, защёлка раннего запроса, регистрация
    /// отмены и перевод НОМЕРА карточки в новеллу. Всё это — устройство карусели,
    /// вытекшее в вызывающий код, и оно тут же разошлось: карусель обновляла
    /// прогресс по требованию оболочки, хаб — сам; отмена у одной кидала
    /// исключение, у другого возвращала null.</para>
    ///
    /// <para>Дороже всего обошёлся <see cref="RequestTitle"/>. Ссылка вида
    /// <c>?title=cold</c> открывала новеллу мимо витрины — но защёлкивалась она
    /// в КАРУСЕЛИ, а ждал ответа ХАБ. В режиме хаба ссылка не делала ничего и
    /// при этом рапортовала об успехе: тот самый молчаливый отказ, про который
    /// соседняя строка обработчика диплинка пишет «худший вид отказа».</para>
    /// </summary>
    public interface ILvnBrowse : ILvnContentAware
    {
        /// <summary>Поверхность витрины — её показывают и прячут.</summary>
        VisualElement View { get; }

        /// <summary>Спросить игрока. Ответ — выбранная новелла или null: игрок
        /// ушёл, не выбрав (или виток отменили). Витрина сама освежает себя
        /// перед показом и сама разбирает защёлку раннего запроса.</summary>
        Task<LvnTitle> PickTitleAsync(CancellationToken ct = default);

        /// <summary>Открыть новеллу без спроса — диплинк, автозапуск, тест.
        /// Запрос, поданный ДО того, как витрина взяла управление, защёлкивается
        /// и срабатывает в тот же миг. false — новеллы с таким id нет.</summary>
        bool RequestTitle(string titleId);

        // «Приехал свежий манифест» — общая пометка ILvnContentAware: витрина
        // держится на нём так же, как вкладка гардероба и магазин.
    }
}
