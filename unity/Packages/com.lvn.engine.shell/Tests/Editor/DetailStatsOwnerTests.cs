using Lvn.Content;
using Lvn.UI.Screens;
using Newtonsoft.Json.Linq;
using NUnit.Framework;

namespace Lvn.Tests
{
    /// <summary>
    /// КАРТОЧКА НЕ ПОКАЗЫВАЕТ ЧУЖОЙ ПРОГРЕСС.
    ///
    /// <para>Хост ставит новеллу на карточку сразу, а её статы грузит из
    /// хранилища — то есть ждёт сеть. Пока он ждёт, витрина ещё на экране, и
    /// игрок успевает открыть вторую карточку. Опоздавшая загрузка первой
    /// писала свои значения поверх уже показанной второй: игрок видел на
    /// новелле, в которую не играл, чужой прогресс.</para>
    ///
    /// <para>Замер по коду 06.09: `Detail.Title = t` стоит ДО ожидания
    /// `LoadScopedVarsAsync`, а `StatVars` и `Rebuild` — ПОСЛЕ; поля публичны и
    /// пишутся раздельно. Проверка живёт в самом экране, потому что забыть её
    /// может любой, кто их заполняет.</para>
    ///
    /// <para>Денег это не касается, и это проверено отдельно: второй показ
    /// упирается в `if (_open) return false` у модального экрана, поэтому
    /// «Играть» отрабатывает у того потока, который экран открыл, со своей
    /// новеллой. Гипотеза о списании за чужую новеллу оказалась ложной.</para>
    /// </summary>
    public class DetailStatsOwnerTests
    {
        private static LvnTitle Новелла(string id) => new LvnTitle { id = id, name = id };

        [Test]
        public void СтатыСвоейНовеллыПринимаются()
        {
            var экран = new TitleDetailScreen(null);
            var первая = Новелла("первая");
            экран.Title = первая;

            Assert.IsTrue(экран.SetStatsFor(первая, new JObject { ["глава"] = 3 }),
                "экран отказал статам той новеллы, которую сам и показывает");
            Assert.AreEqual(3, (int)экран.StatVars["глава"], "статы не легли");
        }

        [Test]
        public void ОпоздавшиеСтатыЧужойНовеллыНеЛожатся()
        {
            var экран = new TitleDetailScreen(null);
            var первая = Новелла("первая");
            var вторая = Новелла("вторая");

            // Игрок открыл первую, статы поехали…
            экран.Title = первая;
            // …и, не дождавшись, открыл вторую.
            экран.Title = вторая;
            экран.SetStatsFor(вторая, new JObject { ["глава"] = 0 });

            // Теперь вернулась загрузка ПЕРВОЙ.
            Assert.IsFalse(экран.SetStatsFor(первая, new JObject { ["глава"] = 7 }),
                "экран принял статы новеллы, которую уже не показывает");
            Assert.AreEqual(0, (int)экран.StatVars["глава"],
                "на карточке второй новеллы оказался прогресс первой — игрок видит, "
                + "что «прошёл» историю, которую не открывал");
        }

        [Test]
        public void ПустыеСтатыНеРоняютЭкран()
        {
            var экран = new TitleDetailScreen(null);
            var одна = Новелла("одна");
            экран.Title = одна;

            Assert.IsTrue(экран.SetStatsFor(одна, null), "пустая загрузка отвергнута как чужая");
            Assert.IsNotNull(экран.StatVars, "вместо пустых статов положен null — читатель упадёт");
        }
    }
}
