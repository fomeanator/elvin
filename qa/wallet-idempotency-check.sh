#!/usr/bin/env bash
# ПОВТОР НЕ СПИСЫВАЕТ ДВАЖДЫ — И СКОЛЬКО ЭТО ПОМНИТСЯ.
#
# Связь рвётся посреди покупки чаще, чем кажется: ответ потерялся, клиент не
# знает, дошло ли, и повторяет. Обещание такое: одна и та же операция,
# присланная дважды, списывает РОВНО ОДИН РАЗ. Ключ идемпотентности приходит от
# клиента (op_id), а сервер помнит недавние.
#
# Из «помнит недавние» следуют два вопроса, которые обычно не задают:
#
#   ПЕРЕЗАПУСК  память об операции живёт в документе кошелька или только в
#               процессе? Если в процессе — повтор после перезапуска спишет
#               второй раз, и это худший вид потери: деньги игрока;
#   ГОРИЗОНТ    список недавних конечен. Сколько ЧУЖИХ операций может пройти
#               между списанием и повтором, прежде чем повтор снова сработает?
#               Число надо ЗАМЕРИТЬ, а не прочитать в константе: между
#               константой и поведением стоит код.
#
# Стенд поднимает настоящий сервер и говорит с ним по HTTP.
#
# ПРОВЕРКА ОБЯЗАНА УМЕТЬ ПАДАТЬ. Стенд, который ничего не списал, отрапортует
# «баланс не изменился» и соврёт. Поэтому первое списание обязано изменить
# баланс, а -bite повторяет с ДРУГИМ ключом и требует, чтобы баланс изменился:
# стенд, не видящий двойного списания, не увидит и настоящего.
#
#   qa/wallet-idempotency-check.sh [-bite]
set -uo pipefail
cd "$(dirname "$0")/.."
BITE=""; [ "${1:-}" = "-bite" ] && BITE=1

command -v go   >/dev/null 2>&1 || { echo "нет go — пропускаю"; exit 0; }
command -v curl >/dev/null 2>&1 || { echo "нет curl — пропускаю"; exit 0; }

W="$(mktemp -d)"; PID=""
cleanup() { [ -n "$PID" ] && kill "$PID" 2>/dev/null; rm -rf "$W"; }
trap cleanup EXIT

go build -C server -o "$W/srv" . || { echo "сервер не собрался"; exit 1; }

PORT="${LVN_PORT:-8077}"
probe() { curl -fsS -m 1 "http://127.0.0.1:$1/healthz" >/dev/null 2>&1; }
if probe "$PORT"; then
  PORT=0
  for p in 8078 8079 8081 8082; do probe "$p" || { PORT=$p; break; }; done
  [ "$PORT" = "0" ] && { echo "порты заняты — пропускаю"; exit 0; }
fi
BASE="http://127.0.0.1:$PORT"
mkdir -p "$W/content"; echo '{"titles":[]}' > "$W/content/manifest.json"

boot() {
  "$W/srv" -addr "127.0.0.1:$PORT" -content "$W/content" -auth-dev >>"$W/server.log" 2>&1 &
  PID=$!
  for _ in $(seq 1 60); do probe "$PORT" && return 0; sleep 0.2; done
  echo "сервер не поднялся:"; tail -5 "$W/server.log"; return 1
}

# ПОРТ ОБЯЗАН УМЕРЕТЬ, А НЕ ПРОСТО ПЕРЕСТАТЬ БЫТЬ НАШИМ.
#
# Убитый процесс и молчащий порт — разные вещи. Если на порту остался ЧУЖОЙ
# сервер (хвост прошлого прогона), стенд продолжит разговаривать с ним: тот
# ответит бодро, с другим каталогом и другими деньгами, и «пережило перезапуск»
# окажется рассказом про постороннего. Проверено на себе — один заблудившийся
# сервер подряд наврал три раза, и каждый раз правдоподобно.
stop() {
  [ -n "$PID" ] || return 0
  kill "$PID" 2>/dev/null; wait "$PID" 2>/dev/null; PID=""
  for _ in $(seq 1 50); do probe "$PORT" || return 0; sleep 0.2; done
  echo "ПОРТ $PORT ОТВЕЧАЕТ ПОСЛЕ ОСТАНОВКИ — на нём чужой сервер, замер недействителен"
  return 1
}

probe "$PORT" && { echo "порт $PORT занят до старта — замер говорил бы с чужим сервером"; exit 2; }
boot || exit 1

TOK="$(curl -sS -X POST "$BASE/v1/auth/register" -H 'Content-Type: application/json' \
        -d '{"device_id":"stand-device-0000001"}' |
        python3 -c 'import json,sys;print(json.load(sys.stdin)["token"])')"
[ -n "$TOK" ] || { echo "учётка не завелась"; exit 1; }

api() { curl -sS -X POST "$BASE/v1/wallet/$1" -H "Authorization: Bearer $TOK" \
          -H 'Content-Type: application/json' -d "$2"; }
soft() { curl -sS "$BASE/v1/wallet" -H "Authorization: Bearer $TOK" |
         python3 -c 'import json,sys;print(json.load(sys.stdin)["balances"].get("soft",0))'; }
hist() { curl -sS "$BASE/v1/wallet" -H "Authorization: Bearer $TOK" |
         python3 -c 'import json,sys;print(len(json.load(sys.stdin).get("history") or []))'; }

fail=0
say() { echo "  $1"; }

# earn открыт НАМЕРЕННО (тестовый режим партнёра) — им и пополняем стенд.
api earn '{"currency":"soft","amount":2000,"reason":"стенд"}' >/dev/null
start="$(soft)"
[ "$start" = "2000" ] || { say "✗ пополнение не прошло (баланс $start)"; exit 1; }

SPEND='{"currency":"soft","amount":100,"reason":"покупка","op_id":"op-стенд-1"}'
WANT=$((start - 100))   # ожидание считается, а не вписывается числом

# ── 1. Списание действительно происходит ───────────────────────────────────
api spend "$SPEND" >/dev/null
after="$(soft)"; h1="$(hist)"
say "списание: $start → $after (записей в истории: $h1)"
[ "$after" = "$WANT" ] || { say "✗ списание не сработало — мерить нечего"; fail=1; }

# ── 2. Повтор того же ключа ────────────────────────────────────────────────
if [ -n "$BITE" ]; then
  api spend '{"currency":"soft","amount":100,"reason":"покупка","op_id":"op-стенд-ДРУГОЙ"}' >/dev/null
  b="$(soft)"
  say "УКУС: повтор с ДРУГИМ ключом → баланс $b (ждём 300)"
  [ "$b" = "300" ] && { say "стенд честный: двойное списание он видит"; exit 0; }
  say "СТЕНД СЛЕП: списание с новым ключом не изменило баланс"; exit 2
fi

api spend "$SPEND" >/dev/null
b2="$(soft)"; h2="$(hist)"
say "повтор того же ключа: баланс $b2 (записей: $h2)"
[ "$b2" = "$WANT" ] || { say "✗ ПОВТОР СПИСАЛ ВТОРОЙ РАЗ"; fail=1; }
[ "$h2" = "$h1" ] || { say "✗ повтор дописал историю ($h1 → $h2) — деньги целы, журнал врёт"; fail=1; }

# ── 3. Перезапуск процесса ─────────────────────────────────────────────────
stop || exit 2
boot || exit 1
api spend "$SPEND" >/dev/null
b3="$(soft)"
say "повтор после перезапуска: баланс $b3"
[ "$b3" = "$WANT" ] || { say "✗ ПЕРЕЗАПУСК ЗАБЫЛ ОПЕРАЦИЮ — повтор списал второй раз"; fail=1; }

# ── 4. Горизонт памяти ─────────────────────────────────────────────────────
# Гоняем чужие операции по одной и после каждой пробуем повтор старого ключа.
# Как только он сработает — это и есть горизонт, замеренный, а не вычитанный.
horizon=""
for i in $(seq 1 260); do
  api spend "{\"currency\":\"soft\",\"amount\":1,\"reason\":\"шум\",\"op_id\":\"шум-$i\"}" >/dev/null
  before="$(soft)"
  if [ "$before" -lt 100 ]; then
    say "деньги кончились на $i-й операции — горизонт не замерен, увеличьте пополнение"
    fail=1; break
  fi
  api spend "$SPEND" >/dev/null
  now="$(soft)"
  if [ "$now" != "$before" ]; then horizon="$i"; break; fi
done
if [ -n "$horizon" ]; then
  say "горизонт памяти: старый ключ снова сработал после $horizon чужих операций"
else
  say "горизонт памяти: за 260 чужих операций ключ не забылся"
fi

# ── 5. Свежая покупка ПОСЛЕ окна, затем перезапуск ─────────────────────────
# Здесь и жил дефект. В памяти список ключей был исправен, поэтому повтор без
# перезапуска ловился всегда — а на диск после окна не попадал НИ ОДИН новый
# ключ: обрезка списка не двигала курсор записи, и хвост для сохранения
# оставался пустым навсегда. Виден дефект только так: много операций, свежая
# покупка, перезапуск, повтор.
FRESH='{"currency":"soft","amount":300,"reason":"крупная","op_id":"op-свежий-после-окна"}'
api spend "$FRESH" >/dev/null
f1="$(soft)"
stop || exit 2
boot || exit 1
f2="$(soft)"
api spend "$FRESH" >/dev/null
f3="$(soft)"
say "свежая покупка после окна: $f1 → перезапуск $f2 → повтор $f3"
[ "$f2" = "$f1" ] || { say "✗ перезапуск потерял покупку"; fail=1; }
[ "$f3" = "$f2" ] || { say "✗ ДВОЙНОЕ СПИСАНИЕ после перезапуска: ушло ещё $((f2 - f3))"; fail=1; }

[ "$fail" = "0" ] && { echo "ПОВТОР НЕ СПИСЫВАЕТ ДВАЖДЫ"; exit 0; }
echo "ДЕНЬГИ ТЕРЯЮТСЯ"; exit 1
