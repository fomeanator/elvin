#!/bin/zsh
# ПРОВЕРКА ПЕРЕД ВЫГРУЗКОЙ В ПУБЛИЧНЫЙ РЕПОЗИТОРИЙ.
#
# Движок открыт: всё, что уедет в origin, увидят немедленно. Партнёрский
# контент, название продукта и секреты туда попадать не должны — не потому что
# «неаккуратно», а потому что убрать это можно только переписыванием истории с
# принудительной выгрузкой, и старые коммиты всё равно остаются доступны по
# прямому SHA, пока площадка не соберёт мусор.
#
# ПОЧЕМУ СКРИПТ, А НЕ СПИСОК КОМАНД В ЗАМЕТКЕ. Список был, и он врал: команды
# в нём кончались на `| head`, а `grep` в конвейере отдаёт наружу код ПОСЛЕДНЕЙ
# команды. Совпадений нет — grep выходит с единицей, head с нулём, `|| echo
# "чисто"` не срабатывает, и на экране пусто. Пустой экран читается как
# «чисто», хотя означает лишь «ничего не напечатали». 04.09 автор этих строк
# на этом и попался — за час до того, как в шестой раз поймал тот же приём в
# чужом коде.
#
# Поэтому здесь: явные ЧИСЛА вместо пустого экрана, и САМОПРОВЕРКА — образец
# подкладывается нарочно, и если мерка его не ловит, скрипт падает. Ноль,
# полученный сломанной меркой, хуже единицы.
#
#   qa/leak-scan.sh            что уедет при выгрузке (origin/main..HEAD)
#   qa/leak-scan.sh <диапазон> любой другой диапазон
set -e
REPO=${0:A:h:h}
cd "$REPO"
RANGE=${1:-origin/main..HEAD}

# Партнёрский контент и продукт. Список ведётся по живым утечкам, а не по
# воображению: каждое слово здесь однажды уже уезжало наружу.
CONTENT='Cold_|timeromance|Time Romance|Katya|Матвей|Adele|Philipp|Bogdan|Lyuba|victoria|hill/'
# Секреты. Полные значения не пишем даже здесь — только их узнаваемая форма.
SECRETS='FjB8|149\.33\.41\.201|glrt-|ADMIN_TOKEN *='

fail=0
count() { grep -icE "$2" <<< "$1" || true; }

# САМОПРОВЕРКА ПЕРВОЙ. Если мерка не ловит заведомый образец, все нули ниже
# ничего не значат, и продолжать нельзя.
if [ "$(count 'ветка про timeromance' "$CONTENT")" -lt 1 ] ||
   [ "$(count 'токен glrt-xxx' "$SECRETS")" -lt 1 ]; then
  echo "ОСТАНОВ: мерка не ловит подложенный образец — нули ниже были бы ложью"
  exit 2
fi

msgs=$(git log --format="%h %s%n%b" "$RANGE" 2>/dev/null || true)
adds=$(git diff "$RANGE" --unified=0 2>/dev/null | grep '^+' || true)
bins=$(git diff "$RANGE" --numstat 2>/dev/null | awk '$1=="-"' || true)

n1=$(count "$msgs" "$CONTENT")
n2=$(count "$adds" "$CONTENT")
n3=$(count "$adds" "$SECRETS")
n4=$(printf '%s' "$bins" | grep -c . || true)

printf 'диапазон: %s\n' "$RANGE"
printf '  1) контент в СООБЩЕНИЯХ коммитов: %s\n' "$n1"
printf '  2) контент в добавленных строках: %s\n' "$n2"
printf '  3) секреты:                       %s\n' "$n3"
printf '  4) двоичные файлы:                %s\n' "$n4"

[ "$n1" = 0 ] || { echo "  ↳ сообщения коммитов забывают чаще всего: git rebase -i или filter-branch --msg-filter"; fail=1; }
[ "$n2" = 0 ] || { echo "  ↳ обезличьте строки: партнёрский каст → демо-состав, продукт → «продуктовый домен»"; fail=1; }
[ "$n3" = 0 ] || { echo "  ↳ секрет в диффе: вынесите в env/lvn.env и перепишите коммит"; fail=1; }
[ "$n4" = 0 ] || { echo "  ↳ двоичные файлы; убедитесь, что это не контент и не тяжесть:"; printf '%s\n' "$bins" | sed 's/^/     /'; fail=1; }

# Ложное срабатывание, не пугаться: terrainFadeLength ловится на «adeLe».
if [ "$fail" = 0 ]; then echo "ЧИСТО — можно выгружать"; else echo "НЕ ВЫГРУЖАТЬ"; exit 1; fi
