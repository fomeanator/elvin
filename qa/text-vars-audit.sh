#!/usr/bin/env bash
# ОТКУДА В РЕПЛИКУ ПРИХОДЯТ ПОДСТАНОВКИ — и кто их проверяет.
#
# Автор пишет «Привет, {имя}!». Если в имени опечатка, движок покажет игроку
# буквально «Привет, {имя_с_опечаткй}!» — решение осознанное (видимая дыра
# честнее пустоты), но узнаёт о ней автор только из игры.
#
# Соблазн — научить компилятор ругаться на незнакомое имя. Замер показывает,
# почему так нельзя: область видимости переменной ШИРЕ ФАЙЛА. Она приходит из
# манифеста новеллы (title.vars_url), из предыдущих глав, от хоста (имя игрока)
# — а компилятор видит одну главу.
#
# Этот стенд не сторожит, а МЕРИТ: сколько подстановок в контенте и сколько из
# них не объясняются своей же главой. Повторяемый замер, по которому видно
# движение — и который сразу скажет, если проверка на уровне новеллы всё-таки
# появится и число упадёт до нуля.
#
#   qa/text-vars-audit.sh [-bite]
#
# -bite подкладывает главу с заведомо чужой подстановкой: замер обязан её
# заметить. Мерка, не видящая подставленного, не увидит и настоящего.
set -uo pipefail
cd "$(dirname "$0")/.."
BITE=""; [ "${1:-}" = "-bite" ] && BITE=1

command -v python3 >/dev/null 2>&1 || { echo "нет python3 — пропускаю"; exit 0; }

DIR="server/content/scripts"
[ -d "$DIR" ] || { echo "нет каталога скриптов — пропускаю"; exit 0; }

W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT
if [ -n "$BITE" ]; then
  cp -R "$DIR" "$W/scripts"
  printf '{"scene":"bite","script":[{"op":"say","text":"Привет, {совершенно_чужое_имя}!"}]}' \
    > "$W/scripts/bite-probe.lvn"
  DIR="$W/scripts"
fi

python3 - "$DIR" "${BITE:-}" <<'PY'
import collections, glob, json, os, re, sys
d, bite = sys.argv[1], sys.argv[2]

# Имена, которые приходят НЕ из главы и это законно: их даёт хост или общий
# каталог новеллы. Список короткий намеренно — он и есть договор.
ИЗВНЕ = {"player", "net_error"}

files = 0
подстановок = 0
чужие = collections.Counter()
for p in sorted(glob.glob(os.path.join(d, "*.lvn"))):
    try:
        doc = json.load(open(p, encoding="utf-8"))
    except Exception:
        continue
    ops = doc.get("script") or []
    if not ops:
        continue
    files += 1
    заданные = set()
    for c in ops:
        op = c.get("op")
        if op in ("set", "inc"):
            заданные.add(str(c.get("key") or c.get("var") or ""))
        if op == "input":
            заданные.add(str(c.get("var") or ""))
    for c in ops:
        for поле in ("text", "who"):
            for m in re.findall(r"\{([^}]+)\}", str(c.get(поле) or "")):
                m = m.strip()
                подстановок += 1
                if not re.fullmatch(r"[A-Za-zА-Яа-я_][\w_]*", m):
                    continue          # выражение, а не простое имя
                if m in заданные or m in ИЗВНЕ:
                    continue
                чужие[m] += 1

print(f"  скриптов:                    {files}")
print(f"  подстановок в тексте:        {подстановок}")
print(f"  имён без объяснения в главе: {len(чужие)}")
for имя, n in чужие.most_common(6):
    print(f"     {имя}: {n}")

if bite:
    sys.exit(0 if "совершенно_чужое_имя" in чужие else 1)
sys.exit(0)
PY
code=$?

if [ -n "$BITE" ]; then
  if [ "$code" = "0" ]; then
    echo "укус чист: подложенную чужую подстановку замер увидел"
    exit 0
  fi
  echo "СТЕНД СЛЕП: чужая подстановка легла в контент, а замер её не назвал"
  exit 2
fi

echo
echo "Эти имена НЕ ошибка: они приходят из манифеста новеллы (title.vars_url),"
echo "из предыдущих глав или от хоста. Проверить их может только инструмент,"
echo "видящий новеллу целиком, — а сегодня и компилятор, и walk работают по"
echo "одной главе. Замер повторяемый: число упадёт, когда такая проверка появится."
exit 0
