#!/usr/bin/env bash
# ЧЕСТНЫ ЛИ САМИ МЕРКИ — прогон всех укусов разом.
#
# В репозитории договор: у стенда есть флаг `-bite`, который ЛОМАЕТ то, что
# стенд охраняет. Мерка обязана покраснеть; не покраснела — её зелёный цвет
# ничего не значит, и «держит» в каноне держится на честном слове.
#
# Каждый стенд проверяет свой укус сам, но НИКТО не проверял, что честны они
# ВСЕ. Этот прогон закрывает пробел: он один раз проходит по всем стендам с
# флагом укуса и считает коды возврата — 0 честен, 2 слеп.
#
# Смотрим именно на КОД, а не на слова. Замер 06.09 показал, почему: стенды
# пишут по-разному — «укус чист», «укус замечен», «стенд честный», — и разбор
# по фразе дал два ложных «СЛЕП» подряд. Код возврата един для всех.
#
# ОТЧЁТ НЕ ГОВОРИТ ПРО ТО, ЧЕГО НЕ МЕРИЛ. Замер 07.09: в прогоне судьи
# (--quick) спрашивали СЕМЬ мерок из сорока семи, а внизу печаталось «каждая
# мерка доказала, что умеет заметить поломку». Ещё четыре стенда не имеют
# укуса вовсе и молча выпадали из счёта — их не было ни в одной строке.
# Признание «держит» стоит ровно столько, сколько проверено под ним.
#
#   qa/bites-honest-check.sh [--quick|-bite]
#
# Без флага проходит ВСЕ стенды (долго: каждый поднимает свой сервер).
# --quick берёт только те, что не требуют сборки сервера.
# -bite проверяет САМ ОТЧЁТ: подсовывает непроверенную мерку и требует, чтобы
# вердикт перестал говорить «все». Заметил — 0, смолчал — 2.
set -uo pipefail
cd "$(dirname "$0")/.."
QUICK=""; [ "${1:-}" = "--quick" ] && QUICK=1
BITE=""; [ "${1:-}" = "-bite" ] && { BITE=1; QUICK=1; }

# Сколько стендов вовсе без укуса — терпимо, но НЕ МОЛЧА. Бюджет измерен
# 07.09; вырастет — значит завели ещё одну мерку, чей зелёный цвет никем не
# проверен, и об этом надо узнать сразу, а не через год.
NOBITE_BUDGET=4

clean=0; blind=0; skipped=0; broken=0; total=0
declare -a bad=()
declare -a nobite=()

for f in qa/*-check.sh; do
  name="$(basename "$f")"
  [ "$name" = "bites-honest-check.sh" ] && continue     # сам себя не кусает
  if ! grep -q '\-bite' "$f"; then nobite+=("$name"); continue; fi
  total=$((total+1))
  if [ -n "$QUICK" ] && grep -q "go build" "$f"; then
    skipped=$((skipped+1)); continue
  fi
  nice -n 10 bash "$f" -bite >/dev/null 2>&1
  case "$?" in
    0) clean=$((clean+1)) ;;
    2) blind=$((blind+1)); bad+=("$name: СЛЕП — сломали то, что он охраняет, а он промолчал") ;;
    *) broken=$((broken+1)); bad+=("$name: укус кончился ошибкой (не 0 и не 2) — стенд не смог даже сломать") ;;
  esac
done

# УКУС САМОГО ОТЧЁТА. Разбираем ровно ту развилку, которую чиним: делаем вид,
# что проверено ВСЁ, кроме одной мерки. Тогда единственная причина не говорить
# «все» — эта одна; скажет «все» — соврал про непроверенное.
#
# Просто добавить пропущенную было бы негодным укусом: в --quick их и так
# сорок, и вердикт свернул бы на честную ветку сам, ничего не доказав.
if [ -n "$BITE" ]; then
  nobite=(); skipped=1
fi

echo "  мерок с укусом: $total"
echo "  честных укусов: $clean"
echo "  слепых мерок:   $blind"
echo "  сломанных:      $broken"
echo "  не спрошено:    $skipped$([ "$skipped" -gt 0 ] && echo "  (нужен собранный сервер — полный прогон без --quick)")"
if [ "${#nobite[@]}" -gt 0 ]; then
  echo "  БЕЗ УКУСА ВОВСЕ: ${#nobite[@]} — ${nobite[*]}"
fi

if [ "${#nobite[@]}" -gt "$NOBITE_BUDGET" ]; then
  bad+=("мерок без укуса стало ${#nobite[@]} при бюджете $NOBITE_BUDGET — у новой мерки зелёный цвет никем не проверен")
fi

if [ "${#bad[@]}" -gt 0 ]; then
  echo "РВЁТСЯ:"
  for b in "${bad[@]}"; do echo "   $b"; done
  [ -n "$BITE" ] && exit 0
  exit 1
fi

# ПРИЗНАНИЕ РОВНО ПО ПРОВЕРЕННОМУ. «Все» говорится только когда спрошены все.
if [ "$skipped" -gt 0 ] || [ "${#nobite[@]}" -gt 0 ]; then
  [ -n "$BITE" ] && { echo "укус замечен: одна мерка не спрошена — вердикт про всех не говорит"; exit 0; }
  echo "держит проверенное: $clean из $total мерок доказали укус; $skipped не спрошено, у ${#nobite[@]} укуса нет вовсе"
  exit 0
fi
[ -n "$BITE" ] && { echo "УКУС НЕ ЗАМЕЧЕН: одну мерку не спрашивали, а вердикт всё равно сказал «все»"; exit 2; }
echo "держит: все $total мерок доказали, что умеют заметить поломку"
