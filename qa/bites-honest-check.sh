#!/usr/bin/env bash
# ЧЕСТНЫ ЛИ САМИ МЕРКИ — прогон всех укусов разом.
#
# В репозитории договор: у стенда есть флаг `-bite`, который ЛОМАЕТ то, что
# стенд охраняет. Мерка обязана покраснеть; не покраснела — её зелёный цвет
# ничего не значит, и «держит» в каноне держится на честном слове.
#
# Каждый стенд проверяет свой укус сам, но НИКТО не проверял, что честны они
# ВСЕ. Этот прогон закрывает пробел: он один раз проходит по всем стендам с
# флагом укуса и считает коды возврата — 0 честен, 2 слеп.
#
# Смотрим именно на КОД, а не на слова. Замер 06.09 показал, почему: стенды
# пишут по-разному — «укус чист», «укус замечен», «стенд честный», — и разбор
# по фразе дал два ложных «СЛЕП» подряд. Код возврата един для всех.
#
#   qa/bites-honest-check.sh [--quick]
#
# Без флага проходит ВСЕ стенды (долго: каждый поднимает свой сервер).
# --quick берёт только те, что не требуют сборки сервера.
set -uo pipefail
cd "$(dirname "$0")/.."
QUICK=""; [ "${1:-}" = "--quick" ] && QUICK=1

clean=0; blind=0; skipped=0; broken=0
declare -a bad=()

for f in qa/*-check.sh; do
  name="$(basename "$f")"
  [ "$name" = "bites-honest-check.sh" ] && continue     # сам себя не кусает
  grep -q '\-bite' "$f" || continue
  if [ -n "$QUICK" ] && grep -q "go build" "$f"; then
    skipped=$((skipped+1)); continue
  fi
  nice -n 10 bash "$f" -bite >/dev/null 2>&1
  case "$?" in
    0) clean=$((clean+1)) ;;
    2) blind=$((blind+1)); bad+=("$name: СЛЕП — сломали то, что он охраняет, а он промолчал") ;;
    *) broken=$((broken+1)); bad+=("$name: укус кончился ошибкой (не 0 и не 2) — стенд не смог даже сломать") ;;
  esac
done

echo "  честных укусов: $clean"
echo "  слепых мерок:   $blind"
echo "  пропущено:      $skipped"
echo "  сломанных:      $broken"

if [ "${#bad[@]}" -gt 0 ]; then
  echo "РВЁТСЯ:"
  for b in "${bad[@]}"; do echo "   $b"; done
  exit 1
fi
echo "держит: каждая мерка доказала, что умеет заметить поломку"
